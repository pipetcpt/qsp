chk <- function(label, value, lo, hi, unit = "") {
  ok <- !is.na(value) && value >= lo && value <= hi
  cat(sprintf("  [%s] %-56s %8.2f %-12s (target %g-%g)\n",
              if (ok) "PASS" else "FAIL", label, value, unit, lo, hi))
  ok
}
g <- function(scn, col, d) {
  s <- sim[sim$scenario == scn, ]
  at(d, s[[col]], s$time)
}
