# =============================================================================
#  Kidney Transplant Rejection & Immunosuppression — QSP model (mrgsolve)
#  ---------------------------------------------------------------------------
#  ktx_mrgsolve_model.R   ·   companion to ktx_qsp_model.dot / ktx_shiny_app.R
#
#  WHAT THIS MODEL IS ABOUT
#  ------------------------
#  A kidney transplant is the only condition in this library whose pathology is
#  produced by a NORMALLY FUNCTIONING immune system, and whose treatment target
#  is therefore not a pathway but a SET POINT.  The model is built around one
#  scalar, NET IMMUNOSUPPRESSION (NIS), and the two failure modes that sit on
#  either side of it:
#
#      too little NIS  ->  TCMR, de novo DSA, ABMR      ->  graft loss
#      too much  NIS  ->  BK nephropathy, CMV, PTLD     ->  graft loss
#
#  Everything else in the model exists to make that trade-off quantitative.
#
#  THREE FEEDBACK LOOPS DO THE WORK
#  --------------------------------
#  LOOP 1  alloimmune amplification
#          injury -> DAMP -> antigen presentation (AG) -> effector traffic ->
#          injury.  Sub-critical under adequate immunosuppression, supercritical
#          without it: this is what makes untreated rejection an ignition event
#          (Banff t reaches ~2.5 within 10-14 days) rather than a slow drift.
#
#  LOOP 2  nephron mass / hyperfiltration (Brenner)
#          nephron loss -> single-nephron hyperfiltration -> TGF-beta -> IFTA ->
#          nephron loss.  DRUG-INDEPENDENT.  It is why every graft declines at
#          roughly -1 mL/min/1.73 m2/year even when nothing immunological
#          ever happens.
#
#  LOOP 3  the clinical control loop
#          BK viraemia -> the clinician reduces immunosuppression -> the virus
#          clears -> alloimmunity rebounds.  This one is implemented as a REAL
#          closed-loop controller inside $ODE (see BKRED), not as a scripted
#          dose change, so the rebound is generated by the model rather than
#          assumed by the modeller.
#
#  THE TWO THRESHOLDS THAT GENERATE THE PHENOTYPES
#  -----------------------------------------------
#  (a) T-cell ignition.  Alloreactive blast proliferation is autocatalytic
#      through IL-2 (PROLT below).  Its rate constant must exceed the blast
#      loss rate (KDIFF + KDTACT) for a lesion to ignite.  Under tacrolimus the
#      calcineurin term keeps it unconditionally sub-critical - which is why a
#      CYP3A5 expresser at a trough of 4 ng/mL gets a bigger lesion but not a
#      florid one.  Under belatacept there is NO calcineurin term, so the
#      system is only CONDITIONALLY stable: a recipient with a large CD28-null
#      CD57+ memory pool (FCD28N high) tips over it and rejects, while the
#      same regimen in a memory-poor recipient does not.  That is the model's
#      mechanistic account of the BENEFIT paradox (more early acute rejection,
#      better long-term GFR).
#
#  (b) Germinal-centre ignition.  GC B-cell proliferation requires ongoing Tfh
#      help (BHELP), scales with the eplet-mismatch load (BEPI), and is
#      suppressed by mycophenolate.  Standard therapy sits below the threshold
#      (DSA stays < 300 MFI for 5 years); halving exposure through
#      non-adherence pushes it above, and because long-lived plasma cells then
#      accumulate irreversibly, the resulting DSA does not come back down when
#      adherence is restored.  This is the model's account of why late graft
#      loss is dominated by dnDSA + non-adherence.
#
#  WHY THERE ARE (ALMOST) NO DOSING EVENTS
#  ---------------------------------------
#  This is a 5-year disease-progression model, not a first-dose PK study, so
#  chronic oral drugs enter as continuous input rates and the model carries the
#  AVERAGE concentration.  Reported troughs are recovered with published
#  Cavg->C0 ratios (RTROUGH = 0.75 for tacrolimus, since AUC0-12/C0 ~ 16 h;
#  RTRCSA = 0.45; RTRMPA = 0.40; RTREVR = 0.50).  Episodic IV agents (ATG,
#  basiliximab, belatacept, rituximab, anti-IL-6, anti-CD38, IVIG, steroid
#  pulses, plasma exchange, imlifidase) enter through smooth rectangular
#  windows so their real peak-to-trough behaviour is preserved.  Every scenario
#  is therefore a pure parameter set: reproducible, and diff-able.
#
#  THERAPEUTIC DRUG MONITORING IS A CONTROLLER, NOT A DOSE TABLE
#  -------------------------------------------------------------
#  DOSEADJ is a state: an integral controller that moves the tacrolimus dose
#  towards the protocol trough target (9 ng/mL to month 3, 7 to month 12, 6
#  thereafter).  Two consequences fall out of that and are worth stating:
#    - a CYP3A5 expresser on fixed mg/kg dosing (TDM = 0) sits at C0 ~ 4 ng/mL,
#      while the same patient under TDM is dose-corrected back to target;
#    - a NON-ADHERENT patient is NOT dose-corrected, because the trough the
#      clinic measures is drawn after a dose the patient did take ("white-coat
#      adherence").  The controller therefore sees a normal trough while true
#      exposure is halved - modelled as C0MEAS = C0 / ADH.  This is the single
#      most important reason non-adherence is invisible until the DSA appears.
#
#  WHAT IS DELIBERATELY *NOT* CLAIMED
#  ----------------------------------
#  This is a deterministic single-patient model.  It does not produce incidence
#  rates; a scenario either crosses a lesion threshold or it does not.  Trial
#  percentages (BPAR ~10-12%, dnDSA ~15-25% at 5 y) are population statements
#  and are used here only as sanity anchors for the phenotypes, never as
#  fitted targets.  Parameters are literature-anchored where a number exists
#  (all PK, CYP3A5 1.9x, trough targets, MPA AUC window, BK 10^4 threshold,
#  eGFR levels and slopes) and hand-calibrated otherwise.  Not for clinical use.
#
#  Requires: mrgsolve, dplyr, tidyr, ggplot2
#  Run:      Rscript ktx_mrgsolve_model.R
# =============================================================================

