double tt = SOLVERTIME;

// ---------------------------------------------------------------- exposures
double TACAVG = TAC_C / V2TAC * 1000.0;            // ng/mL, average
double TACC0  = RTROUGH * TACAVG;                  // ng/mL, trough
double CSAAVG = CSA_C / V2CSA * 1000.0;
double CSAC0  = RTRCSA * CSAAVG;
double CMPA   = MPA_C / VMPA;                      // mg/L, average
double CPRED  = (PRED_C / VPRED + MP_C / VMP) * 1000.0;   // ng/mL prednisolone-eq
double CEVR   = EVR_C / VEVR * 1000.0;             // ng/mL
double CATG   = ATG_C / VATG;                      // ug/mL
double CBAS   = BAS_C / VBAS;
double CBELA  = BELA_C / VBELA;
double CRTX   = RTX_C / VRTX;
double CTCZ   = TCZ_C / VTCZ;
double CFZB   = FZB_C / VFZB;
double CIVIG  = IVIG_C / VIVIG;                    // g/L
double CGCV   = GCV_C / VGCV;                      // mg/L

// potency-normalised CNI exposure.  Two different equivalences on purpose:
// cyclosporine is relatively MORE vasoconstrictive than it is immunosuppressive,
// which is the mechanistic reason its GFR sits below tacrolimus at equal
// rejection control.
double TACEQ  = TACC0 + CSAC0 / 25.0;
double TACEQV = TACC0 + CSAC0 / 15.0;

// ------------------------------------------------------------- drug effects
double CNINH   = EMAXCNI * pow(TACEQ, HCNI) / (pow(IC50CNI, HCNI) + pow(TACEQ, HCNI) + 1e-12);
double MPAINH  = EMAXMPA * CMPA / (IC50MPA + CMPA);
double STINH   = EMAXST * CPRED / (IC50ST + CPRED);
double COSBLK  = EMAXBELA * CBELA / (IC50BELA + CBELA);
double COSBLKN = COSBLK;                            // naive T: fully blockable
double COSBLKM = COSBLK * (1.0 - FCD28N);           // CD28-null CD57+ Tem escape
double IL2RBLK = EMAXBAS * CBAS / (IC50BAS + CBAS);
double MTORINH = EMAXMTOR * CEVR / (IC50MTOR + CEVR);
double ATGKILL = KMAXATG * CATG / (C50ATG + CATG);
double RTXKILL = KMAXRTX * CRTX / (C50RTX + CRTX);
double CD38KIL = KMAXCD38 * CFZB / (C50CD38 + CFZB);
double IL6BLK  = EMAXIL6 * CTCZ / (IC50IL6 + CTCZ);
double ECUBLK  = EMAXECU * ECUON;
double GCVE    = EMAXGCV * CGCV / (IC50GCV + CGCV);

double LYMPH   = TN + TMEM + TEFF;
double ATGDEPL = pos(1.0 - LYMPH / LYMPH0);

// ------------------------------------- NET IMMUNOSUPPRESSION (the set point)
double NIS = WCNI * CNINH + WMPA * MPAINH + WST * STINH + WCOS * COSBLK
           + WIL2 * IL2RBLK + WDEPL * ATGDEPL + WMTOR * MTORINH;
if(NIS > 0.97) NIS = 0.97;

// ------------------------- LOOP 3: BK screening as a closed-loop controller
// plasma PCR crosses 10^4 copies/mL -> mycophenolate is cut ~60% and the
// tacrolimus target ~30%.  Nothing about this is scheduled.
double BKRED = BKSCREEN / (1.0 + exp(-(log10(BKV + 1.0) - 4.0) / 0.15));

// --------------------------------------------------------------- drug input
double TACTGT = (tt < 90.0 ? TACTGT1 : (tt < 365.0 ? TACTGT2 : TACTGT3)) * (1.0 - 0.30 * BKRED);
double TACIN  = TACON * TACMGKG * WT * 2.0 * ADH * DOSEADJ;
double CSAIN  = CSAON * CSAMGKG * WT * ADH * DOSEADJ;
double MMFIN  = MMFON * MMFDOSE * ADH * (1.0 - 0.60 * BKRED);
double PREDD  = (tt < 7.0 ? 20.0 : (tt < 30.0 ? 10.0 : 5.0)) * (tt < PREDSTOP ? 1.0 : 0.0);
double PREDIN = PREDON * PREDD * FPRED * ADH;
double MPIN   = MPON * MPDOSE * win(tt, MPSTART, MPDAYS);
double EVRIN  = EVRON * EVRDOSE * ADH;
double ATGIN  = ATGON  * ATGMGKG * WT * win(tt, 0.0, ATGDAYS)
              + ATG2ON * ATGMGKG * WT * win(tt, ATG2START, ATGDAYS);
double BASIN  = BASON * 20.0 * (win(tt, 0.0, 1.0) + win(tt, 4.0, 1.0));

double belasum = 0.0;
for(int k = 0; k < 70; k++) belasum += win(tt, 112.0 + 28.0 * k, 1.0);
double BELAIN = BELAON * WT * (10.0 * (win(tt, 0.0, 1.0) + win(tt, 4.0, 1.0) + win(tt, 14.0, 1.0)
              + win(tt, 28.0, 1.0) + win(tt, 56.0, 1.0) + win(tt, 84.0, 1.0)) + 5.0 * belasum);

double RTXIN = RTXON * 700.0 * win(tt, RTXDAY, 1.0);

double tczsum = 0.0;
for(int k = 0; k < (int)TCZN; k++) tczsum += win(tt, TCZSTART + 28.0 * k, 1.0);
double TCZIN = TCZON * 8.0 * WT * tczsum;

double fzbsum = 0.0;
for(int k = 0; k < 5; k++) fzbsum += win(tt, FZBSTART + 14.0 * k, 1.0);
for(int k = 0; k < 4; k++) fzbsum += win(tt, FZBSTART + 70.0 + 28.0 * k, 1.0);
double FZBIN = FZBON * 16.0 * WT * fzbsum;

double IVIGIN = IVIGON * 2000.0 * WT * win(tt, IVIGSTART, 1.0);
double GCVIN  = VGCON * VGCDOSE * FGCV * (tt < VGCSTOP ? 1.0 : 0.0);

double plexsum = 0.0;
for(int k = 0; k < (int)PLEXN; k++) plexsum += win(tt, PLEXSTART + 2.0 * k, 0.2);
double PLEXK = KPLEX * PLEXON * plexsum;
double IDESK = KIDES * IDESON * win(tt, IDESDAY, 1.0);

// ---------------------------------------------------------------------- PK
double CLT = CLTAC * (CYP3A5 > 0.5 ? 1.9 : 1.0) * (1.0 + IPVAMP * sin(2.0 * M_PI * tt / PIPV));

dxdt_TAC_A1 = TACIN - KA_TAC * TAC_A1;
dxdt_TAC_A2 = KA_TAC * TAC_A1 - KA_TAC * TAC_A2;
dxdt_TAC_C  = FTAC * KA_TAC * TAC_A2 - CLT / V2TAC * TAC_C
            - QTAC * (TAC_C / V2TAC - TAC_P / V3TAC);
dxdt_TAC_P  = QTAC * (TAC_C / V2TAC - TAC_P / V3TAC);
dxdt_CSA_C  = 0.30 * CSAIN - CLCSA / V2CSA * CSA_C - QCSA * (CSA_C / V2CSA - CSA_P / V3CSA);
dxdt_CSA_P  = QCSA * (CSA_C / V2CSA - CSA_P / V3CSA);

// mycophenolate with explicit enterohepatic recirculation (~30-40% of AUC)
dxdt_MMF_D = MMFIN + KBIL * FEHC * MPAG - KA_MPA * MMF_D;
dxdt_MPA_C = FMPA * KA_MPA * MMF_D - CLMPA / VMPA * MPA_C - QMPA * (MPA_C / VMPA - MPA_P / V3MPA);
dxdt_MPA_P = QMPA * (MPA_C / VMPA - MPA_P / V3MPA);
dxdt_MPAG  = CLMPA / VMPA * MPA_C - (KBIL + KREN) * MPAG;

dxdt_PRED_C = PREDIN - CLPRED / VPRED * PRED_C;
dxdt_MP_C   = MPIN   - CLMP / VMP * MP_C;
dxdt_EVR_C  = 0.20 * EVRIN - CLEVR / VEVR * EVR_C;
dxdt_ATG_C  = ATGIN  - CLATG / VATG * ATG_C;
dxdt_BAS_C  = BASIN  - CLBAS / VBAS * BAS_C;
dxdt_BELA_C = BELAIN - CLBELA / VBELA * BELA_C;
dxdt_RTX_C  = RTXIN  - CLRTX / VRTX * RTX_C;
dxdt_TCZ_C  = TCZIN  - CLTCZ / VTCZ * TCZ_C;
dxdt_FZB_C  = FZBIN  - CLFZB / VFZB * FZB_C;
dxdt_IVIG_C = IVIGIN / 1000.0 - CLIVIG / VIVIG * IVIG_C;

// ------------------------------------------------ graft haemodynamics / GFR
double NMs    = NM > 1e-3 ? NM : 1e-3;
double HYPER  = 1.0 / (NM > 0.15 ? NM : 0.15) - 1.0;
if(HYPER > HYPMAX) HYPER = HYPMAX;
if(HYPER < 0.0)    HYPER = 0.0;
double VASO   = FVASO * TACEQV / (TACEQV + KVASO);
double AKIF   = AKI / (AKI + 0.35);
double GFRMAX = GFRK - GFRSL * KDPI;
double EGFR   = GFRMAX * pow(NMs, EXPNM) * (1.0 - VASO) * (1.0 - FAKI * AKIF);

dxdt_GCV_C = GCVIN - CLGCV * (EGFR / 70.0) / VGCV * GCV_C;

// ------------------------------------ TDM: an integral controller, bounded
// C0MEAS is what the CLINIC sees.  In a non-adherent patient the sample is
// drawn after a dose that was actually taken, so the measured trough looks
// normal while true exposure is ADH-fold lower -> no dose correction happens.
double ADHm   = ADH > 0.25 ? ADH : 0.25;
double C0MEAS = TACC0 / ADHm;
double TDMERR = TACON > 0.5 ? (TACTGT - C0MEAS) / TACTGT
                            : (200.0 - CSAC0 / ADHm) / 200.0;
double TDMBRK = TDMERR > 0.0 ? (1.0 - DOSEADJ / DOSEMAX) : (DOSEADJ / DOSEMAX);
dxdt_DOSEADJ  = TDM * KTDM * DOSEADJ * TDMERR * pos(TDMBRK) / (1.0 + exp(-(tt - 3.0)));

// ----------------------------------------------------- LOOP 1: alloimmunity
double AGLOAD = 0.30 + 0.70 * HLAMM / 6.0;
double BEPI   = 0.30 + 0.70 * EPLET / 20.0;
dxdt_AG = KAGIN * AGLOAD * (1.0 + FPASS * exp(-KPASS * tt)) * (1.0 + GDAMP * DAMP)
        - KAGOUT * AG;
double S1 = AG / (AG50 + AG);

double ACT   = KACT  * TN   * S1 * (1.0 - COSBLKN) * (1.0 - 0.5 * STINH);
double ACTM  = KACTM * TMEM * S1 * (1.0 - COSBLKM) * (1.0 - 0.4 * STINH);
double IL2DR = IL2 / (KIL2 + IL2);
// autocatalytic (IL-2-driven) clonal expansion: the ignition term
double PROLT = KPROL * TACT * S1 * IL2DR * pos(1.0 - TACT / TACTMAX)
             * (1.0 - CNINH) * (1.0 - MPAINH) * (1.0 - IL2RBLK) * (1.0 - MTORINH);

dxdt_TN   = KTNPROD - ACT - KDTN * TN - ATGKILL * TN;
dxdt_TACT = ACT + ACTM + PROLT - KDIFF * TACT - KDTACT * TACT - ATGKILL * TACT;
dxdt_TEFF = KDIFF * TACT * FEFF - KMIG * TEFF - KDTEFF * TEFF - ATGKILL * TEFF;
dxdt_TMEM = KDIFF * TACT * (1.0 - FEFF) * pos(1.0 - TMEM / TMEMMAX)
          + KHOMEO * TMEM * pos(1.0 - LYMPH / LYMPH0)          // post-depletion skew
          - KDTMEM * TMEM - ATGKILL * FMEMRES * TMEM;
dxdt_TREG = KTREGP + KTREGI * TACT * (1.0 - 0.7 * CNINH) * (1.0 + 0.8 * MTORINH)
          - KDTREG * TREG - 0.6 * ATGKILL * TREG;
double SUP = TREG / (TREG + TEFF + 0.05);
dxdt_TINF = KMIG * TEFF * (1.0 + 2.0 * ENDO / (1.0 + ENDO))
          - KDINF * TINF * (1.0 + 2.0 * SUP) - ATGKILL * TINF
          - KAPOP * pow(STINH, 3.0) * TINF;   // apoptosis is a HIGH-dose steroid effect
dxdt_IL2  = KIL2P * TACT * (1.0 - CNINH) * (1.0 - 0.6 * STINH) - KDIL2 * IL2;
dxdt_IFNG = KIFN * (TINF + 0.3 * NKACT) * (1.0 - 0.6 * STINH) - KDIFN * IFNG;

// --------------------------------------------------- B cells -> DSA -> ABMR
double TFH   = TACT;
double BHELP = TFH * (1.0 - 0.6 * IL6BLK) * (1.0 - 0.85 * COSBLKN);
double BACT  = KBACT * BN * S1 * BEPI * (0.02 + BHELP);
dxdt_BN  = KBPROD - BACT - KDB * BN - RTXKILL * BN;
// GC proliferation is the second ignition term: needs help, scales with eplet
// load, and is what mycophenolate actually prevents
dxdt_BGC = BACT + KPROLB * BGC * pos(1.0 - BGC / BGCMAX) * BHELP / (KBH + BHELP)
         * sqrt(BEPI / BEPIREF) * (1.0 - MPAINH) * (1.0 - MTORINH) * (1.0 - 0.5 * IL6BLK)
         - KDIFFB * BGC - KDBGC * BGC - RTXKILL * BGC;
dxdt_PB   = KDIFFB * BGC * FPB - KDPB * PB - CD38KIL * PB - KLL * PB;
// long-lived plasma cells are CD20-NEGATIVE: rituximab has no term here.
dxdt_LLPC = KLL * PB - KDLLPC * LLPC - 0.6 * CD38KIL * LLPC;
dxdt_DSA  = KIGG * (PB * WPB + LLPC * WLL) - KDDSA * DSA
          - PLEXK * DSA - IDESK * DSA - KIVIGN * CIVIG * DSA;

double DSAB = DSA / (DSA + KB50);                  // saturable binding to the graft
double MAC  = KMAC * DSAB * (1.0 - ECUBLK);        // eculizumab blocks MAC, not C4d
dxdt_C4D   = KC4D * DSAB * (1.0 - C4D) - KDC4D * C4D;
dxdt_NKACT = KNK * (DSAB * 1.5 + MISSSELF * DSAB * 0.8 + 0.05 * MISSSELF) * (1.0 - NKACT)
           - KDNK * NKACT - 0.8 * CD38KIL * NKACT;
dxdt_ENDO  = KENDO * (MAC + 0.7 * NKACT + 0.25 * IFNG + 0.3 * DAMP) * (1.0 - ENDO)
           - KDENDO * ENDO;
dxdt_MVI   = KMVI * (NKACT + MAC + 0.4 * TINF) * (1.0 - MVI) - KDMVI * MVI * (1.0 + 0.5 * STINH);
dxdt_TG    = KTG * MVI * MVI / (MVI * MVI + KTG50 * KTG50) * (1.0 - 0.4 * MTORINH)
           * (1.0 - TG) - KDTG * TG;

// ------------------------------------------------------------ graft lesions
dxdt_TUB  = (KTUB * TINF * (1.0 - 0.7 * SUP) + KBKTUB * BKVAN) * (1.0 - TUB)
          - KTUBREP * TUB * (1.0 + 0.8 * STINH);
dxdt_AKI  = -KREC * AKI * (1.0 - 0.35 * MTORINH);          // mTORi impairs repair
dxdt_DAMP = KDAMP * (AKI + 0.5 * TUB + 0.4 * MVI) - KDDAMP * DAMP;

// LOOP 2: the drug-independent chronic loop
double TGFB = TGFB0 + 0.20 * TUB + 0.30 * MVI + 0.50 * AKI + 0.10 * CNIHYAL
            + KHYPER * HYPER + 0.20 * PROT;
dxdt_IFTA    = KFIB * TGFB * (1.0 - IFTA) - KDFIB * IFTA;
dxdt_CNIHYAL = KHYALIN * TACEQ / (TACEQ + 8.0) * (1.0 - CNIHYAL) - KDHYAL * CNIHYAL;

// nephron destruction: cubic kernels, so trace inflammation is survivable and
// a full-blown lesion is not
double LOSST = KNTCMR * pow(TUB, 3.0) / (pow(TUB, 3.0) + pow(KTUB50, 3.0));
double LOSSM = KNMVI  * pow(MVI, 3.0) / (pow(MVI, 3.0) + pow(KMVI50, 3.0));
dxdt_NM = -(LOSST + LOSSM + KNTG * TG + KNIFTA * IFTA + KNBK * BKVAN + KNHYAL * CNIHYAL) * NM;

dxdt_SCR   = (GCR - EGFR * 1.44 * SCR) / VCR;
dxdt_PROT  = KPROT * (PROTB + 0.6 * TG + 0.3 * MVI + 0.25 * IFTA + 0.4 * MTORINH)
           - KDPROT * PROT;
dxdt_CFDNA = KCF * (CFB + 0.8 * TUB + 2.2 * MVI + 1.2 * TG + 1.5 * AKI + 0.4 * BKVAN)
           - KDCF * CFDNA;

// ---------------------------------------- the other arm of the U: infection
dxdt_BKV   = BKV * (RBK * (0.25 + 0.75 * NIS) * (1.0 - BKV / BKMAX) - CBK * (1.0 - NIS))
           + BKSEED * BKSUSC;
dxdt_BKVAN = KBKN * pos(log10(BKV + 1.0) - 4.0) / 3.0 * (1.0 - BKVAN) - KDBKN * BKVAN;
double CMVIMM = 1.0 - CMVDR;
dxdt_CMV = CMV * (RCMV * (0.20 + 0.80 * NIS) * (1.0 - CMV / CMVMAX)
         - CCMV * (1.0 - NIS) * (1.0 + 2.0 * CMVIMM) - GCVE) + CMVSEED * CMVSUSC;

double GCVMY = CGCV / (CGCV + 2.0);
dxdt_WBC = KWBCP * (1.0 - 0.55 * MPAINH - 0.45 * GCVMY) - KDWBC * WBC - 0.25 * ATGKILL * WBC;
double TACF = TACEQ / (TACEQ + 10.0);
dxdt_GLU = KGLU * (5.2 + 2.2 * STINH + 1.2 * TACF) - KDGLU * GLU;
dxdt_NISAUC = NIS;

// ------------------------------------------------------------- behaviour
double ADHTGT = (tt >= ADHSTART && tt < ADHEND) ? ADHFINAL : 1.0;
dxdt_ADH = KADHR * (ADHTGT - ADH);

// ----------------------------------------------- outcome (iBox-style hazard)
double BG   = 3.0 * MVI * MVI / (MVI * MVI + 0.0900);
double BPTC = 3.0 * MVI * MVI / (MVI * MVI + 0.0625);
double BCG  = 3.0 * TG * TG / (TG * TG + 0.1225);
double BCI  = 3.0 * IFTA * IFTA / (IFTA * IFTA + 0.0900);
double HR = exp(B1 * (60.0 - EGFR) / 10.0 + B2 * log(1.0 + PROT) + B3 * (BG + BPTC)
          + B4 * BCG + B5 * 2.0 * BCI + B6 * log10(1.0 + DSA / 1000.0));
dxdt_HAZ = H0 * HR;
dxdt_CUMREJ = 1.0 / (1.0 + exp(-(TUB - 0.5) / 0.1)) + 1.0 / (1.0 + exp(-(MVI - 0.5) / 0.1));

