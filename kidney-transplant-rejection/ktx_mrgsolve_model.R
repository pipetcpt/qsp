run_scen <- function(nm, pars) {
  m <- if (length(pars)) param(mod, pars) else mod
  out <- m %>%
    mrgsim(end = TEND, delta = 1, hmax = 3, atol = 1e-8, rtol = 1e-5) %>%
    as_tibble()
  out$scenario <- nm
  out
}

