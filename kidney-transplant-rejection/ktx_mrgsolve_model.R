#define WINK 40.0

// smooth, differentiable rectangular window: 1 between start and start+dur
double win(double tt, double start, double dur) {
  double a = -WINK * (tt - start);
  double b =  WINK * (tt - start - dur);
  if(a >  50.0) a =  50.0;
  if(a < -50.0) a = -50.0;
  if(b >  50.0) b =  50.0;
  if(b < -50.0) b = -50.0;
  return 1.0 / (1.0 + exp(a)) / (1.0 + exp(b));
}

double pos(double x) { return x > 0.0 ? x : 0.0; }

