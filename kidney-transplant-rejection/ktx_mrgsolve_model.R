// Banff-style semi-quantitative scores (0-3), squared-Hill mappings
double BANFF_T   = 3.0 * TUB * TUB / (TUB * TUB + 0.1225);
double BANFF_I   = 3.0 * TUB * TUB / (TUB * TUB + 0.1000);
double BANFF_G   = 3.0 * MVI * MVI / (MVI * MVI + 0.0900);
double BANFF_PTC = 3.0 * MVI * MVI / (MVI * MVI + 0.0625);
double BANFF_CG  = 3.0 * TG * TG / (TG * TG + 0.1225);
double BANFF_CI  = 3.0 * IFTA * IFTA / (IFTA * IFTA + 0.0900);
double BANFF_AH  = 3.0 * CNIHYAL * CNIHYAL / (CNIHYAL * CNIHYAL + 0.0900);
double BANFF_C4D = 3.0 * C4D;
double MVISUM    = BANFF_G + BANFF_PTC;              // g+ptc, the ABMR criterion

