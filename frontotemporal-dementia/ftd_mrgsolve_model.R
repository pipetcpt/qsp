if (FALSE) {
  ## Predicted onset ages (compare GENFI/ALLFTD: MAPT ~50, C9 ~57, GRN ~61)
  for (g in c("MAPT", "C9", "GRN", "sporadic")) {
    bi <- FTD_burnin(FTD_genotype(g))
    cat(sprintf("%-9s predicted onset age %.1f y\n", g, bi$onset_age))
  }

  res <- FTD_simulate_scenarios()

  ## The biomarker / target dissociation
  res |>
    filter(scenario %in% c("06 GRN untreated reference (from onset)",
                           "07 GRN + latozinemab 60 mg/kg q4w",
                           "08 GRN + AAV-GRN gene therapy (single dose)"),
           time == max(time)) |>
    select(scenario, PGRNPL_PCT, PGRNCSF_PCT, PGRNLYS_PCT, CDR, NFLPL, BMPCSF)

  ## The sign flip, and the invariance of the plasma biomarker
  FTD_sweep_p()
}
