##  Disease  : Frontotemporal lobar degeneration — the leading cause of dementia
##             under age 60 alongside early-onset Alzheimer's. Three Mendelian
##             genes account for most familial disease and converge on TWO
##             distinct proteinopathies:
##               GRN     (progranulin haploinsufficiency) -> FTLD-TDP type A
##               C9orf72 (GGGGCC repeat expansion)        -> FTLD-TDP type B +ALS
##               MAPT    (tau mutations)                  -> FTLD-tau, NO TDP-43
##             All three funnel into lysosomal / proteostatic failure, microglial
##             activation with COMPLEMENT-MEDIATED synapse elimination, and
##             degeneration of one specific large-scale network: salience network
##             / von Economo neurons -> bvFTD; anterior temporal -> svPPA;
##             left inferior frontal -> nfvPPA.
##
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>= 1.5)
##  Time     : DAYS.
##
##  Scope    : 49 ODE compartments —
##             PK  (15): latozinemab 2-cmt with quasi-equilibrium TMDD on
##                       sortilin + CSF compartment; AAV-GRN vector -> transduced
##                       transgene pool; C9orf72 ASO (IT, CSF->tissue depot);
##                       MAPT ASO (IT, CSF->tissue depot); SSRI, trazodone and
##                       donepezil (oral).
##             PD  (34): THREE-compartment progranulin system (PLASMA / CSF /
##                       LYSOSOMAL), lysosomal function, lipofuscin, TDP-43
##                       (nuclear vs aggregate) with STMN2 / UNC13A cryptic
##                       splicing, C9 repeat RNA + poly-GP + poly-GR, MAPT mRNA
##                       -> soluble -> phospho -> aggregated tau, microglia ->
##                       C1q -> C3 -> synaptic pruning, astrocytes, synaptic
##                       density, two regional neuron pools, two regional
##                       volumes, CSF & plasma NfL, plasma GFAP, CSF BMP,
##                       serotonergic / cholinergic / dopaminergic tone,
##                       CDR plus NACC-FTLD SB, NPI, cumulative mortality hazard.
##
##  ==========================================================================
##  THE STRUCTURAL POINT THIS MODEL IS BUILT TO EXPOSE
##  ==========================================================================
##  Anti-sortilin therapy (latozinemab / AL001) reliably NORMALIZES plasma and
##  roughly DOUBLES CSF progranulin in GRN carriers — textbook target engagement
##  — and yet the phase 3 clinical endpoint did not move. In this model that
##  outcome is a PREDICTION of the structure, not a fudge.
##
##  Sortilin is BOTH (a) the dominant clearance route that sets extracellular
##  PGRN concentration and (b) one of the delivery routes filling the LYSOSOMAL
##  PGRN pool where progranulin actually does its job. Blocking it raises the
##  ligand and removes a delivery route AT THE SAME TIME. At steady state:
##
##      f     = sortilin share of CSF PGRN CLEARANCE
##      p     = sortilin share of LYSOSOMAL PGRN DELIVERY   (P_LYS_SORT)
##      theta = fractional sortilin occupancy by drug
##
##      CSF PGRN fold-rise       = 1 / (1 - f*theta)
##      LYSOSOMAL delivery ratio = (1 - p*theta) / (1 - f*theta)
##
##  Consequences, all dose-independent in sign:
##    * the sign of benefit depends ONLY on sign(f - p) — a property of the
##      BIOLOGY, not of the drug or the dose;
##    * if p = f the lysosomal pool is UNCHANGED at every occupancy: full
##      biomarker normalisation with mathematically zero delivery benefit;
##    * if p > f the drug LOWERS lysosomal PGRN while RAISING the biomarker;
##    * the ceiling as theta -> 1 is (1-p)/(1-f). You cannot dose past it,
##      because raising occupancy raises the ligand and removes delivery
##      capacity in lockstep;
##    * plasma PGRN rises for ANY value of p — so the registrational biomarker
##      is STRUCTURALLY INCAPABLE of measuring the parameter that decides
##      whether the drug works.
##
##  AAV-GRN gene therapy is NOT subject to this: it raises PRODUCTION, so
##  lysosomal delivery scales with transgene output and the receptor penalty
##  never appears. The model therefore predicts a qualitative separation
##  between two therapies with overlapping plasma-PGRN signatures — and in the
##  verified run the antibody reaches 49% of wild-type lysosomal PGRN from a
##  95%-of-control plasma level, while gene therapy reaches 80% from a LOWER
##  80% plasma level. A plasma-PGRN biomarker ranks them BACKWARDS.
##
##  P_LYS_SORT is NOT measured in humans. It is the single most consequential
##  number in this file and it is an assumption, exposed as a top-level
##  parameter precisely so it can be swept (see FTD_sweep_p()).
##  ==========================================================================
##
##  Numerically verified in ftd_reference_model.py (independent dependency-free
##  RK4 implementation of the same 49 states) — see ftd_model_report.txt for the
##  computed output, including the residual between the closed form above and
##  the integrated solution. Verified headline values:
##    * predicted onset ages MAPT 50.5 / C9orf72 54.3 / sporadic 59.2 y
##      (observed cohort means 50 / 57 / 58) and GRN 55.8 vs 61 observed — a
##      structural miss the report explains rather than hides;
##    * CSF/plasma antibody ratio 0.21%; peripheral occupancy 1.000, CNS 0.658;
##    * plasma PGRN 35% -> 95% of control, CSF 35% -> 73%, LYSOSOMAL 35% -> 49%;
##    * predicted 96-week CDR+NACC-FTLD SB slowing 0.65% — a predicted phase 3
##      miss coexisting with unambiguous target engagement;
##    * the benefit sign flips exactly at p = f_CSF = 0.780, at ANY dose;
##    * trazodone dNPI -5.8; donepezil dNPI +3.2 with dCDR EXACTLY 0.000;
##    * C9 ASO lowers CSF poly-GP 50% and moves CDR by -0.035;
##    * MAPT ASO lowers soluble tau 46% but AGGREGATED tau only 17%.
##
##  Calibration anchors (full citations in ftd_references.md):
##    * Plasma PGRN ~200 ng/mL in controls, ~1/3 of control in GRN carriers
##      (diagnostic cut-off commonly quoted near 110 ng/mL); CSF PGRN ~3 ng/mL
##      in controls, ~50% reduced in carriers. NOTE the asymmetry — plasma falls
##      to ~33% but CSF only to ~50%; the model reproduces both with DIFFERENT
##      compartment clearance structures rather than one gene-dose scalar.
##    * Latozinemab 60 mg/kg IV q4w: plasma PGRN restored to control range, CSF
##      PGRN ~2x, CSF C1QA and C3 reduced (INFRONT-1/2). INFRONT-3 did not meet
##      its primary CDR plus NACC-FTLD SB endpoint.
##    * Plasma NfL ~10 pg/mL in controls, ~50-80 pg/mL symptomatic; CSF NfL
##      ~700 vs 3000-5000; strongest single prognostic marker in FTD.
##    * CDR plus NACC-FTLD SB (0-24) progresses ~1.5-2.5 points/year when
##      symptomatic; brain atrophy 2-3 %/y vs ~0.5 %/y in controls.
##    * Genetic onset ages (GENFI / ALLFTD): MAPT ~50, C9orf72 ~57, GRN ~61 y.
##    * C9orf72 ASO (WVE-004, FOCUS-C9): CSF poly-GP lowered up to ~50%; NO
##      clinical benefit; programme discontinued. Modelled as such.
##    * MAPT ASO (BIIB080 class): CSF tau lowered ~30-50%.
##    * Trazodone (Lebert 2004 crossover RCT): NPI improved ~6-10 points.
##    * Memantine (Boxer 2013) negative; donepezil documented to WORSEN
##      behavioural disinhibition in bvFTD (Mendez 2007).
##    * The cholinergic system is largely PRESERVED in FTD, encoded here as
##      ACH_INTEGRITY = 0.95 so the AChEI null result emerges from STRUCTURE:
##      donepezil raises cholinergic tone and the cognitive endpoint does not
##      depend on it, so dCDR is exactly zero while behaviour gets worse.
##
##  KNOWN STRUCTURAL LIMITATION (stated, not hidden): the model has no
##  compensated latent phase — damage accumulates monotonically from t=0. That
##  single defect causes both the ~5-year GRN onset error and a presymptomatic
##  NfL lead time of ~15 y where ~1-2 y is reported. Fixing it requires a
##  different structure (a compensated regime that collapses at a threshold),
##  not a different parameter. See section J of ftd_model_report.txt.
##
