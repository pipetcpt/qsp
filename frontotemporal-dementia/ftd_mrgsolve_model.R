ev_latozinemab <- function(mgkg = 60, bwt = 70, n = 24, start = 0) {
  ev(time = start, amt = mgkg * bwt, cmt = "CLATO", ii = 28, addl = n - 1)
}
# AAV-GRN: single administration into the vector compartment
ev_aav_grn <- function(dose = 1.0, start = 0) {
  ev(time = start, amt = dose, cmt = "AAVVG")
}
# C9orf72 ASO intrathecal q12w
ev_aso_c9 <- function(dose = 100, n = 8, start = 0) {
  ev(time = start, amt = dose, cmt = "ASO9CSF", ii = 84, addl = n - 1)
}
# MAPT ASO intrathecal q12w
ev_aso_mapt <- function(dose = 100, n = 8, start = 0) {
  ev(time = start, amt = dose, cmt = "ASOTCSF", ii = 84, addl = n - 1)
}
# SSRI (citalopram 30 mg) PO daily
ev_ssri <- function(dose = 30, n = 672, start = 0) {
  ev(time = start, amt = dose, cmt = "SSRIG", ii = 1, addl = n - 1)
}
# Trazodone 150 mg PO daily (dosed into the plasma compartment, scaled by V
# so that amt/V is the concentration increment)
ev_trazodone <- function(dose = 150, n = 672, start = 0, V = 90) {
  ev(time = start, amt = dose / V, cmt = "TRZC", ii = 1, addl = n - 1)
}
# Donepezil 10 mg PO daily — the NULL / HARM arm
ev_donepezil <- function(dose = 10, n = 672, start = 0, V = 830) {
  ev(time = start, amt = dose / V, cmt = "DNPC", ii = 1, addl = n - 1)
}

## ---------------------------------------------------------------------------
## 13 PREBUILT SCENARIOS
##   1-5   natural history by genotype / phenotype (onset age is an OUTPUT)
##   6-10  disease-modifying therapy from the model's own onset state
##   11-12 symptomatic pharmacology, including the null/harm arm
##   13    the rival hypothesis: same drug, opposite prediction
## ---------------------------------------------------------------------------
FTD_simulate_scenarios <- function(nat_years = 45, weeks = 96) {

  G <- list(GRN = FTD_genotype("GRN"), C9 = FTD_genotype("C9"),
            MAPT = FTD_genotype("MAPT"), SPO = FTD_genotype("sporadic"))
  svppa <- c(G$SPO, list(PHENO_TEMP = 1, TEMP_SHIFT = 0.40))

  nat <- function(label, pars) {
    FTD_mod |> param(pars) |>
      mrgsim(end = nat_years * 365, delta = 30) |>
      as_tibble() |> mutate(scenario = label)
  }
  tx <- function(label, pars, events = NULL) {
    bi <- FTD_burnin(pars)
    FTD_from_onset(pars, bi, events, weeks = weeks) |>
      mutate(scenario = label, onset_age = bi$onset_age)
  }

  bind_rows(
    ## --- natural history -------------------------------------------------
    nat("01 GRN natural history (onset age predicted)",   G$GRN),
    nat("02 C9orf72 FTD-ALS natural history",             G$C9),
    nat("03 MAPT FTLD-tau natural history",               G$MAPT),
    nat("04 Sporadic bvFTD natural history",              G$SPO),
    nat("05 Sporadic svPPA (temporal-predominant)",       svppa),

    ## --- disease-modifying ------------------------------------------------
    tx("06 GRN untreated reference (from onset)",         G$GRN),
    tx("07 GRN + latozinemab 60 mg/kg q4w",               G$GRN,
       ev_latozinemab(60, 70, n = ceiling(weeks * 7 / 28))),
    tx("08 GRN + AAV-GRN gene therapy (single dose)",     G$GRN,
       ev_aav_grn(1.0)),
    tx("09 C9orf72 + repeat-targeting ASO q12w",          G$C9,
       ev_aso_c9(100, n = 8)),
    tx("10 MAPT + MAPT-lowering ASO q12w",                G$MAPT,
       ev_aso_mapt(100, n = 8)),

    ## --- symptomatic ------------------------------------------------------
    tx("11 GRN + SSRI + trazodone",                       G$GRN,
       c(ev_ssri(30, n = weeks * 7), ev_trazodone(150, n = weeks * 7))),
    tx("12 GRN + donepezil (NULL / HARM arm)",            G$GRN,
       ev_donepezil(10, n = weeks * 7)),

    ## --- rival hypothesis -------------------------------------------------
    tx("13 Latozinemab, extracellular-PGRN hypothesis",
       c(G$GRN, list(W_ACT_LYS = 0.20, W_ACT_EXTRA = 0.80)),
       ev_latozinemab(60, 70, n = ceiling(weeks * 7 / 28)))
  )
}

## ---------------------------------------------------------------------------
## Sensitivity sweep on the pivotal unmeasured parameter P_LYS_SORT
##   Reproduces the sign flip at p = f_CSF = 0.780 and the (1-p)/(1-f) ceiling,
##   and shows that plasma PGRN is INVARIANT across the whole sweep.
## ---------------------------------------------------------------------------
FTD_sweep_p <- function(p_grid = seq(0, 0.95, by = 0.05), weeks = 96) {
  G <- FTD_genotype("GRN")
  lapply(p_grid, function(pv) {
    pars <- c(G, list(P_LYS_SORT = pv))
    bi <- FTD_burnin(pars)
    n <- ceiling(weeks * 7 / 28)
    treated <- FTD_from_onset(pars, bi, ev_latozinemab(60, 70, n = n),
                              weeks = weeks)
    control <- FTD_from_onset(pars, bi, NULL, weeks = weeks)
    tibble(
      P_LYS_SORT   = pv,
      PGRNPL_PCT   = tail(treated$PGRNPL_PCT, 1),
      PGRNLYS_PCT  = tail(treated$PGRNLYS_PCT, 1),
      lyso_ratio   = tail(treated$PGRNLYS, 1) / tail(control$PGRNLYS, 1),
      ceiling      = (1 - pv) / (1 - 0.78),
      dCDR         = tail(treated$CDR, 1) - tail(control$CDR, 1),
      dBMP         = tail(treated$BMPCSF, 1) - tail(control$BMPCSF, 1)
    )
  }) |> bind_rows()
}

