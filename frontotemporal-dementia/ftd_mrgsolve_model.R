## ---------------------------------------------------------------------------
## FTD_burnin() — the disease clock
##
##   Runs the natural history from a clinically silent carrier until the CDR
##   plus NACC-FTLD SB reaches `cdr_target`, and returns that state together
##   with the elapsed time. Trial scenarios START HERE rather than from
##   hand-set "symptomatic baseline" initial conditions, so a treated and an
##   untreated arm share one continuous trajectory and every baseline
##   biomarker value is EARNED by the model instead of assumed.
## ---------------------------------------------------------------------------
FTD_burnin <- function(pars, cdr_target = 5.5, max_years = 80, delta = 1) {
  out <- FTD_mod |>
    param(pars) |>
    mrgsim(end = max_years * 365, delta = delta) |>
    as_tibble()
  hit <- which(out$CDR >= cdr_target)
  if (!length(hit)) {
    stop("burn-in never reached CDR = ", cdr_target,
         " (max CDR ", round(max(out$CDR), 2), ")")
  }
  i <- hit[1]
  states <- mrgsolve::cmt(FTD_mod)
  list(
    time = out$time[i],
    onset_age = pars$AGE0 + out$time[i] / 365,
    init = as.list(out[i, states]),
    trajectory = out[seq_len(i), ]
  )
}

## Run a scenario forward from a burn-in state.
FTD_from_onset <- function(pars, bi, events = NULL, weeks = 96, delta = 7) {
  m <- FTD_mod |> param(pars) |> init(bi$init)
  tend <- weeks * 7
  if (is.null(events)) {
    mrgsim(m, end = tend, delta = delta) |> as_tibble()
  } else {
    mrgsim_e(m, events, end = tend, delta = delta) |> as_tibble()
  }
}

