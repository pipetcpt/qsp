##  Anorexia Nervosa (AN) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Anorexia Nervosa — the psychiatric illness with the highest
##             mortality (SMR ~5.9), in which cognitively driven caloric
##             restriction (fear of weight gain, body-image distortion,
##             habit-entrenched restriction, compulsive exercise) produces a
##             sustained NEGATIVE ENERGY BALANCE. The resulting starvation
##             state triggers a coordinated neuroendocrine adaptation —
##             hypoleptinemia, low-T3 (euthyroid-sick) syndrome, adaptive
##             thermogenesis, hypercortisolemia, hepatic GH resistance with
##             low IGF-1, and suppression of the GnRH pulse generator giving
##             functional hypothalamic amenorrhea — which uncouples bone
##             remodeling (P1NP down / CTX up -> BMD Z-score decline) and
##             drives cardiovascular adaptation (bradycardia, QTc risk).
##             Nutritional rehabilitation reverses these axes but carries its
##             own hazard: the REFEEDING SYNDROME (insulin-driven
##             intracellular shift of phosphate/potassium/magnesium onto an
##             occult total-body deficit, plus thiamine consumption).
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 31 ODE compartments —
##             * Drug/intervention PK (9): olanzapine (gut + systemic),
##               fluoxetine + norfluoxetine, transdermal estradiol (patch
##               depot + systemic), teriparatide, skeletal bisphosphonate,
##               psychotherapy engagement.
##             * Behavior & energetics (6): ED-cognition drive, energy intake,
##               metabolic adaptation-to-intake state (which sets the
##               refeeding insulin surge), fat mass, fat-free mass, adaptive
##               thermogenesis.
##             * Neuroendocrine axes (7): leptin, ghrelin, free T3, cortisol,
##               GnRH pulse index, estradiol, IGF-1.
##             * Skeletal (3): P1NP, CTX, BMD Z-score.
##             * Cardiac (1): heart rate (QTc derived algebraically).
##             * Refeeding safety (5): total-body phosphate depletion index,
##               serum phosphate, potassium, magnesium, thiamine stores.
##  Time     : days. Default horizon 365 d (weight restoration takes months;
##             menses resumption and BMD recovery take 6-18 months).
##  Units    : kcal/day (intake/expenditure), kg (FM/FFM), kg/m^2 (BMI),
##             ng/mL (leptin, IGF-1), pg/mL (T3, estradiol, ghrelin),
##             ug/dL (cortisol), ug/L (P1NP), ng/mL (CTX), Z-score (BMD),
##             bpm (HR), ms (QTc), mg/dL (phosphate, magnesium),
##             mEq/L (potassium), 0-1 index (drive, thiamine, depletion).
##             Drug compartments are dose-proportional "exposure" units (au) —
##             this library's standard surrogate when the disease-relevant PD
##             is what matters rather than literal plasma concentration.
##  Scenarios: 10 prebuilt — see AN_simulate_scenarios() at the bottom.
##  Anchors  : Keys 1950 Minnesota Semi-Starvation Experiment (starvation
##             itself reproduces AN cognition and rigidity -> the
##             starvation-perpetuation term); Forbes 1987 / Hall 2011 Lancet
##             378:826 (FM/FFM partition dFFM/dFM = C/FM); Dulloo 2015
##             Obes Rev 16(S1):25 (adaptive thermogenesis); Grinspoon 1996
##             JCEM 81:3861 and Misra 2004 (hypoleptinemia, GH resistance,
##             low IGF-1); Kopp 1997 Mol Psychiatry 2:335 / Audi 2002 Horm Res
##             58:65 (leptin ~1.85 ng/mL threshold for menses resumption);
##             Misra & Klibanski 2014 Lancet Diabetes Endocrinol 2:581
##             (low-formation/high-resorption skeletal phenotype); Misra 2011
##             J Bone Miner Res 26:2430 (transdermal — not oral — estradiol
##             improves BMD); Fazeli 2014 JCEM 99:1322 (teriparatide in adult
##             AN); Golden 2013 / O'Connor 2016 / Garber 2021 J Adolesc Health
##             68:1 (higher-calorie refeeding is safe with phosphate
##             monitoring and shortens length of stay); Attia 1998 Am J
##             Psychiatry 155:548 and Walsh 2006 JAMA 295:2605 (fluoxetine
##             ineffective in the underweight state -> explicit nutritional
##             GATE); Attia 2019 Am J Psychiatry 176:449 (olanzapine: modest
##             BMI benefit, no psychopathology benefit); Lock 2010 Arch Gen
##             Psychiatry 67:1025 (FBT for adolescents); Arcelus 2011 Arch Gen
##             Psychiatry 68:724 (SMR 5.86).
##  Disclaimer: For research / education / hypothesis generation only. Not a
##             substitute for clinical judgment and NOT a refeeding protocol —
##             refeeding a severely malnourished patient is an inpatient
##             medical procedure with mandatory electrolyte monitoring.
##  ============================================================================
[PROB]
QSP model of Anorexia Nervosa linking eating-disorder cognition, energy intake
and a Forbes-partitioned two-compartment body composition to the starvation
neuroendocrine cascade (leptin, ghrelin, T3, cortisol, GnRH, estradiol,
IGF-1), skeletal remodeling (P1NP/CTX/BMD), cardiac adaptation (bradycardia,
QTc) and refeeding-syndrome safety (phosphate, potassium, magnesium,
thiamine), with PK/PD for olanzapine, fluoxetine (nutritionally gated),
transdermal estradiol, teriparatide, risedronate and psychotherapy.

