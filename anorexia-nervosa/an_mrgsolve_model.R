double surge0  = (EI - EI_ADAPT)/K_SURGE;
if (surge0 < 0) surge0 = 0;
double REE     = ree_raw*(1 - ADAPT)*(1 + K_HYPERMET*surge0);   // refeeding hypermetabolism

// Restriction capacity fails at extreme emaciation (hunger, weakness, care)
double rcap = (pmBMI - RESTRICT_FLOOR)/(RESTRICT_FULL - RESTRICT_FLOOR);
if (rcap < 0) rcap = 0;
if (rcap > 1) rcap = 1;

double sih = 1 + K_SIH*(1 - LEP/LEP_NORM);
if (sih < 1) sih = 1;
double EXER = K_EXER * DRIVE * sih * (inpt>0 ? 0.10 : 1.0) * rcap;

double need  = REE*(1 + PAL0) + EXER;         // requirement excluding TEF
double TEF   = TEF_FRAC*EI;
double TEE   = need + TEF;
double EB    = EI - TEE;                      // kcal/day

// Starvation index: depleted stores (slow) + acute energy-flow deficit (fast)
double store_def = (1 - pmBMI)/STORE_REF;
if (store_def < 0) store_def = 0;
if (store_def > 1) store_def = 1;
double flow_def = 1 - EI/(need/(1 - TEF_FRAC));
if (flow_def < FLOW_MIN) flow_def = FLOW_MIN;
if (flow_def > 1) flow_def = 1;
double fdef = W_STORE*store_def + W_FLOW*flow_def;
if (fdef < 0) fdef = 0;
if (fdef > 1) fdef = 1;

//=========================================================================
// 3. Eating-disorder cognition drive
//=========================================================================
double starve_gain = K_STARVE_DRV*(1 - pmBMI/0.95);
if (starve_gain < 0) starve_gain = 0;

// SSRI efficacy is GATED by nutritional restoration (Attia 1998; Walsh 2006)
double gate    = pow(pmBMI, GATE_HILL)/(pow(GATE_MBMI50, GATE_HILL) + pow(pmBMI, GATE_HILL));
double flx_eff = EMAX_FLX * sert * gate;

double drive_target = SEV*(1 + starve_gain)*(1 - tx_eff)*(1 - olz_cog)*(1 - flx_eff);
if (drive_target < DRIVE_FLOOR) drive_target = DRIVE_FLOOR;
if (drive_target > 1) drive_target = 1;
dxdt_DRIVE = KOUT_DRIVE*(drive_target - DRIVE);

//=========================================================================
// 4. Energy intake behavior
//=========================================================================
// Without a meal plan the patient eats a self-imposed fraction of need;
// a structured (especially supervised) plan can push intake above need.
double maint = need/(1 - TEF_FRAC);
double free_intake = maint*(1 - REL_DEF_MAX*DRIVE*rcap);
double adhere = (inpt>0) ? ADHERE_IN : (1 - ADHERE_OUT*DRIVE);
if (adhere < 0.15) adhere = 0.15;
double plan_intake = plan*adhere;

// A meal plan is written to restore weight and is then tapered to maintenance
// as the goal weight is reached — without this the plan would overshoot.
double taper = (pmBMI - GOAL_LO)/(GOAL_HI - GOAL_LO);
if (taper < 0) taper = 0;
if (taper > 1) taper = 1;
plan_intake = plan_intake*(1 - taper) + maint*taper;

// Gastroparesis/early satiety limits how far intake can be pushed ABOVE what
// the patient would eat on their own; it does not push intake below that.
double gi_pen = GI_SAT_MAX*(1 - pmBMI);
if (gi_pen < 0) gi_pen = 0;
double excess = plan_intake - free_intake;
if (excess < 0) excess = 0;
double purge_act = (PURGE>0) ? DRIVE : 0.0;

double ei_target = (free_intake + excess*(1 - gi_pen))*(1 + olz_app)*(1 - PURGE_LOSS*purge_act);
if (ei_target < 150) ei_target = 150;
dxdt_EI       = KOUT_EI*(ei_target - EI);
dxdt_EI_ADAPT = KOUT_EIA*(EI - EI_ADAPT);

//=========================================================================
// 5. Body composition (Forbes partition, asymmetric tissue energy cost)
//=========================================================================
// Forbes: dFFM/dFM = C/FM (mass ratio), closed with energy conservation
//   EB = rho_FM*dFM + rho_FFM*dFFM  ->  dFM = EB/(rho_FM + rho_FFM*ratio)
double ratio = FORBES_C/FM;
double cort_relx = CORT/CORT_NORM - 1;
if (cort_relx < 0) cort_relx = 0;
if (EB < 0) ratio *= (1 + K_CORT_PART*cort_relx);   // cortisol spares fat, wastes lean
if (ratio < RATIO_MIN) ratio = RATIO_MIN;
if (ratio > RATIO_MAX) ratio = RATIO_MAX;

double rho_fm  = (EB >= 0) ? RHO_FM_GAIN  : RHO_FM_LOSS;
double rho_ffm = (EB >= 0) ? RHO_FFM_GAIN : RHO_FFM_LOSS;
double dFM = EB/(rho_fm + rho_ffm*ratio);
dxdt_FM  = dFM;
dxdt_FFM = ratio*dFM;
if (FM  < 0.4 && dxdt_FM  < 0) dxdt_FM  = 0;    // physiologic floors
if (FFM < 20  && dxdt_FFM < 0) dxdt_FFM = 0;

double adapt_target = ADAPT_MAX*fdef;
dxdt_ADAPT = KOUT_ADAPT*(adapt_target - ADAPT);

//=========================================================================
// 6. Adipose & gut hormones
//=========================================================================
double lep_target = K_LEP_FM*FM*(1 - LEP_ACUTE*fdef);
if (lep_target < 0.1) lep_target = 0.1;
dxdt_LEP = KOUT_LEP*(lep_target - LEP);

double ghrl_target = GHRL_NORM + (GHRL_MAX - GHRL_NORM)*(1 - pmBMI);
if (ghrl_target < 200) ghrl_target = 200;
dxdt_GHRL = KOUT_GHRL*(ghrl_target - GHRL);

//=========================================================================
// 7. Thyroid & HPA
//=========================================================================
dxdt_T3   = KOUT_T3*(T3_NORM*(1 - T3_SUPP*fdef) - T3);
dxdt_CORT = KOUT_CORT*(CORT_NORM*(1 + K_CORT_DEF*fdef + K_CORT_STRESS*DRIVE) - CORT);

//=========================================================================
// 8. HPG axis — leptin/adiposity-gated GnRH pulse generator
//=========================================================================
double lepgate = pow(LEP, LEP_HILL)/(pow(LEP50_GNRH, LEP_HILL) + pow(LEP, LEP_HILL));
double fatgate = pow(fmfrac, FAT_HILL)/(pow(FM_FRAC_GATE, FAT_HILL) + pow(fmfrac, FAT_HILL));
double cortbrk = 1.0/(1 + K_CORT_GNRH*(CORT/CORT_NORM - 1));
if (cortbrk > 1) cortbrk = 1;
dxdt_GNRH = KOUT_GNRH*(lepgate*fatgate*cortbrk - GNRH);
dxdt_E2   = KOUT_E2*((E2_MAX*GNRH + E2_PATCH_GAIN*E2_EXO) - E2);

//=========================================================================
// 9. GH resistance / IGF-1
//=========================================================================
dxdt_IGF1 = KOUT_IGF1*(IGF1_NORM*(1 - IGF_SUPP*fdef)*(1 - OCP_ORAL*OCP_IGF_SUPP) - IGF1);

//=========================================================================
// 10. Bone remodeling — low formation, high resorption
//=========================================================================
double cort_rel = CORT/CORT_NORM - 1;  if (cort_rel < 0) cort_rel = 0;
double lep_def  = 1 - LEP/LEP_NORM;    if (lep_def  < 0) lep_def  = 0;
double e2_def   = 1 - E2/E2_NORM;      if (e2_def   < 0) e2_def   = 0;

double p1np_target = P1NP_NORM * pow(IGF1/IGF1_NORM, K_P1NP_IGF)
                     * (1 - K_P1NP_CORT*cort_rel)
                     * (1 - K_P1NP_LEP*lep_def)
                     * (1 + tptd_eff);
if (p1np_target < 3) p1np_target = 3;
dxdt_P1NP = KOUT_P1NP*(p1np_target - P1NP);

double ctx_target = CTX_NORM*(1 + K_CTX_E2*e2_def)*(1 + K_CTX_CORT*cort_rel)*(1 - bis_eff);
if (ctx_target < 0.05) ctx_target = 0.05;
dxdt_CTX = KOUT_CTX*(ctx_target - CTX);

double accrue = (ADOLESCENT>0 && pmBMI > 0.92) ? K_BMD_ACCRUE : 0.0;
dxdt_BMD = K_BMD_TURN*(P1NP/P1NP_NORM - CTX/CTX_NORM) + accrue;

//=========================================================================
// 11. Cardiac adaptation
//=========================================================================
double hr_target = HR_NORM - HR_BRADY_MAX*(0.6*(1 - T3/T3_NORM) + 0.4*fdef);
if (hr_target < 32) hr_target = 32;
dxdt_HR = KOUT_HR*(hr_target - HR);

//=========================================================================
// 12. Refeeding: insulin surge, electrolyte shifts, thiamine
//=========================================================================
// The surge is driven by intake ABOVE what the tissues are adapted to, so the
// RATE of escalation onto an occult deficit — not absolute calories — sets
// the hypophosphatemia risk.
double surge = (EI - EI_ADAPT)/K_SURGE;
if (surge < 0) surge = 0;

double repl_drive = (EB > 0) ? EB/1000.0 : 0.0;
dxdt_DEPL = K_DEPL_ON*fdef*(1 - DEPL) - K_DEPL_OFF*repl_drive*DEPL;

dxdt_PHOS = KIN_PHOS - KOUT_PHOS*PHOS - K_SHIFT_PHOS*surge*DEPL + PHOS_SUP;
dxdt_POT  = KIN_K    - KOUT_K*POT     - K_SHIFT_K*surge*DEPL
            - K_PURGE_LOSS*purge_act  + K_SUP;
dxdt_MG   = KIN_MG   - KOUT_MG*MG     - K_SHIFT_MG*surge*DEPL + MG_SUP;

dxdt_THIA = THIA_SUP*(1 - THIA) + THIA_DIET*EI*(1 - THIA)
            - K_THIA_GLYC*EI*surge - KOUT_THIA*THIA;
if (THIA < 0.02 && dxdt_THIA < 0) dxdt_THIA = 0;

