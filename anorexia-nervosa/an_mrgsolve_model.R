double W0 = BASE_BMI * HT * HT;
FM_0      = W0 * FM_FRAC0;
FFM_0     = W0 - FM_0;
DRIVE_0   = SEV;

// Chronic (weight-stable) starvation signal from depleted body stores alone
double store_def0 = (1 - BASE_BMI/MEDIAN_BMI)/STORE_REF;
if (store_def0 < 0) store_def0 = 0;
if (store_def0 > 1) store_def0 = 1;
double fdef0 = W_STORE*store_def0;
if (fdef0 > 1) fdef0 = 1;

ADAPT_0 = ADAPT_MAX * fdef0;
LEP_0   = K_LEP_FM * FM_0 * (1 - LEP_ACUTE*fdef0);
GHRL_0  = GHRL_NORM + (GHRL_MAX - GHRL_NORM)*(1 - BASE_BMI/MEDIAN_BMI);
T3_0    = T3_NORM * (1 - T3_SUPP*fdef0);
CORT_0  = CORT_NORM * (1 + K_CORT_DEF*fdef0 + K_CORT_STRESS*DRIVE_0);

// Baseline energetics: the untreated patient sits close to energy balance
double ree_raw0 = RMR_FFM*FFM_0 + RMR_FM*FM_0 + RMR_CONST;
double REE0     = ree_raw0 * (1 - ADAPT_0);
double sih0     = 1 + K_SIH*(1 - LEP_0/LEP_NORM);
if (sih0 < 1) sih0 = 1;
double pm0      = BASE_BMI/MEDIAN_BMI;
double rcap0    = (pm0 - RESTRICT_FLOOR)/(RESTRICT_FULL - RESTRICT_FLOOR);
if (rcap0 < 0) rcap0 = 0;
if (rcap0 > 1) rcap0 = 1;
double EXER0    = K_EXER * DRIVE_0 * sih0 * (INPATIENT>0 ? 0.10 : 1.0) * rcap0;
double need0    = REE0*(1 + PAL0) + EXER0;
EI_0            = need0/(1 - TEF_FRAC) * (1 - REL_DEF_MAX*DRIVE_0*rcap0);
EI_ADAPT_0      = EI_0;

double fmfrac0  = FM_0/W0;
double lepgate0 = pow(LEP_0, LEP_HILL)/(pow(LEP50_GNRH, LEP_HILL) + pow(LEP_0, LEP_HILL));
double fatgate0 = pow(fmfrac0, FAT_HILL)/(pow(FM_FRAC_GATE, FAT_HILL) + pow(fmfrac0, FAT_HILL));
double cortbrk0 = 1.0/(1 + K_CORT_GNRH*(CORT_0/CORT_NORM - 1));
if (cortbrk0 > 1) cortbrk0 = 1;
GNRH_0 = lepgate0 * fatgate0 * cortbrk0;
E2_0   = E2_MAX * GNRH_0;

IGF1_0 = IGF1_NORM * (1 - IGF_SUPP*fdef0) * (1 - OCP_ORAL*OCP_IGF_SUPP);

double cort_rel0 = CORT_0/CORT_NORM - 1;   if (cort_rel0 < 0) cort_rel0 = 0;
double lep_def0  = 1 - LEP_0/LEP_NORM;     if (lep_def0  < 0) lep_def0  = 0;
double e2_def0   = 1 - E2_0/E2_NORM;       if (e2_def0   < 0) e2_def0   = 0;
P1NP_0 = P1NP_NORM * pow(IGF1_0/IGF1_NORM, K_P1NP_IGF)
         * (1 - K_P1NP_CORT*cort_rel0) * (1 - K_P1NP_LEP*lep_def0);
if (P1NP_0 < 3) P1NP_0 = 3;
CTX_0  = CTX_NORM * (1 + K_CTX_E2*e2_def0) * (1 + K_CTX_CORT*cort_rel0);
BMD_0  = BMD_BASE;

HR_0 = HR_NORM - HR_BRADY_MAX*(0.6*(1 - T3_0/T3_NORM) + 0.4*fdef0);
if (HR_0 < 32) HR_0 = 32;

// Occult total-body phosphate depletion scales with severity and chronicity
double depl0 = (1 - BASE_BMI/MEDIAN_BMI) * (1.6 + 0.35*ILLNESS_DUR);
if (depl0 > 0.95) depl0 = 0.95;
if (depl0 < 0.05) depl0 = 0.05;
DEPL_0 = depl0;
PHOS_0 = PHOS_NORM * (1 - 0.06*depl0);      // serum stays normal until refed
POT_0  = K_NORM - (PURGE>0 ? 0.55 : 0.0);
MG_0   = MG_NORM * (1 - 0.05*depl0);
THIA_0 = 1 - 0.45*depl0;

