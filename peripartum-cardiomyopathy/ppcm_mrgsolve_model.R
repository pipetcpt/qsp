double ef    = EF_MAX*contr/(1 + KAF_EF*(af - 1));
if (ef < 5.0)  ef = 5.0;
if (ef > 72.0) ef = 72.0;
double sv = ef/100.0*LVEDV;
double hr = HR_BASE*(1 + KHR_NEURO*nex)*(1 - EHR_BB*bb - EHR_IVA*0.0);
double co = sv*hr/1000.0;
double isch = (CAP < 1) ? (1 - CAP) : 0.0;

// =========================================================================
// Drug PK / exposure kinetics
// =========================================================================
dxdt_BRC_G = -KA_BRC*BRC_G;
dxdt_BRC_C =  KA_BRC*BRC_G - KOUT_BRC*BRC_C - KTR_BRC*BRC_C + KTR_BRC*BRC_P;
dxdt_BRC_P =  KTR_BRC*BRC_C - KTR_BRC*BRC_P;
dxdt_BB    = -KOUT_BB*BB;
dxdt_RASI  = -KOUT_RASI*RASI;
dxdt_MRA   = -KOUT_MRA*MRA;
dxdt_DIU   = -KOUT_DIU*DIU;
dxdt_SG    = -KOUT_SG*SG;
dxdt_VD    = -KOUT_VD*VD;
dxdt_AC    = -KOUT_AC*AC;
dxdt_DIG   = -KOUT_DIG*DIG;

// =========================================================================
// Prolactin axis: lactation state, 23K-PRL, cathepsin D, 16K-PRL
// =========================================================================
// lactation is an autocatalytic supply-demand system: once involuted below
// LACT_MIN it cannot restart, which is why a completed bromocriptine course
// permanently removes the lactational prolactin drive
double lgrow = (LACT > LACT_MIN) ? KLACT_ON*LACT*(BF - LACT) : 0.0;
dxdt_LACT = lgrow - KLACT_OFF*brc*LACT;

double drive = (antepartum > 0.5) ? DRIVE_PREG : (1 + (DRIVE_LACT - 1)*LACT);
dxdt_PRL23 = KIN_PRL*drive*(1 - brc) - KOUT_PRL*PRL23;

dxdt_CTSD = KIN_CTSD*(1 + KC_ROS*(ROS - 1)) - KOUT_CTSD*CTSD;

// THE PPCM SWITCH: 16K-PRL is generated only when cathepsin D is activated
// ABOVE its physiological baseline. A normal lactating woman has abundant
// 23K-PRL but no cathepsin D activation, hence no vasoinhibin and no disease.
double ctsd_act = (CTSD > CTSD_TOL) ? (CTSD - CTSD_TOL) : 0.0;
dxdt_PRL16 = K16*ctsd_act*PRL23 - KOUT16*PRL16;

// =========================================================================
// Oxidative stress: the STAT3/MnSOD deficit amplifies STRESS-driven ROS only
// =========================================================================
double amp    = 1.0/((1 - LOSS_STAT3)*(1 + ESG_ROS*sg));
double stress = KR_LOAD*(load - 1)
              + KR_INF*((INF > 1) ? (INF - 1) : 0.0)
              + KR_ISCH*isch;
dxdt_ROS = KIN_ROS*(1 + amp*stress) - KOUT_ROS*ROS;

// =========================================================================
// Anti-angiogenic milieu: placental sFlt-1, PGC-1alpha/VEGF, capillary density
// =========================================================================
dxdt_SFLT = KIN_SFLT*antepartum*(1 + PREECL_SFLT*PREECL) - KOUT_SFLT*SFLT;

double pgc = 1.0/(1 + PGC_LOSS*((ROS > 1) ? (ROS - 1) : 0.0));
dxdt_VEGF = KIN_V*pgc - KOUT_V*VEGF - KTRAP*SFLT*VEGF;

// two-hit: 16K-PRL and miR-146a act far more strongly in an oxidatively
// stressed myocardium, which is why the vulnerable window is early
double ox_amp = 1 + KAMP_ROS*((ROS > 1) ? (ROS - 1) : 0.0);
double h16 = (PRL16*ox_amp)/(PRL16*ox_amp + P50_16);
double hsf = SFLT/(SFLT + S50_SFLT);
double vdef = (VEGF < 1) ? (1 - VEGF) : 0.0;
double aa  = W16*h16 + WSF*hsf + WV*vdef + SYN_2HIT*h16*hsf;
dxdt_CAP = KCAP_IN*VEGF*(1 - CAP) - KCAP_OUT*aa*CAP;

// =========================================================================
// miR-146a exosome axis -> cardiomyocyte survival signalling
// =========================================================================
dxdt_MIR = KMIR*PRL16 - KOUT_MIR*MIR;
double hmir = (MIR*ox_amp)/(MIR*ox_amp + MIR50);
dxdt_SURV = KIN_S*(1 - SURV) - KS_MIR*hmir*SURV;

// =========================================================================
// Cardiomyocyte mass, irreversible scar, fibrosis, inflammation
// =========================================================================
double gen_inj = 1 + GEN_INJ*GEN_TTN;
double gen_rec = 1 - GEN_REC*GEN_TTN;
double inj = KINJ*gen_inj*(W_ISCH*isch
                         + W_SURV*(1 - SURV)
                         + W_INF*((INF > 1) ? (INF - 1) : 0.0)
                         + W_NE*nex*(1 - 0.7*bb)
                         + W_LOAD*(load - 1));
double rev_cap = CAP*SURV*(1 - 0.6*fibf)*gen_rec;
double ceiling = (1 - SCAR > 0) ? (1 - SCAR) : 0.0;
double headroom = (ceiling - CM > 0) ? (ceiling - CM) : 0.0;
dxdt_CM = -inj*CM + KREC*rev_cap*headroom;

// only supra-physiological injury leaves permanent scar
double inj_ex = (inj > INJ_TOL) ? (inj - INJ_TOL) : 0.0;
dxdt_SCAR = FSCAR*inj_ex*CM;

double fib_drive = 0.5*((ws > 1) ? (ws - 1) : 0.0)
                 + KF_NEURO*nex
                 + KF_INJ*(1 - CM);
double fib_room = (1 - FIB/FIB_MAX > 0) ? (1 - FIB/FIB_MAX) : 0.0;
dxdt_FIB = KFIB*fib_drive*(1 - EMRA_FIB*mra - ERASI_FIB*rasi)*fib_room
         - KOUT_FIB*(1 + EMRA_REG*mra)*FIB;

dxdt_INF = KIN_INF*(1 + KI_ROS*(ROS - 1) + KI_INJ*(1 - CM)) - KOUT_INF*INF;

// =========================================================================
// Neurohormonal activation and congestion
// =========================================================================
double co_def = (co < CO_NORM) ? (1 - co/CO_NORM) : 0.0;
dxdt_NEURO = KIN_N*(1 + KN_CO*co_def + KN_VOL*VOL)*(1 - EBB_N*bb)*(1 - ERASI_N*rasi)
           - KOUT_N*NEURO;
dxdt_VOL = KVOL_IN*nex*(1 + KV_LOAD*(load - 1))
         - KVOL_OUT*(1 + EDIU_V*diu + ESG_V*sg)*VOL;

// =========================================================================
// Chamber remodelling, NT-proBNP, LV thrombus
// =========================================================================
double dil_room = (1 - LVEDV/LVEDV_MAX > 0) ? (1 - LVEDV/LVEDV_MAX) : 0.0;
double rev = rev_cap*CM;
dxdt_LVEDV = KDIL*((ws > 1) ? (ws - 1) : 0.0)*(1 + KDIL_VOL*VOL)*dil_room
           - KREM*rev*(LVEDV - LVEDV_MIN);

dxdt_NTBNP = KIN_BNP*pow(ws, BNP_EXP)*(1 + KB_VOL*VOL) - KOUT_BNP*NTBNP;

double stasis = (ef < 35.0) ? ((35.0 - ef)/35.0) : 0.0;
// smooth "drug on board" indicator (avoids a hard switch inside the solver)
double brc_on = BRC_C/(BRC_C + 0.02);
dxdt_THR = KTHR*stasis*(1 + PROTHR_BRC*brc_on) - KOUT_THR*(1 + EAC_THR*ac)*THR;

