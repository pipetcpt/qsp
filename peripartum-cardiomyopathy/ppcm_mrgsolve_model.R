##        Dosing records may be present; the effect simply does not exist until
##        delivery. Hydralazine + nitrate is the antepartum-safe substitute.
##    (2) Bromocriptine effect is forced to ZERO while t < T_DELIVERY
##        (it is a postpartum intervention).
