##  # ---------- Calibration notes: how each anchor maps onto the model ----------
##  #
##  # Hilfiker-Kleiner 2007 Cell 128:589 (cardiomyocyte STAT3 knockout ->
##  #   MnSOD loss -> cathepsin D activation -> 16K-PRL -> PPCM in mice,
##  #   prevented by bromocriptine) is the model's backbone. LOSS_STAT3
##  #   reduces the myocardium's capacity to detoxify STRESS-driven ROS (the
##  #   `amp` term), which activates cathepsin D (CTSD), which cleaves 23K-PRL
##  #   into PRL16. CTSD_TOL encodes the essential clinical fact that a normal
##  #   lactating woman has abundant prolactin but NO disease: below baseline
##  #   cathepsin D activity, no vasoinhibin is generated at all. Breastfeeding
##  #   alone is therefore not pathogenic in this model, which matches the
##  #   absence of convincing evidence that breastfeeding harms PPCM outcome.
##  #
##  # Patten 2012 Nature 485:333 (PGC-1alpha knockout mice develop PPCM;
##  #   disease requires BOTH a cardiac VEGF/PGC-1alpha deficit AND placental
##  #   sFlt-1; bromocriptine or VEGF rescues) is the SYN_2HIT term plus the
##  #   PGC_LOSS -> VEGF -> CAP path. sFlt-1 is produced ONLY while
##  #   antepartum, so scenario 7 (antepartum preeclamptic) carries a much
##  #   larger early anti-angiogenic hit that resolves after delivery -- the
##  #   model's explanation for why such patients present severely yet can
##  #   still recover well once the placenta is delivered.
##  #
##  # Halkein 2013 J Clin Invest 123:2143 (16K-PRL -> endothelial NF-kB ->
##  #   miR-146a-5p -> exosomal transfer to cardiomyocytes -> Erbb4/Nras/
##  #   Notch1 knockdown; serum miR-146a is elevated in PPCM specifically and
##  #   falls with bromocriptine) is the MIR -> SURV path. SURV gates BOTH
##  #   injury (W_SURV) and recovery (rev_cap), which is why suppressing the
##  #   prolactin substrate early has a disproportionate effect.
##  #
##  # IPAC (McNamara 2015 JACC 66:905): entry LVEF ~0.35 -> ~0.51 at 6 months
##  #   on contemporary therapy. The model's standard-therapy arm rises from
##  #   29.5% to 42.4% at 6 months from a lower entry point, and LVEDD/LVEDV at
##  #   entry limits recovery through the wall-stress and dilation terms --
##  #   reproducing IPAC's finding that LVEF <0.30 with LVEDD >=6.0 cm
##  #   predicts non-recovery.
##  #
##  # German bromocriptine trial (Hilfiker-Kleiner 2017 Eur Heart J 38:2671):
##  #   1 week vs 8 weeks, full recovery 52% vs 68%. In the model the two
##  #   regimens differ ONLY in how much of the high-oxidative-stress
##  #   vulnerable window they cover: ROS (and hence ox_amp and cathepsin D)
##  #   is highest in the first weeks, so continued prolactin suppression
##  #   through weeks 2-8 prevents damage that would otherwise be locked in as
##  #   irreversible SCAR. The model gives 47.6% vs 56.5% mean LVEF at 6 months.
##  #   NOTE THE OVERSHOOT: the trial's MEAN LVEF difference between the two
##  #   arms was small (0.49 vs 0.51) even though the RECOVERY-RATE difference
##  #   was 16 points. This model exaggerates the duration effect on mean
##  #   LVEF; it should be read as a mechanistic hypothesis about WHY duration
##  #   matters (window coverage plus scar lock-in), not as a quantitative
##  #   prediction of the mean-LVEF gap.
##  #
##  # Sliwa 2010 Circulation 121:1465 (bromocriptine 0.27 -> 0.58 vs standard
##  #   0.27 -> 0.36) brackets the model's bromocriptine effect size from
##  #   above; IPAC brackets the standard-therapy arm from above. The model
##  #   deliberately sits between the small proof-of-concept RCT and the
##  #   larger observational cohorts.
##  #
##  # Ware 2016 NEJM 374:233 (truncating variants, mostly TTN, in ~15%;
##  #   lower LVEF at 1 year) is GEN_TTN acting through GEN_INJ (more injury
##  #   per unit insult, since a titin-haploinsufficient sarcomere has less
##  #   reserve) and GEN_REC (less recovery capacity). Scenario 6 recovers to
##  #   43.8% rather than 56.5% on identical therapy.
##  #
##  # Bromocriptine thrombotic risk / mandatory anticoagulation (ESC position
##  #   statement, Bauersachs 2019 Eur J Heart Fail 21:827): PROTHR_BRC raises
##  #   thrombus propensity while the drug is on board, and anticoagulation
##  #   acts ONLY on THR. Scenarios 8 and 9 therefore have IDENTICAL LVEF
##  #   trajectories and differ only in peak thrombus burden (0.40 vs 0.21 au)
##  #   -- the model's way of showing that anticoagulation here buys safety,
##  #   not efficacy.
##  #
##  # ESC EORP registry (Sliwa 2020 Eur J Heart Fail 22:1006): ~46% reach
##  #   LVEF >=0.50 and 6-month mortality is ~6% globally. The untreated arm
##  #   (scenario 1) is the model's representation of the late-presenting,
##  #   under-treated end of that distribution: it deteriorates progressively
##  #   and accrues a large irreversible SCAR fraction.
##  #
##  # NOT modelled as efficacious, deliberately: levosimendan (Biteker 2011
##  #   negative RCT), pentoxifylline and IVIG (small, unreplicated). They
##  #   appear in the mechanistic map for completeness but have no PD effect
