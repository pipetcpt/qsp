##  Peripartum Cardiomyopathy (PPCM) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Peripartum Cardiomyopathy — new-onset systolic heart failure
##             (LVEF <45%, no other identifiable cause) presenting in the last
##             month of pregnancy or within ~5 months postpartum. Core
##             pathobiology modelled here is the PROLACTIN-CLEAVAGE / ANTI-
##             ANGIOGENIC cascade: peripartum haemodynamic + hormonal load on a
##             susceptible myocardium (STAT3/MnSOD-deficient, often carrying a
##             TTN truncating variant) -> myocardial oxidative stress ->
##             lysosomal CATHEPSIN D activation -> cleavage of 23-kDa prolactin
##             into 16-kDa prolactin (VASOINHIBIN) -> together with placental
##             sFlt-1 (a "two-hit" anti-angiogenic milieu) -> coronary
##             microvascular endothelial apoptosis and capillary rarefaction,
##             plus NF-kB-driven endothelial miR-146a-5p packaged into exosomes
##             and transferred to cardiomyocytes -> downregulation of
##             Erbb4/Nras/Notch1 -> loss of cardiomyocyte survival and
##             metabolic signalling -> myocyte loss, fibrosis, LV dilation and
##             systolic failure, with neurohormonal (RAAS/SNS) amplification.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 30 ODE compartments —
##             (a) 11 drug PK/exposure states: bromocriptine (oral depot +
##                 2-compartment plasma), beta-blocker, ACEi/ARB/ARNI ("RASI"),
##                 MRA, loop diuretic, SGLT2 inhibitor, antepartum-safe
##                 vasodilator (hydralazine/nitrate), anticoagulant, digoxin;
##             (b) 19 disease states: 23-kDa prolactin, active cathepsin D,
##                 16-kDa prolactin (vasoinhibin), myocardial ROS, placental
##                 sFlt-1, free VEGF, myocardial capillary density, cardiomyocyte
##                 miR-146a load, Erbb4/Nras/Notch1 survival-signalling capacity,
##                 viable contractile myocyte mass, irreversible scar, fibrosis,
##                 inflammatory burden, neurohormonal activation, congestion /
##                 volume excess, LV end-diastolic volume, NT-proBNP, LV
##                 thrombus propensity, and lactation state.
##  Time     : days. t = 0 is the moment of PPCM DIAGNOSIS / PRESENTATION.
##             T_DELIVERY is expressed on the same clock, so T_DELIVERY = -7
##             means the patient delivered one week before presenting (the
##             commonest early-postpartum phenotype) and T_DELIVERY = +14 means
##             an ANTEPARTUM diagnosis with delivery planned two weeks later.
##  Units    : drug exposure compartments in dose-proportional arbitrary units
