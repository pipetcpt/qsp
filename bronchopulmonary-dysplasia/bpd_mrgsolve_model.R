// -- growth gate ------------------------------------------------------------
VEGF    : VEGF-A signalling (1.0 = healthy)
NOB     : NO bioavailability (1.0 = healthy)
IGF1    : IGF-1 axis activity (1.0 = term-equivalent)
RASIG   : Retinoate/RAR signalling (1.0 = replete)
EPC     : Endothelial progenitor pool (1.0 = healthy)
// -- structure --------------------------------------------------------------
ALV     : Alveolar gas-exchange surface (1.0 = healthy 36-wk PMA lung)
CAPD    : Pulmonary microvascular density (1.0 = healthy 36-wk PMA lung)
SEPT    : Septal thickening / interstitial fibrosis (0 = none)
ASM     : Airway smooth muscle mass (0 = none)
LW      : Extravascular lung water (0 = none)
// -- support ----------------------------------------------------------------
SUP     : Respiratory support intensity index (0-1)
MVF     : Fraction of the day on invasive mechanical ventilation (0-1)
UREA    : Ureaplasma airway burden (0-1)
// -- pulmonary vascular -----------------------------------------------------
VREM    : Pulmonary vascular remodelling (0 = none)
RVHY    : RV hypertrophy index (0 = none)
// -- accumulators / endpoints ----------------------------------------------
WT      : Body weight (kg)
LOSTW   : Lost developmental window (alveolar surface never built)
NDIC    : Neurodevelopmental cost accumulator (au)
VDAYS   : Cumulative days of invasive ventilation
O2DAYS  : Cumulative days of supplemental oxygen
HAZ     : Cumulative mortality hazard

$MAIN
// ---- initial conditions --------------------------------------------------
// The alveolar surface an infant is BORN with follows the uninjured
// trajectory of the same programme equation, evaluated at PMA = GA:
//     ALV(p) = ALVMAX - (ALVMAX - A20) * exp(-r * PHI(p)),
//     r = KALV / PHI(36),  PHI computed in closed form by bpd_phi()
// so no separate birth-surface table is needed and the gestational gradient
// of BPD emerges from the geometry rather than from a fitted coefficient.
double phi_ga  = bpd_phi(GA,   PMAPK, SDW_L, SDW_R);
double phi_36  = bpd_phi(36.0, PMAPK, SDW_L, SDW_R);
double r_prog  = KALV / phi_36;
double ALV_birth = ALVMAX - (ALVMAX - A20) * exp(-r_prog * phi_ga);

double bw = (BW > 0.01) ? BW : (0.0 + exp(0.2718 * GA - 6.35));  // GA-based default
if (IUGR > 0.5) bw = bw * 0.72;

ALV_0   = ALV_birth;
CAPD_0  = ALV_birth;                 // capillary bed tracks surface at birth
SEPT_0  = 0.0;
ASM_0   = 0.0;
// Antenatal steroids reduce surfactant deficiency and therefore the initial
// atelectasis/oedema load. Written as a PENALTY for an incomplete course so
// that ANTESTER = 1 (the reference) leaves the baseline untouched.
LW_0    = ((SURF > 0.5) ? LW0_SURF : LW0_NOSURF) * (1.0 + 0.25 * (1.0 - ANTESTER));
NFKB_0  = NF0 * (1.0 + 2.5 * CHORIO) * (1.0 + 0.8 * GENRISK);
IL1B_0  = NFKB_0 * KIN_IL1 / KOUT_IL1;
NEUT_0  = (KIN_NE * (IL1B_0 + 0.5 * NFKB_0)) / KOUT_NE;
TGFB_0  = 0.05 + 0.25 * CHORIO;
ROS_0   = 0.10;
VEGF_0  = 1.0 / (1.0 + AV_IL1 * IL1B_0 + AV_SFLT * 0.35 * IUGR);
NOB_0   = 1.0 / (1.0 + AN_ROS * ROS_0);
IGF1_0  = (IGFB0 + IGFBSL * (GA - 24.0)) * (IUGR > 0.5 ? 0.65 : 1.0);
RASIG_0 = (RET_S0 * 0.12) / (KM_RA + RET_S0 * 0.12);
EPC_0   = 1.0 / (1.0 + AE_ROS * ROS_0);
SUP_0   = (LISA > 0.5) ? 0.25 : 0.55;
MVF_0   = (LISA > 0.5) ? 0.05 : 0.90;
UREA_0  = (UREA0 > 0.5) ? 0.35 : 0.0;
VREM_0  = 0.0;
RVHY_0  = 0.0;
WT_0    = bw;
RETS_0  = RET_S0;
RETP_0  = 0.35 * RET_VD * bw;        // plasma retinol ~0.35 micromol/L, deficient
LOSTW_0 = 0.0; NDIC_0 = 0.0; VDAYS_0 = 0.0; O2DAYS_0 = 0.0; HAZ_0 = 0.0;
DEXEQ_0 = 0.0;

$ODE
// ==========================================================================
// 0. CLOCKS
// ==========================================================================
double PMA = GA + SOLVERTIME / 7.0;
double wS  = (PMA < PMAPK) ? SDW_L : SDW_R;
double zS  = (PMA - PMAPK) / wS;
double SDEV = exp(-0.5 * zS * zS);                    // septation drive
double r_prog2 = KALV / bpd_phi(36.0, PMAPK, SDW_L, SDW_R);
double phi_now_ode = bpd_phi(PMA, PMAPK, SDW_L, SDW_R);
double wt = (WT > 0.35) ? WT : 0.35;

// ==========================================================================
// 1. DOSING WINDOWS -> INFUSION-LIKE INPUT RATES (mg/day, not bolus events)
//    Continuous rates are used deliberately: the interesting timescale here
//    is DAYS of gate suppression, not the q8h ripple.
// ==========================================================================
// --- caffeine: citrate mg/kg -> BASE mg (factor 0.5) ----------------------
double caf_on   = ((SOLVERTIME >= CAF_T0) && (SOLVERTIME <= CAF_T1)) ? 1.0 : 0.0;
double caf_load = ((SOLVERTIME >= CAF_T0) && (SOLVERTIME < CAF_T0 + 0.25))
                    ? (0.5 * CAF_LD * wt / 0.25) : 0.0;
double caf_in   = caf_on * (0.5 * CAF_MD * wt) + caf_load;

// --- dexamethasone: flat rate, or the DART taper -------------------------
double dex_rate = 0.0;
if (DEX_DART > 0.5) {
  double d = SOLVERTIME - DEX_T0;
  if      (d >= 0.0 && d < 3.0)  dex_rate = 0.15;
  else if (d >= 3.0 && d < 6.0)  dex_rate = 0.10;
  else if (d >= 6.0 && d < 8.0)  dex_rate = 0.05;
  else if (d >= 8.0 && d < 10.0) dex_rate = 0.02;
} else if (SOLVERTIME >= DEX_T0 && SOLVERTIME <= DEX_T1) {
  dex_rate = DEX_RATE;
}
double dex_in = dex_rate * wt;

// --- hydrocortisone: flat rate, or the PREMILOC schedule ----------------
double hc_rate = 0.0;
if (HC_PREM > 0.5) {
  double d = SOLVERTIME - HC_T0;
  if      (d >= 0.0 && d < 7.0)  hc_rate = 1.0;    // 0.5 mg/kg BID
  else if (d >= 7.0 && d < 10.0) hc_rate = 0.5;    // 0.5 mg/kg daily
} else if (SOLVERTIME >= HC_T0 && SOLVERTIME <= HC_T1) {
  hc_rate = HC_RATE;
}
double hc_in = hc_rate * wt;

// --- intratracheal budesonide: BUD_N doses q8h ---------------------------
double bud_in = 0.0;
if (BUD_DOSE > 0.0) {
  double dwin = BUD_N / 3.0;                       // q8h -> N/3 days
  if (SOLVERTIME >= BUD_T0 && SOLVERTIME < BUD_T0 + dwin)
    bud_in = BUD_DOSE * BUD_N * wt / dwin;
}

// --- vitamin A: VITA_N IM doses at VITA_IVL intervals ---------------------
double vita_in = 0.0;
if (VITA_T0 < 900.0) {
  double dwin = VITA_N * VITA_IVL;
  if (SOLVERTIME >= VITA_T0 && SOLVERTIME < VITA_T0 + dwin) {
    // 1 IU retinol = 0.3 microgram = 0.001047 micromol
    vita_in = VITA_IU * 0.001047 / VITA_IVL;
  }
}

double azi_in = ((SOLVERTIME >= AZI_T0) && (SOLVERTIME <= AZI_T1)) ? AZI_RATE * wt : 0.0;
double sil_in = ((SOLVERTIME >= SIL_T0) && (SOLVERTIME <= SIL_T1))
                  ? SIL_F * SIL_RATE * wt : 0.0;

// ==========================================================================
// 2. PK -> CONCENTRATIONS -> RECEPTOR OCCUPANCIES
// ==========================================================================
// caffeine clearance matures with PMA (t1/2 ~90 h at PMA 26 -> ~6 h at PMA 60)
double pmh    = pow(PMA, CAF_HILL);
double caf_cl = CAF_CLI * pmh / (pow(CAF_PMA50, CAF_HILL) + pmh) * wt;
double Ccaf   = CAFC / (CAF_VD * wt);
double Cdex   = DEXC / (DEX_VD * wt);
double Chc    = HCC  / (HC_VD  * wt);
double Cbudl  = BUDL / (BUD_VL * wt);
double Cbudc  = BUDC / (BUD_VD * wt);
double Cret   = RETP / (RET_VD * wt);
double Cazi   = AZIC / (AZI_VD * wt);
double Csil   = SILC / (SIL_VD * wt);

// ONE receptor, THREE ligands: everything is dexamethasone-equivalent mg/L.
// The systemic occupancy drives NDI cost; the lung occupancy drives the local
// anti-inflammatory and antiproliferative effects. Intratracheal budesonide
// separates the two, which is exactly why it is interesting.
double DXE_sys  = Cdex + HC_POT * Chc + BUD_POT * Cbudc;
double DXE_lung = Cdex + HC_POT * Chc + BUD_POT * Cbudl;
double GRocc_s  = DXE_sys  / (GR_EC50 + DXE_sys);
double GRocc_l  = DXE_lung / (GR_EC50 + DXE_lung);

double E_transrep = GR_EMAXR * GRocc_l;              // NF-kB suppression
double E_comp     = GR_ECOMP * GRocc_l;              // compliance / extubation
double E_antiprol = AG_GR    * GRocc_l;              // THE HIDDEN COST
double E_caf_ap   = CAF_EMAX * Ccaf / (CAF_EC50 + Ccaf);
double E_caf_alv  = CAF_EALV * Ccaf / (CAF_ECA  + Ccaf);
double E_sil      = SIL_EMAX * Csil / (SIL_EC50 + Csil);
double E_ino      = INO_EMAX * INO_PPM / (INO_EC50 + INO_PPM);
double E_azi      = AZI_KILL * Cazi / (AZI_EC50 + Cazi);
double E_furo     = ((FURO > 0.5) && (SOLVERTIME >= FURO_T0)) ? FURO_EMAX : 0.0;
double E_msc      = ((MSC  > 0.5) && (SOLVERTIME >= MSC_T0))
                      ? MSC_EMAX * exp(-(SOLVERTIME - MSC_T0) / MSC_TAU) : 0.0;
double E_rhigf    = ((RHIGF > 0.5) && (SOLVERTIME <= RHIGF_T1)) ? RHIGF_E : 0.0;
double E_il1ra    = ((IL1RA > 0.5) && (SOLVERTIME >= IL1RA_T0)
                     && (SOLVERTIME <= IL1RA_T1)) ? IL1RA_E : 0.0;
double E_era      = (ERA   > 0.5) ? ERA_EMAX : 0.0;
double E_bd       = (BRONCHO > 0.5) ? BRONCHO_E : 0.0;

// ==========================================================================
// 3. GAS EXCHANGE -> REQUIRED FiO2 -> CLINICIAN ESCALATION LOOP
//    This is the vicious cycle, written as a feedback loop rather than
//    asserted in prose: worse lung -> more support -> more injury.
// ==========================================================================
// Oxygen requirement is built from TWO physiologically distinct terms:
//
//  (a) a DIFFUSION/RESERVE term from the surface and capillary deficit,
//      measured against the GESTATION-MATCHED IDEAL (a healthy 25-weeker
//      breathes room air, so the deficit relative to its own developmental
//      trajectory is what costs oxygen). The lung has large reserve: demand
//      up to DTHR is tolerated on room air, and only beyond DTHR does FiO2
//      climb. That reserve is why the 36-week FiO2 is a POOR readout of the
//      developmental deficit, and why this model carries LOSTW separately.
//
//  (b) a SHUNT term from atelectasis, oedema, septal fibrosis and airway
//      narrowing, measured ABOVE the healthy baseline (LW_BASE, SEPT_BASE),
//      because a normal lung carries some water and normal septa and still
//      needs no oxygen. Shunt has NO reserve: it raises FiO2 immediately,
//      which is exactly what makes a diuretic look like it is working.
double aid_e = ALVMAX - (ALVMAX - A20) * exp(-r_prog2 * phi_now_ode);
double rel_a = (ALV  / aid_e > 1e-4) ? ALV  / aid_e : 1e-4;
double rel_c = (CAPD / aid_e > 1e-4) ? CAPD / aid_e : 1e-4;

double Dmd_s = 1.0 / (pow(rel_a, PALV) * pow(rel_c, PCAP));
Dmd_s = Dmd_s / (1.0 + 0.35 * E_comp);               // steroid compliance gain
double Rex = (Dmd_s - DTHR > 0.0) ? Dmd_s - DTHR : 0.0;

double sept_sat = SEPT / (1.0 + SEPT);
double lw_ex = (LW - LW_BASE > 0.0) ? LW - LW_BASE : 0.0;
double sp_ex = (sept_sat - SEPT_BASE > 0.0) ? sept_sat - SEPT_BASE : 0.0;
double sh_arg = KSH * (KLWO / 1.28 * lw_ex + 0.5 * sp_ex
                       + KASMO * ASM * (1.0 - E_bd));
sh_arg = sh_arg / (1.0 + 0.35 * E_comp);
double Sh = sh_arg / (1.0 + sh_arg);
double Dmd = Dmd_s * (1.0 + KSEPTO * sp_ex + KLWO * lw_ex);

double band = (SPO2HI > 0.5) ? 1.0 : BANDF;
double FiO2 = 0.21 + 0.79 * (1.0 - (1.0 - Sh) * exp(-KFIO2 * Rex));
FiO2 = 0.21 + (FiO2 - 0.21) * band;
if (FiO2 > 1.0)  FiO2 = 1.0;
if (FiO2 < 0.21) FiO2 = 0.21;

double sup_tgt = 1.0 - exp(-KSUP * (Rex + 2.0 * Sh));

// apnoea of prematurity: matures spontaneously, suppressed by caffeine
double apnoea = AP0 * exp(-SOLVERTIME / TAU_AP) * (1.0 - CAF_DRIVE * E_caf_ap);
double mvdrive = sup_tgt + WAP * apnoea - 0.25 * LISA - 0.30 * E_comp;
if (SOLVERTIME >= TRACH_T) mvdrive = 1.0;
double mvf_tgt = 1.0 / (1.0 + exp(-(mvdrive - THRMV) / SMV));

// ==========================================================================
// 4. INJURY DRIVE
// ==========================================================================
double vili = KVILI * MVF * pow(SUP, NVILI)
                * (1.0 - EFF_VTV * VTV) * (1.0 - EFF_PHC * PHC)
              + KNIV * (1.0 - MVF) * pow(SUP, NVILI);

// Male sex is associated with later lung and antioxidant maturation; written
// as a BONUS for female sex so MALE = 1 (the reference) is the baseline.
double aoxpma_e = AOXPMA - 0.8 * (1.0 - MALE);
double aoxm  = AOX0 / (1.0 + exp(-(PMA - aoxpma_e) / AOXSL));
double fexc  = (FiO2 - 0.21) / 0.79;
double oxtox = KOX * pow(fexc, NOX) / (1.0 + aoxm);

// hypoxaemia burden: the low SpO2 band and unresolved apnoea both contribute
double hb = ((SPO2HI > 0.5) ? 0.0 : BANDHX) + 0.55 * apnoea;
double hypox = KHYPOX * hb;

double pda = ((SOLVERTIME >= PDA_T0) &&
              ((PDA_T1 <= 0.0) || (SOLVERTIME <= PDA_T1))) ? PDA_MAG : 0.0;
double sepsis = ((SOLVERTIME >= SEP_T0) && (SOLVERTIME <= SEP_T0 + SEP_DUR))
                  ? SEP_MAG : 0.0;
double ante = KANTE * CHORIO * exp(-SOLVERTIME / TAU_ANTE);

double INJ = vili + oxtox
             + KURE * UREA * (1.0 - ((E_azi > 0.0) ? AZI_AI : 0.0))
             + KSEP * sepsis + KPDAI * pda
             + ante + KROSI * ROS;

// ==========================================================================
// 5. INFLAMMATION
// ==========================================================================
double sflt = 0.35 * IUGR + 0.15 * CHORIO;

// Every cascade node is a SATURATING target-approach, so no amount of injury
// can make the mediators unbounded. Biologically this is receptor and
// transcription-factor saturation; numerically it is what makes the escalation
// loop settle into a PHENOTYPE instead of diverging. A linear cascade here
// produces an infant who is on 100% oxygen by day 3 and dies, which is not
// the disease being modelled.
double nf_tgt = (NF0 + (NFMAX - NF0) * INJ / (KINJ50 + INJ))
                / (1.0 + 2.0 * E_transrep);
dxdt_NFKB = (nf_tgt - NFKB) * KOUT_NF;

double il1_tgt = KIN_IL1 * NFKB * (1.0 + FNLRP3 * ROS / (1.0 + ROS))
                 / (1.0 + 0.9 * E_transrep + 2.0 * E_il1ra);
dxdt_IL1B = (il1_tgt - IL1B) * KOUT_IL1;

double ne_tgt = KIN_NE * (IL1B + 0.5 * NFKB) / (1.0 + 0.8 * E_transrep);
dxdt_NEUT = (ne_tgt - NEUT) * KOUT_NE;

double tg_tgt = KIN_TG * (WTG_MECH * vili + (1.0 - WTG_MECH) * NFKB);
dxdt_TGFB = (tg_tgt - TGFB) * KOUT_TG;

double ro_tgt = KIN_RO * (oxtox + 0.30 * NEUT) / (1.0 + aoxm);
dxdt_ROS  = (ro_tgt - ROS) * KOUT_RO;

// ==========================================================================
// 6. THE GROWTH GATE  G
// ==========================================================================
double vegf_t = (1.0 + MSC_EMAX * 0.0 + E_msc)
                / (1.0 + AV_IL1 * IL1B + AV_ROS * ROS + AV_SFLT * sflt);
double no_t   = (0.35 + 0.65 * VEGF) / (1.0 + AN_ROS * ROS + AN_ADMA * hb);
double igf_b  = IGFB0 + IGFBSL * (PMA - 24.0);
if (igf_b > 1.15) igf_b = 1.15;
double igf_t  = igf_b * (1.0 - AI_INFL * NFKB / (1.0 + NFKB))
                      * (1.0 - AI_DEX  * GRocc_s)
                      * (1.0 + (NUTR > 0.5 ? NUTR_EFF : 0.0))
                      * (1.0 + E_rhigf)
                      * (IUGR > 0.5 ? 0.80 : 1.0);
double ra_t   = Cret / (KM_RA + Cret);
double epc_t  = (1.0 + 0.5 * E_msc) / (1.0 + AE_ROS * ROS);

dxdt_VEGF  = (vegf_t - VEGF) / TAU_V;
dxdt_NOB   = (no_t   - NOB)  / TAU_NO;
dxdt_IGF1  = (igf_t  - IGF1) / TAU_I;
dxdt_RASIG = (ra_t   - RASIG)/ TAU_R;
dxdt_EPC   = (epc_t  - EPC)  / TAU_E;

// cGMP tone: NO bioavailability, amplified by PDE5 inhibition and iNO
double cgmp = NOB * (1.0 + E_sil) + E_ino;
if (cgmp > 2.5) cgmp = 2.5;

double v_e = (VEGF  > 1e-4) ? VEGF  : 1e-4;
double n_e = (cgmp  > 1e-4) ? cgmp  : 1e-4;
double i_e = (IGF1  > 1e-4) ? IGF1  : 1e-4;
double r_e = (RASIG > 1e-4) ? RASIG : 1e-4;
double e_e = (EPC   > 1e-4) ? EPC   : 1e-4;

double Gcore = exp(WV*log(v_e) + WN*log(n_e) + WI*log(i_e)
                 + WR*log(r_e) + WE*log(e_e));
double G = Gcore / (1.0 + AG_TGF * TGFB)
                 / (1.0 + AG_IL1 * IL1B)
                 * (1.0 - E_antiprol)
                 * (1.0 + E_caf_alv);
if (G < 0.0) G = 0.0;
if (G > 1.6) G = 1.6;

// ==========================================================================
// 7. STRUCTURE — the programme equation and its shadow, the LOST WINDOW
// ==========================================================================
double head_alv = r_prog2 * SDEV * (ALVMAX - ALV) / 7.0;   // per DAY
double head_cap = KCAPREL * r_prog2 * SDEV * (CAPMAX - CAPD) / 7.0;
double Gv = exp(0.45*log(v_e) + 0.30*log(n_e) + 0.15*log(i_e) + 0.10*log(e_e))
            / (1.0 + 0.5 * AG_TGF * TGFB) * (1.0 - E_antiprol);
if (Gv > 1.6) Gv = 1.6;

dxdt_ALV  = head_alv * G  - KDEGALV * NEUT * ALV;
dxdt_CAPD = head_cap * Gv - KDEGALV * 0.6 * NEUT * CAPD;

// THE COUNTER: surface that the programme was scheduled to build and did not.
dxdt_LOSTW = head_alv * (1.0 - G);

dxdt_SEPT = KSEPT * TGFB - KOUT_SEPT * SEPT;
// ASM is EXCESS smooth muscle: driven by IL-1beta above its basal level, so
// a healthy lung sits at ASM = 0 and contributes nothing to the shunt term.
dxdt_ASM  = KASM * (((IL1B - IL1B_BAS > 0.0) ? IL1B - IL1B_BAS : 0.0)
                    + 0.3 * MVF) - KOUT_ASM * ASM;
dxdt_LW   = KLW * (pda + 0.5 * NEUT / (1.0 + NEUT) + 0.4 * FLUID)
            - KOUT_LW * LW * (1.0 + E_furo);

// ==========================================================================
// 8. SUPPORT DYNAMICS (the loop closes here)
// ==========================================================================
dxdt_SUP = (sup_tgt - SUP) / TAU_SUP;
dxdt_MVF = (mvf_tgt - MVF) / TAU_MV;

// ==========================================================================
// 9. UREAPLASMA
// ==========================================================================
dxdt_UREA = URE_GROW * UREA * (1.0 - UREA / URE_MAX) - E_azi * UREA;

// ==========================================================================
// 10. PULMONARY VASCULAR / RV
// ==========================================================================
double XS = pow((CAPD > 0.02 ? CAPD : 0.02), 1.0);
double et1 = (0.25 + 0.6 * ROS + 0.5 * hb) * (1.0 - E_era);
double hpv = hb / (1.0 + 1.2 * (cgmp - 1.0 > 0.0 ? cgmp - 1.0 : 0.0));
double PVRn = (1.0 / pow(XS, PXS)) * (1.0 + KHPV * hpv) * (1.0 + KVR * VREM);

dxdt_VREM = KVRIN * (hb + KET1 * et1 + 0.2 * pda) - KVROUT * VREM;
dxdt_RVHY = KRV * ((PVRn - 1.0 > 0.0) ? PVRn - 1.0 : 0.0) - KRVOUT * RVHY;

// ==========================================================================
// 11. PK ODEs
// ==========================================================================
dxdt_CAFG = caf_in - CAF_KA * CAFG;
dxdt_CAFC = CAF_KA * CAFG - caf_cl * Ccaf;
dxdt_DEXC = dex_in - DEX_CL * wt * Cdex;
dxdt_HCC  = hc_in  - HC_CL  * wt * Chc;
dxdt_BUDL = bud_in - BUD_KLS * BUDL;
dxdt_BUDC = BUD_KLS * BUDL - BUD_CL * wt * Cbudc;
dxdt_RETS = vita_in + RET_DIET - RET_KR * RETS;
dxdt_RETP = RET_KR * RETS - RET_CL * wt * Cret;
dxdt_AZIC = azi_in - AZI_CL * wt * Cazi;
dxdt_SILC = sil_in - SIL_CL * wt * Csil;
dxdt_DEXEQ = dex_rate + HC_POT * hc_rate
             + (bud_in > 0.0 ? BUD_POT * 0.05 * bud_in / wt : 0.0);

// ==========================================================================
// 12. BODY WEIGHT
// ==========================================================================
double gr = GRMAX * (1.0 - AW_DEX * GRocc_s)
                  * (1.0 - AW_INFL * NFKB / (1.0 + NFKB))
                  * (1.0 + (NUTR > 0.5 ? NUTR_EFF : 0.0));
double wl = WLOSS * exp(-SOLVERTIME / TAU_WL);
dxdt_WT = WT * (gr - wl);

// ==========================================================================
// 13. ENDPOINT ACCUMULATORS
// ==========================================================================
double early_w = 1.0 + W_EARLY * exp(-SOLVERTIME / 7.0);
dxdt_NDIC  = W_DEX * (dex_rate + HC_POT * hc_rate) * early_w
             + W_HYPOX * hb
             + W_HYPOCAP * HYPOCAP * MVF * (1.0 - VTV);
dxdt_VDAYS  = MVF;
dxdt_O2DAYS = (FiO2 > FIO2_THR) ? 1.0 : 0.0;
dxdt_HAZ    = H0 + H_HYPOX * hb + H_PVR * ((PVRn > 1.5) ? PVRn - 1.5 : 0.0)
              + H_SEP * sepsis + H_G3 * MVF;

$TABLE
double PMAout = GA + TIME / 7.0;
double wt_o   = (WT > 0.35) ? WT : 0.35;

double Ccaf_o = CAFC / (CAF_VD * wt_o);
double Cdex_o = DEXC / (DEX_VD * wt_o);
double Chc_o  = HCC  / (HC_VD  * wt_o);
double Cret_o = RETP / (RET_VD * wt_o);
double Csil_o = SILC / (SIL_VD * wt_o);
double Cazi_o = AZIC / (AZI_VD * wt_o);
double Cbud_o = BUDL / (BUD_VL * wt_o);

double DXEs_o = Cdex_o + HC_POT * Chc_o + BUD_POT * (BUDC / (BUD_VD * wt_o));
double DXEl_o = Cdex_o + HC_POT * Chc_o + BUD_POT * Cbud_o;
double GRo_s  = DXEs_o / (GR_EC50 + DXEs_o);
double GRo_l  = DXEl_o / (GR_EC50 + DXEl_o);

double wSo = (PMAout < PMAPK) ? SDW_L : SDW_R;
double zSo = (PMAout - PMAPK) / wSo;
double SDEVo = exp(-0.5 * zSo * zSo);

double alv_o = (ALV  > 0.02) ? ALV  : 0.02;
double cap_o = (CAPD > 0.02) ? CAPD : 0.02;
double Ecmp  = GR_ECOMP * GRo_l;
double Ebd_o = (BRONCHO > 0.5) ? BRONCHO_E : 0.0;
double phi_now = bpd_phi(PMAout, PMAPK, SDW_L, SDW_R);
double r_prog_o = KALV / bpd_phi(36.0, PMAPK, SDW_L, SDW_R);
double ALV_ideal = ALVMAX - (ALVMAX - A20) * exp(-r_prog_o * phi_now);

double rel_ao = (alv_o / ALV_ideal > 1e-4) ? alv_o / ALV_ideal : 1e-4;
double rel_co = (cap_o / ALV_ideal > 1e-4) ? cap_o / ALV_ideal : 1e-4;
double Dmd_so = 1.0 / (pow(rel_ao, PALV) * pow(rel_co, PCAP));
Dmd_so = Dmd_so / (1.0 + 0.35 * Ecmp);
double Rexo = (Dmd_so - DTHR > 0.0) ? Dmd_so - DTHR : 0.0;

double sept_sato = SEPT / (1.0 + SEPT);
double lw_exo = (LW - LW_BASE > 0.0) ? LW - LW_BASE : 0.0;
double sp_exo = (sept_sato - SEPT_BASE > 0.0) ? sept_sato - SEPT_BASE : 0.0;
double sh_argo = KSH * (KLWO / 1.28 * lw_exo + 0.5 * sp_exo
                        + KASMO * ASM * (1.0 - Ebd_o));
sh_argo = sh_argo / (1.0 + 0.35 * Ecmp);
double Sho = sh_argo / (1.0 + sh_argo);
double Dmdo = Dmd_so * (1.0 + KSEPTO * sp_exo + KLWO * lw_exo);

double bando = (SPO2HI > 0.5) ? 1.0 : BANDF;
double FIO2 = 0.21 + 0.79 * (1.0 - (1.0 - Sho) * exp(-KFIO2 * Rexo));
FIO2 = 0.21 + (FIO2 - 0.21) * bando;
if (FIO2 > 1.0)  FIO2 = 1.0;
if (FIO2 < 0.21) FIO2 = 0.21;

double apn_o = AP0 * exp(-TIME / TAU_AP)
               * (1.0 - CAF_DRIVE * (CAF_EMAX * Ccaf_o / (CAF_EC50 + Ccaf_o)));
double hbo = ((SPO2HI > 0.5) ? 0.0 : BANDHX) + 0.55 * apn_o;

double XSo = cap_o;
double cgmpo = NOB * (1.0 + SIL_EMAX * Csil_o / (SIL_EC50 + Csil_o))
               + INO_EMAX * INO_PPM / (INO_EC50 + INO_PPM);
double hpvo = hbo / (1.0 + 1.2 * ((cgmpo - 1.0 > 0.0) ? cgmpo - 1.0 : 0.0));
double PVR = (1.0 / pow(XSo, PXS)) * (1.0 + KHPV * hpvo) * (1.0 + KVR * VREM);

// ---- Jensen/NICHD 2019 grade, evaluated on the support the model needs ----
double GRADE = 0.0;
if      (MVF >= 0.50)                      GRADE = 3.0;
else if (SUP >= THRNIV)                    GRADE = 2.0;
else if (FIO2 > FIO2_THR)                  GRADE = 1.0;
double PSURV = exp(-HAZ);
double NETU  = PSURV * ((GRADE < 0.5) ? 1.0 : 0.0) - W_NDI * NDIC;

// ---- the "surface debt": ALV_ideal was computed above from the same
//      closed-form window integral, so this is the exact shortfall ---------
double ALV_PCT = 100.0 * ALV / ALV_ideal;

$CAPTURE @annotated
PMAout  : Postmenstrual age (weeks)
FIO2    : Model-required FiO2 to hold the SpO2 target band
GRADE   : BPD grade by mode of support (0 none, 1, 2, 3)
SDEVo   : Septation drive S_dev(PMA)
ALV_ideal: Alveolar surface of an uninjured fetus at the same PMA
ALV_PCT : Alveolar surface as % of the gestation-matched ideal
PVR     : Pulmonary vascular resistance (1.0 = healthy)
Ccaf_o  : Caffeine concentration (mg/L)
Cdex_o  : Dexamethasone concentration (mg/L)
Chc_o   : Hydrocortisone concentration (mg/L)
Cret_o  : Plasma retinol (micromol/L)
Csil_o  : Sildenafil concentration (mg/L)
Cazi_o  : Azithromycin concentration (mg/L)
Cbud_o  : Budesonide lung concentration (mg/L)
GRo_s   : Systemic GR occupancy (drives NDI cost and growth failure)
GRo_l   : Lung GR occupancy (drives anti-inflammatory and antiproliferative effects)
Dmdo    : Oxygenation demand index (1.0 = healthy)
hbo     : Hypoxaemia burden
PSURV   : Modelled probability of survival to the current time
NETU    : Net utility = survival without BPD minus W_NDI x NDI cost
'

mod <- mcode("bpd_qsp", bpd_code, soloc = tempdir())

