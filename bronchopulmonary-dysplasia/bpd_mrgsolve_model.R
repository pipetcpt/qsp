## ============================================================================
##  A5. THE SpO2 TARGET IS A TRADE-OFF, NOT AN OPTIMUM
## ============================================================================
#' Sweep the oxygen-saturation target band
#'
#' Reproduces the shape of the NeOProM/SUPPORT/BOOST-II result: the low band
#' reduces hyperoxic lung and retinal injury but costs survival, so the two
#' curves cross and the "best" band depends entirely on the weight put on
#' mortality relative to lung and eye.
BPD_spo2_sweep <- function(bands = seq(0, 1, by = 0.25)) {
  out <- lapply(bands, function(b) {
    p <- modifyList(BPD_reference, list(CAF_T0 = 1))
    p$BANDF  <- 1.0 - 0.14 * (1 - b)   # 0 = 85-89%, 1 = 91-95%
    p$SPO2HI <- 1
    p$KHYPOX <- 0.90 * (1 + 0.9 * (1 - b))
    s <- BPD_run(p, end_pma = 36.01); r <- tail(s, 1)
    data.frame(band_index = b, FiO2_36 = round(r$FIO2, 3),
               ALV36 = round(r$ALV, 4), grade = r$GRADE,
               P_survive = round(r$PSURV, 4),
               surv_no_BPD = round(r$PSURV * (r$GRADE < 1), 4),
               PVR36 = round(r$PVR, 3))
  })
  dplyr::bind_rows(out)
}

## ============================================================================
##  A6. PK SANITY CHECKS — the model must reproduce published neonatal PK
## ============================================================================
#' Caffeine half-life across PMA, and the concentration achieved by CAP dosing
BPD_caffeine_pk_check <- function() {
  pma  <- c(26, 28, 32, 36, 44, 52, 60)
  clkg <- 4.60 * pma^4 / (60^4 + pma^4)          # L/day/kg
  tibble::tibble(
    PMA_weeks   = pma,
    CL_L_h_kg   = round(clkg / 24, 4),
    t_half_h    = round(log(2) * 0.85 / clkg * 24, 1),
    Css_5mgkg_citrate  = round(0.5 * 5  / clkg, 1),
    Css_10mgkg_citrate = round(0.5 * 10 / clkg, 1)
  )
}

