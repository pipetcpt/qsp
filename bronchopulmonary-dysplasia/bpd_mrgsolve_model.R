##  Bronchopulmonary Dysplasia (BPD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Bronchopulmonary dysplasia — the chronic lung disease of
##             prematurity, defined (Jensen/NICHD 2019) by the MODE of
##             respiratory support still required at 36 weeks postmenstrual age
##             (PMA): grade 1 = nasal cannula <=2 L/min, grade 2 = >2 L/min or
##             non-invasive positive pressure, grade 3 = invasive mechanical
##             ventilation.
##
##  THE ORGANISING IDEA OF THIS MODEL
##  ---------------------------------
##  Almost every BPD model in the literature is written as a damage model:
##  oxygen and pressure injure the lung, injury accumulates, the lung ends up
##  scarred. That framing is wrong in a way that matters for drug development,
##  because it predicts that a more potent anti-injury drug given at any time
##  should help — and forty years of trials say otherwise.
##
##  This model poses BPD instead as a SCHEDULING problem.
##
##  Alveolarisation is a developmental PROGRAMME that runs on the PMA clock,
##  not on the postnatal clock. Let S_dev(PMA) be the septation drive. Its
##  integral over a lifetime is FINITE and it peaks at ~32 weeks PMA — i.e.
##  precisely while a 24-week infant is lying on a ventilator. Injury does not
##  primarily destroy alveoli; it closes a multiplicative GROWTH GATE
##
##      G(t) = [VEGF^wv * cGMP^wn * IGF1^wi * RA^wr * EPC^we] / (1 + a*TGFb)
##
##  and the surface actually built is
##
##      ALV(36 wk) = integral of  k * S_dev(PMA(t)) * G(t) * (1 - ALV/ALVmax) dt
##
##  Three consequences fall straight out of that structure, and they are the
##  reason this file exists:
##
##   (1) TIMING BEATS POTENCY. Because S_dev is decaying while the infant is
##       in the NICU, a therapy that opens G by 40% on day 1 buys more surface
##       than one that opens it by 100% on day 21. There is a computable
##       crossover day. This is PREMILOC vs DART, expressed as arithmetic
##       rather than as a difference of opinion about steroids.
##
##   (2) THERAPIES SPLIT INTO THREE CLASSES BY WHICH TERM THEY TOUCH, and the
##       class — not the potency — sets the ceiling:
##         (a) EXPOSURE reducers shrink the injury input   (caffeine via
##             ventilator days, LISA/nCPAP, volume-targeted ventilation,
##             permissive hypercapnia, PDA closure, SpO2 band);
##         (b) TRANSDUCTION suppressors shrink injury -> G  (hydrocortisone,
##             dexamethasone, intratracheal budesonide, azithromycin in
##             Ureaplasma-positive infants, IL-1Ra);
##         (c) PROGRAMME supporters raise G directly       (vitamin A/retinoate,
##             rhIGF-1/BP3, MSC, the small direct A2A arm of caffeine).
##       Anything that touches NONE of the three can move a number for hours
##       and change nothing at 36 weeks. Furosemide is the model's designated
##       example and it is included on purpose.
##
##   (3) THE LOST WINDOW IS THE READOUT, NOT THE SUPPORT LEVEL. The model
##       carries an explicit counter LOSTW = integral of k*S_dev*(1-G)*
##       (1-ALV/ALVmax) dt — the surface that was never built. Two infants can
##       share a 36-week FiO2 and carry completely different LOSTW, and it is
##       LOSTW, not FiO2, that predicts the adult FEV1 plateau.
##
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.0)
##  Time     : DAYS of postnatal life. t = 0 is birth. PMA(t) = GA + t/7 weeks.
##
##  Scope    : 37 ODE compartments —
##             (a) 11 PK/exposure states with REAL neonatal pharmacokinetics
##                 in mg and mg/L (not arbitrary units): caffeine depot +
##                 central (PMA-maturing clearance, t1/2 90 h -> 6 h),
##                 dexamethasone, hydrocortisone, intratracheal budesonide
##                 (lung + systemic), hepatic retinol store + plasma retinol,
##                 azithromycin, sildenafil, and a cumulative dexamethasone-
##                 equivalent dose ledger;
##             (b) 5 inflammation states: NF-kB activity, IL-1beta, airway
##                 neutrophil/elastase burden, TGF-beta1, ROS;
##             (c) 5 growth-gate states: VEGF, NO bioavailability, IGF-1,
##                 retinoate signalling, endothelial progenitor pool;
##             (d) 5 structural states: alveolar surface, microvascular
##                 density, septal thickening, airway smooth muscle, lung water;
##             (e) 3 support/exposure states: support intensity, fraction of
##                 day on invasive MV, Ureaplasma burden;
##             (f) 2 pulmonary-vascular states: vascular remodelling, RV
##                 hypertrophy;
##             (g) 6 accumulators that ARE the clinically reported endpoints:
##                 body weight, LOSTW (lost developmental window), NDI cost,
##                 ventilator days, supplemental-oxygen days, mortality hazard.
##
##  Units    : PK in mg (amounts) and mg/L (concentrations) — caffeine doses
##             are entered as CAFFEINE CITRATE mg/kg and halved internally to
##             caffeine base. Steroid exposure is expressed throughout as
##             DEXAMETHASONE-EQUIVALENT mg/L so that hydrocortisone,
##             dexamethasone and budesonide share one receptor-occupancy
##             equation. Structural states are normalised so that 1.0 = the
##             value of a HEALTHY infant at 36 weeks PMA; ALV can exceed 1.0
##             after term because alveolarisation continues. Weight in kg.
##
##  Scenarios: 15 prebuilt — see BPD_simulate_scenarios() at the bottom.
##
##  ==========================  IMPORTANT CAVEAT  ==============================
##  This is a MECHANISTIC TEACHING/RESEARCH model, calibrated to reproduce the
##  DIRECTION and rough MAGNITUDE of the landmark trials named in
##  bpd_references.md (CAP, PREMILOC, DART, Tyson vitamin A, Yeh budesonide,
##  NeOProM/SUPPORT, SAIL, the LISA meta-analyses). It has NOT been fitted to
##  individual patient data and MUST NOT be used for clinical decisions,
##  dosing, or regulatory submission. Where the model and the literature
##  disagree, bpd_references.md and the directory README say so explicitly
##  rather than hiding it.
##  ============================================================================

