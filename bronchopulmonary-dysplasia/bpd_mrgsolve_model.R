#' Simulate one scenario out to a chosen PMA
#'
#' @param pars named list of parameter overrides
#' @param end_pma  PMA (weeks) at which to stop; 36 is the definitional stop,
#'                 but the model is informative out to 50-60 weeks because the
#'                 septation window is still open there.
BPD_run <- function(pars = BPD_reference, end_pma = 40, dt = 0.25) {
  ga  <- if (!is.null(pars$GA)) pars$GA else 25
  end <- (end_pma - ga) * 7
  mod %>%
    param(pars) %>%
    mrgsim(end = end, delta = dt, atol = 1e-8, rtol = 1e-6, hmax = 0.25) %>%
    as_tibble()
}

#' Endpoint summary at exactly 36 weeks PMA (the definitional clock stop)
BPD_endpoints <- function(sim, ga) {
  t36 <- (36 - ga) * 7
  r <- sim[which.min(abs(sim$time - t36)), ]
  tibble::tibble(
    PMA36_day   = round(t36, 1),
    ALV36       = round(r$ALV, 4),
    ALV_pct_ideal = round(r$ALV_PCT, 1),
    CAP36       = round(r$CAPD, 4),
    LOSTW       = round(r$LOSTW, 4),
    FiO2_36     = round(r$FIO2, 3),
    grade       = r$GRADE,
    MV_frac_36  = round(r$MVF, 3),
    vent_days   = round(r$VDAYS, 1),
    O2_days     = round(r$O2DAYS, 1),
    PVR36       = round(r$PVR, 3),
    RVH36       = round(r$RVHY, 3),
    weight36    = round(r$WT, 3),
    DEXEQ_mgkg  = round(r$DEXEQ, 3),
    NDI_cost    = round(r$NDIC, 4),
    P_survive   = round(r$PSURV, 4),
    net_utility = round(r$NETU, 4)
  )
}

#' Run every prebuilt scenario and return one endpoint table
BPD_simulate_scenarios <- function(scenarios = BPD_scenarios, end_pma = 40) {
  out <- lapply(names(scenarios), function(nm) {
    p  <- scenarios[[nm]]
    s  <- BPD_run(p, end_pma = end_pma)
    e  <- BPD_endpoints(s, ga = if (!is.null(p$GA)) p$GA else 25)
    dplyr::bind_cols(tibble::tibble(scenario = nm), e)
  })
  dplyr::bind_rows(out)
}

## ============================================================================
##  A1. THE GESTATIONAL GRADIENT COMES FROM THE WINDOW, NOT FROM A COEFFICIENT
## ============================================================================
#' How much of the alveolarisation programme is still ahead at birth?
#'
#' Returns, for each GA, the fraction of the total S_dev integral that has NOT
#' yet been spent at the moment of birth. This is the quantity that has to be
#' completed EX UTERO, on a ventilator, in oxygen — and it is why the GA
#' gradient of BPD is as steep as it is.
BPD_window_remaining <- function(ga = c(22, 24, 26, 28, 30, 32, 34, 37),
                                 pmapk = 32, wl = 4, wr = 14) {
  sdev <- function(p) {
    w <- ifelse(p < pmapk, wl, wr)
    exp(-0.5 * ((p - pmapk) / w)^2)
  }
  tot <- integrate(sdev, 20, 120)$value
  tibble::tibble(
    GA = ga,
    frac_spent_in_utero = round(sapply(ga, function(g)
      integrate(sdev, 20, g)$value) / tot, 3),
    frac_remaining_ex_utero = round(1 - sapply(ga, function(g)
      integrate(sdev, 20, g)$value) / tot, 3),
    frac_of_window_between_birth_and_36wk = round(sapply(ga, function(g)
      integrate(sdev, g, 36)$value) / tot, 3)
  )
}

## ============================================================================
##  A2. TIMING vs POTENCY — the crossover day
## ============================================================================
#' Compare an EARLY WEAK gate-opener against a LATE STRONG one
#'
#' Both arms are given the same idealised "gate opener" implemented as a
#' fractional reduction of IL-1beta (a transduction-class drug). The early arm
#' is weak (eff_early), the late arm is strong (eff_late). The function returns
#' the 36-week alveolar surface for each start day so the crossover can be read
#' off directly.
BPD_timing_vs_potency <- function(eff_early = 0.40, eff_late = 1.00,
                                  start_days = c(1, 3, 5, 7, 10, 14, 21, 28),
                                  base = BPD_reference) {
  run1 <- function(eff, t0) {
    p <- modifyList(base, list(IL1RA = 1, IL1RA_E = eff, IL1RA_T0 = t0,
                               IL1RA_T1 = 999))
    s <- BPD_run(p, end_pma = 36.01)
    tail(s$ALV, 1)
  }
  base_alv <- tail(BPD_run(base, end_pma = 36.01)$ALV, 1)
  out <- lapply(start_days, function(t0) {
    data.frame(
      start_day  = t0,
      ALV36_weak   = round(run1(eff_early, t0), 4),
      ALV36_strong = round(run1(eff_late,  t0), 4)
    )
  })
  out <- dplyr::bind_rows(out)
  out$ALV36_untreated <- round(base_alv, 4)
  # the claim: early-weak beats late-strong up to the crossover day
  early_weak <- out$ALV36_weak[out$start_day == min(start_days)]
  out$early_weak_still_wins <- out$ALV36_strong < early_weak
  out
}

## ============================================================================
##  A3. WHERE DOES CAFFEINE'S BENEFIT ACTUALLY COME FROM?
## ============================================================================
#' Decompose caffeine into its exposure arm and its biology arm
#'
#' S01 has both arms; S02 has only the direct A2A alveolarisation arm. The
#' difference between them is the share of caffeine's 36-week benefit that is
#' attributable to getting the infant off the ventilator sooner rather than to
#' any direct effect on the lung.
BPD_caffeine_decomposition <- function() {
  arms <- list(
    "no caffeine"        = BPD_scenarios[["S00 reference (no adjunct)"]],
    "caffeine, full"     = BPD_scenarios[["S01 caffeine (CAP dosing)"]],
    "caffeine, A2A only" = BPD_scenarios[["S02 caffeine, drive arm OFF (biology arm only)"]]
  )
  tab <- BPD_simulate_scenarios(arms, end_pma = 40)
  base <- tab$ALV36[1]
  tab$delta_ALV <- round(tab$ALV36 - base, 4)
  tab$share_of_full_benefit <- round(tab$delta_ALV /
                                       (tab$ALV36[2] - base), 3)
  tab[, c("scenario", "ALV36", "delta_ALV", "share_of_full_benefit",
          "vent_days", "grade", "LOSTW")]
}

## ============================================================================
##  A4. THE VIRTUAL POPULATION — turning one infant into an incidence
## ============================================================================
#' Deterministic grid population (no RNG, fully reproducible)
#'
#' Two covariates dominate between-infant variance in this model: the severity
#' of the antenatal hit and the individual sensitivity of the lung to
#' mechanical injury. A weighted 7x7 grid over those two reproduces a BPD
#' incidence that can be compared with the CAP-trial control arm.
BPD_virtual_population <- function(pars = BPD_reference, end_pma = 36.01,
                                   gas = c(25, 26, 27, 28, 29),
                                   gaw = c(0.12, 0.20, 0.26, 0.24, 0.18)) {
  q  <- c(-1.5, 0, 1.5)
  wq <- exp(-0.5 * q^2); wq <- wq / sum(wq)
  gw <- gaw / sum(gaw)
  chors <- list(c(0, 0.65), c(1, 0.35))
  base_ante <- if (!is.null(pars$KANTE)) pars$KANTE else 2.24
  base_vili <- if (!is.null(pars$KVILI)) pars$KVILI else 0.583

  rows <- list()
  for (gi in seq_along(gas)) for (ch in chors)
    for (i in seq_along(q)) for (j in seq_along(q)) {
      p <- pars
      p$GA <- gas[gi]; p$BW <- 0; p$CHORIO <- ch[1]
      p$KANTE <- base_ante * exp(0.40 * q[i])
      p$KVILI <- base_vili * exp(0.35 * q[j])
      r <- tail(BPD_run(p, end_pma = end_pma), 1)
      rows[[length(rows) + 1]] <- data.frame(
        w = gw[gi] * ch[2] * wq[i] * wq[j],
        grade = r$GRADE, alv = r$ALV, lostw = r$LOSTW, psurv = r$PSURV)
    }
  res <- do.call(rbind, rows)
  tibble::tibble(
    n_virtual_infants = nrow(res),
    BPD_any_pct     = round(100 * sum(res$w * (res$grade >= 1)), 1),
    BPD_grade23_pct = round(100 * sum(res$w * (res$grade >= 2)), 1),
    BPD_grade3_pct  = round(100 * sum(res$w * (res$grade >= 3)), 1),
    death_pct       = round(100 * sum(res$w * (1 - res$psurv)), 1),
    mean_ALV36      = round(sum(res$w * res$alv), 4),
    mean_LOSTW      = round(sum(res$w * res$lostw), 4),
    surv_no_BPD_pct = round(100 * sum(res$w * res$psurv * (res$grade < 1)), 1)
  )
}

