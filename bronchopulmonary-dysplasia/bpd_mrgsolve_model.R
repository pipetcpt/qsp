# BPD QSP model — alveolarisation as a scheduling problem
# ALV(36wk) = int k*S_dev(PMA)*G(t)*(1-ALV/ALVmax) dt ; LOSTW = the shortfall

$GLOBAL
// Closed-form integral of the septation-drive window S_dev from PMA 20 to p.
// S_dev is a two-sided Gaussian in PMA with different widths either side of
// the peak, so its integral is a difference of error functions — no numerical
// quadrature is needed anywhere in the model, and the "uninjured ideal"
// trajectory is therefore exact rather than approximate.
#define BPD_SQRT2      1.41421356237309505
#define BPD_SQRT_PI_2  1.25331413731550025

double bpd_gauss_int(double a, double b, double m, double w) {
  return w * BPD_SQRT_PI_2 * (erf((b - m) / (w * BPD_SQRT2))
                            - erf((a - m) / (w * BPD_SQRT2)));
}

double bpd_phi(double pma, double pk, double wl, double wr) {
  if (pma <= 20.0) return 0.0;
  if (pma <= pk)   return bpd_gauss_int(20.0, pma, pk, wl);
  return bpd_gauss_int(20.0, pk, pk, wl) + bpd_gauss_int(pk, pma, pk, wr);
}

