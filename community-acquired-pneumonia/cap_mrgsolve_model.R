double kdrug_p = FTOL_BL*kbl + FTOL_MAC*kazi + FTOL_FQ*klvx;

//===========================================================================
// 3. Corticosteroid: ONE effect site, TWO opposite-signed arms
//===========================================================================
double gc      = (HCE > 0.0) ? HCE : 0.0;
double GC_ANTI = 1.0 - IMAX_GC  * gc / (IC50_GC  + gc);   // protective: NF-kB transrepression
double GC_PHAG = 1.0 - IMAX_GCP * gc / (IC50_GCP + gc);   // ADVERSE: phagocyte suppression
double GC_MIG  = 1.0 - IMAX_GCN * gc / (IC50_GCP + gc);   // annexin-A1: less neutrophil influx

//===========================================================================
// 4. Macrolide immunomodulation -- travels the toxin/cytokine channel,
//    survives full macrolide RESISTANCE (MIC_AZI = 64 kills kazi, not this)
//===========================================================================
double MAC_ANTI = 1.0 - IMAX_MAC  * Cazi_elf / (IC50_MAC + Cazi_elf);
double MAC_PLY  = 1.0 - IMAX_PLY  * Cazi_elf / (IC50_MAC + Cazi_elf);
double MAC_MIG  = 1.0 - IMAX_MIGM * Cazi_elf / (IC50_MAC + Cazi_elf);

//===========================================================================
// 5. Pathogen dynamics
//===========================================================================
double virfac  = 1.0 + EVIR_ADH * VIR / (0.3 + VIR);
double grow    = KG * virfac * be * (1.0 - (be + bp)/BMAX);

double il10sup = 1.0 - IMAX_IL10 * IL10 / (IC50_IL10 + IL10);
double opson   = (VACC > 0.5 ? OPS_VACC : 1.0) * (1.0 - 0.65*IMMSUP);
double phagcap = (KPHAG_AM*AM + KPHAG_N*NL) * opson * il10sup * GC_PHAG;
double hostkill_e = phagcap * be / (be + KM_PHAG);
double hostkill_p = FTOL_HOST * phagcap * bp / (bp + KM_PHAG);

double drugkill_e = kdrug * be;
double drugkill_p = kdrug_p * bp;

dxdt_BE = grow - hostkill_e - drugkill_e - KPERS*be + KREV*bp - KTRANS*perm*be;
dxdt_BP = KPERS*be - KREV*bp - hostkill_p - drugkill_p;
dxdt_BB = KTRANS*perm*be*1e-3 - (KCLBB + 0.6*kdrug)*bb;
dxdt_VIR = -KVIR * VIR;

//===========================================================================
// 6. PAMP pool -- THE lysis-coupled term. beta-lactam kill is a PAMP SOURCE.
//===========================================================================
double lysis_release = (YLYS_BL*kbl + YLYS_FQ*klvx + YLYS_MAC*kazi) * be;
double pamp_in = (YLIVE*grow_pos(grow) + YHOST*hostkill_e + lysis_release)
                 * (1.0 - PLYFRAC*(1.0 - MAC_PLY));
dxdt_PAMP = pamp_in - KPAMP*pamp;

//===========================================================================
// 7. Innate immune activation
//===========================================================================
double STIM = pamp / (pamp + KMPAMP);

dxdt_AM = KAM_IN*(1.0 + EAM*STIM) - KAM_OUT*AM;

double migr = KMIG * IL8 * NB * MAC_MIG * GC_MIG * (1.0 - NL/NLMAX);
if (migr < 0.0) migr = 0.0;
dxdt_NB = KNB_OUT*NB0*(1.0 + EGCSF*(IL6 + IL1)) - KNB_OUT*NB - migr;
dxdt_NL = migr - KNL_OUT*NL;

double effero = KNL_OUT * NL;                      // apoptotic-neutrophil uptake

//===========================================================================
// 8. Cytokine network: feed-forward amplifier, damped by IL-10, SPMs,
//    corticosteroid transrepression and macrolide immunomodulation
//===========================================================================
double cytsum = TNF + IL1 + IL6;
double AMP = 1.0 + EAMP * cytsum/(KAMP + cytsum)
                 * (1.0 - ESPM*SPM/(KSPM50 + SPM));
if (AMP < 1.0) AMP = 1.0;

double src   = (STIM*AM + FNEUT_CYT*NL/10.0) * AMP * GC_ANTI * MAC_ANTI;
double srcv  = 0.55 * VIR/(0.3 + VIR) * AMP * GC_ANTI;   // viral contribution
double inflm = 1.0 - IMAX_IL10*IL10/(IC50_IL10 + IL10);

dxdt_TNF = KS_TNF *(src + srcv)*inflm - KD_TNF *TNF;
dxdt_IL1 = KS_IL1 *(src*STIM + 0.4*srcv)*inflm - KD_IL1 *IL1;   // inflammasome-gated
dxdt_IL6 = KS_IL6 *(src + srcv)*inflm - KD_IL6 *IL6;
dxdt_IL8 = KS_IL8 *(src + 0.3*srcv)*inflm - KD_IL8 *IL8;
dxdt_IL10 = KS_IL10*cytsum/(KAMP + cytsum)*GC_ANTI*0.6 + KD_IL10*6.0 - KD_IL10*IL10;
dxdt_SPM = KS_SPM*effero*(1.0 + 2.0*(1.0 - STIM)) - KD_SPM*SPM;

//===========================================================================
// 9. Acute-phase biomarkers. CRP tracks IL-6; PCT tracks BACTERIAL PAMP and
//    is suppressed by the antiviral interferon programme -> the two markers
//    separate in viral disease and PCT falls first after sterilisation.
//===========================================================================
dxdt_CRP = KS_CRP * IL6/(IL6 + KM_CRP_IL6) + KD_CRP*CRP0 - KD_CRP*CRP;
double pct_vir = 1.0 - IPCT_VIR * VIR/(0.3 + VIR);
dxdt_PCT = KS_PCT * pamp/(pamp + KM_PCT) * pct_vir + KD_PCT*PCT0 - KD_PCT*PCT;
dxdt_LYM = KLYM_OUT*LYM0 - KLYM_OUT*LYM - ELYM*(cytsum + 700.0*gc/(IC50_GC+gc))*LYM;

//===========================================================================
// 10. Alveolar barrier, oedema, surfactant, shunt
//===========================================================================
double injury = KS_PERM*(TNF + IL1) + KS_PERM_N*NL + EVIR_BAR*KS_PERM_N*VIR/(0.3+VIR);
dxdt_PERM = injury - KD_PERM*(perm - 1.0)*(1.0 + 0.8*SPM);

double afc = KAFC * surf * (1.0 - IAFC_IL8*IL8/(IC50_AFC + IL8));
dxdt_EDEM = KFILT*(perm - 1.0)*(1.0 - edem) - afc*edem;
dxdt_SURF = KS_SURF*(1.0 - surf) - KD_SURF*(NL/10.0 + (perm - 1.0))*surf;
dxdt_FIBP = KS_FIB*edem*edem*(1.0 + 0.5*FIBP) - KD_FIB*FIBP;

//===========================================================================
// 11. Systemic haemodynamics, lactate, kidney
//===========================================================================
double logbb = (bb > 1.0) ? log10(bb) : 0.0;
double mapdrive = KS_MAP*(TNF + IL1) + KS_MAP_BB*logbb;
double supp_extra = EVASO*VASOPRESS + EMAP_GC*gc/(IC50_GC + gc);   // mmHg-equivalents
dxdt_MAPD = mapdrive - KD_MAP*MAPD*(1.0 + supp_extra/10.0);

double mapexc = (MAPD > MAPTH) ? (MAPD - MAPTH) : 0.0;
dxdt_LACT = KS_LACT*mapexc + KS_LACT_C*cytsum + KD_LACT*LACT0 - KD_LACT*LACT;
dxdt_AKID = KS_AKI*mapexc*(1.0 - AKID) - KD_AKI*AKID;

//===========================================================================
// 12. PK
//===========================================================================
dxdt_CEFC = -CLcef/V1_CEF*CEFC - Q_CEF/V1_CEF*CEFC + Q_CEF/V2_CEF*CEFP;
dxdt_CEFP =  Q_CEF/V1_CEF*CEFC - Q_CEF/V2_CEF*CEFP;
dxdt_AMXD = -KA_AMX*AMXD;
dxdt_AMXC =  KA_AMX*AMXD*F_AMX - CLamx/V_AMX*AMXC;
dxdt_AZID = -KA_AZI*AZID;
dxdt_AZIC =  KA_AZI*AZID*F_AZI - CL_AZI/V1_AZI*AZIC - Q_AZI/V1_AZI*AZIC + Q_AZI/V2_AZI*AZIT;
dxdt_AZIT =  Q_AZI/V1_AZI*AZIC - Q_AZI/V2_AZI*AZIT;
dxdt_LVXD = -KA_LVX*LVXD;
dxdt_LVXC =  KA_LVX*LVXD*F_LVX - CLlvx/V_LVX*LVXC;
dxdt_HCC  = -CL_HC/V_HC*HCC;
dxdt_HCE  =  KE0_HC*(Chc_p - HCE);

//===========================================================================
// 13. Emergent PK/PD indices and cumulative hazard
//===========================================================================
// the "active" beta-lactam is whichever one is actually on board; if both,
// use the more demanding (higher) MIC so fT>MIC is never flattered.
double blconc = Ccef_elf + Camx_elf;
double blmic  = MIC_CEF;
if ((AMXC + AMXD) > 1e-9 && MIC_AMX > blmic) blmic = MIC_AMX;
if ((AMXC + AMXD) > 1e-9 && CEFC < 1e-9)     blmic = MIC_AMX;
double above = 1.0/(1.0 + exp(-8.0*(log((blconc + 1e-12)/blmic))));
dxdt_TAM  = above;
dxdt_AUCF = Clvx_elf;

// severity -> hazard
double qs_raw = QS0 + (QSMAX - QS0)*pow(edem,HQS)/(pow(edem,HQS)+pow(E50_QS,HQS));
double hpv    = HPV_MAX*(1.0 - IHPV_CYT*cytsum/(KAMP + cytsum));
double qs     = qs_raw*(1.0 - hpv);
double pf     = 500.0*exp(-KPF*qs);
double mapnow = MAP0 - MAPD;

double sofa_r = (pf < 100 ? 4 : (pf < 200 ? 3 : (pf < 300 ? 2 : (pf < 400 ? 1 : 0))));
double sofa_c = (VASOPRESS > 0.5 ? 3 : (mapnow < 70 ? 1 : 0));
double sofa_k = (AKID > 0.75 ? 4 : (AKID > 0.55 ? 3 : (AKID > 0.35 ? 2 : (AKID > 0.15 ? 1 : 0))));
double sofa_n = (LACT > 4.0 ? 2 : 0);
double sofa   = sofa_r + sofa_c + sofa_k + sofa_n;

double logbe = (be > 1.0) ? log10(be) : 0.0;
dxdt_CHZ = HAZ0 * exp(HAZ_SOFA*sofa + HAZ_AGE*(AGE > 50 ? AGE - 50 : 0)
                      + HAZ_BB*logbb + 0.10*logbe + 0.9*IMMSUP);

[TABLE]
double edm  = (EDEM < 0) ? 0 : ((EDEM > 0.98) ? 0.98 : EDEM);
double cyts = TNF + IL1 + IL6;

// ---- gas exchange ---------------------------------------------------------
double qsr  = QS0 + (QSMAX - QS0)*pow(edm,HQS)/(pow(edm,HQS)+pow(E50_QS,HQS));
double hpvf = HPV_MAX*(1.0 - IHPV_CYT*cyts/(KAMP + cyts));
double Qs   = qsr*(1.0 - hpvf);
double PF   = 500.0*exp(-KPF*Qs);
double PaO2 = PF*FIO2;
double SpO2 = 100.0/(23400.0/(pow(PaO2,3.0) + 150.0*PaO2) + 1.0);
if (SpO2 > 99.5) SpO2 = 99.5;

// ---- vitals ---------------------------------------------------------------
double Temp = TEMP0 + (1.0 - ANTIPYR)*KTEMP*(IL6 + IL1)/(KMTEMP + IL6 + IL1);
double MAPv = MAP0 - MAPD;
double RR   = RR0 + KRR_QS*Qs + KRR_CYT*cyts;
double HR   = HR0 + KHR_T*(Temp - TEMP0) + KHR_MAP*MAPD;

// ---- scores ---------------------------------------------------------------
double sr = (PF < 100 ? 4 : (PF < 200 ? 3 : (PF < 300 ? 2 : (PF < 400 ? 1 : 0))));
double sc = (VASOPRESS > 0.5 ? 3 : (MAPv < 70 ? 1 : 0));
double sk = (AKID > 0.75 ? 4 : (AKID > 0.55 ? 3 : (AKID > 0.35 ? 2 : (AKID > 0.15 ? 1 : 0))));
double sn = (LACT > 4.0 ? 2 : 0);
double SOFA = sr + sc + sk + sn;

double conf   = (LACT > 4.0 || MAPv < 65) ? 1 : 0;         // confusion surrogate
double curb   = conf + (AKID > 0.35 ? 1 : 0) + (RR >= 30 ? 1 : 0)
                + (MAPv < 65 ? 1 : 0) + (AGE >= 65 ? 1 : 0);

// ---- Halm criteria for clinical stability ---------------------------------
double stable = ((Temp <= 37.8) && (HR <= 100) && (RR <= 24) && (MAPv >= 70)
                 && (SpO2 >= 90)) ? 1 : 0;

// ---- exposure indices -----------------------------------------------------
double hrs   = (TIME > 0.0) ? TIME : 1.0;
double fTMIC = 100.0*TAM/hrs;                                   // % of elapsed time
double fAUCMIC = AUCF/MIC_LVX;                                  // running fAUC/MIC
double Mort  = 100.0*(1.0 - exp(-CHZ));                         // cumulative mortality %

// ---- concentrations (report) ----------------------------------------------
double Ccef  = CEFC/V1_CEF;
double Cazie = (AZIT/V2_AZI)*KP_AZI_ELF*FU_AZI;
double Clvxe = (LVXC/V_LVX)*FU_LVX*PEN_LVX;
double Ccefe = (CEFC/V1_CEF)*FU_CEF*PEN_CEF;
double Camxe = (AMXC/V_AMX)*FU_AMX*PEN_AMX;
double Chc   = HCC/V_HC;
double Gluc  = 5.4 + EGLU_GC*HCE/(IC50_GC + HCE);

double logBE = (BE > 1.0) ? log10(BE) : 0.0;
double logBP = (BP > 1.0) ? log10(BP) : 0.0;
double logBB = (BB > 1.0) ? log10(BB) : 0.0;

