capture Persisters_log10      = logBP;
capture Bacteraemia_log10     = logBB;
capture PAMP_pool             = PAMP;
capture Ceftriaxone_plasma    = Ccef;
capture Ceftriaxone_ELF_free  = Ccefe;
capture Amoxicillin_ELF_free  = Camxe;
capture Azithromycin_ELF      = Cazie;
capture Levofloxacin_ELF_free = Clvxe;
capture Hydrocortisone_plasma = Chc;
capture fT_above_MIC_pct      = fTMIC;
capture fAUC_over_MIC         = fAUCMIC;
capture Alveolar_macrophage   = AM;
