##  Community-Acquired Pneumonia (CAP) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Community-acquired pneumonia, pneumococcal-archetype. Micro-
##             aspiration of colonising Streptococcus pneumoniae -> alveolar
##             replication -> PAMP release (LTA/peptidoglycan/CpG DNA/
##             pneumolysin) -> TLR2/4/9-NLRP3-NF-kB innate activation ->
##             feed-forward TNF/IL-1b/IL-6/IL-8 amplification -> neutrophil
##             recruitment, alveolar-capillary barrier failure, protein-rich
##             oedema and consolidation -> intrapulmonary shunt -> hypoxaemia;
##             with systemic spill-over (bacteraemia, vasoplegia, lactate, AKI)
##             and a resolution arm (efferocytosis, SPMs, alveolar fluid
##             clearance) that is rate-limiting for radiographic recovery.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  ---------------------------------------------------------------------------
##  THE THREE STRUCTURAL COMMITMENTS (why this model is not the usual cartoon)
##  ---------------------------------------------------------------------------
##  Most CAP models write "antibiotic kills bug -> patient improves". That
##  cannot simultaneously hold six facts that the CAP literature insists on:
##
##   (a) fT>MIC and fAUC/MIC are not inputs. They are the emergent time-integral
##       of a saturating concentration-effect curve. So they are NOT parameters
##       here: TAM and AUCF are ODE accumulators, and the class difference
##       between ceftriaxone (flat Emax, low Hill) and levofloxacin (steep
##       Hill) falls out of the two Hill coefficients rather than being
##       hard-coded as "time-dependent" vs "concentration-dependent".
##
##   (b) KILLING IS A PAMP SOURCE, NOT A PAMP SINK. beta-lactams kill by
##       PBP inhibition -> LytA-mediated autolysis -> a bolus of cell wall and
##       pneumolysin into the alveolus. Non-lytic killing (macrolide, and to a
##       lesser degree fluoroquinolone) liberates far less. This model makes
##       PAMP release proportional to (kill rate x a drug-specific lysis yield
##       YLYS), which is what generates the observed EARLY (6-24 h) post-first-
##       dose inflammatory surge and clinical deterioration, and is why adding
##       a macrolide helps in severe pneumococcal CAP even when the isolate is
##       macrolide-RESISTANT: its benefit travels the toxin/cytokine channel
##       (PLY suppression + IL-8/neutrophil damping), not the kill channel.
##       Setting MIC_AZI = 64 (ermB) leaves KILL_AZI ~ 0 while MAC_IMM persists.
##
##   (c) CORTICOSTEROID IS TWO-ARMED AND ITS SIGN IS CONDITIONAL. The GC effect
##       compartment feeds BOTH a beneficial NF-kB transrepression term (damps
##       the cytokine amplifier, the barrier, the shunt, the vasoplegia) AND an
##       adverse term that suppresses opsonophagocytic killing. Net benefit
##       therefore depends on whether antibiotic-driven kill has made host
##       killing redundant. With a susceptible organism and an adequate
##       beta-lactam, steroid is protective (CAPE-COD). With a resistant
##       organism, or with a viral pneumonia where there is no bacterial
##       target for the antibiotic, the same dose is harmful. Scenarios 6 vs 7
##       vs 9 are built to show precisely this sign flip on one parameter set.
##
##  ---------------------------------------------------------------------------
##  Scope    : 38 ODE compartments =
##             11 PK  (ceftriaxone 2-cmt IV; amoxicillin oral 1-cmt; azithro-
##                     mycin oral 2-cmt with deep lung accumulation; levo-
##                     floxacin oral/IV 1-cmt; hydrocortisone central + effect)
##            + 5 pathogen (alveolar extracellular, tolerant/intracellular
##                     persisters, bacteraemia, free PAMP pool, respiratory
##                     virus)
##            + 9 immune (alveolar macrophage, blood & lung neutrophils,
##                     TNF-a, IL-1b, IL-6, IL-8, IL-10, pro-resolving mediators)
##            + 3 biomarker (CRP, procalcitonin, lymphocyte count)
##            + 4 lung (barrier permeability, alveolar oedema/consolidation,
##                     surfactant function, organising/fibroproliferative index)
##            + 3 systemic (MAP deficit, lactate, renal injury)
##            + 3 accumulators (fT>MIC, free ELF AUC, cumulative mortality
##                     hazard -> 28-day mortality = 1 - exp(-CHZ))
##  Time     : HOURS (default horizon 336 h = 14 d). Hours, not days, because
##             the whole point of (a) and (b) above is sub-dosing-interval
##             resolution of exposure and of the post-dose PAMP surge.
##  Units    : drug mg and mg/L; bacteria CFU/mL of epithelial lining fluid;
##             cytokines pg/mL; CRP mg/L; PCT ng/mL; cells 10^9/L; MAP mmHg;
##             lactate mmol/L; oedema and shunt dimensionless fractions.
##  Scenarios: 9 prebuilt -- see CAP_simulate_scenarios() at the bottom.
##  ---------------------------------------------------------------------------
##  Calibration anchors (see cap_references.md for the full list)
##   * Untreated natural history reproduces the pre-antibiotic-era pneumococcal
##     "crisis" at ~day 7-9 in survivors (host-only clearance), with a high
##     cumulative hazard -- KPHAG_AM/KPHAG_N and KG tuned to that.
##   * Ceftriaxone 2 g q24h: Cmax ~150 mg/L total, trough ~10 mg/L, fu ~0.10,
##     ELF/plasma free ~0.4; against MIC 0.25 mg/L this yields fT>MIC ~100%.
##   * Levofloxacin 750 mg q24h: Cmax ~8-12 mg/L, AUC24 ~100 mg.h/L, fu 0.70,
##     ELF/plasma ~1.0-1.4 -> fAUC/MIC ~70 at MIC 1 (target >=30-40).
##   * Azithromycin 500 mg q24h: serum Cmax only ~0.4 mg/L but ELF 1-3 mg/L and
##     alveolar-macrophage concentrations two orders higher -- hence the
##     separate deep AZIT compartment.
##   * Halm 1998: median time to clinical stability ~3 d on effective therapy.
##   * CAPE-COD (Dequin 2023): hydrocortisone 200 mg/d in severe CAP, 28-d
##     mortality 6.2% vs 11.9% -- scenario 6 vs 3.
##   * Uranga 2016 / Dinh 2021: 5-day (and 3-day) courses non-inferior when the
##     patient is stable -- scenario 8, with BP (persisters) governing relapse.
##   * Schuetz 2018: PCT falls faster than CRP and safely shortens therapy --
##     PCT t1/2 24 h vs CRP t1/2 19 h but with different production drivers.
##  Disclaimer: research / education / hypothesis generation only. Not fitted to
##              patient-level data; not for clinical or regulatory use.
##  ============================================================================

[PROB]
QSP model of community-acquired pneumonia coupling pneumococcal burden,
lysis-mode-dependent PAMP liberation, innate immune amplification, alveolar
barrier failure and intrapulmonary shunt, systemic organ dysfunction, and the
PK/PD of ceftriaxone, amoxicillin, azithromycin, levofloxacin and
hydrocortisone, with fT>MIC / fAUC/MIC as emergent accumulators and a
two-armed (protective + immunosuppressive) corticosteroid effect.

