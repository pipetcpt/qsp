dxdt_MP_PERIPH =  KTR_MP*MP_CENT - KTR_MP*MP_PERIPH;
dxdt_RIL_DEPOT = -KA_RIL*RIL_DEPOT;
dxdt_RIL_CENT  =  KA_RIL*RIL_DEPOT - KOUT_RIL*RIL_CENT;
dxdt_MINO_CENT = -KOUT_MINO*MINO_CENT;
dxdt_GLY_CENT  = -KOUT_GLY*GLY_CENT;
dxdt_NOGO_ITH  = -KOUT_NOGO*NOGO_ITH;
dxdt_BAC_CENT  = -KOUT_BAC*BAC_CENT;
dxdt_PGB_CENT  = -KOUT_PGB*PGB_CENT;
dxdt_MP_AUC    =  MP_CENT;                 // toxicity depends on DOSE, not timing

