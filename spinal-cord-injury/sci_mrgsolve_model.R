double mp_cyt    = EMAX_MP_CYT * MP_CENT/(EC50_MP + MP_CENT);
double mp_neu    = EMAX_MP_NEU * MP_CENT/(EC50_MP + MP_CENT);
double ril_rel   = EMAX_RIL_REL * RIL_CENT/(EC50_RIL + RIL_CENT);
double ril_up    = K_RIL_UPTAKE * RIL_CENT/(EC50_RIL + RIL_CENT);
double mino_m1   = EMAX_MINO_M1   * MINO_CENT/(EC50_MINO + MINO_CENT);
double mino_casp = EMAX_MINO_CASP * MINO_CENT/(EC50_MINO + MINO_CENT);
double gly_blk   = EMAX_GLY  * GLY_CENT/(EC50_GLY + GLY_CENT);
double nogo_blk  = EMAX_NOGO * NOGO_ITH/(EC50_NOGO + NOGO_ITH);
double bac_eff   = EMAX_BAC  * BAC_CENT/(EC50_BAC + BAC_CENT);
double pgb_eff   = EMAX_PGB  * PGB_CENT/(EC50_PGB + PGB_CENT);

