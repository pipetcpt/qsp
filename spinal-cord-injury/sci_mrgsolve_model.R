                  + K_ROS_NEUT*NEUT + K_ROS_IRON*INJ;
dxdt_ROS = ros_prod*(1.0 - mp_lp) - KOUT_ROS*ROS;

// ---------- neuroinflammation ----------
double cyto_prod = (K_CYTO_DAMP*INJ + K_CYTO_M1*M1 + K_CYTO_NEUT*NEUT)*(1.0 - mp_cyt);
dxdt_CYTO = cyto_prod - KOUT_CYTO*CYTO - K_CYTO_M2*M2*CYTO;
dxdt_NEUT = K_NEUT_IN*(CYTO/CYTO_REF)*(1.0 - mp_neu) - KOUT_NEUT*NEUT;

double m1_drive = (K_M1_DAMP*INJ + K_M1_CYTO*(CYTO/CYTO_REF)
                   + K_M1_DEBRIS*DEBRIS)*(1.0 - mino_m1);
double m1_switch = K_SWITCH*M1*(1.0 + K_MINO_SWITCH*mino_m1);
dxdt_M1 = m1_drive - KOUT_M1*M1 - m1_switch - K_M2_SUPPRESS*M2*M1;
dxdt_M2 = m1_switch + K_M2_BASE*DEBRIS - KOUT_M2*M2;

