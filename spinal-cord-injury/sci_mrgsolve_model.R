              - K_DEB_CLEAR*M2*DEBRIS - KOUT_DEB*DEBRIS;

dxdt_NEURON = -(K_DEATH_N*ap_eff + K_NEC_ISCH*isch_eff*isch_eff)*NEURON;
dxdt_OLIG   = -olig_loss*OLIG
              + K_REMYEL*(1.0/(1.0 + DEBRIS/DEB50))*(OLIG_CAP > OLIG ? OLIG_CAP - OLIG : 0.0);
