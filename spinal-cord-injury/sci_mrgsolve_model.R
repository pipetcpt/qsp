// activity and perfusion deficit are physiological, and without this the model
// would drain axons for ever at its (tiny) chronic steady state
double ap_eff   = APOP - APOP_THR;      if (ap_eff  < 0) ap_eff  = 0;
double isch_eff = ISCHEMIA - ISCH_THR;  if (isch_eff < 0) isch_eff = 0;

