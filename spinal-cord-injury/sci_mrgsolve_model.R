double isch_target = 1.0/(1.0 + exp(zi)) - isch_base0;
if (isch_target < 0) isch_target = 0;
if (isch_target > 1) isch_target = 1;
isch_target += K_ISCH_COMP*comp;
if (isch_target > 1) isch_target = 1;
dxdt_ISCHEMIA = KOUT_ISCH*(isch_target - ISCHEMIA);

// ---------- acute drivers ----------
