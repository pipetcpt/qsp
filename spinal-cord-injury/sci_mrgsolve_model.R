##  ## ---------- CALIBRATION NOTES ----------
##  ## Natural history by AIS grade is the primary calibration target, because it
##  ## is the comparator every trial arm has to beat (Fawcett 2007 Spinal Cord
##  ## 45:190; EMSCI cohort trajectories). With default parameters and standard
##  ## care (decompression at 24 h, rehabilitation 0.5 from day 14) the model
##  ## reproduces, for a C5 lesion, initial -> 1-year ISNCSCI total motor:
##  ##     AIS A  11.2 -> 12.1    (+0.9;  little conversion, gains are root-level)
##  ##     AIS B  17.3 -> 22.1    (+4.8)
##  ##     AIS C  38.9 -> 51.3    (+12.4, largest absolute gain in the mid-range)
##  ##     AIS D  67.8 -> 79.7    (+11.9)
##  ## with intensive rehabilitation (REHAB = 1.0) adding a further ~0.4-4.4
##  ## points (A +1.3, B +7.0, C +16.8, D +15.0 from baseline),
##  ## the acute nadir at day 2-3 driven by edema/ischemia conduction block, and
##  ## ~90% of the change complete by 3-6 months (KOUT_MOTOR = 0.04/d).
##  ##
##  ## Methylprednisolone (Bracken 1990 NASCIS II; Bracken 1997 NASCIS III;
##  ## Cochrane 2012): a small benefit that shrinks with delay and a toxicity
##  ## that does not. Modelled: EMAX_MP_LP = 0.60 acting on ROS PRODUCTION (the
##  ## non-genomic high-dose lipid-peroxidation mechanism) plus EMAX_MP_CYT/NEU
##  ## on the genomic arm; because ROS production is a decaying pulse, the
##  ## efficacy integral collapses with start time while MP_AUC — and therefore
##  ## MP_complication_index — is identical. The 48-h regimen doubles exposure
##  ## for no further modelled benefit, which is the NASCIS III harm signal and
##  ## the reason MPSS was downgraded in the AANS/CNS guidelines.
##  ##
##  ## Early decompression (Fehlings 2012 STASCIS; Badhiwala 2021 Lancet Neurol):
##  ## modelled as relief of COMP0, which removes both the direct compressive
##  ## ischemia (K_ISCH_COMP) and the ISP contribution (K_ISP_COMP), breaking the
##  ## compression-edema-ischemia cycle. The model reproduces a graded, not
##  ## cliff-edged, benefit across 4-72 h — the shape Badhiwala's pooled analysis
##  ## reports — and shows that leaving the cord compressed indefinitely is
##  ## categorically different from being late (peak ischemia never resolves).
##  ##
##  ## Riluzole (RISCIS programme; Grossman 2014 J Neurotrauma 31:239): 55%
##  ## presynaptic release inhibition + enhanced astrocytic uptake gives a ~9%
##  ## reduction in lesion index and, at C5, +0.2 (AIS A) to +1.8 (AIS C) motor
##  ## points — deliberately calibrated to the small, grade-dependent effect
##  ## sizes the trial programme actually reports rather than to preclinical
##  ## enthusiasm.
##  ##
##  ## Minocycline (Casha 2012 Brain 135:1224): M1 blockade plus caspase
##  ## inhibition; largest effect on the lesion index among the drug arms here,
##  ## reflecting that its target (the macrophage phase) lasts days rather than
##  ## minutes — a wider window with a smaller instantaneous flux.
##  ##
##  ## Hemodynamic management (Hawryluk 2015 J Neurotrauma 32:1958; Squair 2017
##  ## Neurology 89:1660): VASO_GAIN = 20 mmHg for 7 days is the single most
##  ## effective modelled intervention (~55% lesion-index reduction, +2 motor
##  ## points at C5 AIS A), because it acts on the SCPP term that gates the
##  ## entire cascade for as long as the cord is swollen. This is a testable
##  ## model prediction and the reason SCPP is captured as an output.
##  ##
##  ## Plasticity-directed therapy (NISCI anti-Nogo-A, Kucher 2018; activity-
##  ## based rehabilitation; Angeli 2018 / Wagner 2018 epidural stimulation):
##  ## these act on PLAST and on the G_ESTIM amplification of residual drive,
##  ## NOT on AXON — so they change function without changing the imaging
##  ## surrogate at all, the mirror image of the neuroprotection problem.
##  ##
##  ## Spasticity, pain, bladder and dysreflexia are driven by REFLEX, which
##  ## matures with K_REFLEX = 0.05/d toward (1 - 0.85*hill): the LESS descending
##  ## drive survives, the MORE reflex pathology develops. Baclofen reduces
##  ## Ashworth through the same GABA-B mechanism that produces weakness
##  ## (K_BAC_WEAK), so the modelled motor score falls when spasticity is
##  ## suppressed — the trade-off is structural, not incidental.
##  ##
##  ## What is deliberately NOT modelled: GM-1 ganglioside (Sygen), naloxone and
##  ## tirilazad (negative trials, no mechanism worth carrying); cell
##  ## transplantation and chondroitinase beyond a parameter stub (CHASE);
##  ## syringomyelia and late neurological decline; pressure injuries, VTE and
##  ## the full cardiometabolic sequelae, which appear on the mechanistic map
##  ## but have no ODE here.
