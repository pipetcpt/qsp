##  Traumatic Spinal Cord Injury (SCI) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Traumatic spinal cord injury — an IRREVERSIBLE primary mechanical
##             insult (contusion / persistent compression / axonal shear)
##             followed by a TIME-WINDOWED secondary injury cascade:
##             compression + cord swelling raise intraspinal pressure (ISP) and
##             lower spinal cord perfusion pressure (SCPP = MAP - ISP) ->
##             ischemia -> ATP failure, SUR1-TRPM4/AQP4-mediated cytotoxic edema
##             (a compression-edema-ischemia VICIOUS CYCLE) -> glutamatergic
##             excitotoxicity -> Ca2+ overload / calpain -> lipid peroxidation
##             and peroxynitrite -> neutrophil then M1/M2 macrophage
##             neuroinflammation -> caspase-mediated neuron and oligodendrocyte
##             death -> demyelination, cystic cavitation and a CSPG/Nogo-A glial
##             scar that closes the plasticity window. What survives is a small
##             fraction of descending tracts; what is recovered on top of it is
##             rehabilitation- and plasticity-dependent circuit reorganization.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 43 ODE compartments — PK for methylprednisolone (2-cmt), riluzole
##             (depot+central), minocycline, glibenclamide, intrathecal
##             anti-Nogo-A antibody, baclofen and pregabalin, plus cumulative
##             steroid exposure; hemodynamics (neurogenic shock, MAP);
##             the secondary cascade (ischemia, edema, glutamate, Ca2+, ROS,
##             neutrophils, cytokines, M1/M2, caspase activity, debris);
##             tissue state (neurons, oligodendrocytes, remyelination ceiling,
##             spared descending axons, GFAP, CSPG, lesion index); recovery
##             (critical period, plasticity, atrophy, ISNCSCI motor score);
##             and the LATE complications that reflex reorganization creates
##             (spasticity, neuropathic pain, neurogenic bladder, autonomic
##             dysreflexia), plus respiratory function and sublesional BMD.
##  Time     : DAYS (1 h = 1/24 d).  Default horizon 365 d; the acute cascade
##             lives in the first 72 h, the plasticity window in the first
##             ~3 months, and BMD/atrophy over the whole year.
##  Units    : drug compartments in dose-proportional au (mg/kg-equivalent for
##             methylprednisolone, mg-equivalent for oral/IV agents — this
##             library's standard surrogate for a full mechanistic plasma PK
##             when the disease-relevant PD is what matters); MAP in mmHg;
##             ISNCSCI total motor score 0-100; modified Ashworth 0-4; pain
##             NRS 0-10; vital capacity in % predicted; BMD as a fraction of
##             baseline; lesion index 0-1 (multiply by CAV_ML for a mL-scale
##             read-out); cascade species in normalized au.
##  Scenarios: 18 prebuilt — see SCI_simulate_scenarios() at the bottom,
##             including the two window experiments the model exists to make
##             quantitative (methylprednisolone start time; time to surgical
##             decompression) and the early-vs-late rehabilitation contrast.
##
##  THREE THINGS THIS MODEL IS BUILT TO SHOW
##  ----------------------------------------------------------------------------
##  (1) TIMING DOMINATES DOSE. Efficacy of every neuroprotectant is the integral
##      of its effect against a cascade flux that has largely run to completion
##      within ~72 h. Toxicity, by contrast, is a function of DOSE ALONE. The
##      modelled complication index of methylprednisolone is IDENTICAL whether
##      the drug is given at 1 h or at 24 h, while its benefit falls ~4-fold —
##      which is the shape of the NASCIS II post-hoc "<8 h" story, and why a
##      48-h infusion (NASCIS III) buys ~1.4x the complication index for no
##      further benefit.
##  (2) THE SURROGATE AND THE ENDPOINT ARE NOT THE SAME VARIABLE. MOTOR is a
##      steep saturating Hill function of effective descending drive CONN
##      (TH50 = 0.22, HILL = 2.2). DOUBLING spared drive is worth ~+4 ISNCSCI
##      motor points in a severe AIS A patient (below the ~5-point measurement
##      noise) and ~+29 points in the mid-range. A neuroprotectant can cut
##      lesion volume by the same ~9% in every grade and be simultaneously
##      mechanistically real and clinically undetectable — which is an argument
##      about WHO you enroll, not about whether the drug works.
##  (3) THERE ARE TWO CLOCKS, AND RECOVERY CREATES ITS OWN PATHOLOGY. The
##      neuroprotection clock runs in hours; the plasticity clock runs in weeks
##      and is shut by the CSPG scar (CRIT decays with rate K_CRIT*(1+
##      K_CRIT_SCAR*CSPG)). The SAME rehabilitation dose given from day 120
##      instead of day 14 yields a fraction of the plasticity. Meanwhile the
##      return of sublesional reflex excitability — a marker of "recovery" —
##      is exactly what generates spasticity, detrusor overactivity and
##      autonomic dysreflexia: the same bladder distension that is harmless in
##      the flaccid first week is a hypertensive emergency at 6 months.
##
##  Anchors  : Bracken 1990 N Engl J Med 322:1405 (NASCIS II, the <8 h post-hoc
##             window) and Bracken 1997 JAMA 277:1597 (NASCIS III, 48-h arm
##             toxicity); Fehlings 2012 PLoS One 7:e32037 (STASCIS: early <24 h
##             decompression, ~2.8x odds of >=2-grade AIS improvement) and
##             Badhiwala 2021 Lancet Neurol 20:117 (pooled individual-patient
##             analysis of decompression timing); Fehlings 2023/RISCIS riluzole
