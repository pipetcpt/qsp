dxdt_ABLOCK = -K_ABLOCK*ABLOCK;

// ---------- edema: the compression-edema-ischemia vicious cycle ----------
double ed_drive = (K_ED_ISCH*ISCHEMIA + K_ED_INJ*INJ
                   + K_ED_INFL*(CYTO/CYTO_REF))*(1.0 - gly_blk);
dxdt_EDEMA = ed_drive*(1.0 - EDEMA) - KOUT_EDEMA*EDEMA;

// ---------- excitotoxicity ----------
double glu_prod = (K_GLU_INJ*INJ + K_GLU_ISCH*ISCHEMIA)*(1.0 - ril_rel);
dxdt_GLU = glu_prod - KOUT_GLU*GLU*(1.0 + ril_up);
dxdt_CAI = K_CA_GLU*GLU - KOUT_CA*CAI;

// ---------- oxidative stress (the methylprednisolone target) ----------
