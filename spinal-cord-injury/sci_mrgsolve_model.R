double vaso_on  = VASO*(1.0 - SWTCH(t, TVASO_END));
double rehab_on = REHAB*SWTCH(t, TREHAB_START)*(1.0 - SWTCH(t, TREHAB_END));
double estim_on = ESTIM*SWTCH(t, TESTIM_START);
double fes_on   = FES*SWTCH(t, TREHAB_START);

