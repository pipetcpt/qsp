//===========================================================================
// A. PHARMACOKINETICS
//===========================================================================
dxdt_CARB_C = -(CL_CARB / V_CARB) * CARB_C;

dxdt_PTX_C  = -(CL_PTX / V1_PTX) * PTX_C
              - (Q_PTX / V1_PTX) * PTX_C + (Q_PTX / V2_PTX) * PTX_P;
dxdt_PTX_P  =  (Q_PTX / V1_PTX) * PTX_C - (Q_PTX / V2_PTX) * PTX_P;

dxdt_IO_C   = -(CL_IO / V1_IO) * IO_C
              - (Q_IO / V1_IO) * IO_C + (Q_IO / V2_IO) * IO_P;
dxdt_IO_P   =  (Q_IO / V1_IO) * IO_C - (Q_IO / V2_IO) * IO_P;

dxdt_LEN_G  = -KA_LEN * LEN_G;
dxdt_LEN_C  =  KA_LEN * LEN_G - (CLF_LEN / VF_LEN) * LEN_C;

dxdt_PRG_G  = -KA_PRG * PRG_G;
dxdt_PRG_C  =  KA_PRG * PRG_G - (CLF_PRG / VF_PRG) * PRG_C;

dxdt_LTZ_G  = -KA_LTZ * LTZ_G;
dxdt_LTZ_C  =  KA_LTZ * LTZ_G - (CLF_LTZ / VF_LTZ) * LTZ_C;

dxdt_EVE_G  = -KA_EVE * EVE_G;
dxdt_EVE_C  =  KA_EVE * EVE_G - (CLF_EVE / VF_EVE) * EVE_C;

//===========================================================================
// B. DRUG EFFECT SITES
//===========================================================================
// Progestin: the levonorgestrel IUS delivers a high LOCAL endometrial
// concentration from a low systemic one — the entire rationale for the
// fertility-sparing route. Modelled as a route-dependent effect-site
// multiplier rather than a separate compartment.
double prg_eff_conc = (PRG_C / VF_PRG) * (LOCAL_IUS > 0.5 ? IUS_FACTOR : 1.0);
double PRG_occ  = prg_eff_conc / (EC50_PRG + prg_eff_conc);      // PR occupancy
double PRG_act  = EMAX_PRG * PRG_occ * PR_EXP;                   // requires PR-B to be present

double LTZ_inh  = EMAX_LTZ * CP_LTZ / (IC50_LTZ + CP_LTZ);       // aromatase blockade
double EVE_inh  = EMAX_EVE * CP_EVE / (IC50_EVE + CP_EVE);       // mTORC1 blockade
double PD1_blk  = EMAX_IO  * CP_IO  / (IC50_IO  + CP_IO);        // PD-1 pathway blockade
double VEGFR_i  = CP_LEN / (IC50_VEGFR + CP_LEN);                // VEGFR-2 inhibition
double FGFR_i   = CP_LEN / (IC50_FGFR  + CP_LEN);                // FGFR inhibition

//===========================================================================
// C. ENDOCRINE AXIS — unopposed oestrogen and its opposition
//===========================================================================
double e2_in = KSYN_E2 * AROMv * (POSTMENO > 0.5 ? 1.0 : PREMENO_E2) * (1.0 - LTZ_inh);
dxdt_E2 = e2_in - KEL_E2 * E2;

// ERa activity has TWO inputs: ligand (E2) and ligand-INDEPENDENT activation
// by mTOR/ERK phosphorylation of ERa Ser167/118. The second term is why
// everolimus restores letrozole sensitivity (Slomovitz 2015) and why an
// aromatase inhibitor alone underperforms in a PI3K-driven tumour.
double er_ligand = E2 / (EC50_ER + E2);
double er_target = ERPR_POS > 0.5
                 ? fmin(1.0, er_ligand + W_LIGIND * PI3K_A * (1.0 - EVE_inh)) * (1.0 - PRG_act)
                 : 0.05;
dxdt_ER_ACT = KOUT_ER * (er_target - ER_ACT);

// PR-B expression: down-regulated by sustained progestin occupancy (the
// mechanism of acquired hormonal resistance in fertility-sparing therapy),
// re-induced by tamoxifen alternation (GOG-153) and by ERa signalling itself
// (PGR is an oestrogen target gene), recovering slowly off drug.
double pr_max = ERPR_POS > 0.5 ? PR0 : 0.05;
dxdt_PR_EXP = -K_PRDOWN * PRG_occ * PR_EXP
              + K_PRUP  * (pr_max - PR_EXP)
              + K_TAM_PR * TAM_PULSE * (pr_max - PR_EXP)
              + 0.004 * ER_ACT * (pr_max - PR_EXP);

//===========================================================================
// D. PI3K/AKT/mTOR
//===========================================================================
double pi3k_target = fmin(1.0, (PI3K_BASE + PTENv + HER2v + W_ER_PI3K * ER_ACT)
                               * (1.0 - EVE_inh));
dxdt_PI3K_A = KOUT_PI3K * (pi3k_target - PI3K_A);

//===========================================================================
// E. ANGIOGENESIS AND PERFUSION
//===========================================================================
double TUM_TOT = TUM_S + TUM_R;
double hypoxia = TUM_TOT / (TUM_TOT + 80.0 * MVD);   // burden per unit perfusion
dxdt_VEGF = KIN_VEGF * (hypoxia + 0.45 * PI3K_A) - KOUT_VEGF * VEGF;

// Lenvatinib blocks BOTH the VEGF axis and the FGF escape route — the FGFR
// arm is why it outperforms a pure anti-VEGF agent in this setting.
double angio_drive = VEGF * (1.0 - VEGFR_i) + W_FGF_ESC * (1.0 - FGFR_i);
dxdt_MVD = KIN_MVD * angio_drive - KOUT_MVD * MVD;

double perfusion = fmax(PERF_FLOOR, fmin(1.6, MVD));

// Vascular normalisation: partial VEGFR inhibition IMPROVES T-cell delivery
// even as it reduces vessel density. Peaks at intermediate inhibition.
double vasc_norm = 1.0 + LEN_NORM * 4.0 * VEGFR_i * (1.0 - VEGFR_i);

//===========================================================================
// F. IMMUNOSUPPRESSIVE COMPARTMENTS
//===========================================================================
dxdt_TREG = KIN_TREG * (0.55 + 0.55 * VEGF) - KOUT_TREG * TREG;
dxdt_MDSC = KIN_MDSC * (0.45 + 0.70 * VEGF) * (1.0 - LEN_MDSC * VEGFR_i)
            - KOUT_MDSC * MDSC;

//===========================================================================
// G. NEOANTIGEN -> PRIMING -> EFFECTOR -> KILL
//===========================================================================
// Platinum adds immunogenic cell death on top of the constitutive,
// TMB-determined neoantigen supply.
double chemo_kill_rate = EMAX_CARB * CP_CARB / (EC50_CARB + CP_CARB)
                       + EMAX_PTX  * CP_PTX  / (EC50_PTX  + CP_PTX);
double doublet = CHEMOSv * chemo_kill_rate * (1.0 + SYN_CP
                 * (CP_CARB / (EC50_CARB + CP_CARB)) * (CP_PTX / (EC50_PTX + CP_PTX)));

double icd = ICD_CHEMO * (CP_CARB / (EC50_CARB + CP_CARB));
dxdt_NEO = KIN_NEO * IMMUNv * APCv * (1.0 + icd) * (TUM_TOT / fmax(TUMBASE, 1.0))
           - KOUT_NEO * NEO;

double priming = KPRIME * NEO / (NEO50 + NEO);

// Suppression: Treg + MDSC + the obesity penalty on T-cell metabolic fitness.
double obes_pen = fmin(0.45, OBES_TCELL * fmax(BMI - 30.0, 0.0));
double suppression = SUP_TREG * TREG + SUP_MDSC * MDSC;

dxdt_TEFF = priming * vasc_norm * (1.0 - obes_pen)
            - K_EXH * (1.0 - PD1_blk) * TEFF
            + K_REINVIG * PD1_blk * TEXH
            - KDEATH_T * TEFF
            - 0.06 * suppression * TEFF;

dxdt_TEXH = K_EXH * (1.0 - PD1_blk) * TEFF
            - K_REINVIG * PD1_blk * TEXH
            - KOUT_TEXH * TEXH;

// Immune kill: saturating in effector density, gated by immune exclusion.
// This is where the whole TMB axis cashes out into tumour shrinkage.
double immune_kill = KKILL_IMM * (TEFF / (KM_TEFF + TEFF)) * (1.0 - EXCLv);

//===========================================================================
// H. TUMOUR DYNAMICS
//===========================================================================
double growth_drive = PRODRIVE * AGGRv
                    * (1.0 + W_ER_GROW * ER_ACT + W_PI3K_GROW * PI3K_A)
                    * perfusion;
double space = fmax(0.0, 1.0 - TUM_TOT / TUM_MAX);

// Direct progestin cytostatic/differentiating effect — requires PR-B, which
// is exactly what chronic progestin exposure erodes.
double prg_kill = K_PRGKILL * PRG_act;

// Trastuzumab acts twice: it removes HER2 pathway drive (via HER2v, above)
// AND recruits NK-cell ADCC. Both terms are gated on HER2 amplification, so
// the drug does nothing at all in a HER2-normal tumour — which is the whole
// finding of Fader 2018.
double her2_kill = (HER2_AMP > 0.5 && HER2_TX > 0.5) ? K_HER2KILL : 0.0;

dxdt_TUM_S = KG_TUM * growth_drive * space * TUM_S
             - doublet * TUM_S
             - immune_kill * TUM_S
             - prg_kill * TUM_S
             - her2_kill * TUM_S
             - K_RESEMERGE * doublet * TUM_S;

dxdt_TUM_R = KG_RES_REL * KG_TUM * growth_drive * space * TUM_R
             + K_RESEMERGE * doublet * TUM_S
             - immune_kill * TUM_R          // immunity still sees the resistant clone
             - 0.25 * prg_kill * TUM_R
             - her2_kill * TUM_R;

//===========================================================================
// I. BIOMARKERS
//===========================================================================
dxdt_CA125 = KOUT_CA125 * (CA125_BASE + K_CA125 * CA_MULT * TUM_TOT - CA125);
dxdt_CTDNA = KOUT_CTDNA * (K_CTDNA * TUM_TOT - CTDNA);

//===========================================================================
// J. FRIBERG MYELOSUPPRESSION (carboplatin + paclitaxel)
//===========================================================================
double edrug = fmin(0.95, SLOPE_CARB * CP_CARB + SLOPE_PTX * CP_PTX);
double fb    = pow(CIRC0 / fmax(CIRC, 0.05), GAMMA_FB);
dxdt_PROL = KTR_FB * PROL * (1.0 - edrug) * fb - KTR_FB * PROL;
dxdt_TR1  = KTR_FB * (PROL - TR1);
dxdt_TR2  = KTR_FB * (TR1  - TR2);
dxdt_TR3  = KTR_FB * (TR2  - TR3);
dxdt_CIRC = KTR_FB * (TR3  - CIRC);

//===========================================================================
// K. LENVATINIB HYPERTENSION (the dose-limiting toxicity in KEYNOTE-775)
//===========================================================================
dxdt_SBP = KOUT_SBP * (SBP0 + K_SBP_LEN * VEGFR_i - SBP);

//===========================================================================
// L. HAZARD ACCUMULATOR -> PFS/OS surrogate
//===========================================================================
// Normalised to a FIXED reference burden, not to this subject's baseline:
// otherwise an adjuvant run started at 8 mm and a metastatic run started at
// 100 mm would report the same hazard at the same relative change, which is
// exactly backwards.
dxdt_HAZ = H0_HAZ * pow(fmax(TUM_TOT, 1.0) / HAZ_REF, GAMMA_HAZ);

