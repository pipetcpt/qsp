[MAIN]
//---------------------------------------------------------------------------
// 1. THE TMB AXIS — the single continuous variable this model is organised on
//---------------------------------------------------------------------------
if (TMB_OVR > 0) {
  TMBv = TMB_OVR;                       // continuous-axis / TMB-guided scenarios
} else if (MOLCLASS < 1.5) {
  TMBv = TMB_POLE;                      // POLEmut  — ultramutated
} else if (MOLCLASS < 2.5) {
  TMBv = TMB_MMRD;                      // MMRd     — hypermutated
} else if (MOLCLASS < 3.5) {
  TMBv = TMB_NSMP;                      // NSMP     — copy-number-low
} else {
  TMBv = TMB_P53;                       // p53abn   — copy-number-high
}

// MSI frameshift indels are more immunogenic PER MUTATION than POLE-driven
// SNVs (indel neoantigens are wholly non-self across their reading frame),
// so the MMRd class gets an effective-TMB uplift rather than a separate curve.
double tmb_eff = TMBv * (1.0 + FS_WEIGHT * ((MOLCLASS > 1.5 && MOLCLASS < 2.5) ? 1.0 : 0.0));

// THE central equation: a saturating Hill function of mutational burden.
// TMB50 = 13 mut/Mb lands almost exactly on the clinical dMMR/pMMR boundary —
// the binary biomarker works because the cut sits on the steepest part of a
// continuum, which is also why borderline tumours must be misclassified.
IMMUNv = pow(tmb_eff, HILL_TMB) / (pow(TMB50, HILL_TMB) + pow(tmb_eff, HILL_TMB));

// Antigen-presentation competence: B2M loss uncouples TMB from visibility.
APCv = B2M_LOSS > 0.5 ? 0.15 : 1.0;

//---------------------------------------------------------------------------
// 2. Host endocrine / phenotype modifiers
//---------------------------------------------------------------------------
AROMv    = 1.0 + AROM_SLOPE * fmax(BMI - 22.0, 0.0);   // adipose aromatase capacity
PTENv    = (MOLCLASS > 2.5 && MOLCLASS < 3.5) ? PTEN_HIT
         : (MOLCLASS < 2.5 ? 0.85 * PTEN_HIT : 0.40 * PTEN_HIT);
EXCLv    = (MOLCLASS > 3.5) ? EXCL_P53 : EXCL_BASE;

// HER2: amplification adds pathway drive; trastuzumab removes most of it.
// Fader 2018 showed the benefit is confined to the HER2-amplified serous
// subset, so the term is gated on HER2_AMP and vanishes without it.
HER2v    = (HER2_AMP > 0.5)
         ? HER2_DRIVE * (1.0 - HER2_BLOCK * (HER2_TX > 0.5 ? 1.0 : 0.0))
         : 0.0;

PRODRIVE = 1.0 + GRADE_SLOPE * fmax(GRADE - 1.0, 0.0);

// Intrinsic aggressiveness is NOT the same variable as immunogenicity. p53abn
// is the most aggressive class (p53 checkpoint loss, CCNE1 amplification)
// AND the least immunogenic; POLEmut is the least aggressive AND the most
// immunogenic. Conflating the two would make the model unable to say which
// of the two effects drives the prognostic gap.
AGGRv    = (MOLCLASS < 1.5) ? AGG_POLE
         : (MOLCLASS < 2.5) ? AGG_MMRD
         : (MOLCLASS < 3.5) ? AGG_NSMP : AGG_P53;

// Chemosensitivity is a THIRD independent class axis, and it runs the opposite
// way from immunogenicity: losing the p53 G1 checkpoint lets damaged cells
// enter S and M phase, so the class that responds worst to checkpoint blockade
// responds BEST to platinum/taxane. This is the mechanistic content of the
// PORTEC-3 molecular analysis, in which the adjuvant chemoradiotherapy benefit
// was concentrated in p53abn while POLEmut did well regardless of treatment.
CHEMOSv  = (MOLCLASS < 1.5) ? CHS_POLE
         : (MOLCLASS < 2.5) ? CHS_MMRD
         : (MOLCLASS < 3.5) ? CHS_NSMP : CHS_P53;
CA_MULT  = (MOLCLASS > 3.5) ? SEROUS_CA : 1.0;
KTR_FB   = 4.0 / (MTT_NEUT / 24.0);                    // hours -> 1/day
TUMBASE  = TUM0;

//---------------------------------------------------------------------------
// 3. Initial conditions
//---------------------------------------------------------------------------
double e2_ss = (KSYN_E2 * AROMv * (POSTMENO > 0.5 ? 1.0 : PREMENO_E2)) / KEL_E2;
E2_0     = e2_ss;
ER_ACT_0 = ERPR_POS > 0.5 ? e2_ss / (EC50_ER + e2_ss) : 0.05;
PR_EXP_0 = ERPR_POS > 0.5 ? PR0 : 0.05;
PI3K_A_0 = fmin(1.0, PI3K_BASE + PTENv + HER2v);

TUM_S_0  = TUM0 * (1.0 - RESFRAC0);
TUM_R_0  = TUM0 * RESFRAC0;

// Pre-treatment immune steady state — the untreated tumour has already
// reached an equilibrium between neoantigen-driven priming and suppression.
NEO_0    = (KIN_NEO * IMMUNv * APCv) / KOUT_NEO;
TREG_0   = 1.0;
MDSC_0   = 1.0;
// Initialise the T-cell compartments at the UNTREATED steady state rather
// than at an arbitrary "hot vs cold" guess. The tumour is clinically
// detectable precisely because priming and suppression have already reached
// an equilibrium the tumour wins; treatment has to move that equilibrium.
// A consequence worth stating: the exhausted-cell pool at diagnosis scales
// with prior antigen exposure, so a high-TMB tumour arrives with a LARGER
// reservoir of reinvigoratable cells — which is a second, independent reason
// checkpoint blockade works better there, on top of ongoing priming.
double prime_ss = KPRIME * NEO_0 / (NEO50 + NEO_0);
double obes_ss  = fmin(0.45, OBES_TCELL * fmax(BMI - 30.0, 0.0));
double supp_ss  = SUP_TREG * 1.0 + SUP_MDSC * 1.0;
TEFF_0   = prime_ss * (1.0 - obes_ss) / (K_EXH + KDEATH_T + 0.06 * supp_ss);
TEXH_0   = K_EXH * TEFF_0 / KOUT_TEXH;
VEGF_0   = 1.0;
MVD_0    = 1.0;

CA125_0  = CA125_BASE + K_CA125 * CA_MULT * TUM0;
CTDNA_0  = K_CTDNA * TUM0;

PROL_0   = CIRC0;
TR1_0    = CIRC0;
TR2_0    = CIRC0;
TR3_0    = CIRC0;
CIRC_0   = CIRC0;
SBP_0    = SBP0;
HAZ_0    = 0.0;

