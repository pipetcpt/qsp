##  Endometrial Carcinoma (EC) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Endometrial carcinoma — the most common gynaecologic malignancy
##             in high-income countries and one of the few whose incidence is
##             RISING, tracking the obesity epidemic. Two intertwined engines:
##             (i) an ENDOCRINE engine — adipose aromatase converts adrenal/
##             ovarian androstenedione to estrone, hyperinsulinaemia lowers SHBG
##             and raises the free estradiol fraction, and in the absence of
##             luteal progesterone the endometrium sees UNOPPOSED oestrogen ->
##             ERa-driven proliferation -> hyperplasia -> EIN -> endometrioid
##             carcinoma; and (ii) a GENOMIC engine — PTEN/PIK3CA/PIK3R1 lesions
##             (PI3K pathway altered in >90% of endometrioid tumours), ARID1A,
##             CTNNB1, KRAS, and — the axis this model is built around —
##             DNA-repair status: POLE exonuclease-domain mutation, mismatch-
##             repair deficiency (Lynch or sporadic MLH1 hypermethylation), or
##             neither, with TP53 abnormality marking the copy-number-high
##             serous-like class.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  ---------------------------------------------------------------------------
##  THE ORGANISING CLAIM OF THIS MODEL
##  ---------------------------------------------------------------------------
##  Endometrial cancer is the solid tumour in which the MOLECULAR CLASS, not the
##  histology and not the stage, reorders the entire therapeutic decision tree.
##  The TCGA four classes (POLEmut / MMRd / NSMP / p53abn) are treated here NOT
##  as four discrete diseases but as FOUR POINTS ON ONE CONTINUOUS AXIS —
##  tumour mutational burden — separated by nearly two orders of magnitude:
##
##      p53abn  ~2.3 mut/Mb        NSMP ~2.9 mut/Mb
##      MMRd    ~18-40 mut/Mb      POLEmut  >100 mut/Mb
##
##  Everything immunological in this model hangs off a single saturating Hill
##  function of that axis:
##
##      IMMUNOGENICITY = TMB^h / (TMB50^h + TMB^h),   TMB50 = 13, h = 1.4
##
##  This one equation is not fitted to the immunotherapy trials — it is
##  parameterised from the mutation-rate literature and then CHECKED against
##  them. It reproduces, without further tuning, the central empirical fact of
##  modern EC therapeutics: the same anti-PD-1 antibody has hazard ratio ~0.28
##  in dMMR (RUBY) and ~0.76 in pMMR, because dMMR sits high on the shoulder of
##  the curve (I = 0.79, after the frameshift uplift) and pMMR sits on the
##  floor (I = 0.11).
##
##  Three consequences follow, and they are the reason to build the model this
##  way rather than as four separate disease models:
##
##  1. TMB50 = 13 mut/Mb sits almost exactly where the clinical dMMR/pMMR
##     dichotomy is drawn. The biomarker "works" precisely BECAUSE the
##     threshold was placed on the steepest part of a continuous curve — which
##     also means patients near the boundary (MSI-low, MMR-heterogeneous,
##     subclonal MLH1 methylation) are the ones a binary test must get wrong.
##     EMC_tmb_sweep() at the bottom of this file moves TMB continuously with
##     everything else fixed and shows the dichotomy is a convenience, not a
##     biological edge.
##  2. Because the curve SATURATES, POLEmut (TMB 140, I = 0.965) is barely more
##     immunogenic than a hypothetical TMB-60 tumour. POLEmut's spectacular
##     prognosis is therefore NOT a dose-response argument for more therapy —
##     it is the quantitative case for DE-ESCALATION (the RAINBO POLE-BLUE
##     hypothesis). In the adjuvant/micrometastatic setting the model puts
##     POLEmut at essentially the same 3-year tumour burden with and without
##     chemotherapy (4.8 vs 4.6 mm); the chemotherapy only makes the fall
##     faster, not deeper.
##  3. The floor of the curve is where the pharmacology has to be different in
##     kind, not in dose. pMMR tumours cannot be rescued by more checkpoint
##     blockade; they are rescued by CHANGING THE TME — lenvatinib's
##     anti-angiogenic MDSC-depleting vascular-normalising effect is modelled
##     as a multiplier on T-cell infiltration rather than as tumour kill.
##     Lenvatinib has NO tumour-kill term anywhere in this model. Zeroing
##     LEN_MDSC and LEN_NORM cuts the pembrolizumab+lenvatinib response in an
##     NSMP tumour from -60% to -26% and the survival surrogate from 0.64 to
##     0.43 — so roughly two thirds of the combination benefit is immunological
##     reprogramming and one third is plain perfusion starvation. That split is
##     the model's falsifiable claim about the KEYNOTE-775 mechanism.
##
##  Scope    : 35 ODE compartments —
##             PK (13): carboplatin, paclitaxel (2-cmt), anti-PD-1 mAb (2-cmt,
##                      dostarlimab/pembrolizumab), lenvatinib (oral, 2-cmt),
##                      progestin (megestrol PO or levonorgestrel IUS local),
##                      everolimus (oral), letrozole (oral)
##             Endocrine (3): free estradiol, ERa transcriptional activity,
##                      PR-B receptor expression (with chronic-progestin
##                      down-regulation = acquired hormonal resistance)
##             Oncogenic signalling (1): PI3K/AKT/mTOR activity
##             Tumour (2): chemo/hormone-sensitive and resistant clones
##             Immunity (5): neoantigen load, CD8 effector, exhausted T cells,
##                      Treg, MDSC
##             Vasculature (2): VEGF-A, microvessel density
##             Biomarkers (2): CA-125, ctDNA VAF
##             Myelosuppression (5): Friberg proliferating + 3 transit +
##                      circulating neutrophils
##             Toxicity/outcome (2): systolic blood pressure, cumulative hazard
##  Time     : days. Default horizon 730 d (advanced/recurrent disease) or
##             180-360 d for the fertility-sparing hormonal scenarios.
##  Units    : plasma PK in mg/L with literature-derived CL/V where available;
##             tumour burden as RECIST sum of target-lesion diameters (mm);
##             immune compartments in normalised density units (baseline = 1);
##             CA-125 U/mL; neutrophils 10^9/L; SBP mmHg.
##  Scenarios: 8 prebuilt — see EMC_simulate_scenarios() at the bottom.
##  Anchors  : Kandoth 2013 Nature 497:67 (TCGA integrated genomic
##             characterisation, the four classes); Talhouk 2015 Br J Cancer
##             113:299 / 2017 Cancer 123:802 (ProMisE surrogate classifier);
##             Leon-Castillo 2020 J Clin Oncol 38:3388 (PORTEC-3 molecular
##             subgroup analysis); Mirza 2023 N Engl J Med 388:2145 (RUBY,
##             dostarlimab + chemo, dMMR HR 0.28); Eskander 2023 N Engl J Med
##             388:2159 (NRG-GY018, pembrolizumab + chemo, dMMR HR 0.30 /
##             pMMR HR 0.54); Makker 2022 N Engl J Med 386:437 (KEYNOTE-775,
##             lenvatinib + pembrolizumab in pMMR, PFS HR 0.60, OS HR 0.68);
##             Oaknin 2020 JAMA Oncol 6:1766 (GARNET, dostarlimab monotherapy,
