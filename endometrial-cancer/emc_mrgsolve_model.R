[PROB]
QSP model of endometrial carcinoma linking the unopposed-oestrogen endocrine
axis (adipose aromatase, SHBG, ERa/PR-B balance) and the PI3K/PTEN oncogenic
axis to the TCGA molecular class, and from molecular class through a single
continuous tumour-mutational-burden -> neoantigen -> T-cell-priming Hill
function to checkpoint-inhibitor efficacy. Includes mechanistic PK/PD for
carboplatin, paclitaxel, anti-PD-1 (dostarlimab/pembrolizumab), lenvatinib,
progestin (megestrol / levonorgestrel IUS), everolimus and letrozole, plus
Friberg myelosuppression, lenvatinib hypertension, and RECIST/PFS endpoints.

