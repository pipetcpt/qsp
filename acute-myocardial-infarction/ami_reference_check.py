def geometry(V, MASS):
    """Thin-walled sphere.  V in mL, MASS in g; returns r and h in cm."""
    r = (3.0 * V / (4.0 * math.pi)) ** (1.0 / 3.0)
    sa = 4.0 * math.pi * r * r
    return r, MASS / (1.05 * sa)


def baseline_setpoints(p):
    EDV, ESV, MASS = p['EDV0'], p['ESV0'], p['MASS0']
    r_ed, h_ed = geometry(EDV, MASS)
    r_es, h_es = geometry(ESV, MASS)
    Pes = 0.90 * p['SBP0']
    return dict(
        WS_SET=p['PED0'] * r_ed / (2.0 * h_ed),
        WS_SET_ES=Pes * r_es / (2.0 * h_es),
        EMAX0=Pes / (ESV - p['V0E']),
        CO0=(EDV - ESV) * p['HR0'] / 1000.0,
    )


def initial_state(p):
    y = np.zeros(NST)
    for i in range(NL):
        y[IDX['E'] + i] = 1.0
        y[IDX['G'] + i] = 1.0
    for nm in ('PLG', 'FIB', 'PAI', 'NE', 'ANG', 'ALD', 'BNP', 'VOL'):
        y[IDX[nm]] = 1.0
    # The culprit lesion is already thrombosed at t = 0: plaque rupture is
    # the initial condition, not something the model has to grow.  Whether
    # that thrombus actually obstructs flow is governed separately by the
