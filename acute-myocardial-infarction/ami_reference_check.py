"""
=======================================================================
 ami_reference_check.py
 Acute Myocardial Infarction (STEMI) — QSP reference implementation
=======================================================================

This file is the *numerical source of truth* for the acute myocardial
infarction (AMI / STEMI) QSP model in this directory.  It re-implements
the equations of ``ami_mrgsolve_model.R`` in numpy + scipy so that every
number quoted in ``README.md`` can be regenerated by anyone with a
Python install (R and mrgsolve are not needed to check the arithmetic).

    python3 ami_reference_check.py             # run every experiment
    python3 ami_reference_check.py 2 8         # run experiments 2 and 8

---------------------------------------------------------------------
THE CLAIM THIS MODEL IS BUILT TO MAKE
---------------------------------------------------------------------
An infarct is not "the artery closed, therefore the muscle died".
It is TWO RACES and ONE BIFURCATION:

  Race 1 (minutes to hours).  A wavefront of necrosis crawls from
      endocardium to epicardium.  Its speed is set by how far residual
      collateral flow falls short of BASAL metabolic demand -- not of
      resting demand.  Tissue that can pay its basal bill stops
      contracting and survives indefinitely; tissue that cannot, dies.
      The clock it races is time-to-reperfusion.
  Race 2 (the first minutes of reflow).  Ischemia leaves two things
      behind: acid, which holds the mitochondrial permeability
      transition pore SHUT, and succinate, which becomes an oxidant
      burst the instant oxygen returns.  Restoring flow washes out the
      acid and ignites the succinate at the same moment.  Reperfusion
      is simultaneously the treatment and a second injury.
  The bifurcation (weeks to months).  Laplace wall stress -> dilation
      -> more wall stress is a POSITIVE loop.  Concentric hypertrophy
      is the negative loop opposing it.  Whether a given infarct
      settles into a stable ventricle or runs away into heart failure
      is a bifurcation, not a dose.

Nothing in the parameter list is called ``golden_hour``,
``critical_infarct_size``, ``no_reflow_switch``, ``reperfusion_injury_
fraction``, ``therapeutic_window`` or ``severity``.  Each of those
appears below only as a computed result.

---------------------------------------------------------------------
STATE VECTOR
---------------------------------------------------------------------
The area at risk (AAR, as a fraction of the LV) is divided into NL = 5
transmural layers, i = 0 (subendocardial) ... 4 (subepicardial).  Each
layer carries 8 states.  The transmural gradient of COLLATERAL FLOW is
the only asymmetry between the layers; everything else about the
wavefront is emergent.

  layer block (8 x 5 = 40)
    E      energy charge (1 = normal ATP/PCr status)
    G      glycogen available to anaerobic glycolysis
    H      tissue acid load (H+/lactate)
    C      cytosolic + mitochondrial Ca2+ load
    P      mPTP open fraction
    NI     necrotic fraction from energy failure  (ischemic)
    NR     necrotic fraction from mPTP opening    (reperfusion)
    SUC    ischemic succinate pool

  global (29)
    ROS MVO THR PLN PLG FIB PAI DAMP NEU M1 M2 IL1 IL6 CRP TGF MYOF
    COL MMP EDVS MASS THIN STUN NE ANG ALD BNP VOL TNI CKMB

  pharmacokinetic (13)
    TNK1 TNK2 TICd TICc METd METc RAMd RAMc EPL EMP COLC CAN CSA

EDVS deserves a note: it is the STRUCTURAL (unstressed) chamber size,
not the observed end-diastolic volume.  Observed EDV is EDVS displaced
along the diastolic pressure-volume relation by the actual filling
pressure.  That is what lets one variable carry both the day-1 dilation
(impaired emptying raises filling pressure) and the six-month dilation
(EDVS itself grows) without conflating the two.

Author: QSP disease-model library (see repository README).
"""

