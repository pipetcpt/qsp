    print("\n  PART B -- the same comparison as a two-subpopulation mixture")
    print(f"    lysis succeeds ({100*P_LYT:.0f}%): IS {o_lyt['IS']:.2f} %LV; "
          f"fails ({100*(1-P_LYT):.0f}%): IS {is_fail:.2f} %LV"
          f"  ->  expected {exp_lyt:.2f} %LV")
