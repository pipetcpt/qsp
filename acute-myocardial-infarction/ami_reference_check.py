    print("     shorter than the 60-120 min in the guidelines.  The model is not")
    print("     wrong here; the comparison is.  A single deterministic trajectory")
    print("     cannot represent the fact that in roughly 40% of lytic patients the")
    print("     artery does not open at all.  Note also WHY partial patency is")
    print("     nearly as good as full patency here: once antegrade flow exceeds")
    print("     basal demand (0.20) the wavefront stops, so even TIMI-2 flow")
    print("     arrests it.  That is physiology, not a modelling shortcut.")

    # ---- part B: the mixture ----------------------------------------------
    # These two weights are NOT model parameters.  They are the angiographic
    # patency RATES observed in trials (about 60% TIMI-3 at 90 min for a
    # fibrinolytic with full adjunctive therapy; about 95% for primary PCI).
    # Feeding them in as subpopulation weights is the only honest way to
    # compare a stochastic-success therapy with a near-deterministic one.
