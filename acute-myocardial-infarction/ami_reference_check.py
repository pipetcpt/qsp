NL = 5                       # transmural layers


def relu(x):
    return x if x > 0.0 else 0.0


def clip01(x):
    return 0.0 if x < 0.0 else (1.0 if x > 1.0 else x)


def sstep(t, t0, width=0.03):
    """Smooth 0->1 step.  A tanh rather than an if(), so the stiff solver
    never has to integrate across a true discontinuity.  Width is in
    hours; 0.03 h ~ 2 min, far faster than any biology modelled here."""
    if t0 is None:
        return 0.0
    z = (t - t0) / width
    if z > 20.0:
        return 1.0
    if z < -20.0:
        return 0.0
    return 0.5 * (1.0 + math.tanh(z))


def window(t, t0, dur, width=0.03):
    if t0 is None:
        return 0.0
    return sstep(t, t0, width) * (1.0 - sstep(t, t0 + dur, width))


def hill(x, k, n):
    if x <= 0.0:
        return 0.0
    xn = x ** n
    return xn / (k ** n + xn)


