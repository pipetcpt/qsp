def perfusion(t, y, p, d, rpp, hr):
    """Layer-by-layer flow, substrate supply and affordable contraction.

    The most consequential line here is CF: a layer spends what it can
    afford on contraction and no more.  A layer whose supply still
    covers basal metabolism therefore goes AKINETIC BUT STAYS ALIVE
    (hibernating myocardium) instead of dying -- which is why a
    subepicardial rim survives a permanently occluded artery.
    """
    THR = clip01(y[IDX['THR']])
    MVO = clip01(y[IDX['MVO']])
    occ = sstep(t, d['T_OCC'], 0.02)
    pat = 1.0 - occ * THR                       # epicardial patency 0..1
    # BASAL metabolism is rate-INDEPENDENT: it is by definition the
    # non-contractile cost of ion homeostasis and does not scale with the
    # rate-pressure product.  Letting it scale was an error -- it made a
    # tachycardic patient's subepicardium unable to pay a bill that had risen
    # under it, which wiped out the surviving rim Reimer and Jennings measured.
    # Only CONTRACTILE demand scales with RPP, which is where rpp appears below.
    basal = p['DEM_BAS'] * p['DEM']
    # Collateral flow is DIASTOLIC, so it rises when the heart slows.
    diast = (p['HR0'] / max(hr, 1.0)) ** p['KDIAST']
    out = []
    for i in range(NL):
        q_ante = relu(pat * (1.0 - p['GM'][i] * MVO))
        q_coll = (1.0 - pat) * p['COLL'] * p['GC'][i] * diast
        q = q_ante + q_coll
        qc = min(q, 1.0)
        G = max(y[IDX['G'] + i], 0.0)
        H = max(y[IDX['H'] + i], 0.0)
        E = clip01(y[IDX['E'] + i])
        # anaerobic glycolysis, limited by glycogen AND by its own acid
        anaer = p['F_ANAERO'] * relu(1.0 - qc) * G / (1.0 + H / p['HI50'])
        supply = q + anaer
        afford = clip01((supply / max(p['DEM'] * rpp, 1e-6) - p['DEM_BAS'])
                        / (1.0 - p['DEM_BAS']))
        out.append(dict(q=q, qc=qc, q_ante=q_ante, anaer=anaer, supply=supply,
                        deficit=relu(basal - supply),
                        surplus=relu(supply - basal),
                        CF=afford * E))
    return pat, out


def mechanics(t, y, p, d, sp, pdv):
    """Closed-loop LV mechanics.

    Causal order (it matters):
      NE and drugs        -> HR, SBP -> rate-pressure product -> demand
      demand and flow     -> affordable contraction, layer by layer
      contractile mass    -> Emax    -> ESV
      ESV + volume status -> filling pressure
      filling pressure    -> observed EDV along the diastolic PV curve
      EDV + wall mass     -> Laplace wall stress
    Wall stress then drives dEDVS/dt (the positive loop) and dMASS/dt
    (the negative loop).  That pair is the whole remodelling
    bifurcation; nothing else is needed to make it bistable.
    """
    NI = [clip01(y[IDX['NI'] + i]) for i in range(NL)]
    NR = [clip01(y[IDX['NR'] + i]) for i in range(NL)]
    VIA = [max(1.0 - NI[i] - NR[i], 0.0) for i in range(NL)]
    W = p['W']
    STUN = clip01(y[IDX['STUN']])

    is_lv = p['AAR'] * sum(W[i] * (NI[i] + NR[i]) for i in range(NL))
    ni_lv = p['AAR'] * sum(W[i] * NI[i] for i in range(NL))
    nr_lv = p['AAR'] * sum(W[i] * NR[i] for i in range(NL))

    EDVS = max(y[IDX['EDVS']], 25.0)
    MASS = max(y[IDX['MASS']], 40.0)
    COL = max(y[IDX['COL']], 0.0)
    THIN = clip01(y[IDX['THIN']])
    VOL = max(y[IDX['VOL']], 0.3)
    NE = max(y[IDX['NE']], 0.0)
    ANG = max(y[IDX['ANG']], 0.0)
    ALD = max(y[IDX['ALD']], 0.0)
    BNP = max(y[IDX['BNP']], 0.0)
    # Scar strength is MATURITY, not amount.  A small infarct lays down less
    # collagen in absolute terms but its scar is just as cross-linked, so both
    # the half-maximal constant and the saturating cap have to be scaled by how
    # much of the at-risk bed actually needs a scar.  Without this the
    # normalised scar of a small infarct never matures, infarct expansion never
    # switches off, and every infarct diverges however small it is.
    inj = max(is_lv / max(p['AAR'], 1e-6), 0.02)
    col_n = COL / (COL + p['KSC'] * inj)

    ne_eff = 1.0 + (NE - 1.0) * (1.0 - p['BB_NE'] * pdv['bb'])
    ald_eff = ALD * (1.0 - pdv['mra'])          # MRA blocks the RECEPTOR
    np_eff = BNP * (1.0 + 0.80 * p['ARNI'])

    HR = p['HR0'] * (1.0 + 0.30 * (ne_eff - 1.0)) * (1.0 - p['BB_HR'] * pdv['bb'])
    HR = min(max(HR, 45.0), 160.0)
    SBP = p['SBP0'] * (1.0 + 0.12 * (ANG - 1.0) + 0.08 * (ne_eff - 1.0)
                       - 0.10 * pdv['acei'] - 0.06 * p['ARNI'])
    SBP = min(max(SBP, 70.0), 200.0)
    Pes = 0.90 * SBP
    rpp = (HR / p['HR0']) * (SBP / p['SBP0'])

    pat, lay = perfusion(t, y, p, d, rpp, HR)

    # contractile capacity: the remote zone, plus whatever the at-risk
    # layers can still afford, minus post-reperfusion stunning
    contractile = (1.0 - p['AAR']) + p['AAR'] * sum(
        W[i] * VIA[i] * lay[i]['CF'] * (1.0 - STUN) for i in range(NL))
    emax = (sp['EMAX0'] * max(contractile, 0.02)
            * (MASS / p['MASS0']) ** p['EMASS_N']
            * (1.0 - p['NE_DESENS'] * min(relu(NE - 1.0) / 2.0, 1.0)))
    # The ESPVR volume intercept is NOT fixed: it shifts rightward as the
    # chamber remodels.  Without this, end-systolic volume stays small however
    # far the ventricle dilates, ejection fraction rises instead of falling,
    # end-systolic wall stress never rises, and the concentric-hypertrophy
    # brake never engages -- so every infarct diverges.  One term, and it is
    # what makes the bifurcation have a stable branch at all.
    v0 = p['V0E'] * (EDVS / p['EDV0'])
    emax = emax / (EDVS / p['EDV0']) ** p['EDIL_N']
    ESV = v0 + Pes / max(emax, 0.15)

    # Filling pressure is set by regulated volume status, plus a SATURATING
    # contribution from incomplete emptying.  Diastolic stiffening does not
    # raise the filling pressure -- it reduces the volume reached at that
    # pressure, which is where it belongs (restrictive physiology).
    x = relu(ESV / p['ESV0'] - 1.0)
    Ped = p['PED0'] * VOL * (1.0 + p['KPES'] * x / (1.0 + x / p['PESSAT']))
    EDV = EDVS * ((Ped / p['PED0']) / (1.0 + p['KSTIF_COL'] * col_n)) ** (1.0 / p['NPED'])
    ESV = min(ESV, EDV - 5.0)
    SV = max(EDV - ESV, 5.0)
    CO = SV * HR / 1000.0

    r_ed, h_ed = geometry(EDV, MASS)
    r_es, h_es = geometry(max(ESV, 15.0), MASS)
    h_inf = max(h_ed * (1.0 - THIN), 0.15)

    return dict(
        lay=lay, pat=pat, rpp=rpp, VIA=VIA, W=W,
        is_lv=is_lv, ni_lv=ni_lv, nr_lv=nr_lv, col_n=col_n,
        contractile=contractile, ne_eff=ne_eff, ang_eff=ANG,
        ald_eff=ald_eff, np_eff=np_eff,
        HR=HR, SBP=SBP, Pes=Pes, emax=emax, ESV=ESV, Ped=Ped,
        EDV=EDV, EDVS=EDVS, MASS=MASS, SV=SV, CO=CO, THIN=THIN,
        r_ed=r_ed, h_ed=h_ed, h_inf=h_inf,
        ws_ed=Ped * r_ed / (2.0 * h_ed),
        ws_es=Pes * r_es / (2.0 * h_es),
        ws_inf=Ped * r_ed / (2.0 * h_inf),
    )


# =====================================================================
# 4.  the right-hand side
# =====================================================================

def rhs(t, y, p, d, sp):
    dy = np.zeros(NST)
    W = p['W']

    # -- 4a. drug input rates (mg/h) ---------------------------------
    r_tnk = (d['TNK_DOSE'] / (5.0 / 60.0) * window(t, d['T_LYT'], 5.0 / 60.0)
             if d['T_LYT'] is not None else 0.0)
    if d['T_TIC'] is not None:
        r_tic = (d['TIC_LOAD'] / (5.0 / 60.0) * window(t, d['T_TIC'], 5.0 / 60.0)
                 + d['TIC_MAINT'] / d['TIC_TAU'] * sstep(t, d['T_TIC'] + d['TIC_TAU'], 0.2))
    else:
        r_tic = 0.0
    r_met_iv = (d['MET_IV_DOSE'] / (10.0 / 60.0) * window(t, d['T_MET_IV'], 10.0 / 60.0)
                if d['T_MET_IV'] is not None else 0.0)
    r_met_po = d['MET_PO'] / 24.0 * sstep(t, d['T_MET_PO'], 0.2)
    r_ram = d['RAM_PO'] / 24.0 * sstep(t, d['T_RAM'], 0.2)
    r_epl = d['EPL_PO'] / 24.0 * sstep(t, d['T_EPL'], 0.2)
    r_emp = d['EMP_PO'] / 24.0 * sstep(t, d['T_EMP'], 0.2)
    r_colc = d['COLC_PO'] / 24.0 * sstep(t, d['T_COLC'], 0.2)
    r_can = (d['CAN_DOSE'] / 6.0 * window(t, d['T_CAN'], 6.0, 0.2)
             if d['T_CAN'] is not None else 0.0)
    r_csa = (d['CSA_DOSE'] / (10.0 / 60.0) * window(t, d['T_CSA'], 10.0 / 60.0)
             if d['T_CSA'] is not None else 0.0)

    # -- 4b. pharmacokinetics ----------------------------------------
    c_tnk = max(y[IDX['TNK1']], 0.0) / p['TNK_V1']
    c_tnk2 = max(y[IDX['TNK2']], 0.0) / p['TNK_V2']
    dy[IDX['TNK1']] = r_tnk - p['TNK_CL'] * c_tnk - p['TNK_Q'] * c_tnk + p['TNK_Q'] * c_tnk2
    dy[IDX['TNK2']] = p['TNK_Q'] * c_tnk - p['TNK_Q'] * c_tnk2

    pdv = drug_pd(t, y, p, d)
    dy[IDX['TICd']] = r_tic * p['TIC_F'] - p['TIC_KA'] * max(y[IDX['TICd']], 0.0)
    dy[IDX['TICc']] = p['TIC_KA'] * max(y[IDX['TICd']], 0.0) - p['TIC_CL'] * pdv['c_tic']
    dy[IDX['METd']] = r_met_po * p['MET_F'] - p['MET_KA'] * max(y[IDX['METd']], 0.0)
    dy[IDX['METc']] = (r_met_iv + p['MET_KA'] * max(y[IDX['METd']], 0.0)
                       - p['MET_CL'] * pdv['c_met'])
    dy[IDX['RAMd']] = r_ram * p['RAM_F'] - p['RAM_KA'] * max(y[IDX['RAMd']], 0.0)
    dy[IDX['RAMc']] = p['RAM_KA'] * max(y[IDX['RAMd']], 0.0) - p['RAM_CL'] * pdv['c_ram']
    dy[IDX['EPL']] = r_epl - p['EPL_KEL'] * max(y[IDX['EPL']], 0.0)
    dy[IDX['EMP']] = r_emp - p['EMP_KEL'] * max(y[IDX['EMP']], 0.0)
    dy[IDX['COLC']] = r_colc - p['COLC_KEL'] * max(y[IDX['COLC']], 0.0)
    dy[IDX['CAN']] = r_can - p['CAN_KEL'] * max(y[IDX['CAN']], 0.0)
    dy[IDX['CSA']] = r_csa - p['CSA_KEL'] * max(y[IDX['CSA']], 0.0)

    # -- 4c. mechanics (which also gives us flow per layer) ----------
    m = mechanics(t, y, p, d, sp, pdv)
    lay = m['lay']

    ROS = max(y[IDX['ROS']], 0.0)
    MVO = clip01(y[IDX['MVO']])
    THR = clip01(y[IDX['THR']])
    PLN = max(y[IDX['PLN']], 0.0)
    PLG = clip01(y[IDX['PLG']])
    FIB = max(y[IDX['FIB']], 0.0)
    PAI = max(y[IDX['PAI']], 0.0)
    DAMP = max(y[IDX['DAMP']], 0.0)
    NEU = max(y[IDX['NEU']], 0.0)
    M1 = max(y[IDX['M1']], 0.0)
    M2 = max(y[IDX['M2']], 0.0)
    IL1 = max(y[IDX['IL1']], 0.0)
    IL6 = max(y[IDX['IL6']], 0.0)
    CRP = max(y[IDX['CRP']], 0.0)
    TGF = max(y[IDX['TGF']], 0.0)
    MYOF = clip01(y[IDX['MYOF']])
    COL = max(y[IDX['COL']], 0.0)
    MMP = max(y[IDX['MMP']], 0.0)
    STUN = clip01(y[IDX['STUN']])

    # -- 4d. epicardial thrombus, lysis, fibrinolytic system ---------
    lysis = p['KLYS0'] + p['KLYS_PL'] * hill(PLN, p['KPL50'], p['NPL'])
    plt_drive = (1.0 - pdv['plt_inh']) * (1.0 + p['KPLT_PLN'] * PLN) * (1.0 - pdv['hep'])
    pci = p['KPCI'] * sstep(t, d['T_PCI'], 0.05)
    dy[IDX['THR']] = (p['KREG'] * plt_drive * (1.0 - THR) - lysis * THR
                      - pci * relu(THR - p['PCI_FAIL']))

    tnk_n = c_tnk / 5.0
    dy[IDX['PLN']] = p['KPG'] * tnk_n * PLG / (1.0 + PAI / p['KI_PAI']) - p['KPLD'] * PLN
    dy[IDX['PLG']] = -p['KPGD'] * tnk_n * PLG + p['KPGS'] * (1.0 - PLG)
    dy[IDX['FIB']] = -p['KFIBD'] * PLN + p['KFIBS'] * (1.0 - FIB)
    dy[IDX['PAI']] = p['KPAID'] * (1.0 + p['KPAI_I'] * IL6 - PAI)

    # -- 4e. per-layer ischemia / reperfusion  ==  THE WAVEFRONT -----
    dNI_tot = dNR_tot = reox_flux = mvo_endo = qavg = 0.0
    for i in range(NL):
        L = lay[i]
        E = clip01(y[IDX['E'] + i])
        G = max(y[IDX['G'] + i], 0.0)
        H = max(y[IDX['H'] + i], 0.0)
        C = max(y[IDX['C'] + i], 0.0)
        PO = clip01(y[IDX['P'] + i])
        SU = max(y[IDX['SUC'] + i], 0.0)
        VIA = m['VIA'][i]

        # Energy charge falls only when supply cannot cover BASAL demand.
        # The E/(E+EFLOOR) factor is not biology, it is a soft floor: it
        # keeps the fall near-linear while there is ATP left and stops the
        # state going negative once there is not.
        dy[IDX['E'] + i] = p['KE'] * (-L['deficit'] * E / (E + p['EFLOOR'])
                                      + p['KREC'] * L['surplus'] * (1.0 - E))
        dy[IDX['G'] + i] = -p['KGLY'] * L['anaer'] + p['KGLYREP'] * L['qc'] * (1.0 - G)

        # acid: made anaerobically, removed ONLY by flow.  This is the
        # whole of the pH paradox -- the tissue's own protection against
        # the pore is washed away by the treatment.
        dy[IDX['H'] + i] = p['KH'] * L['anaer'] - p['KHW'] * L['qc'] * H

        # succinate: accumulates while anaerobic, burned the instant
        # oxygen returns.  Its oxidation IS the oxidant burst, which is
        # why the burst is a reperfusion event and is exactly zero in a
        # heart that was never ischemic.
        suc_ox = p['KSUCO'] * L['qc'] * SU
        dy[IDX['SUC'] + i] = p['KSUC'] * L['anaer'] - suc_ox

        # calcium: gained as energy fails, plus a surge at reflow that is
        # proportional to accumulated acid (NHE -> Na+ -> reverse NCX)
        dy[IDX['C'] + i] = (p['KCA'] * relu(1.0 - E) ** p['NCA']
                            + p['KCA_RP'] * L['qc'] * H
                            - p['KCAO'] * E * C)

        # mPTP: needs calcium AND oxidant AND the acid gate to have opened
        ph_gate = 1.0 / (1.0 + H / p['HP50'])
        kon = p['KP_ON'] * (1.0 - pdv['csa']) * (1.0 - p['PRECOND'] * p['PRECOND_EFF'])
        dy[IDX['P'] + i] = (kon * hill(C, p['CA50'], p['NP_CA'])
                            * hill(ROS, p['R50'], p['NP_R']) * ph_gate * (1.0 - PO)
                            - p['KP_OFF'] * PO * E)

        # necrosis: two mechanisms, tracked separately, so the split
        # between them is a RESULT and not an assumption
        dy[IDX['NI'] + i] = (p['KNI'] * relu(1.0 - E) ** p['NNI']
                             * (1.0 + p['KOSM'] * H) * VIA)
        dy[IDX['NR'] + i] = p['KNR'] * PO * VIA
        dNI_tot += W[i] * dy[IDX['NI'] + i]
        dNR_tot += W[i] * dy[IDX['NR'] + i]

        reox_flux += W[i] * VIA * suc_ox
        mvo_endo += W[i] * p['GM'][i] * relu(1.0 - E) ** 3 * min(L['q_ante'], 1.0)
        qavg += W[i] * L['qc']

    dy[IDX['ROS']] = p['KROS'] * reox_flux + p['KROS_N'] * NEU - p['KROSD'] * ROS

    # -- 4f. microvascular obstruction, and its positive feedback ----
    # lysing or crushing a clot sends some of it downstream, so distal
    # embolisation is proportional to the RATE of proximal clot removal
    embol = p['KMVO_P'] * (1.0 - pdv['plt_inh']) * relu(-dy[IDX['THR']])
    dy[IDX['MVO']] = ((p['KMVO_E'] * mvo_endo + p['KMVO_N'] * NEU + embol) * (1.0 - MVO)
                      - p['KMVO_R'] * MVO)

    # -- 4g. inflammation and healing --------------------------------
    il1_act = IL1 * (1.0 - pdv['can'])
    inv = 1.0 / (NEU + 0.05)
    switch = inv / (p['KSW50'] + inv)          # M1->M2 follows PMN clearance

    dy[IDX['DAMP']] = p['KD1'] * (dNI_tot + dNR_tot) - p['KD2'] * DAMP
    dy[IDX['NEU']] = p['KN1'] * DAMP * qavg - p['KN2'] * NEU
    dy[IDX['M1']] = (p['KM1'] * (0.6 * DAMP + 0.4 * NEU)
                     - p['KSW'] * M1 * switch - p['KM1D'] * M1)
    dy[IDX['M2']] = p['KSW'] * M1 * switch - p['KM2D'] * M2
    dy[IDX['IL1']] = p['KI1'] * (M1 + 0.5 * NEU) * (1.0 - pdv['colc']) - p['KI1D'] * IL1
    dy[IDX['IL6']] = (p['KI6'] * (0.7 * il1_act + 0.3 * relu(m['ne_eff'] - 1.0))
                      - p['KI6D'] * IL6)
    dy[IDX['CRP']] = p['KC1'] * IL6 - p['KC2'] * CRP
    dy[IDX['TGF']] = p['KT1'] * M2 - p['KT2'] * TGF
    dy[IDX['MYOF']] = (p['KMY'] * TGF * (1.0 + 0.4 * relu(m['ald_eff'] - 1.0)) * (1.0 - MYOF)
                       - p['KMYD'] * MYOF * (1.0 + 2.0 * m['col_n']))
    inj = max(m['is_lv'] / max(p['AAR'], 1e-6), 0.02)
    dy[IDX['COL']] = (p['KCO'] * MYOF * relu(1.0 - COL / (p['COLMAX'] * inj))
                      - p['KCOD'] * MMP * COL)
    dy[IDX['MMP']] = (p['KMM'] * (0.5 * NEU + 0.3 * M1 + 0.2 * il1_act)
                      - p['KMMD'] * MMP)

    # -- 4h. mechanics  ==  THE BIFURCATION --------------------------
    scar = m['col_n']
    over_ed = relu(m['ws_ed'] / sp['WS_SET'] - 1.0)
    over_es = relu(m['ws_es'] / sp['WS_SET_ES'] - 1.0)
    over_inf = relu(m['ws_inf'] / sp['WS_SET'] - 1.0)
    under_ed = relu(1.0 - m['ws_ed'] / sp['WS_SET'])
    amp = ((1.0 + p['KDIL_A'] * relu(m['ang_eff'] - 1.0)
            + p['KDIL_L'] * relu(m['ald_eff'] - 1.0))
           * (1.0 - 0.15 * pdv['sglt'])
           * (1.0 - 0.10 * min(relu(m['np_eff'] - 1.0) / 3.0, 1.0)))

    room = relu(1.0 - m['EDVS'] / p['EDVMAX'])      # numerical ceiling only
    unhealed = relu(1.0 - scar / p['SCARSET'])
    dy[IDX['EDVS']] = ((p['KDIL'] * m['EDVS'] * over_ed * amp
                        + p['KEXP'] * m['EDVS'] * over_inf * unhealed
                        * m['is_lv'] / max(p['AAR'], 1e-6)) * room
                       - p['KREVR'] * m['EDVS'] * under_ed)
    # SCAR CANNOT HYPERTROPHY.  Only surviving myocardium can add mass in
    # response to wall stress, so the compensatory brake is scaled by the
    # living fraction (1 - infarct fraction).  That single factor is what
    # makes the remodelling bifurcation exist: below some infarct size the
    # surviving wall can still add mass fast enough to hold wall stress at its
    # set point, and above it, it cannot.  No critical infarct size is written
    # anywhere -- it is where these two rates cross.
    alive = relu(1.0 - m['is_lv'])
    headroom = relu(1.0 - m['MASS'] / p['MASSMAX'])
    dy[IDX['MASS']] = (m['MASS'] * alive * headroom
                       * (p['KHYP'] * over_es + p['KHYP_E'] * over_ed)
                       - p['KATR'] * m['MASS'] * relu(1.0 - m['ws_es'] / sp['WS_SET_ES']))
    dy[IDX['THIN']] = (p['KTH'] * over_inf * unhealed * (1.0 + 0.5 * MMP)
                       * relu(p['THINMAX'] - m['THIN'])
                       - p['KTHR'] * m['THIN'] * scar)
    ca_avg = sum(W[i] * max(y[IDX['C'] + i], 0.0) for i in range(NL))
    dy[IDX['STUN']] = (p['KST_ON'] * (ROS + 0.5 * ca_avg) * (1.0 - STUN)
                       - p['KST_OFF'] * STUN)

    # -- 4i. neurohormonal -------------------------------------------
    co_n = m['CO'] / sp['CO0']
    dy[IDX['NE']] = p['KNE'] * (1.0 + p['GNE'] * relu(1.0 - co_n)
                                + p['GNE_IS'] * m['is_lv']
                                - max(y[IDX['NE']], 0.0))
    ang_tgt = ((1.0 + p['GANG'] * relu(1.0 - co_n) + p['GANG_IS'] * m['is_lv']
                + p['GANG_NE'] * relu(m['ne_eff'] - 1.0)) * (1.0 - pdv['acei']))
    dy[IDX['ANG']] = p['KANG'] * (ang_tgt - max(y[IDX['ANG']], 0.0))
    dy[IDX['ALD']] = p['KALD'] * (1.0 + p['GALD'] * relu(y[IDX['ANG']] - 1.0)
                                  - max(y[IDX['ALD']], 0.0))
    ws_ratio = min(m['ws_ed'] / sp['WS_SET'], p['BNPMAX'])
    dy[IDX['BNP']] = p['KBNP'] * (ws_ratio ** p['NBNP'] - max(y[IDX['BNP']], 0.0))
    # the natriuretic-peptide effect on plasma volume saturates; it is a
    # counter-regulator, not an unlimited diuretic
    vol_tgt = max(1.0 + p['GVOL_A'] * relu(m['ald_eff'] - 1.0)
                  - p['GVOL_N'] * min(relu(m['np_eff'] - 1.0), 1.5)
                  - p['GVOL_S'] * pdv['sglt'], 0.6)
    dy[IDX['VOL']] = p['KVOL'] * (vol_tgt - max(y[IDX['VOL']], 0.3))

    # -- 4j. biomarkers.  Release needs perfusion -- which is why a
    #        reperfused infarct gives a tall EARLY troponin peak and an
    #        occluded one a late blunted peak at a LARGER true size.
    wash = p['WASH_FLOOR'] + (1.0 - p['WASH_FLOOR']) * qavg
    ndot = (dNI_tot + dNR_tot) * p['AAR']
    dy[IDX['TNI']] = p['KTN'] * ndot * wash - p['KTND'] * max(y[IDX['TNI']], 0.0)
    dy[IDX['CKMB']] = p['KCK'] * ndot * wash - p['KCKD'] * max(y[IDX['CKMB']], 0.0)

    return dy


# =====================================================================
# 5.  driver
# =====================================================================

def derived(t, y, p, d, sp):
    """Reported quantities, computed through mechanics() -- the same code
    the ODE right-hand side uses, so a report can never disagree with the
    simulation that produced it."""
    pdv = drug_pd(t, y, p, d)
    m = mechanics(t, y, p, d, sp, pdv)
    N = [clip01(y[IDX['NI'] + i]) + clip01(y[IDX['NR'] + i]) for i in range(NL)]
    return dict(
        t=t,
        IS=100.0 * m['is_lv'], IS_ISCH=100.0 * m['ni_lv'], IS_REP=100.0 * m['nr_lv'],
        RPFRAC=100.0 * m['nr_lv'] / m['is_lv'] if m['is_lv'] > 1e-9 else 0.0,
        SALV=100.0 * (p['AAR'] - m['is_lv']) / p['AAR'],
        LAYERS=[100.0 * v for v in N],
        MVO=100.0 * clip01(y[IDX['MVO']]) * p['AAR'],
        EDV=m['EDV'], EDVS=m['EDVS'], ESV=m['ESV'], MASS=m['MASS'],
        EF=100.0 * m['SV'] / m['EDV'], CO=m['CO'], HR=m['HR'], SBP=m['SBP'],
        WS=m['ws_ed'], WS_INF=m['ws_inf'], PED=m['Ped'],
        H_ED=m['h_ed'], H_INF=m['h_inf'], CONTR=m['contractile'],
        THIN=100.0 * clip01(y[IDX['THIN']]), SCAR=m['col_n'],
        TNI=max(y[IDX['TNI']], 0.0), CKMB=max(y[IDX['CKMB']], 0.0),
        BNP=y[IDX['BNP']], CRP=y[IDX['CRP']], FIB=y[IDX['FIB']],
        PAT=100.0 * m['pat'], STUN=100.0 * clip01(y[IDX['STUN']]),
        CEIL=m['EDVS'] > 0.98 * p['EDVMAX'],
    )


def _grid(tend):
    """Output grid.  A STEMI trajectory needs minute resolution in the
    first hours and daily resolution at six months, so a uniform grid is
    the wrong shape -- it is either too coarse to see the mPTP transient
    or absurdly large.  Resolution is piecewise instead."""
    pieces = []
    for a, b, step in ((0.0, 6.0, 0.01), (6.0, 48.0, 0.10),
                       (48.0, 24.0 * 30, 1.0), (24.0 * 30, 24.0 * 400, 6.0)):
        if tend <= a:
            break
        pieces.append(np.arange(a, min(b, tend) + step * 0.5, step))
    g = np.unique(np.concatenate(pieces + [np.array([0.0, tend])]))
    return g[g <= tend + 1e-9]


def _breakpoints(d, tend):
    """Every time at which an input turns on or off.  The integrator is
    restarted at each one so no smooth ramp is ever stepped over -- this
    is what lets a single call span a two-minute mPTP transient and a
    365-day remodelling trajectory without a tiny max_step everywhere."""
    bp = {0.0, float(tend)}
    for k in ('T_OCC', 'T_PCI', 'T_LYT', 'T_ASA', 'T_TIC', 'T_HEP',
              'T_MET_IV', 'T_MET_PO', 'T_RAM', 'T_EPL', 'T_EMP',
              'T_COLC', 'T_CAN', 'T_CSA'):
        v = d.get(k)
        if v is not None and 0.0 <= v <= tend:
            bp.add(float(v))
    if d.get('T_TIC') is not None and d['T_TIC'] + d['TIC_TAU'] <= tend:
        bp.add(float(d['T_TIC'] + d['TIC_TAU']))
    for extra in (0.5, 2.0, 12.0, 48.0, 24.0 * 7, 24.0 * 30):
        if extra < tend:
            bp.add(float(extra))
    return sorted(bp)


def _ceiling_event(t, y, p, d, sp):
    """Terminal event: chamber growth has reached the ceiling.

    Integration STOPS here, for two reasons.  First, nothing past this point
    is meaningful -- the model has no death and no other saturating mechanism,
    so a divergent run just grinds along the ceiling.  Second, it grinds very
    slowly: pinned against the ceiling the system is stiff, and those runs
    dominated the total runtime while contributing no information.
    """
    return y[IDX['EDVS']] - 0.995 * p['EDVMAX']


_ceiling_event.terminal = True
_ceiling_event.direction = 1


def run(tend=24.0, over=None, dose=None):
    """Piecewise-staged integration: the horizon is split at every input
    event; each segment gets a finely stepped first half hour and then a
    step size proportional to its own length."""
    p = dict(P)
    if over:
        p.update(over)
    d = dict(D0)
    if dose:
        d.update(dose)
    sp = baseline_setpoints(p)
    y = initial_state(p)
    tgrid = _grid(float(tend))

    bps = _breakpoints(d, tend)
    ts, ys = [], []
    stopped = False
    for a, b in zip(bps[:-1], bps[1:]):
        if stopped:
            break
        if b <= a:
            continue
        subs = ([(a, a + 0.5, 0.02), (a + 0.5, b, max(0.20, min(4.0, (b - a) / 40.0)))]
                if b - a > 0.5 else [(a, b, 0.02)])
        for (aa, bb, ms) in subs:
            if bb <= aa:
                continue
            te = tgrid[(tgrid > aa) & (tgrid <= bb)]
            te_run = np.unique(np.append(te, bb))     # always reach bb
            sol = solve_ivp(rhs, (aa, bb), y, args=(p, d, sp), method='LSODA',
                            t_eval=te_run, rtol=1e-6, atol=1e-9, max_step=ms,
                            events=_ceiling_event)
            if not sol.success:
                raise RuntimeError(f"segment [{aa:.3f},{bb:.3f}]: {sol.message}")
            if len(te) and sol.y.shape[1]:
                keep = np.isin(sol.t, te)
                ts.append(sol.t[keep])
                ys.append(sol.y[:, keep])
            if sol.y.shape[1]:
                y = sol.y[:, -1].copy()
            if sol.status == 1:                 # ceiling reached: stop here
                if sol.t_events[0].size and (not ts or ts[-1][-1] < sol.t_events[0][0]):
                    ts.append(np.array([float(sol.t_events[0][0])]))
                    ys.append(np.asarray(sol.y_events[0][0]).reshape(-1, 1))
                    y = np.asarray(sol.y_events[0][0]).copy()
                stopped = True
                break

    y0 = initial_state(p).reshape(-1, 1)
    sol = type('Sol', (), {})()
    sol.t = np.concatenate([np.array([0.0])] + ts) if ts else np.array([0.0])
    sol.y = np.concatenate([y0] + ys, axis=1) if ys else y0
    return p, d, sp, sol


def at(sol, p, d, sp, hours):
    k = int(np.argmin(np.abs(sol.t - hours)))
    return derived(sol.t[k], sol.y[:, k], p, d, sp)


def summary(tend=24.0, **kw):
    p, d, sp, sol = run(tend=tend, **kw)
    out = derived(sol.t[-1], sol.y[:, -1], p, d, sp)
    out.update(
        TNI_PEAK=float(np.max(sol.y[IDX['TNI']])),
        TNI_AUC=float(np.trapezoid(sol.y[IDX['TNI']], sol.t)),
        TNI_TPEAK=float(sol.t[int(np.argmax(sol.y[IDX['TNI']]))]),
        CK_PEAK=float(np.max(sol.y[IDX['CKMB']])),
        CK_TPEAK=float(sol.t[int(np.argmax(sol.y[IDX['CKMB']]))]),
        MVO_MAX=float(np.max(sol.y[IDX['MVO']]) * 100 * p['AAR']),
        CRP_PEAK=float(np.max(sol.y[IDX['CRP']])),
        FIB_MIN=float(np.min(sol.y[IDX['FIB']])),
        PLN_AUC=float(np.trapezoid(sol.y[IDX['PLN']], sol.t)),
        sol=sol, p=p, d=d, sp=sp,
    )
    return out


def time_to_patency(sol, thresh=0.70):
    pat = 1.0 - np.clip(sol.y[IDX['THR']], 0, 1)
    idx = np.where(pat >= thresh)[0]
    return float(sol.t[idx[0]]) if len(idx) else float('nan')


def ceiling_day(p, sol):
    """Day on which chamber growth reached EDVMAX, or None.

    Past that point the trajectory is NOT a volume prediction: the model has no
    death and no other saturating mechanism, so a divergent run simply runs into
    the ceiling.  What such a run reports is a VERDICT (this ventricle does not
    stabilise), never a number of millilitres."""
    hit = np.where(sol.y[IDX['EDVS']] >= 0.98 * p['EDVMAX'])[0]
    return float(sol.t[hit[0]] / 24.0) if len(hit) else None


def verdict_of(p, sol, growth):
    if ceiling_day(p, sol) is not None:
        return 'DIVERGED'
    return 'divergent' if growth > 12.0 else ('creeping' if growth > 4.0 else 'stable')


def time_to_fraction(p, d, sp, sol, frac):
    """Time at which the infarct reaches `frac` of its own final size."""
    isv = np.array([derived(sol.t[k], sol.y[:, k], p, d, sp)['IS']
                    for k in range(0, len(sol.t), 5)])
    tt = sol.t[::5]
    if isv[-1] <= 1e-9:
        return float('nan')
    j = np.where(isv >= frac * isv[-1])[0]
    return float(tt[j[0]]) if len(j) else float('nan')


