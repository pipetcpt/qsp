##  Where the model is honest about missing the target: the mortality effects of
##  PRONE POSITION (model ARR 7.2% vs PROSEVA 16.8%) and of DEXAMETHASONE
##  (model ARR 4.9% vs DEXA-ARDS 15%) are roughly half the size reported in
##  those two trials. Both trials are single results with effect sizes at the
##  large end of the ARDS literature, and a mechanistic model that reproduced
##  them exactly would have to attribute more of the mortality signal to
##  regional stress homogenisation, and to NF-kB transrepression, than the
##  physiological evidence supports. The ordering, direction and the mechanism
##  of every intervention are reproduced; the two effect magnitudes are not
##  tuned to match, and should not be read as predictions of trial results.
