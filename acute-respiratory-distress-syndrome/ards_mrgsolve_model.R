##  Acute Respiratory Distress Syndrome (ARDS) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : ARDS (Berlin definition) — an acute, diffuse, inflammatory lung
##             injury in which a direct (pneumonia, aspiration, contusion) or
##             indirect (extrapulmonary sepsis, pancreatitis, trauma, TRALI)
##             insult breaks BOTH sides of the alveolar-capillary barrier. The
##             resulting protein-rich oedema floods and de-recruits alveoli, so
##             the aerated lung shrinks to a "baby lung" of 20-35% of the
##             parenchyma. Shunt through that flooded lung produces refractory
##             hypoxaemia; capillary microthrombosis produces dead space.
##
##             The distinguishing feature of ARDS as a QSP problem is that the
##             TREATMENT IS ALSO THE INJURY: every breath the ventilator gives
##             is delivered into whatever aerated lung is left, so the same
##             tidal volume that is harmless in a normal lung is a strain of
##             1.5-2.0 in a baby lung. This model therefore closes the loop
##
##                inflammation -> barrier failure -> oedema -> loss of aerated
##                lung -> higher strain / driving pressure / mechanical power
##                for the SAME ventilator setting -> VILI -> biotrauma ->
##                more inflammation
##
##             which is why interventions that change nothing about the biology
##             (tidal volume, prone position, ECMO) are the ones with the
##             largest mortality effects, while most anti-inflammatory drugs
##             tested in ARDS have failed.
##
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5; developed and validated under 2.0.1)
##
##  Scope    : 38 ODE compartments —
##             * PK  : dexamethasone, methylprednisolone (both feeding one
##                     glucocorticoid-receptor genomic effect state),
##                     cisatracurium + its neuromuscular-block effect site,
##                     inhaled vasodilator (iNO / epoprostenol) effect site,
##                     tocilizumab, furosemide.
##             * Injury: insult burden, DAMPs, NF-kB, TNF-a, IL-1b, IL-6,
##                     IL-8, IL-10, alveolar neutrophils, NETs/elastase,
##                     oxidant burden, M1 and M2 macrophage programmes.
##             * Barrier: epithelial integrity, AT2 progenitor pool,
##                     surfactant pool, endothelial integrity, angiopoietin-2,
##                     PAI-1, alveolar fibrin/microthrombi.
##             * Physiology: extravascular lung water, cumulative fluid
##                     balance, cumulative VILI burden.
##             * Late phase: TGF-b1, collagen.
##             * Systemic: non-pulmonary SOFA, cumulative mortality hazard,
##                     ICU-acquired weakness, glucose, ventilator-free time.
##
##  Time     : HOURS (default horizon 672 h = 28 days, the standard endpoint
##             window for ventilator-free days and 28-day mortality).
##  Units    : cytokines pg/mL · Ang-2 and PAI-1 ng/mL · EVLW mL/kg PBW ·
##             fluid balance L · pressures cmH2O · PaO2/FiO2 mmHg ·
##             PaCO2 mmHg · compliance mL/cmH2O · mechanical power J/min ·
##             PVR dyn·s·cm^-5 · glucose mg/dL · drugs in mg (amounts) with
##             stated volumes, except tocilizumab which is dosed in mg into a
##             4 L central volume.
##             Barrier integrities (EPI, ENDO, SURF, AT2P) and the macrophage,
##             neutrophil, NET, ROS, DAMP and VILI pools are dimensionless
##             0-1(+) indices — the library's convention when the clinical
##             readout, not the assay, is the object of interest.
##
##  SELF-CALIBRATING BASELINE
##  -------------------------
##  A patient does not arrive at ICU admission in a healthy steady state, and
##  the clinician does not know their alveolar barrier integrity — they know
##  the PaO2/FiO2 ratio. [MAIN] therefore INVERTS the physiology: given the
##  presenting PaO2/FiO2 (PF0), the ventilator settings at enrolment, the
##  direct/indirect injury pattern (DIRECT) and the inflammatory subphenotype
##  (HYPER), it solves backwards for the shunt, the aerated fraction, the
##  split of non-aerated lung between flooding and atelectasis, and finally —
##  by a short fixed-point iteration on the lung-water balance — for the
##  epithelial and endothelial integrities and the surfactant pool that
##  actually produce that PaO2/FiO2. Cytokine production constants are then
##  back-calculated so that the prescribed presenting cytokine profile is the
##  one the model's own NF-kB state supports.
##
##  Consequence: change PF0 from 250 to 90 and every downstream state — EVLW,
##  compliance, driving pressure, mechanical power, hazard — moves the way it
##  moves in a real patient, without touching a single initial condition by
##  hand. Nothing in the untreated arm drifts for bookkeeping reasons; it
##  drifts because the insult resolves (or does not) and because the
##  ventilator keeps delivering energy into a shrunken lung.
##
##  Scenarios: 14 prebuilt — see ARDS_simulate_scenarios() at the bottom.
##
##  Anchors  :
##    * ARDSNet ARMA (NEJM 2000;342:1301) — 6 vs 12 mL/kg PBW: mortality
##      39.8% -> 31.0%. The single largest therapeutic effect in ARDS and the
##      calibration target for the VILI block (scenarios 1-2).
##    * Amato 2015 NEJM 372:747 — driving pressure is the ventilator variable
##      most strongly associated with survival (mediation analysis of 3562
##      patients); implemented as an explicit hazard term, not as a proxy.
##    * Gattinoni 2016 Intensive Care Med 42:1567 — mechanical power; the
##      ~12 J/min region as the inflection for VILI.
##    * PROSEVA (Guerin 2013 NEJM 368:2159) — >=16 h/day prone in PF<150:
##      28-day mortality 32.8% -> 16.0% (scenario 4).
##    * ACURASYS (Papazian 2010 NEJM 363:1107) vs ROSE (NHLBI PETAL 2019 NEJM
##      380:1997) — 48 h cisatracurium: benefit under deep sedation, neutral
##      under light sedation; the model reproduces the divergence through the
##      P-SILI/effort term (scenario 5 vs 5b).
##    * FACTT (Wiedemann 2006 NEJM 354:2564) — conservative fluid strategy:
##      +2.5 ventilator-free days, no change in mortality (scenario 7).
##    * DEXA-ARDS (Villar 2020 Lancet Respir Med 8:267) — dexamethasone 20 mg
##      d1-5 then 10 mg d6-10: +4.8 ventilator-free days, mortality
##      36% -> 21% (scenario 6); RECOVERY (NEJM 2021;384:693) for COVID-ARDS.
##    * ARDSNet LaSRS (Steinberg 2006 NEJM 354:1671) — methylprednisolone
##      started after day 14 increases mortality; reproduced in scenario 13
##      through the secondary-infection and weakness terms.
##    * EOLIA (Combes 2018 NEJM 378:1965) + CESAR — VV-ECMO with
##      ultraprotective settings (scenario 9).
##    * Calfee 2014 Lancet Respir Med 2:611 / Famous 2017 AJRCCM 195:331 —
##      hyper- vs hypo-inflammatory latent classes and their heterogeneous
##      treatment effects (scenarios 11-12).
##    * Taylor 2004 JAMA 291:1603 (iNO: oxygenation up, mortality unchanged)
##      and Matthay 2019 Lancet Respir Med 7:154 (MSC) for the "physiology
##      improves, outcome does not" pattern the hazard block must reproduce
##      (scenario 8).
##  ============================================================================
[PROB]
QSP model of the acute respiratory distress syndrome. Couples (1) a
DAMP/NF-kB-driven cytokine and neutrophil injury cascade, (2) failure and
repair of the alveolar epithelial and pulmonary endothelial barriers with an
explicit surfactant and AT2-progenitor pool, (3) a Starling lung-water balance
with alveolar fluid clearance, (4) a respiratory-mechanics layer in which the
aerated "baby lung" sets compliance, driving pressure, strain and mechanical
power for whatever the ventilator is set to, (5) a VILI feedback that returns
mechanical energy to the inflammatory cascade as biotrauma, and (6) shunt /
dead-space gas exchange with right-ventricular consequences — to the
pharmacology of corticosteroids, neuromuscular blockade, inhaled pulmonary
vasodilators, IL-6 receptor blockade, JAK inhibition and diuretics, and to the
non-pharmacological interventions (low tidal volume, PEEP, prone position,
conservative fluids, VV-ECMO) that actually carry the mortality signal.

