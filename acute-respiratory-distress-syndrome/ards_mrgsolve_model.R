// ---------------------------------------------------------------------------
// ARDS_PHYSIO() — the algebraic respiratory-physiology layer.
//
// Expanded verbatim inside [ODE] and inside [TABLE] so that the mechanics the
// solver integrates against and the mechanics that are reported are, by
// construction, the same code. Parameters and compartments are in scope at
// both expansion sites.
//
// Order of derivation:
//   lung water + surfactant + PEEP -> aerated fraction -> compliance ->
//   driving pressure / plateau -> spontaneous effort (P-SILI) -> effective
//   tidal volume -> strain, mechanical power -> shunt and dead space ->
//   PaO2/FiO2, PaCO2, pH -> PVR and cardiac output -> alveolar fluid
//   clearance and transvascular filtration.
// ---------------------------------------------------------------------------
#define ARDS_PHYSIO()                                                          \
  double pronef  = (PRONE_H > 0.0) ? (PRONE_H / 24.0) : 0.0;                   \
  double vt_kg   = (ECMO > 0.5) ? VT_ECMO : VT_KG;                             \
  double rr_set  = (ECMO > 0.5) ? RR_ECMO : RR;                                \
  double vt_set  = vt_kg * PBW;                                                \
  double edema   = fmax(0.0, EVLW - EVLW_DRY);                                 \
  double ned     = (edema / (edema + K_ED)) * (1.0 - PRONE_ED * pronef);       \
  double natel_p = (1.0 - SURF) * ATEL_MAX;                                    \
  double peep_rel= RECRUIT * PEEP / (PEEP + P50_PEEP);                         \
  double natel   = natel_p * (1.0 - peep_rel) * (1.0 - PRONE_AT * pronef);     \
  double aer     = fmax(0.05, fmin(1.0, (1.0 - ned) * (1.0 - natel)));         \
  double crs     = fmax(8.0, CRS0 * aer / (1.0 + KFIB_CRS * COLL));            \
  double eelv    = aer * FRC0 * (1.0 + 0.030 * (PEEP - 5.0));                  \
  double dp_set  = vt_set / fmax(3.0, crs);                                    \
  double vdvt0   = fmin(0.85, VD0 + KVD_T * FIBA / (FIBA + 1.0)                \
                              + KVD_A * (1.0 - aer));                          \
  double va0     = fmax(0.30, rr_set * (vt_set / 1000.0) * (1.0 - vdvt0));     \
  double vco2    = VCO2 * (1.0 - 0.15 * NMB) * (1.0 + 0.25 * fmin(1.0, PATH)); \
  double pco2_0  = 0.863 * vco2 / va0;                                         \
  double sh_pre  = (1.0 - aer) * (1.0 - HPV0 * (1.0 - KHPV_INF                 \
                     * (IL6 / (IL6 + 400.0))));                                \
  double pf_pre  = PF_MAX * exp(-KSH * fmin(0.80, sh_pre));                    \
  double drive   = DRIVE_GAIN * (fmax(0.0, (220.0 - pf_pre)) / 220.0           \
                     + fmax(0.0, pco2_0 - 45.0) / 25.0);                       \
  double effort  = fmax(0.0, drive * (1.0 - NMB) * (1.0 - SEDATION)            \
                     * (1.0 - 0.60 * ECMO));                                   \
  double vt_eff  = vt_set * (1.0 + EFF_GAIN * effort);                         \
  double dp      = vt_eff / fmax(3.0, crs);                                    \
  double pplat   = PEEP + dp;                                                  \
  double ppeak   = pplat + RAW_P;                                              \
  double strain  = vt_eff / fmax(120.0, eelv);                                 \
  double mpow    = 0.098 * rr_set * (vt_eff / 1000.0) * (ppeak - 0.5 * dp);    \
  double noeff   = EMAX_NO * VDIL / (VDIL + EC50_NO);                          \
  double shunt   = fmin(0.80, fmax(0.02, sh_pre * (1.0 - KNO_SH * noeff)));    \
  double vdvt    = fmin(0.85, VD0 + KVD_T * FIBA / (FIBA + 1.0)                \
                              + KVD_A * (1.0 - aer));                          \
  double va      = fmax(0.30, rr_set * (vt_eff / 1000.0) * (1.0 - vdvt));      \
  double paco2   = 0.863 * vco2 / va;                                          \
  double pf_vent = PF_MAX * exp(-KSH * shunt - KDIFF * edema / (edema + 20.0));\
  double pf      = pf_vent + ECMO * ECMO_PF * (1.0 - 0.5 * shunt);             \
  double phv     = 7.40 - 0.0085 * (paco2 - 40.0) - 0.010 * SOFA;              \
  double pvr     = PVR0 * (1.0 + KPVR_HYP * fmax(0.0, 150.0 - pf) / 150.0      \
                     + KPVR_CO2 * fmax(0.0, paco2 - 45.0) / 15.0               \
                     + KPVR_THR * FIBA / (FIBA + 1.0)                          \
                     + KPVR_P * fmax(0.0, pplat - 25.0) / 8.0)                 \
                   * (1.0 - KNO_PVR * noeff) * (1.0 - PRONE_RV * pronef);      \
  double rvload  = fmax(0.0, pvr / PVR0 - 1.6);                                \
  double co      = CO0 / (1.0 + KCO_RV * rvload);                              \
  double perm    = fmin(PERM_MAX,                                              \
                     1.0 + KPERM_E * (1.0 - ENDO) + KPERM_P * (1.0 - EPI));    \
  double pcap    = PCAP0 + KPC_FL * FLUID + 1.2 * rvload;                      \
  double gc_eff  = GRE;                                                        \
  double afc     = AFC0 * EPI * (1.0 + KGC_AFC * gc_eff)                       \
                     * (1.0 + KB2_AFC * BETA2) * (1.0 - 0.35 * fmin(1.0, ROS));\
  double filt    = KF0 * perm * (pcap / PCAP0)                                 \
                     * fmax(0.0, 1.0 - EVLW / EVLW_MAX);                       \
  double il6sig  = IL6 / (1.0 + TCZ / KD_TCZ) * (1.0 - 0.40 * BARI);           \
  double pf_use  = fmin(500.0, pf);

