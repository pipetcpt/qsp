  // 1. Composite presenting severity from the Berlin PaO2/FiO2 class.
  //------------------------------------------------------------------------
  SEV0 = fmin(1.0, fmax(0.05, (300.0 - PF0) / 240.0));   // PF 300 -> 0, PF 60 -> 1

  //------------------------------------------------------------------------
  // 2. Presenting inflammatory profile by latent class, scaled by severity.
  //    This is solved BEFORE the gas-exchange inversion because inflammation
  //    is what blunts hypoxic pulmonary vasoconstriction, and HPV is what
  //    decides how much of the non-aerated lung actually shunts.
  //------------------------------------------------------------------------
  double sevf = 0.55 + 0.90 * SEV0;
  double tnf0 = (HYPER > 0.5 ?   55.0 : 14.0) * sevf;
  double il60 = (HYPER > 0.5 ? 1600.0 : 190.0) * sevf;
  double il80 = (HYPER > 0.5 ?  340.0 :  75.0) * sevf;
  double il1s = (HYPER > 0.5 ?   45.0 :  12.0) * sevf;
  double i100 = (HYPER > 0.5 ?   75.0 :  22.0) * sevf;
  double ang0 = (HYPER > 0.5 ?   16.0 :   7.0) * sevf;
  double pai0 = (HYPER > 0.5 ?  120.0 :  40.0) * sevf;

  //------------------------------------------------------------------------
  // 3. Invert gas exchange: what shunt, and therefore what aerated fraction,
  //    reproduces the presenting PaO2/FiO2 at the enrolment settings? The
  //    diffusion penalty depends on lung water, which depends on the aerated
  //    fraction, so the inversion is iterated to a fixed point.
  //------------------------------------------------------------------------
  double hpv_eff  = HPV0 * (1.0 - KHPV_INF * il60 / (il60 + 400.0));
  double lpf      = -log(fmin(0.98, PF0 / PF_MAX));
  double ned0 = 0.0;
  double natel0 = 0.0;
  double edema_i = 0.0;
  double prel = RECRUIT * PEEP / (PEEP + P50_PEEP);
  double flood_shr = 0.45 + 0.30 * DIRECT;               // consolidation share

  double natel_max = fmax(0.05, ATEL_MAX * (1.0 - prel));
  for (int itg = 0; itg < 10; ++itg) {
    double diffpen = KDIFF * edema_i / (edema_i + 20.0);
    SHUNT_INIT = fmin(0.80, fmax(0.03, (lpf - diffpen) / KSH));
    AER_INIT   = fmax(0.05, fmin(0.98,
                   1.0 - SHUNT_INIT / fmax(0.20, 1.0 - hpv_eff)));
    // Take the atelectatic share first, capped by what a surfactant pool of
    // zero can physically produce at this PEEP, and make up the remainder of
    // the non-aerated lung with flooding. Solving in this order guarantees the
    // inversion closes for every PaO2/FiO2 instead of silently hitting a floor
    // and returning a patient who is less hypoxaemic than the one requested.
    natel0  = fmin(0.95 * natel_max, (1.0 - AER_INIT) * (1.0 - flood_shr));
    ned0    = fmin(0.93, fmax(0.0, 1.0 - AER_INIT / fmax(0.05, 1.0 - natel0)));
    edema_i = K_ED * ned0 / fmax(0.02, 1.0 - ned0);
  }
  EVLW_INIT = fmin(0.95 * EVLW_MAX, EVLW_DRY + edema_i);
  SURF_INIT = fmax(0.05, fmin(1.0, 1.0 - natel0 / natel_max));

  //------------------------------------------------------------------------
  // 4. Fixed-point solve for the barrier integrities that hold that lung
  //    water: the permeability required is the one whose filtration exactly
  //    balances clearance at EVLW_INIT. The epithelial/endothelial split
  //    follows the direct/indirect injury pattern.
  //------------------------------------------------------------------------
  double edema0 = fmax(0.0, EVLW_INIT - EVLW_DRY);
  double head   = fmax(0.05, 1.0 - EVLW_INIT / EVLW_MAX);  // flooding-capacity term
  double epi_i  = 1.0 - 0.55 * SEV0;
  double endo_i = 1.0 - 0.50 * SEV0;
  for (int itb = 0; itb < 12; ++itb) {
    double clr      = (AFC0 * epi_i + KLYM) * edema0;              // mL/kg/h out
    double perm_req = fmax(1.0, clr / fmax(1e-6, KF0 * head));     // Pcap = PCAP0 at t0
    double lost     = fmax(0.0, perm_req - 1.0);                   // KPERM_E*(1-ENDO)+KPERM_P*(1-EPI)
    // split the required permeability loss between the two barriers
    double w_epi    = 0.30 + 0.45 * DIRECT;                        // direct insult -> epithelium
    double d_epi    = fmin(0.80, lost * w_epi / KPERM_P);
    double d_endo   = fmin(0.80, lost * (1.0 - w_epi) / KPERM_E);
    epi_i  = fmax(0.15, 1.0 - d_epi);
    endo_i = fmax(0.15, 1.0 - d_endo);
  }
  EPI_INIT  = epi_i;
  ENDO_INIT = endo_i;

  //------------------------------------------------------------------------
  // 5. Back-calculate the cytokine production constants so that the presenting
  //    profile of section 2 is stationary for the NF-kB activity that the
  //    presenting DAMP load supports — the profile then evolves only because
  //    the biology (insult clearance, VILI, drugs) makes it evolve.
  //------------------------------------------------------------------------
  double damp0 = KD_PATH * INSULT0 / KDC + KD_EPI * (1.0 - EPI_INIT) / KDC;
  NFKB0        = fmax(0.10, KNF * damp0 / KNFO);

  double m10   = KM1 * (0.6 * INSULT0 + 0.4 * damp0) / (KSWITCH * 0.5 + KMOUT);
  KIN_TNF  = tnf0 * KOUT_TNF  / fmax(0.05, NFKB0 * (1.0 + 0.5 * m10));
  KIN_IL1  = il1s * KOUT_IL1  / fmax(0.05, NFKB0 * (1.0 + KNLRP * damp0 / (damp0 + 5.0)));
  KIN_IL6  = il60 * KOUT_IL6  / fmax(0.05, NFKB0 * (1.0 + 0.4 * m10));
  KIN_IL8  = il80 * KOUT_IL8  / fmax(0.05, NFKB0 * (1.0 + 0.6 * m10));
  KIN_IL10 = i100 * KOUT_IL10 / fmax(0.05, 0.20 * NFKB0 + 0.10);
  KIN_ANG2 = ang0 * KOUT_ANG2 / fmax(0.05,
               tnf0 / (tnf0 + 20.0) + il1s / (il1s + 20.0));
  KIN_PAI  = pai0 * KOUT_PAI  / fmax(0.05,
               il1s / (il1s + 20.0) + tnf0 / (tnf0 + 20.0) + 0.3);

  //------------------------------------------------------------------------
  // 6. Apply the solved baseline.
  //------------------------------------------------------------------------
  PATH_0  = INSULT0;
  DAMP_0  = damp0;
  NFKB_0  = NFKB0;
  TNF_0   = tnf0;
  IL1B_0  = il1s;
  IL6_0   = il60;
  IL8_0   = il80;
  IL10_0  = i100;
  ANG2_0  = ang0;
  PAI1_0  = pai0;
  M1_0    = m10;
  M2_0    = 0.15 * m10;
  NEUTA_0 = KREC_N * (il80 / (il80 + K8_50)) / (KDN + KEFF_N * 0.15 * m10);
  NETS_0  = KNET * NEUTA_0 / KNETC;
  ROS_0   = KROS * NEUTA_0 / (KROSC * ANTIOX);
  EPI_0   = EPI_INIT;
  ENDO_0  = ENDO_INIT;
  SURF_0  = SURF_INIT;
  EVLW_0  = EVLW_INIT;
  AT2P_0  = fmax(0.25, 0.95 - 0.45 * SEV0);
