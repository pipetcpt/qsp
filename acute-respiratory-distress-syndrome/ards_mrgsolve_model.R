##  ---------------------------------------------------------------------------
##  Calibration notes
##  ---------------------------------------------------------------------------
##  * The hazard block is calibrated so that scenario 1 (12 mL/kg) and
##    scenario 2 (6 mL/kg) bracket the ARMA result (39.8% vs 31.0% at 28 days)
##    for the reference patient, and so that adding prone position in a severe
##    patient (PF0 = 90) reproduces the PROSEVA effect size.
##  * The VILI block is deliberately driven by THREE partly redundant
##    mechanical exposures (strain, driving pressure, mechanical power) because
##    no single one of them explains the trial data on its own: ARMA separates
##    on tidal volume, Amato's mediation analysis on driving pressure, and the
##    observational power literature on J/min. A model with only one of the
##    three cannot reproduce all three findings.
##  * Corticosteroid benefit is NOT hard-coded: it emerges from NF-kB
##    transrepression, reduced neutrophil recruitment, increased alveolar fluid
##    clearance and reduced TGF-b. The late-steroid harm in scenario 13 emerges
##    from the secondary-infection seeding term and the weakness term acting on
##    a patient whose collagen is already deposited — no separate "late" rule.
##  * Inhaled NO (scenario 8) improves PaO2/FiO2 by ~20% at 24 h while moving
##    28-day mortality by only 2 percentage points, because it acts only on the
##    shunt term and the hazard is dominated by mechanics, dead space and organ
##    failure. This is the intended behaviour and is the model's main
##    falsifiable claim: an intervention that buys oxygenation without touching
##    the mechanical exposure should not buy survival.
##  * The fluid block contains two feedbacks without which it is meaningless —
##    pressure natriuresis (urine output rises with positive balance) and a
##    volume gate on the diuretic response. Without them a fixed intake or a
##    fixed furosemide order integrates for 28 days into a balance no patient
##    ever has, and the capillary-pressure term then dominates the lung water.
