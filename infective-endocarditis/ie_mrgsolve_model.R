## ---------------------------------------------------------------------------
## IE_seed() — grow the lesion from a seeding inoculum to the day of diagnosis.
##
## Nothing in this model is initialised at "a typical presenting vegetation".
## The presenting state has to be EARNED by simulating the untreated natural
## history, because the vegetation size, the shell structure, the dormant
## fraction and — crucially — the pre-existing rpoB mutant count are all
## consequences of how the lesion grew, not free parameters.
## ---------------------------------------------------------------------------
IE_seed <- function(mod, pheno = "MSSA_native", dx_day = 21, inoc = 1e3,
                    param = list()) {
  p <- IE_PHENO[[pheno]]
  if (is.null(p)) stop("unknown phenotype: ", pheno)
  p[names(param)] <- param
  m <- param(mod, p)
  m <- init(m, list(BSG = inoc, FIB = 3.0))
  out <- mrgsim_df(m, end = dx_day * 24, delta = dx_day * 24)
  last <- out[nrow(out), ]
  nm <- names(as.list(init(mod)))
  st <- as.list(last[intersect(names(last), nm)])
  list(param = p, init = st)
}

## A model object already sitting at the day of diagnosis.
IE_patient <- function(mod, pheno = "MSSA_native", dx_day = 21, inoc = 1e3,
                       param = list()) {
  s <- IE_seed(mod, pheno = pheno, dx_day = dx_day, inoc = inoc, param = param)
  m <- param(mod, s$param)
  m <- init(m, s$init)
  m
}

