// HOMOGENISED vegetation assay reports, and it is 1-2 orders of magnitude
// above the core value that decides the outcome.
double C_VAN_W = FRAC_S * C_VAN_S + FRAC_M * C_VAN_M + FRAC_C * C_VAN_C;
double C_DAP_C = VDAP * exp(-dCt / LAM_DAP);
double C_BL_C  = VBL  * exp(-dCt / LAM_BL);
double C_GEN_C = VGEN * exp(-dCt / LAM_GEN);
double C_RIF_C = VRIF * exp(-dCt / LAM_RIF);
double C_ORL_C = VORL * exp(-dCt / LAM_ORL);

double CVANP = VANC / V1_VAN;
double CDAPP = DAPC / V1_DAP;
double CBLP  = BLC  / V1_BL;
double CGENP = GENC / V1_GEN;
double CRIFP = RIFC / V_RIF;
double CDALP = DALC / V1_DAL;
double CORLP = ORLC / V_ORL;

