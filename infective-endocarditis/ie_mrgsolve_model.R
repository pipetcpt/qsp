$GLOBAL
#define CPOS(x) ((x) > 0.0 ? (x) : 0.0)
#define HILLF(C, EC, H) (pow(CPOS(C), (H)) / (pow(CPOS(C), (H)) + pow((EC), (H))))
// EXTINCTION SWITCH. A continuous state is a fiction below one organism, and
// without this an ODE model will happily regrow a relapse out of 10^-9 CFU --
// which is the single most common way a bacterial PK/PD model lies. EXT() is
// ~0 below 1 CFU and ~1 above 2, and it multiplies every REPLICATION term
// (never a transport or death term, which remain valid for a fractional state).
#define EXT(x) (pow(CPOS(x), 4.0) / (pow(CPOS(x), 4.0) + 1.0))

//===========================================================================
$MAIN
// Nothing time-varying here: all covariate feedback (AKI -> CrCL -> clearance)
// is a STATE-dependent loop and therefore has to live in $ODE.

//===========================================================================
$ODE
//---------------------------------------------------------------------------
// 0. RENAL FUNCTION — the master covariate, and it is a STATE
//---------------------------------------------------------------------------
double AKI_TOT = CPOS(AKI) + GN_IC * 0.35;
double CRCL    = CRCL0 / (1.0 + E_AKI * AKI_TOT);
if (CRCL < 5.0) CRCL = 5.0;

// Rifampicin enzyme induction transmitted to companion drugs
double INDX = CPOS(RIFIND - 1.0);

//---------------------------------------------------------------------------
// 1. PLASMA PHARMACOKINETICS
//---------------------------------------------------------------------------
double CL_VAN = CLVAN_SLP * CRCL * (1.0 + FRIND_VAN * INDX);
double CL_DAP = (CLDAP_INT + CLDAP_SLP * CRCL) * (1.0 + FRIND_DAP * INDX);
double CL_BL  = CLBL_0 * (FR_REN_BL * (CRCL / CRCL0) + (1.0 - FR_REN_BL));
double CL_GEN = CLGEN_SLP * CRCL;
double CL_RIF = CLRIF_0 * RIFIND;
double CL_OR  = CL_ORL * (1.0 + FRIND_ORL * INDX);

double CVAN = VANC / V1_VAN;                 // total plasma, mg/L
double CDAP = DAPC / V1_DAP;
double CBL  = BLC  / V1_BL;
double CGEN = GENC / V1_GEN;
double CRIF = RIFC / V_RIF;
double CDAL = DALC / V1_DAL;
double CORL = ORLC / V_ORL;

dxdt_VANC = -CL_VAN * CVAN - Q_VAN * CVAN + Q_VAN * (VANP / V2_VAN);
dxdt_VANP =  Q_VAN * CVAN - Q_VAN * (VANP / V2_VAN);

dxdt_DAPC = -CL_DAP * CDAP - Q_DAP * CDAP + Q_DAP * (DAPP / V2_DAP);
dxdt_DAPP =  Q_DAP * CDAP - Q_DAP * (DAPP / V2_DAP);

dxdt_BLC  = -CL_BL * CBL - Q_BL * CBL + Q_BL * (BLP / V2_BL);
dxdt_BLP  =  Q_BL * CBL - Q_BL * (BLP / V2_BL);

dxdt_GENC = -CL_GEN * CGEN - Q_GEN * CGEN + Q_GEN * (GENP / V2_GEN);
dxdt_GENP =  Q_GEN * CGEN - Q_GEN * (GENP / V2_GEN);

dxdt_RIFA = -KA_RIF * RIFA;
dxdt_RIFC =  F_RIF * KA_RIF * RIFA - CL_RIF * CRIF;
dxdt_RIFIND = KOUT_IND * (1.0 + EMAX_IND * HILLF(CRIF, EC50_IND, 1.0) - RIFIND);

dxdt_DALC = -CL_DAL * CDAL - Q_DAL * CDAL + Q_DAL * (DALP / V2_DAL);
dxdt_DALP =  Q_DAL * CDAL - Q_DAL * (DALP / V2_DAL);

dxdt_ORLA = -KA_ORL * ORLA;
dxdt_ORLC =  F_ORL * KA_ORL * ORLA - CL_OR * CORL;

dxdt_AUCVAN = CVAN;
dxdt_AUCDAP = CDAP;
dxdt_GENAUC = CGEN;

//---------------------------------------------------------------------------
// 2. VEGETATION GEOMETRY — mass -> volume -> radius -> depths
//---------------------------------------------------------------------------
double FIBP  = CPOS(FIB) + 0.10;                       // mg, floor for numerics
double VOL   = FIBP / RHO_VEG;                          // mm3
double RAD   = pow(3.0 * VOL / (4.0 * 3.14159265), 1.0/3.0);   // mm
double DIAM  = 2.0 * RAD;                               // mm, the echo number

double dS = DEPTH_S * RAD;
double dM = DEPTH_M * RAD;
double dC = DEPTH_C * RAD;

// Nutrient / oxygen availability by shell — an exponential, same physics as
// the drug, different length scale. A SMALL vegetation has no protected core:
// this is why a 3 mm vegetation is a different disease from a 15 mm one.
double AVL_S = exp(-dS / LAM_NUT);
double AVL_M = exp(-dM / LAM_NUT);
double AVL_C = exp(-dC / LAM_NUT);

// Oxygen falls faster than bulk nutrient; aminoglycoside uptake needs the
// proton-motive force that oxidative phosphorylation generates.
double OXY_S = pow(AVL_S, 1.5);
double OXY_M = pow(AVL_M, 1.5);
double OXY_C = pow(AVL_C, 1.5);

// Per-shell carrying capacity (CFU)
double KCAP_S = DENSCAP * FIBP * FRAC_S;
double KCAP_M = DENSCAP * FIBP * FRAC_M;
double KCAP_C = DENSCAP * FIBP * FRAC_C;

//---------------------------------------------------------------------------
// 3. DRUG TRANSPORT INTO THE VEGETATION
//    Two steps: (a) a first-order diffusive lag to the SURFACE of the lesion,
//    (b) an exponential attenuation with DEPTH. Step (b) has no dose in it.
//---------------------------------------------------------------------------
dxdt_VVAN = KEQ_VAN * (FU_VAN * CVAN * PART_VAN - VVAN);
dxdt_VDAP = KEQ_DAP * (FU_DAP * CDAP * PART_DAP - VDAP);
dxdt_VBL  = KEQ_BL  * (FU_BL  * CBL  * PART_BL  - VBL);
dxdt_VGEN = KEQ_GEN * (FU_GEN * CGEN * PART_GEN - VGEN);
dxdt_VRIF = KEQ_RIF * (FU_RIF * CRIF * PART_RIF - VRIF);
dxdt_VDAL = KEQ_DAL * (FU_DAL * CDAL * PART_DAL - VDAL);
dxdt_VORL = KEQ_ORL * (FU_ORL * CORL * PART_ORL - VORL);

double aVAN_S = exp(-dS / LAM_VAN);
double aVAN_M = exp(-dM / LAM_VAN);
double aVAN_C = exp(-dC / LAM_VAN);
double aDAP_S = exp(-dS / LAM_DAP);
double aDAP_M = exp(-dM / LAM_DAP);
double aDAP_C = exp(-dC / LAM_DAP);
double aBL_S = exp(-dS / LAM_BL);
double aBL_M = exp(-dM / LAM_BL);
double aBL_C = exp(-dC / LAM_BL);
double aGEN_S = exp(-dS / LAM_GEN);
double aGEN_M = exp(-dM / LAM_GEN);
double aGEN_C = exp(-dC / LAM_GEN);
double aRIF_S = exp(-dS / LAM_RIF);
double aRIF_M = exp(-dM / LAM_RIF);
double aRIF_C = exp(-dC / LAM_RIF);
double aDAL_S = exp(-dS / LAM_DAL);
double aDAL_M = exp(-dM / LAM_DAL);
double aDAL_C = exp(-dC / LAM_DAL);
double aORL_S = exp(-dS / LAM_ORL);
double aORL_M = exp(-dM / LAM_ORL);
double aORL_C = exp(-dC / LAM_ORL);

//---------------------------------------------------------------------------
// 4. LOCAL SUSCEPTIBILITY — the inoculum effect is a DENSITY effect, so it is
//    computed per shell from the local density, not read off a label.
//---------------------------------------------------------------------------
double NS = CPOS(BSG) + CPOS(BSD) + CPOS(RSG) + CPOS(RSD);
double NM = CPOS(BMG) + CPOS(BMD) + CPOS(RMG) + CPOS(RMD);
double NC = CPOS(BCG) + CPOS(BCD) + CPOS(RCG) + CPOS(RCD);
double NTOT = NS + NM + NC;

double densS = NS / (FIBP * FRAC_S + 1e-9);   // CFU/mg
double densM = NM / (FIBP * FRAC_M + 1e-9);
double densC = NC / (FIBP * FRAC_C + 1e-9);

// MIC assay reference density is 1e5 CFU/mL ~ 1e5 CFU/mg of matrix-equivalent.
double ieS = 1.0 + INOC_EFF * CPOS(log10((densS + 1.0) / 1.0e5));
double ieM = 1.0 + INOC_EFF * CPOS(log10((densM + 1.0) / 1.0e5));
double ieC = 1.0 + INOC_EFF * CPOS(log10((densC + 1.0) / 1.0e5));
if (ieS > INOC_MAX) ieS = INOC_MAX;
if (ieM > INOC_MAX) ieM = INOC_MAX;
if (ieC > INOC_MAX) ieC = INOC_MAX;
if (INOC_BL_ON < 0.5) { ieS = 1.0; ieM = 1.0; ieC = 1.0; }

//---------------------------------------------------------------------------
// 5. KILL RATES PER SHELL
//    Growing cells:  sum over drugs of Emax * Hill(C_shell)
//    Dormant cells:  the SAME expression scaled by FSTAT, the fraction of
//                    activity retained when mu = 0. This single vector of
//                    seven numbers is the whole pharmacological argument of
//                    the model.
//---------------------------------------------------------------------------
// Cell-wall-agent occupancy drives aminoglycoside uptake (the synergy term)
double cw_S = HILLF(VBL * aBL_S, ECF_BL * MIC_BL, 1.0) + HILLF(VVAN * aVAN_S, ECF_VAN * MIC_VAN, 1.0);
double cw_M = HILLF(VBL * aBL_M, ECF_BL * MIC_BL, 1.0) + HILLF(VVAN * aVAN_M, ECF_VAN * MIC_VAN, 1.0);
double cw_C = HILLF(VBL * aBL_C, ECF_BL * MIC_BL, 1.0) + HILLF(VVAN * aVAN_C, ECF_VAN * MIC_VAN, 1.0);
if (cw_S > 1.0) cw_S = 1.0;
if (cw_M > 1.0) cw_M = 1.0;
if (cw_C > 1.0) cw_C = 1.0;

double genfac = (HLAR > 0.5) ? 0.0 : 1.0;

// --- surface shell -------------------------------------------------------
double kBL_S  = EMAX_BL  * HILLF(VBL  * aBL_S,  ECF_BL  * MIC_BL  * ieS, HILL_BL);
double kVAN_S = EMAX_VAN * HILLF(VVAN * aVAN_S, ECF_VAN * MIC_VAN, HILL_VAN);
double kDAP_S = EMAX_DAP * HILLF(VDAP * aDAP_S, ECF_DAP * MIC_DAP, HILL_DAP);
double kGEN_S = genfac * EMAX_GEN * OXY_S * (1.0 + SYN_GEN * cw_S)
                * HILLF(VGEN * aGEN_S, ECF_GEN * MIC_GEN, HILL_GEN);
double kRIF_S = EMAX_RIF * HILLF(VRIF * aRIF_S, ECF_RIF * MIC_RIF, HILL_RIF);
double kDAL_S = EMAX_DAL * HILLF(VDAL * aDAL_S, ECF_DAL * MIC_DAL, HILL_DAL);
double kORL_S = EMAX_ORL * HILLF(VORL * aORL_S, ECF_ORL * MIC_ORL, HILL_ORL);

double kBL_M  = EMAX_BL  * HILLF(VBL  * aBL_M,  ECF_BL  * MIC_BL  * ieM, HILL_BL);
double kVAN_M = EMAX_VAN * HILLF(VVAN * aVAN_M, ECF_VAN * MIC_VAN, HILL_VAN);
double kDAP_M = EMAX_DAP * HILLF(VDAP * aDAP_M, ECF_DAP * MIC_DAP, HILL_DAP);
double kGEN_M = genfac * EMAX_GEN * OXY_M * (1.0 + SYN_GEN * cw_M)
                * HILLF(VGEN * aGEN_M, ECF_GEN * MIC_GEN, HILL_GEN);
double kRIF_M = EMAX_RIF * HILLF(VRIF * aRIF_M, ECF_RIF * MIC_RIF, HILL_RIF);
double kDAL_M = EMAX_DAL * HILLF(VDAL * aDAL_M, ECF_DAL * MIC_DAL, HILL_DAL);
double kORL_M = EMAX_ORL * HILLF(VORL * aORL_M, ECF_ORL * MIC_ORL, HILL_ORL);

double kBL_C  = EMAX_BL  * HILLF(VBL  * aBL_C,  ECF_BL  * MIC_BL  * ieC, HILL_BL);
double kVAN_C = EMAX_VAN * HILLF(VVAN * aVAN_C, ECF_VAN * MIC_VAN, HILL_VAN);
double kDAP_C = EMAX_DAP * HILLF(VDAP * aDAP_C, ECF_DAP * MIC_DAP, HILL_DAP);
double kGEN_C = genfac * EMAX_GEN * OXY_C * (1.0 + SYN_GEN * cw_C)
                * HILLF(VGEN * aGEN_C, ECF_GEN * MIC_GEN, HILL_GEN);
double kRIF_C = EMAX_RIF * HILLF(VRIF * aRIF_C, ECF_RIF * MIC_RIF, HILL_RIF);
double kDAL_C = EMAX_DAL * HILLF(VDAL * aDAL_C, ECF_DAL * MIC_DAL, HILL_DAL);
double kORL_C = EMAX_ORL * HILLF(VORL * aORL_C, ECF_ORL * MIC_ORL, HILL_ORL);

// Rifampicin against the rpoB mutant: same Emax, MIC multiplied by RIF_R_FOLD
double MICRR  = MIC_RIF * RIF_R_FOLD;
double kRIFR_S = EMAX_RIF * HILLF(VRIF * aRIF_S, ECF_RIF * MICRR, HILL_RIF);
double kRIFR_M = EMAX_RIF * HILLF(VRIF * aRIF_M, ECF_RIF * MICRR, HILL_RIF);
double kRIFR_C = EMAX_RIF * HILLF(VRIF * aRIF_C, ECF_RIF * MICRR, HILL_RIF);

// Non-rifampicin kill, growing and dormant, per shell
double KILLG_S = kBL_S + kVAN_S + kDAP_S + kGEN_S + kDAL_S + kORL_S;
double KILLG_M = kBL_M + kVAN_M + kDAP_M + kGEN_M + kDAL_M + kORL_M;
double KILLG_C = kBL_C + kVAN_C + kDAP_C + kGEN_C + kDAL_C + kORL_C;

double KILLD_S = FSTAT_BL*kBL_S + FSTAT_VAN*kVAN_S + FSTAT_DAP*kDAP_S
               + FSTAT_GEN*kGEN_S + FSTAT_DAL*kDAL_S + FSTAT_ORL*kORL_S;
double KILLD_M = FSTAT_BL*kBL_M + FSTAT_VAN*kVAN_M + FSTAT_DAP*kDAP_M
               + FSTAT_GEN*kGEN_M + FSTAT_DAL*kDAL_M + FSTAT_ORL*kORL_M;
double KILLD_C = FSTAT_BL*kBL_C + FSTAT_VAN*kVAN_C + FSTAT_DAP*kDAP_C
               + FSTAT_GEN*kGEN_C + FSTAT_DAL*kDAL_C + FSTAT_ORL*kORL_C;

// Wild-type totals (add rifampicin)
double KWG_S = KILLG_S + kRIF_S;
double KWD_S = KILLD_S + FSTAT_RIF * kRIF_S;
double KWG_M = KILLG_M + kRIF_M;
double KWD_M = KILLD_M + FSTAT_RIF * kRIF_M;
double KWG_C = KILLG_C + kRIF_C;
double KWD_C = KILLD_C + FSTAT_RIF * kRIF_C;

// Mutant totals (rifampicin term collapses)
double KRG_S = KILLG_S + kRIFR_S;
double KRD_S = KILLD_S + FSTAT_RIF * kRIFR_S;
double KRG_M = KILLG_M + kRIFR_M;
double KRD_M = KILLD_M + FSTAT_RIF * kRIFR_M;
double KRG_C = KILLG_C + kRIFR_C;
double KRD_C = KILLD_C + FSTAT_RIF * kRIFR_C;

//---------------------------------------------------------------------------
// 6. GROWTH, PHENOTYPE SWITCHING, IMMUNE KILLING, MIGRATION
//---------------------------------------------------------------------------
double muS = MUMAX * AVL_S * CPOS(1.0 - NS / (KCAP_S + 1.0));
double muM = MUMAX * AVL_M * CPOS(1.0 - NM / (KCAP_M + 1.0));
double muC = MUMAX * AVL_C * CPOS(1.0 - NC / (KCAP_C + 1.0));
double muRS = muS * (1.0 - FIT_COST);
double muRM = muM * (1.0 - FIT_COST);
double muRC = muC * (1.0 - FIT_COST);

double gdS = KGD * (1.0 - AVL_S);
double dgS = KDG * AVL_S;
double gdM = KGD * (1.0 - AVL_M);
double dgM = KDG * AVL_M;
double gdC = KGD * (1.0 - AVL_C);
double dgC = KDG * AVL_C;

// Surgery: a finite window during which everything in the lesion is removed
// at a rate chosen to deliver exactly SURG_LOG log10 over SURG_DUR hours.
double ksurg  = 0.0;
double ksurgF = 0.0;
if (SOLVERTIME >= SURG_T && SOLVERTIME < SURG_T + SURG_DUR) {
  ksurg  = SURG_LOG * 2.302585 / SURG_DUR;
  ksurgF = -log(1.0 - SURG_FIB + 1e-9) / SURG_DUR;
}

double lossG_S = KDEATH_G + KIMM_S + SHED_K + KBUR + ksurg;
double lossD_S = KDEATH_D + KIMM_S * 0.25 + SHED_K + KBUR + ksurg;
double lossG_M = KDEATH_G + KIMM_M + KBUR + KEXP + ksurg;
double lossD_M = KDEATH_D + KIMM_M * 0.25 + KBUR + KEXP + ksurg;
double lossG_C = KDEATH_G + KIMM_C + KEXP + ksurg;
double lossD_C = KDEATH_D + KIMM_C * 0.25 + KEXP + ksurg;

// Mutation supply: mutants arise DURING REPLICATION, so the source term is
// MUTRATE * mu * B and nothing is placed by hand at t = 0.
double mutS = MUTRATE * muS * CPOS(BSG) * EXT(BSG);
double mutM = MUTRATE * muM * CPOS(BMG) * EXT(BMG);
double mutC = MUTRATE * muC * CPOS(BCG) * EXT(BCG);

// --- wild type ------------------------------------------------------------
dxdt_BSG = muS * CPOS(BSG) * EXT(BSG) - (lossG_S + KWG_S) * CPOS(BSG)
         - gdS * CPOS(BSG) + dgS * CPOS(BSD) + KEXP * CPOS(BMG) - mutS;
dxdt_BSD = -(lossD_S + KWD_S) * CPOS(BSD) + gdS * CPOS(BSG) - dgS * CPOS(BSD)
         + KEXP * CPOS(BMD);
dxdt_BMG = muM * CPOS(BMG) * EXT(BMG) - (lossG_M + KWG_M) * CPOS(BMG)
         - gdM * CPOS(BMG) + dgM * CPOS(BMD) + KBUR * CPOS(BSG) + KEXP * CPOS(BCG) - mutM;
dxdt_BMD = -(lossD_M + KWD_M) * CPOS(BMD) + gdM * CPOS(BMG) - dgM * CPOS(BMD)
         + KBUR * CPOS(BSD) + KEXP * CPOS(BCD);
dxdt_BCG = muC * CPOS(BCG) * EXT(BCG) - (lossG_C + KWG_C) * CPOS(BCG)
         - gdC * CPOS(BCG) + dgC * CPOS(BCD) + KBUR * CPOS(BMG) - mutC;
dxdt_BCD = -(lossD_C + KWD_C) * CPOS(BCD) + gdC * CPOS(BCG) - dgC * CPOS(BCD)
         + KBUR * CPOS(BMD);

// --- rpoB mutant ----------------------------------------------------------
dxdt_RSG = muRS * CPOS(RSG) * EXT(RSG) - (lossG_S + KRG_S) * CPOS(RSG)
         - gdS * CPOS(RSG) + dgS * CPOS(RSD) + KEXP * CPOS(RMG) + mutS;
dxdt_RSD = -(lossD_S + KRD_S) * CPOS(RSD) + gdS * CPOS(RSG) - dgS * CPOS(RSD)
         + KEXP * CPOS(RMD);
dxdt_RMG = muRM * CPOS(RMG) * EXT(RMG) - (lossG_M + KRG_M) * CPOS(RMG)
         - gdM * CPOS(RMG) + dgM * CPOS(RMD) + KBUR * CPOS(RSG) + KEXP * CPOS(RCG) + mutM;
dxdt_RMD = -(lossD_M + KRD_M) * CPOS(RMD) + gdM * CPOS(RMG) - dgM * CPOS(RMD)
         + KBUR * CPOS(RSD) + KEXP * CPOS(RCD);
dxdt_RCG = muRC * CPOS(RCG) * EXT(RCG) - (lossG_C + KRG_C) * CPOS(RCG)
         - gdC * CPOS(RCG) + dgC * CPOS(RCD) + KBUR * CPOS(RMG) + mutC;
dxdt_RCD = -(lossD_C + KRD_C) * CPOS(RCD) + gdC * CPOS(RCG) - dgC * CPOS(RCD)
         + KBUR * CPOS(RMD);

//---------------------------------------------------------------------------
// 7. BLOODSTREAM — continuous seeding from the SURFACE shell only
//---------------------------------------------------------------------------
double CBLOOD = CPOS(BLOOD) / VBLOOD;                  // CFU/mL

// Circulating and intracellular organisms are NOT behind the diffusion
// barrier: they see the full FREE PLASMA concentration. That is the reason
// bacteraemia clears long before the vegetation does, and the reason the
// blood culture is a poor surrogate for cure.
double kp_BL  = EMAX_BL  * HILLF(FU_BL  * CBL,  ECF_BL  * MIC_BL,  HILL_BL);
double kp_VAN = EMAX_VAN * HILLF(FU_VAN * CVAN, ECF_VAN * MIC_VAN, HILL_VAN);
double kp_DAP = EMAX_DAP * HILLF(FU_DAP * CDAP, ECF_DAP * MIC_DAP, HILL_DAP);
double kp_GEN = genfac * EMAX_GEN * HILLF(FU_GEN * CGEN, ECF_GEN * MIC_GEN, HILL_GEN);
double kp_RIF = EMAX_RIF * HILLF(FU_RIF * CRIF, ECF_RIF * MIC_RIF, HILL_RIF);
double kp_DAL = EMAX_DAL * HILLF(FU_DAL * CDAL, ECF_DAL * MIC_DAL, HILL_DAL);
double kp_ORL = EMAX_ORL * HILLF(FU_ORL * CORL, ECF_ORL * MIC_ORL, HILL_ORL);
double kill_blood = kp_BL + kp_VAN + kp_DAP + kp_GEN + kp_RIF + kp_DAL + kp_ORL;

// The intracellular reservoir is small but it is shielded: only the lipophilic
// agents follow the organism inside the cell. It is what keeps a blood culture
// intermittently positive for days after the vegetation surface is sterile,
// and it is the second, independent reason rifampicin has a rationale.
double kill_intra = FCELL_BL*kp_BL + FCELL_VAN*kp_VAN + FCELL_DAP*kp_DAP
                  + FCELL_GEN*kp_GEN + FCELL_RIF*kp_RIF + FCELL_DAL*kp_DAL
                  + FCELL_ORL*kp_ORL;

dxdt_BLOOD = SHED_K * (CPOS(BSG) + CPOS(BSD) + CPOS(RSG) + CPOS(RSD))
           + KREL * CPOS(INTRA)
           - (KCL_RES + KUPT + kill_blood) * CPOS(BLOOD);
dxdt_INTRA = KUPT * CPOS(BLOOD) - (KREL + kill_intra) * CPOS(INTRA);

//---------------------------------------------------------------------------
// 8. VEGETATION MATRIX — the fortress the organism builds out of host material
//---------------------------------------------------------------------------
// Coagulase, staphylothrombin and platelet-activating exoproteins are made by
// METABOLICALLY ACTIVE cells, so the matrix drive tracks the SURFACE GROWING
// population — the same quantity that drives valve destruction and embolic
// fragility. Deposition happens on the surface of the lesion, so it scales as
// FIB^(2/3) (area) rather than FIB (volume). Both choices matter: together
// they mean that effective antibiotic therapy stops accretion within hours,
// after which fibrinolysis and organisation shrink the lesion, the diffusion
// path shortens, the core wakes up, and the kill rate RISES. That positive
// feedback in the favourable direction is what a 6-week course is buying.
double NSG0 = CPOS(BSG) + CPOS(RSG);
double asa = (ASA_ON > 0.5) ? (1.0 - ASA_EFF) : 1.0;
double fibdrive = COAG * (NSG0 / (NSG0 + KM_FIB));
dxdt_FIB = KFIB * asa * fibdrive * pow(FIBP, 2.0/3.0) * CPOS(1.0 - FIBP / FIBMAX)
         - KLYS * FIBP - ksurgF * FIBP;

//---------------------------------------------------------------------------
// 9. VALVE DESTRUCTION (a RATCHET) AND HAEMODYNAMICS
//---------------------------------------------------------------------------
double NSG = CPOS(BSG) + CPOS(RSG);      // only metabolically active cells
                                          // make proteases and toxins
double destdrive = NSG / (NSG + KM_DEST);
double valve_rep = 0.0;
if (SOLVERTIME >= SURG_T && SOLVERTIME < SURG_T + SURG_DUR)
  valve_rep = (SURG_VALVE - CPOS(VALVE)) / SURG_DUR;
dxdt_VALVE = -KDEST * VIR * destdrive * CPOS(VALVE) + CPOS(valve_rep);

double REGURG   = RFMAX * pow(CPOS(1.0 - VALVE), HDEST);
double LVEDVTGT = LVEDV0 * (1.0 + GAIN_V * REGURG);
dxdt_LVEDV = KREM * (LVEDVTGT - LVEDV);
dxdt_NTBNP = KIN_BNP * (1.0 + S_BNP * REGURG * (LVEDV / LVEDV0)) - KOUT_BNP * NTBNP;

double absdrive = (NM + NC) / (NM + NC + KM_ABS);
dxdt_ABSC = KABS * VIR * absdrive * CPOS(1.0 - ABSC) - KABSR * CPOS(ABSC);
dxdt_PRMS = KPR * (PR0 + PR_MAX * CPOS(ABSC) - PRMS);

//---------------------------------------------------------------------------
// 10. EMBOLIC HAZARD
//     Fragility tracks the SURFACE GROWING population, not the matrix. That is
//     the whole reason effective antibiotics drop the hazard within days while
//     the vegetation is still clearly visible on echo for weeks — and the
//     reason an antiplatelet agent, which acts on matrix accretion, does not.
//---------------------------------------------------------------------------
double FRAG = FRAGMIN + (1.0 - FRAGMIN) * (NSG / (NSG + KM_FRAG));
double hemb = (HAZ0 / 24.0) * pow(DIAM / 10.0, HZP) * FRAG * EMB_ORG;
dxdt_HEMB = hemb;
dxdt_HCNS = CNS_SHARE * hemb;

//---------------------------------------------------------------------------
// 11. INFLAMMATION AND BIOMARKERS
//---------------------------------------------------------------------------
dxdt_IL6 = KIN_IL6 * (1.0 + S_IL6 * (NTOT / (NTOT + KM_IL6)) + S_ABS * CPOS(ABSC))
         - KOUT_IL6 * CPOS(IL6);
dxdt_CRP = KCRP * CPOS(IL6) - KOUT_CRP * CPOS(CRP);
dxdt_PCT = KIN_PCT * (1.0 + S_PCT * CBLOOD / (CBLOOD + 2.0)) - KOUT_PCT * CPOS(PCT);
dxdt_NEU = KIN_NEU * (1.0 + S_NEU * CPOS(IL6) / (CPOS(IL6) + KM_NEU)) - KOUT_NEU * CPOS(NEU);

//---------------------------------------------------------------------------
// 12. TOXICITY AND THE AKI FEEDBACK LOOP
//     AKI -> CrCL down -> vancomycin clearance down -> exposure up -> AKI.
//     This is a genuine positive feedback and it is why AUC-guided dosing has
//     to be re-estimated, not set once.
//---------------------------------------------------------------------------
double akidrive = pow(CPOS(CVAN) / CAKI50_V, HAKI)
                + W_GEN_AKI * (CPOS(GENAUC) / GAUC50)
                + W_PIP_AKI * 0.55 * pow(CPOS(CVAN) / CAKI50_V, HAKI);
// The loop AKI -> CrCL down -> exposure up -> AKI has gain > 1 above roughly
// AUC24 750, i.e. it genuinely runs away rather than settling higher. That is
// the clinical death spiral and the model should show it, but an unbounded
// state is not useful, so the drive is capped at a level corresponding to
// severe (KDIGO 3 / dialysis-range) injury.
if (akidrive > 6.0) akidrive = 6.0;
dxdt_AKI = KIN_AKI * akidrive - KOUT_AKI * CPOS(AKI);

dxdt_CK  = KIN_CK  * (1.0 + S_CK * CPOS(CDAP)) - KOUT_CK * CPOS(CK);
dxdt_ALT = KIN_ALT * (1.0 + S_ALT_RIF * CPOS(CRIF) + S_ALT_BL * CPOS(CBL))
         - KOUT_ALT * CPOS(ALT);

// Core beta-lactam fT>MIC accumulator — the PD index that the guideline uses,
// evaluated where it matters instead of in plasma.
dxdt_TAMBL = (VBL * aBL_C > MIC_BL) ? 1.0 : 0.0;

