  cat("The comparison that matters is row 2 vs row 1 (non-inferiority) AND row 2\n")
  cat("vs row 3 (stopping early is not the same as switching route).\n\n")
  print(out, row.names = FALSE)
  cat("\nThe model's reading of POET: by day 10 of effective IV therapy the SURFACE\n")
  cat("shell is already sterile and the remaining work is in the core, where the\n")
