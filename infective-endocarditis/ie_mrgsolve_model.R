double P_EMB = 1.0 - exp(-CPOS(HEMB));
double P_CNS = 1.0 - exp(-CPOS(HCNS));
double CRCLT = CRCL0 / (1.0 + E_AKI * (CPOS(AKI) + GN_IC * 0.35));
if (CRCLT < 5.0) CRCLT = 5.0;
