##  Infective Endocarditis (IE) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Infective endocarditis — microbial infection of the endocardial
##             surface, usually a native or prosthetic valve, in which the
##             organism grows inside a platelet-fibrin VEGETATION that it builds
##             out of host material. In-hospital mortality ~18-23% and 6-month
##             mortality ~30% have barely moved in three decades despite
##             organisms that are, on paper, susceptible to the drugs given.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>= 1.0);  developed and run under mrgsolve 2.0.1
##
##  ---------------------------------------------------------------------------
##  THE ORGANISING CLAIM OF THIS MODEL
##  ---------------------------------------------------------------------------
##  Almost every antibacterial PK/PD model in existence is built on one number:
##  the MIC. The MIC is measured on ~10^5 CFU/mL of LOG-PHASE PLANKTONIC cells
##  suspended in nutrient broth, stirred, for 18-20 h.
##
##  The lesion this model is about presents:
##
##      * 10^9 - 10^11 CFU per GRAM  (5-6 logs above the assay inoculum)
##      * cells at CARRYING CAPACITY, i.e. STATIONARY PHASE, mu -> 0
##      * behind 2-5 mm of AVASCULAR platelet-fibrin matrix into which drug
##        arrives by DIFFUSION ONLY, with no convection and no capillaries
##
##  So the model is not posed as "is the organism susceptible?" It is posed as:
##
##      INFECTIVE ENDOCARDITIS IS A GEOMETRY PROBLEM WEARING THE CLOTHES OF A
##      SUSCEPTIBILITY PROBLEM.
##
##  Everything peculiar about IE therapy is then a consequence rather than a
##  convention, and the model is required to reproduce each of them WITHOUT
##  being fitted to the trial that demonstrates it:
##
##  1. THE LEDGER. Cure means driving the whole vegetation below 1 CFU. From
##     10^9-10^10 total organisms that is 9-10 log10 of NET killing, sustained.
##     A bacteraemia needs 14 days; this needs 4-6 weeks. IE_ledger() prints the
##     accounting per shell: logs required, logs delivered, and where the
##     shortfall is. No other number in the file matters as much.
##
##  2. THE EXPONENTIAL. Drug concentration inside an avascular lesion falls as
##     C(x) ~ C_surface * exp(-x / lambda), where lambda = sqrt(D / k_bind) is
##     the penetration length. lambda is a property of the MOLECULE and the
##     MATRIX, not of the dose. Doubling the plasma AUC shifts the whole
##     exponential up by a factor of two; it does not change its slope. Beyond
##     a depth of a few lambda, extra plasma exposure buys essentially nothing.
##
##  3. THE STRUCTURAL CONSEQUENCE — VANCOMYCIN HAS NO SAFE WINDOW FOR THIS
##     LESION. Core exposure saturates in plasma exposure (point 2). Toxicity
##     does not: AKI scales super-linearly with plasma AUC and then enters a
##     positive feedback (AKI -> CrCL down -> AUC up -> AKI). IE_aucsweep()
##     puts numbers on both. Across AUC24 300 -> 1000 the marginal core log-kill
##     per extra 100 mg.h/L falls from 1.74 to 0.82 while the marginal AKI index
##     per extra 100 rises from 0.13 to 1.58 — the benefit-to-harm ratio of
##     extra exposure collapses about 30-fold. And the punchline is not a
##     comfortable optimum: the exposure that first sterilises a 7 mm MRSA
##     vegetation in this model (AUC ~800) is the same exposure at which KDIGO
##     stage 1 injury appears. There is no setting of the dial that both cures
##     the lesion and spares the kidney. That is a mechanistic statement of why
##     vancomycin has been steadily displaced in staphylococcal endocarditis,
##     and why the 2020 consensus 400-600 window is best read not as "the dose
##     that works" but as "the region where extra exposure is still worth
##     something" — above roughly 700 it stops being.
##
##  4. THE GROWTH-RATE TRAP. beta-lactam killing requires an actively
##     remodelling cell wall, so kill rate scales with mu. In the core mu ~ 0.
##     This is TOLERANCE, not resistance: the MIC on the lab report is
##     unchanged and completely uninformative. Daptomycin (membrane
##     depolarisation) and rifampicin (transcription) do not need mu, which is
##     the single mechanistic reason they matter in a vegetation and the reason
##     linezolid — bacteriostatic — cannot carry a 10-log lesion alone.
##
##  5. RESISTANCE IS NOT BAD LUCK, IT IS ARITHMETIC. rpoB mutants arise at
##     ~10^-8 per replication. Growing a vegetation from a seed to 10^10 cells
##     generates ~10^-8 x 10^10 = ~100 rifampicin-resistant organisms BEFORE THE
##     FIRST DOSE IS GIVEN. Rifampicin monotherapy therefore fails
##     DETERMINISTICALLY, not stochastically. The model is not told this; the
##     mutation term is per-replication and IE_rifmono() counts what comes out.
##
##  ---------------------------------------------------------------------------
##  WHAT THE MODEL IS REQUIRED TO GET RIGHT (calibration / falsification set)
##  ---------------------------------------------------------------------------
##   T1  Time to blood-culture sterilisation: MSSA + antistaphylococcal
##       penicillin ~2-3 d; MRSA + vancomycin ~7-9 d. A 3-4x difference between
##       two regimens both "active" by MIC.            (Khatib 2006; Levine 1991)
##   T2  Vegetation:serum drug ratio ~0.2-0.4 for vancomycin on whole-vegetation
##       homogenate, with a much steeper true gradient because homogenate is
##       volume-weighted and dominated by the outer shells.   (Cremieux 1989)
##   T3  Embolic hazard is FRONT-LOADED: roughly two thirds of embolic events
##       occur before or within the first two weeks, and the hazard falls about
##       an order of magnitude once therapy is effective.  (Dickerman 2007 AHJ;
##       Thuny 2005 Circulation)
##   T4  Vegetation >10 mm and especially >15 mm raise embolic risk steeply.
##   T5  Adjunctive low-dose gentamicin in staphylococcal native-valve IE gives
##       NO clinical benefit and measurable nephrotoxicity.  (Cosgrove 2009 CID)
##   T6  Adjunctive rifampicin in S. aureus bacteraemia gives NO benefit.
##       (ARREST, Lancet 2018)
##   T7  Aspirin does NOT reduce embolic events and increases bleeding.
##       (Chan 2003 JACC)
##   T8  Partial oral step-down after >=10 days IV is non-inferior.
##       (POET, NEJM 2019; 5-year follow-up NEJM 2022)
##   T9  Early surgery reduces EMBOLIC EVENTS; the mortality signal is weak.
##       (EASE, Kang NEJM 2012)
##   T10 Vancomycin AKI rises steeply above AUC24 ~ 600 mg.h/L. (Rybak 2020)
##
##  Items T5, T6 and T7 are NEGATIVE trials. A model that cannot reproduce a
##  negative trial is not a mechanistic model, it is a fitted curve. Each of the
##  three is reproduced here by a structural property that was put in for an
##  independent reason: gentamicin by the loss of proton-motive force in an
##  anoxic core, rifampicin by pre-existing rpoB mutants, aspirin by the fact
##  that embolic fragility tracks the SURFACE bacterial population rather than
##  matrix accretion. IE_negatives() runs all three.
##
##  ---------------------------------------------------------------------------
##  STRUCTURE
##  ---------------------------------------------------------------------------
##  54 ODE compartments:
##    * 7 antibiotics with independent PK (vancomycin, daptomycin, a generic
##      beta-lactam, gentamicin, rifampicin with autoinduction, dalbavancin,
##      an oral step-down composite) = 15 states + 2 exposure integrals
##    * 7 vegetation drug-lag compartments (one per drug), each read out at
##      three depths through an exponential attenuation with drug-specific
##      penetration length lambda
##    * 12 bacterial states = 3 SHELLS (surface / mid / core)
##                          x 2 PHENOTYPES (growing / dormant)
##                          x 2 GENOTYPES (wild-type / rpoB-mutant)
##    * bloodstream CFU, vegetation matrix mass, abscess, IL-6, CRP, PCT,
##      neutrophils, valve integrity, LVEDV, NT-proBNP, PR interval,
##      cumulative embolic and CNS-embolic hazard, AKI, CK, ALT, gentamicin
##      cumulative AUC, and a core beta-lactam fT>MIC accumulator
##
##  Time unit throughout is HOURS. Bacterial states are CFU (absolute counts in
##  the whole vegetation), not densities: cure is an absolute-count statement.
##
##  ---------------------------------------------------------------------------
##  HONEST LIMITATIONS  (see README for the full list)
##  ---------------------------------------------------------------------------
##  * Three shells is a coarse discretisation of a continuous diffusion field.
##    It captures the exponential and the phenotype gradient; it will not give
##    a correct concentration profile near the surface at short times.
##  * The rifampicin-on-companion-drug induction term is set to ZERO by default
##    for vancomycin and daptomycin because both are renally cleared and the
##    reported interaction is inconsistent. It is exposed as FRIND_VAN /
##    FRIND_DAP so the reader can test it, and it is set to 1.0 for the oral
##    composite where the interaction is real and large.
##  * Mortality is not modelled as a state. It is a downstream function of
##    heart failure, embolism and persistent bacteraemia and would add fitted
##    parameters without adding mechanism.
##  * The model is single-lesion. Multivalve and CIED-lead disease are not
##    represented, and metastatic foci are a sink term, not a compartment.
##
##  ---------------------------------------------------------------------------
##  WHAT THE MODEL ACTUALLY PRODUCED  (mrgsolve 2.0.1, IE_report(), as committed)
##  ---------------------------------------------------------------------------
##  Presenting patient: lesion grown for 21 days from a 10^3 CFU seed, giving a
##  7.1-7.3 mm vegetation, 10^9.3 CFU total, CRP 86 mg/L, regurgitant fraction
##  0.36, NT-proBNP 540 pg/mL, 1.9 CFU/mL bacteraemia. Nothing in that list was
##  set; all of it is where the natural-history simulation arrives.
##
##   T1  blood-culture clearance   MSSA/nafcillin 3.6 d (obs 2-3), MSSA/cefazolin
##       3.1 d (2-4), MRSA/vancomycin 6.2 d (7-9), MRSA MIC 2/vancomycin 10.2 d,
##       MRSA/daptomycin 2.3 d (obs 4-8; the one clear miss, see limitations)
##   T2  vancomycin core:free-plasma AUC 0.0025, whole-vegetation homogenate
##       equivalent 0.095 — see the note in IE_penetration() on why the
##       published 0.2-0.4 homogenate ratio and this number are not the same
##       quantity and why the difference is the point
##   T3  hazard before diagnosis + first 14 days = 89% of the 6-week total
##       (clinical figure ~65%); daily hazard week 1 / weeks 5-6 = 6.6x;
##       untreated the same lesion accrues 48x the hazard of the treated one
##   T4  reproduced structurally: hazard scales as diameter^1.6 x fragility
##   T5  gentamicin adds 0.18 log10 of kill and an AKI index of 0.63 (vs 0.00)
##   T6  adjunctive rifampicin benefit 0.00 log10 in a bacteraemia-sized lesion
##       — ARREST's population and ARREST's answer
##   T7  aspirin from diagnosis: P(embolism from diagnosis) 0.0137 -> 0.0136
##   T8  IV 10 d -> oral to day 42 sterilises, as does 42 days of IV; IV 10 d
##       then stopping relapses to 10^9.8
##   T9  surgery on day 2 cuts post-diagnosis embolic probability 57%, day 14
##       only 27%, with the microbiological column barely moving
##   T10 KDIGO stage 1 first appears at AUC24 800 mg.h/L, which is also the
##       lowest AUC that sterilises this lesion — see claim 3 above
##
##  Three additional results that were not targets and fell out anyway:
##   * the rpoB-mutant count at diagnosis is 125 CFU, 6.6x the naive f_mut x N
##     of 19 — the excess is Luria-Delbrück accumulation over the growth phase
##   * a 2 mm vegetation and a 9 mm vegetation are different diseases: dormant
##     fraction 0.41 vs 0.64, core drug 2.25x MIC vs 0.62x MIC, cured vs not
##   * daptomycin sterilises the vegetation but does NOT clear the intracellular
##     reservoir, so it is "sterile" without being "cured" in the scenario table
##
##  Disclaimer: research / education / hypothesis generation only. Not a
##              substitute for clinical judgment, guidelines, or a stewardship
##              pharmacist.
##  ============================================================================

