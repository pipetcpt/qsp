## DIAGNOSTIC 11 — CONTINUOUS vs INTERMITTENT BETA-LACTAM
## ===========================================================================
IE_infusion <- function(mod, pheno = "MSSA_native", days = 28, dx_day = 21) {
  arms <- list("nafcillin 2 g q4h (bolus)" = IE_REGIMEN$nafcillin(days),
               "nafcillin 12 g/24h continuous" = IE_REGIMEN$bl_continuous(days))
  rows <- lapply(names(arms), function(nm) {
    o <- IE_sim(mod, arms[[nm]], days = days, delta = 0.5, pheno = pheno, dx_day = dx_day)
    z <- o[nrow(o), ]
    last <- o[o$time >= (days - 1) * 24, ]
    data.frame(arm = nm,
               plasma_Cmax = round(max(last$CBLP), 1),
               plasma_Cmin = round(min(last$CBLP), 2),
               core_fT_over_MIC_pct = round(100 * mean(last$C_BL_C > 1e-9 &
                 last$CORE_BL_MIC > 1), 1),
               core_mean_xMIC = round(mean(last$CORE_BL_MIC), 2),
               end_log10 = round(z$LOGN, 2),
               core_logkill = round(o$LOGN_C[1] - z$LOGN_C, 2),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== INTERMITTENT vs CONTINUOUS BETA-LACTAM at identical daily dose ===\n\n")
  print(out, row.names = FALSE)
  cat("\nThe core sees a SMOOTHED and DELAYED version of the plasma curve already\n")
  cat("(KEQ_BL = 3/h through a 1 h lag), so the two schedules converge at depth\n")
  cat("far more than they do in plasma. Continuous infusion buys real fT>MIC in\n")
  cat("the mid shell and comparatively little in the core; it is a good idea for\n")
  cat("the reason usually given, but the size of the prize shrinks with depth.\n")
  invisible(out)
}

