  ## 3. Cefazolin 2 g q8h — the tolerability alternative, and the regimen the
  ##    inoculum-effect argument is about.
  cefazolin = function(days = 42)
    .inf("BLC", 2000, 8, days * D, inf_h = 0.5),

  ## 4. Vancomycin 1 g q12h -> AUC24 ~ 500 mg.h/L at CrCL 100.
  vanco = function(days = 42) .inf("VANC", 1000, 12, days * D, inf_h = 1),

  ## 5. Vancomycin dosed to a chosen AUC24 (mg.h/L). Daily dose = AUC24 * CL.
  vanco_auc = function(days = 42, auc = 500, cl = 4.0)
    .inf("VANC", auc * cl / 2, 12, days * D, inf_h = 1),

  ## 6. Daptomycin 8 mg/kg q24h (560 mg) — the dose most IE guidance now uses.
  dapto8 = function(days = 42) .inf("DAPC", 560, 24, days * D, inf_h = 0.5),

  ## 7. Daptomycin 6 mg/kg q24h — the LABEL dose, kept so the difference can
  ##    be seen rather than asserted.
  dapto6 = function(days = 42) .inf("DAPC", 420, 24, days * D, inf_h = 0.5),

  ## 8. Daptomycin 10 mg/kg q24h — high-dose salvage.
  dapto10 = function(days = 42) .inf("DAPC", 700, 24, days * D, inf_h = 0.5),

  ## 9. Gentamicin 1 mg/kg q8h (70 mg) — synergy dosing, first 14 days only,
  ##    which is exactly the regimen Cosgrove 2009 tested.
  gent = function(days = 14) .inf("GENC", 70, 8, min(days, 14) * D, inf_h = 0.5),

  ## 10. Rifampicin 450 mg PO q12h (900 mg/day), started at day 5 as guidelines
  ##     advise for PVE (after bacteraemia clearance).
  rif = function(days = 42, start_day = 5)
    .po("RIFA", 450, 12, days * D, start = start_day * D),

  ## 11. Rifampicin from day 0 — used only to demonstrate the monotherapy trap.
  rif0 = function(days = 42) .po("RIFA", 450, 12, days * D),

  ## 12. Dalbavancin 1500 mg day 1 + 1500 mg day 8 consolidation.
  dalba = function(days = 42) ev(time = c(0, 7 * D), amt = 1500, cmt = "DALC",
                                 rate = 1500 / 0.5),

  ## 13. Oral step-down composite, started after IV lead-in. This slot is a
  ##     TWO-DRUG oral regimen chosen on susceptibility, as POET used (typically
  ##     including rifampicin or linezolid), not a single agent -- hence
  ##     EMAX_ORL 0.65, FSTAT_ORL 0.30 and LAM_ORL 1.6 mm.
  oral = function(days = 42, start_day = 10)
    .po("ORLA", 600, 12, days * D, start = start_day * D),

  ## 14. Ampicillin 2 g q4h (12 g/day) — the E. faecalis backbone.
  ampicillin = function(days = 42) .inf("BLC", 2000, 4, days * D, inf_h = 0.5),

  ## 15. Ceftriaxone 2 g q24h — viridans streptococci, HACEK, OPAT.
  ceftriaxone = function(days = 42) .inf("BLC", 2000, 24, days * D, inf_h = 0.5),

  ## 16. Continuous-infusion beta-lactam at the same daily dose as nafcillin.
  bl_continuous = function(days = 42)
    ev(time = 0, amt = 12000, cmt = "BLC", rate = 12000 / 24, ii = 24,
       addl = days - 1)
)

## Compose regimens: IE_rx("nafcillin", "gent")
IE_rx <- function(..., days = 42) {
  parts <- list(...)
  evs <- NULL
  for (p in parts) {
    e <- if (is.function(p)) p(days = days) else IE_REGIMEN[[p]](days = days)
    if (is.null(e)) next
    evs <- if (is.null(evs)) e else evs + e
  }
  evs
}

## ===========================================================================
## SIMULATION WRAPPER
## ===========================================================================
IE_sim <- function(mod, regimen = NULL, days = 42, delta = 2,
                   pheno = "MSSA_native", dx_day = 21, param = list(),
                   param_post = list(), surgery_day = NULL, follow_days = 0, ...) {
  # `param` is applied BEFORE the lesion is grown, so it changes the presenting
  # state; `param_post` is applied AFTER, so it changes only what happens from
  # the day of diagnosis onwards. Getting these the wrong way round silently
  # changes the patient instead of the treatment.
  m <- IE_patient(mod, pheno = pheno, dx_day = dx_day, param = param)
  if (length(param_post)) m <- param(m, param_post)
  if (!is.null(surgery_day)) m <- param(m, SURG_T = surgery_day * 24)
  ev0 <- NULL
  if (!is.null(regimen)) {
    ev0 <- if (is.character(regimen)) {
      do.call(IE_rx, c(as.list(regimen), list(days = days)))
    } else regimen
  }
  end <- (days + follow_days) * 24
  if (is.null(ev0)) mrgsim_df(m, end = end, delta = delta, ...)
  else mrgsim_df(m, events = ev0, end = end, delta = delta, ...)
}

## ===========================================================================
## DIAGNOSTIC 1 — THE LEDGER
## ===========================================================================
## The single most important output of the model. How many logs does the lesion
## require, how many did the regimen deliver, and IN WHICH SHELL was the
## shortfall? Everything else in the file is commentary on this table.
## ---------------------------------------------------------------------------
IE_ledger <- function(mod, regimens = list(
                        "no therapy"            = list(rx = NULL,                  bl = NULL),
                        "nafcillin 12 g/d"      = list(rx = "nafcillin",            bl = "nafcillin"),
                        "cefazolin 6 g/d"       = list(rx = "cefazolin",            bl = "cefazolin"),
                        "vancomycin AUC 500"    = list(rx = "vanco",                bl = NULL),
                        "daptomycin 8 mg/kg"    = list(rx = "dapto8",               bl = NULL),
                        "dapto 8 + rifampicin"  = list(rx = c("dapto8", "rif"),     bl = NULL)),
                      pheno = "MSSA_native", days = 42, dx_day = 21) {
  rows <- lapply(names(regimens), function(nm) {
    r  <- regimens[[nm]]$rx
    pp <- if (is.null(regimens[[nm]]$bl)) list() else IE_BLPK[[regimens[[nm]]$bl]]
    o <- IE_sim(mod, regimen = r, days = days, delta = 6, pheno = pheno,
                dx_day = dx_day, param = pp)
    a <- o[1, ]; z <- o[nrow(o), ]
    data.frame(
      regimen   = nm,
      req_log10 = round(a$LOGN, 2),
      end_log10 = round(z$LOGN, 2),
      delivered = round(a$LOGN - z$LOGN, 2),
      surface   = round(a$LOGN_S - z$LOGN_S, 2),
      mid       = round(a$LOGN_M - z$LOGN_M, 2),
      core      = round(a$LOGN_C - z$LOGN_C, 2),
      sterile   = ifelse(z$STERILE > 0.5, "YES", "no"),
      dorm_end  = round(z$FRAC_DORM, 3),
      stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== THE LOG-KILL LEDGER ===  phenotype:", pheno,
      " therapy:", days, "days\n")
  cat("req_log10 = logs present at diagnosis; cure needs the burden below 1 CFU,\n")
  cat("so 'delivered' must reach 'req_log10' IN EVERY SHELL, not on average.\n\n")
  print(out, row.names = FALSE)
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 2 — PENETRATION
## ===========================================================================
## Measures the core:plasma free-AUC ratio for each drug by simulation rather
## than reading lambda back out of the parameter block.
## ---------------------------------------------------------------------------
IE_penetration <- function(mod, pheno = "MRSA_native", days = 7, dx_day = 21) {
  spec <- list(
    vancomycin  = list(rx = "vanco",     plasma = "CVANP", core = "C_VAN_C", key = "VAN"),
    daptomycin  = list(rx = "dapto8",    plasma = "CDAPP", core = "C_DAP_C", key = "DAP"),
    betalactam  = list(rx = "nafcillin", plasma = "CBLP",  core = "C_BL_C",  key = "BL"),
    gentamicin  = list(rx = "gent",      plasma = "CGENP", core = "C_GEN_C", key = "GEN"),
    rifampicin  = list(rx = "rif0",      plasma = "CRIFP", core = "C_RIF_C", key = "RIF")
  )
  m0 <- IE_patient(mod, pheno = pheno, dx_day = dx_day)
  pp <- as.list(param(m0))
  trap <- function(t, y) sum(diff(t) * (head(y, -1) + tail(y, -1)) / 2)
  # Transport is measured with the GEOMETRY HELD FIXED at the presenting size.
  # Otherwise each drug is measured through a differently sized lesion and the
  # comparison stops being about the molecules.
  froz <- list(KFIB = 0, KLYS = 0)
  rows <- lapply(names(spec), function(nm) {
    s <- spec[[nm]]
    o <- IE_sim(mod, regimen = s$rx, days = days, delta = 0.25, pheno = pheno,
                dx_day = dx_day, param_post = froz)
    o <- o[o$time >= (days - 1) * 24, ]           # last 24 h, at steady state
    aucP <- trap(o$time, o[[s$plasma]])
    aucF <- aucP * pp[[paste0("FU_", s$key)]]
    aucC <- trap(o$time, o[[s$core]])
    lam  <- pp[[paste0("LAM_", s$key)]]
    prt  <- pp[[paste0("PART_", s$key)]]
    rad  <- mean(o$VEGMM) / 2
    wgt  <- mean(exp(-c(0.13, 0.40, 0.72) * rad / lam))     # volume-weighted
    data.frame(drug = nm,
               lambda_mm = pp[[paste0("LAM_", s$key)]],
               AUC24_total_plasma = round(aucP, 1),
               AUC24_free_plasma  = round(aucF, 2),
               AUC24_core         = round(aucC, 3),
               core_over_freeplasma = round(aucC / aucF, 4),
               core_over_total      = round(aucC / aucP, 5),
               homogenate_over_free = round(wgt * prt, 4),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== PENETRATION: what fraction of plasma exposure reaches the CORE ===\n")
  cat("phenotype:", pheno, "; steady state, day", days, "\n")
  cat("The ordering is set by lambda, and lambda is a property of the molecule\n")
  cat("and the matrix. No dose appears in the last three columns.\n\n")
  print(out, row.names = FALSE)
  cat("\nREAD THE LAST TWO COLUMNS TOGETHER. 'homogenate_over_free' is what a\n")
  cat("ground-up vegetation assay measures: a VOLUME-WEIGHTED average, dominated\n")
  cat("by the outer shells that hold most of the volume. 'core_over_freeplasma'\n")
  cat("is what the surviving bacteria experience. For vancomycin the two differ\n")
  cat("by more than an order of magnitude, and the published homogenate ratios\n")
  cat("(~0.2-0.4 of serum) are higher still because they are TOTAL drug and\n")
  cat("include everything bound to the fibrin -- which is the very binding that\n")
  cat("makes lambda short. The standard measurement is reassuring for exactly\n")
  cat("the reason it should not be.\n")
  invisible(out)
}

