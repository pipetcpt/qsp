.inf <- function(cmt, amt, ii, dur_h, start = 0, inf_h = 1) {
  n <- max(1, floor((dur_h - start) / ii))
  ev(time = start, amt = amt, cmt = cmt, ii = ii, addl = n - 1,
     rate = amt / inf_h)
}
.po <- function(cmt, amt, ii, dur_h, start = 0) {
  n <- max(1, floor((dur_h - start) / ii))
  ev(time = start, amt = amt, cmt = cmt, ii = ii, addl = n - 1)
}

