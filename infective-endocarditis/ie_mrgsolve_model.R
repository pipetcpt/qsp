## DIAGNOSTIC 3 — TIME TO BLOOD-CULTURE STERILISATION  (target T1)
## ===========================================================================
IE_clearance <- function(mod, days = 28, dx_day = 21, thresh = 0.25) {
  cases <- list(
    list(lab = "MSSA  + nafcillin 12 g/d",   ph = "MSSA_native", rx = "nafcillin",   bl = "nafcillin",   obs = "2-3 d"),
    list(lab = "MSSA  + cefazolin 6 g/d",    ph = "MSSA_native", rx = "cefazolin",   bl = "cefazolin",   obs = "2-4 d"),
    list(lab = "MSSA  + vancomycin",         ph = "MSSA_native", rx = "vanco",       bl = NULL,          obs = "slower than BL"),
    list(lab = "MRSA  + vancomycin AUC 500", ph = "MRSA_native", rx = "vanco",       bl = NULL,          obs = "7-9 d"),
    list(lab = "MRSA  + daptomycin 8 mg/kg", ph = "MRSA_native", rx = "dapto8",      bl = NULL,          obs = "4-8 d"),
    list(lab = "MRSA (MIC 2) + vancomycin",  ph = "MRSA_MIC2",   rx = "vanco",       bl = NULL,          obs = "prolonged"),
    list(lab = "VGS   + ceftriaxone 2 g/d",  ph = "VGS_native",  rx = "ceftriaxone", bl = "ceftriaxone", obs = "1-2 d"),
    list(lab = "E. faecalis + ampicillin",   ph = "EFAECALIS",   rx = "ampicillin",  bl = "ampicillin",  obs = "prompt; CURE is slow")
  )
  rows <- lapply(cases, function(cs) {
    pp <- if (is.null(cs$bl)) list() else IE_BLPK[[cs$bl]]
    o <- IE_sim(mod, regimen = cs$rx, days = days, delta = 2, pheno = cs$ph,
                dx_day = dx_day, param = pp)
    idx <- which(o$P_BCPOS < thresh)
    tclear <- if (length(idx)) o$time[idx[1]] / 24 else NA_real_
    data.frame(case = cs$lab,
               t_clear_days = ifelse(is.na(tclear), paste0(">", days), sprintf("%.1f", tclear)),
               literature   = cs$obs,
               log_drop_14d = round(o$LOGN[1] - o$LOGN[which.min(abs(o$time - 14 * 24))], 2),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== TIME TO BLOOD-CULTURE STERILISATION ===\n")
  cat("Clearance is declared when the probability that a 20 mL set grows is\n")
  cat("below ", thresh, ", i.e. when two sets drawn together are more likely than\n", sep = "")
  cat("not to be BOTH negative. That is what 'cultures turned negative' means at\n")
  cat("the bedside; a Poisson-exact zero would be a much stricter question.\n")
  cat("Every organism here is SUSCEPTIBLE to the drug it is paired with.\n")
  cat("The spread is produced by lambda, Emax, FSTAT and intracellular access,\n")
  cat("not by the MIC.\n\n")
  print(out, row.names = FALSE)
  cat("\nCaveat the model cannot fix: blood cultures are drawn once or twice a\n")
  cat("day, so no clinical series can report a clearance time below ~1 day.\n")
  cat("Read anything under 1.0 above as 'negative on the first repeat draw'.\n")
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 3b — CEFAZOLIN vs ANTISTAPHYLOCOCCAL PENICILLIN
## ===========================================================================
## A live clinical argument, and one the model can take apart: cefazolin
## achieves roughly 4x the FREE exposure of nafcillin at guideline doses
## (nafcillin is 90% protein bound and cleared at ~15 L/h), which is why it
## wins on every exposure metric. The counter-argument is the type A BlaZ
## INOCULUM EFFECT, which is a DENSITY phenomenon -- and a vegetation is the
## densest bacterial habitat in clinical medicine. So the question is not
## "does the inoculum effect exist" but "is it big enough to cancel a 4x
## exposure advantage at 10^7 CFU/mg". The model answers that arithmetically.
## ---------------------------------------------------------------------------
IE_cefazolin <- function(mod, days = 42, dx_day = 21) {
  grid <- list(
    list(lab = "nafcillin 2 g q4h", rx = "nafcillin", bl = "nafcillin", ie = 1),
    list(lab = "cefazolin 2 g q8h", rx = "cefazolin", bl = "cefazolin", ie = 1),
    list(lab = "cefazolin 2 g q8h, NO inoculum effect", rx = "cefazolin", bl = "cefazolin", ie = 0),
    list(lab = "cefazolin 2 g q8h, SEVERE inoculum effect", rx = "cefazolin", bl = "cefazolin", ie = 2))
  rows <- lapply(grid, function(g) {
    pp <- IE_BLPK[[g$bl]]
    if (g$ie == 0) pp$INOC_BL_ON <- 0
    if (g$ie == 2) { pp$INOC_EFF <- 0.90; pp$INOC_MAX <- 32 }
    o <- IE_sim(mod, g$rx, days = days, delta = 6, pheno = "MSSA_native",
                dx_day = dx_day, param_post = pp)
    z <- o[nrow(o), ]
    d7  <- o[which.min(abs(o$time -  7 * 24)), ]
    d14 <- o[which.min(abs(o$time - 14 * 24)), ]
    fu <- if (is.null(pp$FU_BL)) 0.10 else pp$FU_BL
    last <- o[o$time >= 24 & o$time <= 48, ]
    data.frame(arm = g$lab,
               free_Cavg = round(mean(last$CBLP) * fu, 2),
               free_over_MIC = round(mean(last$CBLP) * fu / 0.5, 1),
               core_log10_d7 = round(d7$LOGN_C, 2),
               core_log10_d14 = round(d14$LOGN_C, 2),
               day_to_sterile = { i <- which(o$STERILE > 0.5)
                                  if (length(i)) round(o$time[i[1]] / 24, 1) else NA },
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== CEFAZOLIN vs NAFCILLIN, AND HOW BIG THE INOCULUM EFFECT HAS TO BE ===\n\n")
  print(out, row.names = FALSE)
  cat("\nThe exposure advantage is real and large -- 17.5x free MIC against 2.6x --\n")
  cat("and in this model it is NOT cancelled by the inoculum effect, not even at\n")
  cat("the severe setting where the MIC is allowed to rise 32-fold at vegetation\n")
  cat("density: sterilisation moves from day 32.2 to day 33.5. The reason is that\n")
  cat("a 32-fold MIC rise takes cefazolin from 17.5x MIC to 0.55x MIC in the\n")
  cat("ASSAY sense, but the kill term is a Hill function of concentration over\n")
  cat("EC50 and cefazolin still has more absolute free drug at every depth than\n")
  cat("nafcillin ever had. That is a falsifiable prediction and it matches the\n")
  cat("direction of the cohort literature, which keeps failing to find a\n")
  cat("cefazolin penalty outside high-inoculum type A producers.\n")
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 4 — RIFAMPICIN MONOTHERAPY IS ARITHMETIC, NOT BAD LUCK
## ===========================================================================
IE_rifmono <- function(mod, pheno = "MRSA_native", days = 42, dx_day = 21) {
  s <- IE_seed(mod, pheno = pheno, dx_day = dx_day)
  n0  <- with(s$init, BSG + BSD + BMG + BMD + BCG + BCD)
  r0  <- with(s$init, RSG + RSD + RMG + RMD + RCG + RCD)
  fmut <- as.list(param(mod))$MUTRATE
  cat("\n=== PRE-EXISTING RESISTANCE AT THE MOMENT OF DIAGNOSIS ===\n")
  cat(sprintf("Wild-type burden ...................... %.3e CFU\n", n0))
  cat(sprintf("rpoB-mutant burden (EMERGENT) ......... %.3e CFU\n", r0))
  cat(sprintf("Observed mutant fraction .............. %.3e\n", r0 / (n0 + r0)))
  cat(sprintf("Naive expectation f_mut ............... %.3e\n", fmut))
  cat(sprintf("Naive count f_mut x N ................. %.3e CFU\n", fmut * n0))
  cat("\nNothing was placed at t=0. The mutation term is MUTRATE * mu * B, so the\n")
  cat("mutants are the by-product of growing the lesion. At 10^9-10^10 cells the\n")
  cat("resistant subpopulation is a THREE-FIGURE NUMBER before the first dose.\n")

  arms <- list("rifampicin alone"          = "rif0",
               "vancomycin alone"          = "vanco",
               "vancomycin + rifampicin"   = c("vanco", "rif0"),
               "daptomycin + rifampicin"   = c("dapto8", "rif0"))
  rows <- lapply(names(arms), function(nm) {
    o <- IE_sim(mod, regimen = arms[[nm]], days = days, delta = 6,
                pheno = pheno, dx_day = dx_day)
    z <- o[nrow(o), ]
    data.frame(arm = nm,
               end_log10_total = round(z$LOGN, 2),
               end_log10_mutant = round(z$LOGR, 2),
               mutant_fraction = ifelse(z$STERILE > 0.5, 0, signif(z$FRAC_R, 3)),
               sterile = ifelse(z$STERILE > 0.5, "YES", "no"),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== WHAT EACH ARM DOES TO THAT SUBPOPULATION (", days, " days) ===\n", sep = "")
  print(out, row.names = FALSE)
  cat("\nRifampicin alone does not fail because the patient was unlucky. It fails\n")
  cat("because the mutants were already there and nothing else was killing them.\n")
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 5 — THE VANCOMYCIN AUC OPTIMUM  (targets T10 and claim 3)
## ===========================================================================
## Core kill saturates in plasma AUC because the exponential attenuation does
## not care about the dose. AKI does not saturate. Two curves, one saturating
## and one not, must cross. This function finds where.
## ---------------------------------------------------------------------------
IE_aucsweep <- function(mod, aucs = c(300, 400, 500, 600, 700, 800, 1000, 1200),
                        pheno = "MRSA_native", days = 42, dx_day = 21) {
  rows <- lapply(aucs, function(a) {
    rx <- IE_REGIMEN$vanco_auc(days = days, auc = a, cl = 4.0)
    o <- IE_sim(mod, regimen = rx, days = days, delta = 6,
                pheno = pheno, dx_day = dx_day)
    z <- o[nrow(o), ]
    data.frame(target_AUC24 = a,
               core_logkill = round(o$LOGN_C[1] - z$LOGN_C, 2),
               total_logkill = round(o$LOGN[1] - z$LOGN, 2),
               peak_AKI_index = round(max(o$AKI), 2),
               peak_SCr = round(max(o$SCR), 2),
               AKI_stage_max = max(o$AKI_STAGE),
               sterile = ifelse(z$STERILE > 0.5, "YES", "no"),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  out$d_kill_per_100 <- c(NA, round(diff(out$core_logkill) /
                                      (diff(out$target_AUC24) / 100), 3))
  out$d_AKI_per_100  <- c(NA, round(diff(out$peak_AKI_index) /
                                      (diff(out$target_AUC24) / 100), 3))
  out$benefit_harm_ratio <- round(out$d_kill_per_100 / out$d_AKI_per_100, 2)
  cat("\n=== VANCOMYCIN AUC SWEEP: a saturating benefit against an accelerating harm ===\n")
  cat("phenotype:", pheno, "; core kill saturates because the exponential\n")
  cat("attenuation with depth has no dose in it. AKI does not saturate because\n")
  cat("the AKI -> CrCL -> exposure loop has gain > 1 at high exposure.\n\n")
  print(out, row.names = FALSE)
  ster <- out$target_AUC24[which(out$sterile == "YES")[1]]
  aki1 <- out$target_AUC24[which(out$AKI_stage_max >= 1)[1]]
  cat("\nBenefit-to-harm ratio of the NEXT 100 mg.h/L collapses across the range.\n")
  cat(sprintf("Lowest AUC24 that sterilises the lesion .......... %s mg.h/L\n",
              ifelse(is.na(ster), "none tested", ster)))
  cat(sprintf("Lowest AUC24 that produces KDIGO stage 1 AKI ..... %s mg.h/L\n",
              ifelse(is.na(aki1), "none tested", aki1)))
  cat("Those two numbers are the finding. For a lesion this size there is no\n")
  cat("setting of the dial that both cures it and spares the kidney -- which is\n")
  cat("the mechanistic version of why vancomycin keeps losing head-to-head\n")
  cat("comparisons in staphylococcal endocarditis. Read the 400-600 consensus\n")
  cat("window as the region where extra exposure is still worth something\n")
  cat("(ratio > 3), not as a dose that reliably sterilises a vegetation.\n")
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 6 — DURATION AND RELAPSE
## ===========================================================================
IE_duration <- function(mod, stop_days = c(7, 14, 21, 28, 35, 42, 56),
                        pheno = "MRSA_native", regimen = "dapto8",
                        follow = 120, dx_day = 21) {
  rows <- lapply(stop_days, function(sd) {
    o <- IE_sim(mod, regimen = regimen, days = sd, delta = 12,
                pheno = pheno, dx_day = dx_day, follow_days = follow)
    at_stop <- o[which.min(abs(o$time - sd * 24)), ]
    z <- o[nrow(o), ]
    data.frame(stop_day = sd,
               log10_at_stop = round(at_stop$LOGN, 2),
               sterile_at_stop = ifelse(at_stop$STERILE > 0.5, "YES", "no"),
               intracell_at_stop = round(at_stop$LOGI, 2),
               log10_at_followup = round(z$LOGN, 2),
               relapsed = ifelse(z$LOGN > at_stop$LOGN + 1, "RELAPSE", "-"),
               veg_mm_end = round(z$VEGMM, 1),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  cat("\n=== DURATION vs RELAPSE ===  ", pheno, " / ", regimen,
      " / ", follow, " days of follow-up after stopping\n\n", sep = "")
  print(out, row.names = FALSE)
  cat("\nThere is no gentle taper of risk here. Either the last decade of organisms\n")
  cat("was killed before the drug stopped or it was not, and the lesion regrows\n")
  cat("from whatever survived at the growth rate of the surface shell.\n")
  invisible(out)
