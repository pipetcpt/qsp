## DIAGNOSTIC 7 — EMBOLIC HAZARD IS FRONT-LOADED  (target T3)
## ===========================================================================
IE_embolic <- function(mod, pheno = "MSSA_native", regimen = "nafcillin",
                       days = 42, dx_day = 21) {
  o <- IE_sim(mod, regimen = regimen, days = days, delta = 2,
              pheno = pheno, dx_day = dx_day)
  on <- IE_sim(mod, regimen = NULL, days = days, delta = 2,
               pheno = pheno, dx_day = dx_day)
  wk <- function(df, a, b) {
    i1 <- which.min(abs(df$time - a * 24)); i2 <- which.min(abs(df$time - b * 24))
    df$HEMB[i2] - df$HEMB[i1]
  }
  # The clinical statement "two thirds of embolic events happen before or in
  # the first two weeks" counts events that occurred BEFORE the diagnosis. The
  # model can separate that window because it grew the lesion rather than
  # starting from a presenting state, so it is reported here explicitly.
  pre <- o$HEMB[1]
  tot <- o$HEMB[nrow(o)]
  out <- data.frame(
    window = c("BEFORE diagnosis (lesion days 0-21)", "therapy days 0-7",
               "therapy days 7-14", "therapy days 14-28", "therapy days 28-42"),
    hazard_treated   = round(c(pre, wk(o, 0, 7), wk(o, 7, 14), wk(o, 14, 28), wk(o, 28, 42)), 4),
    hazard_untreated = round(c(pre, wk(on, 0, 7), wk(on, 7, 14), wk(on, 14, 28), wk(on, 28, 42)), 4),
    stringsAsFactors = FALSE)
  out$pct_of_total <- round(100 * out$hazard_treated / tot, 1)
  cat("\n=== EMBOLIC HAZARD BY WINDOW ===  ", pheno, " / ", regimen, "\n\n", sep = "")
  print(out, row.names = FALSE)
  f2 <- 100 * sum(out$hazard_treated[1:3]) / tot
  r  <- (out$hazard_treated[2] / 7) / (out$hazard_treated[5] / 14)
  cat(sprintf("\nBefore diagnosis + first 14 days of therapy = %.1f%% of the whole\n", f2))
  cat("cumulative hazard (the clinical figure usually quoted is ~65%).\n")
  cat(sprintf("Daily hazard, therapy week 1 / weeks 5-6 = %.1f-fold.\n", r))
  cat(sprintf("Vegetation: %.1f mm at diagnosis, %.1f mm at 6 weeks.\n",
              o$VEGMM[1], o$VEGMM[nrow(o)]))
  cat("The collapse in hazard is FASTER than the shrinkage, because fragility\n")
  cat("tracks the surface BACTERIAL population and that dies in days while the\n")
  cat("matrix takes weeks to resorb. Untreated, the same lesion accrues\n")
  cat(sprintf("%.4f of hazard over the same 6 weeks -- %.0f-fold more.\n",
              sum(out$hazard_untreated[2:5]),
              sum(out$hazard_untreated[2:5]) / sum(out$hazard_treated[2:5])))
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 8 — SURGERY TIMING  (target T9)
## ===========================================================================
IE_surgery <- function(mod, surg_days = c(NA, 2, 5, 7, 14, 21),
                       pheno = "MSSA_native", regimen = "nafcillin",
                       days = 42, dx_day = 28) {
  # Hazard is reported FROM DIAGNOSIS ONWARDS. The cumulative P_EMB includes
  # the events that accrued while the lesion was growing undiagnosed, and no
  # operation can retrieve those; leaving them in buries the effect being
  # measured. dx_day defaults to 28 here -- a >10 mm vegetation -- because that
  # is the population in which surgery for embolism prevention is offered.
  rows <- lapply(surg_days, function(sd) {
    o <- IE_sim(mod, regimen = regimen, days = days, delta = 6, pheno = pheno,
                dx_day = dx_day, surgery_day = if (is.na(sd)) NULL else sd)
    z <- o[nrow(o), ]
    hpost <- -log(1 - z$P_EMB) + log(1 - o$P_EMB[1])
    cpost <- -log(1 - z$P_CNS) + log(1 - o$P_CNS[1])
    data.frame(surgery_day = ifelse(is.na(sd), "none", as.character(sd)),
               end_log10 = round(z$LOGN, 2),
               sterile = ifelse(z$STERILE > 0.5, "YES", "no"),
               P_emb_from_dx = round(1 - exp(-hpost), 4),
               P_CNS_from_dx = round(1 - exp(-cpost), 4),
               regurg_frac = round(z$REG, 3),
               NTproBNP = round(z$NTBNP),
               veg_mm = round(z$VEGMM, 1),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  ref <- out$P_emb_from_dx[1]
  out$emb_rel_reduction <- paste0(round(100 * (1 - out$P_emb_from_dx / ref)), "%")
  cat("\n=== SURGICAL TIMING SWEEP ===  ", pheno, " / ", regimen,
      " / diagnosis on lesion day ", dx_day,
      " / debridement = ", as.list(param(mod))$SURG_LOG, " log10\n\n", sep = "")
  print(out, row.names = FALSE)
  cat("\nTwo things to read off this table. First, the embolic column responds to\n")
  cat("TIMING while the microbiological column mostly does not, once the medical\n")
  cat("arm is already curative -- which is the shape of the EASE result, a\n")
  cat("composite driven by embolic events rather than by mortality. Second, the\n")
  cat("advantage decays fast: by the time the operation happens on day 14 most\n")
  cat("of the hazard it was meant to prevent has already been run through,\n")
  cat("because effective antibiotics collapse vegetation fragility within days.\n")
  cat("Surgery for embolism prevention is a FIRST-WEEK intervention, or it is a\n")
  cat("different operation being done for a different indication.\n")
  invisible(out)
}

## ===========================================================================
## DIAGNOSTIC 9 — THE THREE INFORMATIVE NEGATIVES  (targets T5, T6, T7)
## ===========================================================================
IE_negatives <- function(mod, days = 42, dx_day = 21) {
  cat("\n############ THREE NEGATIVE TRIALS THE MODEL HAS TO REPRODUCE ############\n")

  ## --- T5: adjunctive gentamicin (Cosgrove 2009 CID) ----------------------
  a <- IE_sim(mod, "nafcillin", days = days, delta = 6, pheno = "MSSA_native", dx_day = dx_day)
  b <- IE_sim(mod, c("nafcillin", "gent"), days = days, delta = 6,
              pheno = "MSSA_native", dx_day = dx_day)
  g1 <- data.frame(
    arm = c("nafcillin", "nafcillin + gentamicin x14d"),
    end_log10 = round(c(a$LOGN[nrow(a)], b$LOGN[nrow(b)]), 2),
    day5_log10 = round(c(a$LOGN[which.min(abs(a$time - 120))],
                         b$LOGN[which.min(abs(b$time - 120))]), 2),
    peak_AKI = round(c(max(a$AKI), max(b$AKI)), 3),
    peak_SCr = round(c(max(a$SCR), max(b$SCR)), 2),
    AKI_stage = c(max(a$AKI_STAGE), max(b$AKI_STAGE)))
  cat("\n[T5] Adjunctive low-dose gentamicin, staphylococcal native-valve IE\n")
  print(g1, row.names = FALSE)
  cat("Mechanism in the model: gentamicin uptake is multiplied by OXY = AVL^1.5,\n")
  cat("and lambda_gen is the shortest in the file. In the core it does nothing.\n")
  cat("Nephrotoxicity is driven by cumulative plasma AUC, which is unaffected by\n")
  cat("any of that. The benefit is geometric; the harm is not.\n")

  ## --- T6: adjunctive rifampicin (ARREST, Lancet 2018) ---------------------
  ## ARREST randomised S. AUREUS BACTERAEMIA, only about a tenth of which was
  ## endocarditis. That distinction is the entire explanation, and the model can
  ## make it quantitatively: rifampicin's unique property is that it reaches a
  ## DIFFUSION-LIMITED compartment, so in a patient who does not have one it
  ## offers nothing the companion drug is not already doing.
  settings <- list(
    list(lab = "bacteraemia, minimal lesion (day 4)", ph = "MRSA_native", dx = 4),
    list(lab = "native-valve IE (day 21)",            ph = "MRSA_native", dx = 21),
    list(lab = "prosthetic-valve IE (day 21)",        ph = "MRSA_PVE",    dx = 21))
  tc <- function(o) { i <- which(o$P_BCPOS < 0.25)
                      if (length(i)) round(o$time[i[1]] / 24, 1) else NA }
  g2 <- do.call(rbind, lapply(settings, function(st) {
    a <- IE_sim(mod, "vanco",           days = days, delta = 6, pheno = st$ph, dx_day = st$dx)
    b <- IE_sim(mod, c("vanco", "rif"), days = days, delta = 6, pheno = st$ph, dx_day = st$dx)
    data.frame(setting = st$lab,
               veg_mm_dx = round(a$VEGMM[1], 1),
               vanco_end = round(a$LOGN[nrow(a)], 2),
               vanco_rif_end = round(b$LOGN[nrow(b)], 2),
               benefit_log10 = round(a$LOGN[nrow(a)] - b$LOGN[nrow(b)], 2),
               tclear_vanco = tc(a), tclear_vanco_rif = tc(b),
               peak_ALT = round(max(b$ALT)),
               stringsAsFactors = FALSE)
  }))
  cat("\n[T6] Adjunctive rifampicin — the setting is the whole answer\n")
  print(g2, row.names = FALSE)
  cat("Row 1 is ARREST's actual population and the model reproduces the null:\n")
  cat("with no protected core there is nothing for a 2.5 mm penetration length to\n")
  cat("penetrate. Rifampicin does still shorten the bacteraemia (compare the two\n")
  cat("tclear columns) because it is the only agent in the file with real\n")
  cat("intracellular activity -- which is exactly what ARREST observed, and\n")
  cat("exactly what failed to translate into outcome.\n")
  cat("Rows 2 and 3 are where this model DISAGREES WITH CURRENT PRACTICE, and\n")
  cat("that should be stated rather than buried: it predicts a large rifampicin\n")
  cat("benefit in native-valve IE, while guidelines confine rifampicin to\n")
  cat("prosthetic material. For the guideline to be right and the model wrong,\n")
  cat("at least one of these must hold -- LAM_RIF in a real vegetation is far\n")
  cat("below 2.5 mm; rpoB mutants carry less fitness cost than FIT_COST = 0.15\n")
  cat("allows, so they survive the companion drug; or the binding constraint is\n")
  cat("not pharmacology at all but interactions and hepatotoxicity forcing dose\n")
  cat("interruptions, which this model does not represent. IE_lambda() shows how\n")
  cat("small a change in lambda it would take to move the answer.\n")

  ## --- T7: aspirin (Chan 2003 JACC) ---------------------------------------
  d1 <- IE_sim(mod, "nafcillin", days = days, delta = 6, pheno = "MSSA_native", dx_day = dx_day)
  ## Aspirin is started AT DIAGNOSIS (param_post), which is what the trial did.
  ## Giving it during the growth phase would be a prophylaxis trial, not this one.
  d2 <- IE_sim(mod, "nafcillin", days = days, delta = 6, pheno = "MSSA_native",
               dx_day = dx_day, param_post = list(ASA_ON = 1))
  pfd <- function(o, v) 1 - exp(log(1 - o[[v]][nrow(o)]) - log(1 - o[[v]][1]))
  g3 <- data.frame(
    arm = c("no aspirin", "aspirin 325 mg from diagnosis"),
    veg_mm_d42 = round(c(d1$VEGMM[nrow(d1)], d2$VEGMM[nrow(d2)]), 2),
    P_emb_from_dx = round(c(pfd(d1, "P_EMB"), pfd(d2, "P_EMB")), 4),
    P_CNS_from_dx = round(c(pfd(d1, "P_CNS"), pfd(d2, "P_CNS")), 4),
    relative_bleeding_odds = c(1.00, as.list(param(mod))$ASA_BLEED))
  cat("\n[T7] Aspirin 325 mg for embolism prevention\n")
  print(g3, row.names = FALSE)
  cat("Aspirin acts on MATRIX ACCRETION. Effective antibiotics have already shut\n")
  cat("accretion off within about 48 h, because the matrix drive in this model\n")
  cat("tracks the surface GROWING population and that is the first thing to die.\n")
  cat("So the antiplatelet arm subtracts 30% of a rate that is already close to\n")
  cat("zero. Meanwhile embolic hazard = f(diameter) x FRAGILITY, and fragility\n")
  cat("tracks the same surface population, so it has already collapsed for\n")
  cat("reasons that have nothing to do with platelets. There is no room left for\n")
  cat("the drug to work in. What is left is the bleeding.\n")
  cat("\n########################################################################\n")
  invisible(list(gent = g1, rif = g2, asa = g3))
}

