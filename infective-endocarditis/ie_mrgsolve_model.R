// Reporting floor. Below 1e-3 CFU the state is numerically meaningless (the
// solver tolerance is 1e-6 CFU) and physically it just means "eradicated".
// Floor the logs at -3 so that a ledger of "logs delivered" cannot be inflated
// by the solver chasing a state to 1e-40.
#define LFLOOR(x) log10(((x) > 1e-3) ? (x) : 1e-3)
