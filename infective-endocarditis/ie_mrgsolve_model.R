$TABLE
double FIBPP  = CPOS(FIB) + 0.10;
double VOLT   = FIBPP / RHO_VEG;
double RADT   = pow(3.0 * VOLT / (4.0 * 3.14159265), 1.0/3.0);
double VEGMM  = 2.0 * RADT;

