##  ## ---------------------------------------------------------------------
##  ## Calibration — how the parameters were actually determined
##  ## ---------------------------------------------------------------------
##  ## This model was calibrated numerically, in two stages, against SIX
##  ## independent published anchors. The timescale separation in the model
##  ## makes that cheap: the reflux/injury/inflammation/proliferation
##  ## subsystem equilibrates in weeks, the clonal cascade evolves over years.
##  ##
##  ## Stage 1 (the drug axis) — three free parameters, three anchors, each
##  ## anchor matched to the parameter that dominates it:
##  ##   ACID_POW    = 1.989  <- AspECT high-dose vs low-dose PPI ratio  0.73
##  ##   K_ASA_REG   = 0.0942 <- AspECT aspirin vs no aspirin           0.93
##  ##   K_OBES_REFL = 0.0859 <- central obesity vs lean EAC risk       ~2.0
##  ## Stage 2 (the clonal cascade) — three free rates, three anchors:
##  ##   K_P53 = 0.0934, K_HGD = 5.503e-3, K_EAC = 2.774e-4
##  ##   <- NDBE 0.12 %/yr (Hvid-Jensen), confirmed LGD 9 %/yr (Duits),
##  ##      HGD -> EAC 6 %/yr (Rastogi)
##  ## The two stages were alternated to a joint fixed point (4 rounds); all
##  ## six residuals converged to zero.
##  ##
##  ## Achieved vs target:
##  ##   high-dose PPI ratio   0.729  [AspECT 0.73]
##  ##   aspirin ratio         0.929  [AspECT 0.93]
##  ##   combination ratio     0.675  [AspECT 0.59]  <- PREDICTED, not fitted
##  ##   NDBE EAC incidence    0.120 %/yr  [Hvid-Jensen 0.12 %/yr]
##  ##   obese/lean EAC ratio  2.007  [~2.0]
##  ##   confirmed LGD         9.00 %/yr   [Duits ~9 %/yr]
##  ##   HGD -> EAC            6.00 %/yr   [Rastogi ~6 %/yr]
##  ##
##  ## The COMBINATION arm is the model's one honest miss: because the drug
##  ## effects enter MUT multiplicatively, the model can only predict
##  ## 0.729 x 0.929 = 0.677 for the combination, and it delivers 0.675. The
##  ## trial reported 0.59, i.e. slightly MORE than multiplicative. The model
##  ## therefore under-predicts the combination benefit, and that gap is a
##  ## substantive statement: either AspECT's combination estimate is at the
##  ## favourable end of its confidence interval, or there is a real
##  ## acid x COX interaction that this model does not contain.
##  ##
##  ## Fixed from mechanism rather than fitted:
##  ##   W_*_INJ split      acid 0.70 / bile 0.22 / smoking 0.08 of reference injury
##  ##   Ki-67 composition  IL-6/STAT3 0.35 (COX-INDEPENDENT) / PGE2 0.02
##  ##                      (the aspirin target) / adiposity 0.10 / floor 0.53
##  ##   K_GAS_KI = 4.0     a doubling of gastrin raises Ki-67 by 20%
##  ##                      (Haigh 2003, CCK2R trophic effect)
##  ##   K_PH_BILE = 0.35, PH_BILE_HALF = 0.25, PH_BILE_N = 2
##  ##   KINH_PUMP = 3.26 with KSYN_PUMP = 0.333 (pump resynthesis t1/2 ~50 h)
##  ##     reproduces the acid-control ladder: esomeprazole 20 mg OD -> 53%
##  ##     blockade (AET 12.5 -> 5.8%), 40 mg BID -> 82% (AET -> 2.2%).
##  ##   CL2C19 scales elimination only: PM (0.25) quadruples exposure and
##  ##     lifts 20 mg OD to high-dose-equivalent blockade, UM/*17 (1.8) drops
##  ##     it to ~41% (Furuta / Klotz / CPIC).
##  ##   KACET_COX = 22 with KREC_COX = 0.5/day gives ~87% steady-state mucosal
##  ##     COX inhibition on aspirin 300 mg OD.
##  ##   SEG_POW = 1.0 about SEG_REF = 3 cm gives ~1.7-2x risk per 2 cm
##  ##     (Anaparthy 2013).
##  ##   K_ABL_DYS = 0.85/day over a 3-session q8wk RFA course drives the
##  ##     dysplastic fractions down >99% (CE-D) while K_STRICT = 0.008 keeps
##  ##     the stricture burden in the reported 6-12% band (Shaheen 2009,
##  ##     Phoa 2014).
##  ##   K_LEN = 0.0004/day (tau ~2500 d) sets how fast an ablated segment
##  ##     regrows toward its drive-set target, i.e. the recurrence rate. The
##  ##     first draft used 0.002/day, which regrew the whole segment inside
##  ##     3 years -- far faster than the ~8-10 %/yr recurrence after CE-IM
##  ##     reported by Cotton 2018.
##  ##
##  ## THREE THINGS THAT ARE PREDICTIONS, NOT FITS
##  ##  1. The AspECT combination arm (above).
##  ##  2. Post-ablation recurrence. There is no recurrence parameter. After
##  ##     RFA the segment's target length is still set by the patient's own
##  ##     CDX2 drive, so SEED_BURIED regrows the segment whenever acid AND
##  ##     bile exposure remain uncontrolled. Durability comes out as a
##  ##     reflux-control result rather than an ablation-technique result.
##  ##  3. PPI vs no acid suppression at all. Not an AspECT comparison (every
##  ##     AspECT patient got a PPI); the model produces HR ~0.31, in the same
##  ##     direction and magnitude as the confounded observational estimate of
##  ##     ~0.4 (Kastelein 2013).
##  ##
##  ## THE FALSIFIABLE CORE: set K_PH_BILE = 0 and K_GAS_KI = 0 and high-dose
##  ## PPI monotherapy becomes far more effective than any arm of the real
##  ## trial. Those two parameters are each set from their own mechanistic
##  ## literature (Jenkins 2007 / Nehra 1999 for the pH-bile term; Haigh 2003
##  ## for the gastrin term), NOT tuned to hit AspECT — and together they land
##  ## the model on 0.729 against a measured 0.73. They are the first thing a
##  ## skeptical reader should attack.
