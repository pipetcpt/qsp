##  ============================================================================
##  Barrett's Esophagus (BE) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Barrett's esophagus — chronic acid + bile (duodenogastro-
##             esophageal) reflux injures the distal squamous epithelium ->
##             NF-kB / IL-6-STAT3 inflammation and bile-acid-driven CDX2 /
##             SOX9 / HNF4A reprogramming replace it with specialized
##             intestinal (columnar, goblet-cell) metaplasia -> within that
##             metaplastic field, a stepwise clonal evolution (CDKN2A/p16 loss
##             EARLY -> TP53 mutation as the LGD->HGD gatekeeper -> whole-
##             genome doubling / aneuploidy) drives non-dysplastic BE (NDBE)
##             -> low-grade dysplasia (LGD) -> high-grade dysplasia (HGD) ->
##             intramucosal -> invasive esophageal adenocarcinoma (EAC).
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 32 ODE compartments —
##             (a) PK/PD: esomeprazole (enteric depot -> plasma -> covalent
##                 H+/K+-ATPase inhibition with pump resynthesis, CYP2C19
##                 phenotype scaling), vonoprazan (P-CAB), aspirin (plasma ->
##                 irreversible COX acetylation -> mucosal COX activity),
##                 UDCA, plus decaying pulse drivers for RFA ablation and
##                 EMR/ESD;
##             (b) reflux/injury axis: acid exposure time (AET, % pH<4),
##                 esophageal bile exposure, epithelial injury / oxidative DNA
##                 damage, mucosal inflammation, tissue PGE2, serum gastrin;
##             (c) metaplasia: CDX2 drive, Barrett segment length (Prague M),
##                 Ki-67 proliferative index, post-ablation neosquamous
##                 re-epithelialization, post-ablation stricture;
##             (d) clonal evolution: p16-null clone fraction, LGD fraction,
##                 TP53-mutant fraction OF THE DYSPLASTIC POOL, HGD fraction,
##                 aneuploidy index, invasive EAC burden;
##             (e) clinical endpoints: symptom score and two cumulative-
##                 incidence integrators (EAC alone; AspECT composite of
##                 HGD-or-EAC).
##  Time     : DAYS. Default horizon 3650 d (10 years) — the AspECT trial ran
##             a median 8.9 years, and BE natural history is a decade-scale
##             process, so short horizons are not informative.
##  Units    : Oral drug amounts in dose-proportional arbitrary units (au):
##             1.0 au = esomeprazole 20 mg = aspirin 300 mg = vonoprazan 20 mg
##             (this library's convention when the disease-relevant PD, not
##             plasma concentration, is the object of interest). Physiological
##             states in clinically familiar units: AET %, segment length cm,
##             gastrin pg/mL, Ki-67 %, clone fractions 0-1, cumulative
##             incidence 0-1.
##  Scenarios: 10 prebuilt — see BE_simulate_scenarios() at the bottom
##             (AspECT 2x2 factorial arms, SURF ablation-vs-surveillance in
##             confirmed LGD, vonoprazan, fundoplication, EMR+RFA for HGD,
##             CYP2C19 pharmacogenomics, weight loss in central obesity).
##
##  ---- THE MECHANISTIC TENSION THIS MODEL IS BUILT TO EXPRESS --------------
##  Acid suppression is not the same thing as reflux suppression. A PPI
##  removes the H+ arm of the insult (and inactivates pepsin above pH 4) but
##  does NOT stop the volume reflux that delivers bile acids to the
##  esophagus — and deoxycholate/unconjugated bile acids are MORE membrane-
##  permeant and more potent inducers of NF-kB -> CDX2 at neutral pH than in
##  acid. On top of that, profound acid suppression raises gastrin 2-4x, and
##  gastrin is trophic to Barrett epithelium through CCK2R. The model encodes
##  both terms (K_PH_BILE > 0, K_GAS_KI > 0), so high-dose PPI produces a
##  large drop in acid exposure and symptoms but only a PARTIAL reduction in
##  the mutational drive that governs progression — which is why AspECT's
##  high-dose-PPI hazard ratio was 0.73 rather than near zero, and why adding
##  aspirin (which acts on the PGE2/apoptosis arm the PPI cannot reach) was
##  additive (HR 0.59 for the combination). Any parameterization that makes
##  PPI monotherapy abolish progression has broken this tension.
##  --------------------------------------------------------------------------
##
##  Anchors  : AspECT (Jankowski 2018 Lancet 392:400) — 2557 patients, 2x2
##             factorial esomeprazole 40 mg BID vs 20 mg OD +/- aspirin 300 mg,
##             median 8.9 y, composite of all-cause mortality/EAC/HGD: high-
##             dose PPI HR 0.73, aspirin HR 0.93 (NS alone), high-dose PPI +
##             aspirin vs low-dose PPI alone HR 0.59.
##             SURF (Phoa 2014 JAMA 311:1209) — confirmed LGD, RFA vs
##             surveillance: progression to HGD/EAC 1.5% vs 26.5% at 3 y.
##             AIM Dysplasia (Shaheen 2009 NEJM 360:2277) — RFA: CE-D 90.5%,
##             CE-IM 77.4%, stricture 6%.
##             Hvid-Jensen 2011 NEJM 365:1375 — Danish nationwide cohort,
##             11,028 BE patients: EAC incidence 1.2 per 1000 person-years
##             (0.12%/yr) in NDBE.
##             Duits 2015 Gut 64:700 — expert-confirmed LGD progresses at
##             ~9%/yr; 73% of community LGD is downstaged on review.
##             Prague C&M criteria: Sharma 2006 Gastroenterology 131:1392.
##             Segment length: ~1.7x risk per additional 2 cm
##             (Anaparthy 2013 Clin Gastroenterol Hepatol 11:1430).
##  Disclaimer: For research / education / hypothesis generation only.
##              Not a substitute for clinical judgment or regulatory filings.
##  ============================================================================

[PROB]
QSP model of Barrett's esophagus linking acid + bile reflux exposure,
epithelial injury and oxidative DNA damage, NF-kB/IL-6 inflammation, tissue
PGE2, bile-acid-driven CDX2 metaplastic reprogramming, Barrett segment length
(Prague M), and a stepwise CDKN2A -> TP53 -> aneuploidy clonal cascade
through LGD and HGD to invasive esophageal adenocarcinoma — with mechanistic
PK/PD for esomeprazole (covalent proton-pump inhibition + resynthesis +
CYP2C19 phenotype + hypergastrinemia), vonoprazan (P-CAB), aspirin
(irreversible COX acetylation), UDCA, and pulse drivers for radiofrequency
ablation and EMR/ESD, plus antireflux surgery and weight-loss interventions.

