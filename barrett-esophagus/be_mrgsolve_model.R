dxdt_PUMP = KSYN_PUMP*(1.0 - PUMP) - KINH_PUMP*PPI_CENT*PUMP;

double ppi_block = 1.0 - PUMP;                                  // 0-1
double vpz_block = EMAX_VPZ * VPZ_CENT/(EC50_VPZ + VPZ_CENT);
double acid_block = 1.0 - (1.0 - ppi_block)*(1.0 - vpz_block);
if (acid_block > 0.98) acid_block = 0.98;
g_ppi_block = ppi_block; g_vpz_block = vpz_block; g_acid_block = acid_block;

//===========================================================================
// 3. Aspirin pharmacodynamics — irreversible acetylation vs cell turnover
//===========================================================================
dxdt_COX = KREC_COX*(1.0 - COX) - KACET_COX*ASA_CENT*COX;
double cox_inhib = 1.0 - COX;                                   // 0-1
g_cox_inhib = cox_inhib;

//===========================================================================
// 4. Non-pharmacologic barrier interventions & adiposity
//===========================================================================
double fundo_on = (FUNDO > 0 && SOLVERTIME >= FUNDO_START) ? 1.0 : 0.0;
double barrier_a = (1.0 - EFF_FUNDO_A*fundo_on)
                 * (1.0 - EFF_BACLO*BACLOFEN)
                 * (1.0 - EFF_ALG*ALGINATE);
double barrier_b = (1.0 - EFF_FUNDO_B*fundo_on)
                 * (1.0 - EFF_BACLO*BACLOFEN);

double adipo_target = OBESITY * (SOLVERTIME >= WL_START ? (1.0 - WL_MAG) : 1.0);
dxdt_ADIPO = KOUT_ADI*(adipo_target - ADIPO);
double refl_mech = 1.0 + K_OBES_REFL*ADIPO;

//===========================================================================
// 5. Reflux exposure: acid and bile are NOT the same target
//===========================================================================
double acid_target = BASE_AET * (1.0 - acid_block) * barrier_a * refl_mech
                     * (1.0 + 0.10*(HH_SIZE/3.0 - 1.0));
if (acid_target < 0) acid_target = 0;
dxdt_ACID = KOUT_ACID*(acid_target - ACID);

double udca_block  = EMAX_UDCA * UDCA_CENT/(EC50_UDCA + UDCA_CENT);
double bile_target = BASE_BILE * barrier_b * refl_mech;         // acid suppression does not reduce volume reflux
if (bile_target < 0) bile_target = 0;
dxdt_BILE = KOUT_BILE*(bile_target - BILE);

// Effective bile toxicity RISES with acid blockade: at neutral pH bile acids
// are unconjugated / non-ionized, more membrane-permeant, and stronger
// inducers of NF-kB -> CDX2. The amplification SATURATES (Hill in acid_block)
// because bile-acid ionization is sigmoid in luminal pH: once the patient is
// above pH 4 for much of the day the penalty is essentially fully incurred,
// so it barely grows further when the dose is doubled. UDCA lowers bile-pool
// hydrophobicity and so reduces the effective toxicity directly.
double bile_eff = BILE * (1.0 + K_PH_BILE*HILLF(acid_block, PH_BILE_HALF, PH_BILE_N))
                       * (1.0 - udca_block);
g_udca_block = udca_block; g_bile_eff = bile_eff;

//===========================================================================
// 6. Injury -> inflammation -> PGE2
//    Acid injury is CONVEX in AET (ACID_POW = 2): damage is done by long,
//    deep acid exposures, and pepsin is only proteolytic below pH 4. The
//    consequence is a saturating benefit curve — most of the achievable acid
//    benefit is realized by low-dose PPI, and doubling the dose adds little.
//===========================================================================
double inj_target = W_ACID_INJ*pow(ACID, ACID_POW) + W_BILE_INJ*bile_eff
                    + W_SMOKE_INJ*SMOKE;
dxdt_INJURY = KOUT_INJ*(inj_target - INJURY);

double inf_target = INFLAM_BASE + K_INJ_INF*INJURY + K_ADI_INF*ADIPO;
dxdt_INFLAM = KOUT_INF*(inf_target - INFLAM);

double pge2_target = (PGE2_BASE + K_INF_PGE2*INFLAM) * COX;
dxdt_PGE2 = KOUT_PGE2*(pge2_target - PGE2);

//===========================================================================
// 7. Gastrin — the price of acid suppression, and a trophic signal
//===========================================================================
double gastrin_target = GASTRIN_BASE * (1.0 + K_GASTRIN*pow(acid_block, 1.5));
dxdt_GASTRIN = KOUT_GASTRIN*(gastrin_target - GASTRIN);

//===========================================================================
// 8. Metaplastic reprogramming and segment length
//===========================================================================
double cdx_drive  = K_BILE_CDX2*bile_eff + K_INF_CDX2*INFLAM;
double cdx_target = HILLF(cdx_drive, CDX2_HALF, CDX2_N);
dxdt_CDX2 = KOUT_CDX2*(cdx_target - CDX2);

double abl_eff = EMAX_ABL * ABL_PULSE/(EC50_ABL + ABL_PULSE);
double emr_eff = EMAX_EMR * EMR_PULSE/(EC50_EMR + EMR_PULSE);
g_abl_eff = abl_eff; g_emr_eff = emr_eff;

// Target segment length scales with the metaplastic drive relative to this
// patient's own untreated baseline, capped by BE_MAX.
double len_target = ref_be_len * (CDX2 / (ref_cdx2_0 > 1e-6 ? ref_cdx2_0 : 1e-6));
if (len_target > BE_MAX) len_target = BE_MAX;
dxdt_BE_LEN = K_LEN*(len_target + SEED_BURIED - BE_LEN) - K_ABL_LEN*abl_eff*BE_LEN;
if (BE_LEN < 0.02 && dxdt_BE_LEN < 0) dxdt_BE_LEN = 0;

// Neosquamous cover after ablation; lost again under persistent reflux.
dxdt_NEOSQ = K_NEO*abl_eff*(1.0 - NEOSQ)
           - K_NEO_LOSS*NEOSQ*(INJURY/(ref_injury > 1e-6 ? ref_injury : 1e-6));
dxdt_STRICT = K_STRICT*abl_eff*(1.0 - STRICT) - KOUT_STRICT*STRICT;

//===========================================================================
// 9. Proliferation / apoptosis balance -> mutational drive
//===========================================================================
// K_INF_KI is the COX-INDEPENDENT (IL-6/STAT3) proliferative arm; K_PGE2_KI is
// the COX-DEPENDENT arm, and PGE2 itself is multiplied by COX activity, so
// aspirin reaches only the second term. K_GAS_KI is the price of acid control.
double ki_target = KI67_BASE
                 + K_INF_KI*INFLAM
                 + K_PGE2_KI*PGE2
                 + K_GAS_KI*(GASTRIN/GASTRIN_BASE - 1.0)
                 + K_ADI_KI*ADIPO;
ki_target = ki_target / (1.0 + K_ASA_KI*cox_inhib);             // optional direct effect
if (ki_target < 1.0) ki_target = 1.0;
dxdt_KI67 = KOUT_KI67*(ki_target - KI67);

double inj_rel = INJURY / (ref_injury > 1e-6 ? ref_injury : 1e-6);
double ki_rel  = KI67   / (ref_ki67   > 1e-6 ? ref_ki67   : 1e-6);
double MUT = inj_rel * ki_rel;                                  // == 1 at untreated baseline
if (MUT < 0) MUT = 0;
g_MUT = MUT;

//===========================================================================
// 10. Clonal evolution cascade
//===========================================================================
double seg_factor = pow((BE_LEN + 0.05)/SEG_REF, SEG_POW);
g_seg_factor = seg_factor;

double haz_p16 = K_P16*MUT*(1.0 - FP16);
dxdt_FP16 = haz_p16 - KREG_P16*FP16 - K_ABL_DYS*abl_eff*FP16;

double haz_lgd = K_LGD*MUT*FP16*(1.0 - FLGD);
double haz_hgd = K_HGD*MUT*FP53*FLGD*(1.0 - FHGD);
dxdt_FLGD = haz_lgd
          - KREG_LGD*FLGD*(1.0 + K_ASA_REG*cox_inhib)   // aspirin: apoptosis restoration
          - haz_hgd
          - K_ABL_DYS*abl_eff*FLGD;

dxdt_FP53 = K_P53*MUT*FLGD*(1.0 - FP53) - KREG_P53*FP53 - K_ABL_DYS*abl_eff*FP53;

double haz_eac = K_EAC*MUT*FHGD*seg_factor*(1.0 + K_ANEU_EAC*ANEUPL);
g_haz_lgd = haz_lgd; g_haz_hgd = haz_hgd; g_haz_eac = haz_eac;
dxdt_FHGD = haz_hgd
          - KREG_HGD*FHGD
          - haz_eac
          - K_ABL_DYS*abl_eff*FHGD;

dxdt_ANEUPL = K_ANEU*MUT*FP53*(1.0 - ANEUPL) - KOUT_ANEU*ANEUPL;

dxdt_EAC = EAC_SEED*haz_eac
         + K_GROW_EAC*EAC*(1.0 - EAC/EAC_MAX)
         - K_EMR_EAC*emr_eff*EAC;
if (EAC < 0) EAC = 0;

//===========================================================================
// 11. Clinical endpoint integrators (competing-risk-free cumulative incidence)
//===========================================================================
dxdt_CUM_EAC  = haz_eac * (1.0 - CUM_EAC);
dxdt_CUM_COMP = (haz_hgd + haz_eac) * (1.0 - CUM_COMP);

//===========================================================================
// 12. Symptoms
//===========================================================================
double sym_drive  = W_ACID_SYM*ACID + W_BILE_SYM*BILE;
double sym_target = SYMPT_MAX * sym_drive/(SYMPT_HALF + sym_drive)
                  + 2.0*STRICT;                                  // stricture dysphagia
if (sym_target > SYMPT_MAX) sym_target = SYMPT_MAX;
dxdt_SYMPT = KOUT_SYMPT*(sym_target - SYMPT);

