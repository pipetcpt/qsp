##  KNOWN LIMITATIONS (state these before using any output)
##   1. ULTRADIAN GH PULSES ARE NOT RESOLVED. The model carries a circadian
##      (nocturnal-surge) modulation only, so the simulated endogenous profile is
##      smoother than physiology: peaks are underestimated (~11 vs 15-25 ug/L),
##      troughs overestimated (~1.9 vs <0.2 ug/L) and the 24-h mean therefore
##      sits above the reported 2-3 ug/L. Any question whose answer depends on
##      pulse shape rather than 24-h exposure is out of scope.
##   2. The GH -> STAT5b step uses an APPARENT (system-level) EC50 of 60 ug/L,
##      above the molecular GHR Kd, so that the IGF-1 dose-response stays close
##      to proportional across the therapeutic range as clinical data require.
##      It is a lumped transduction gain, not a receptor-binding constant.
##   3. Height and IGF-1 SDS use smooth internal reference tables (see [GLOBAL]),
##      not a validated national growth chart or an assay-specific IGF-1
##      reference. SDS values are internally consistent, not transferable.
##   4. Provoked GH peaks are compressed (normal ~10 ug/L rather than 15-40), so
##      the model separates severe / partial / normal correctly but should not be
##      used to explore diagnostic cut-offs quantitatively.
##   5. Body composition, insulin resistance, lipids, BMD Z, the intracranial-
##      pressure index and the ADA titre are semi-mechanistic target-tracking
##      representations. Directions and time courses are calibrated; absolute
##      values are illustrative. The ICP term is a relative risk index, not a
