  // linear interpolation with flat extrapolation
  inline double interp(double x, const double *xs, const double *ys) {
    if (x <= xs[0])       return ys[0];
    if (x >= xs[NREF-1])  return ys[NREF-1];
    int i = 0;
    while (i < NREF-2 && x > xs[i+1]) i++;
    double f = (x - xs[i]) / (xs[i+1] - xs[i]);
    return ys[i] + f*(ys[i+1] - ys[i]);
  }

  inline double ht_med(double a, double sex){ return sex > 0.5 ? interp(a,AGEG,HTM_M) : interp(a,AGEG,HTM_F); }
