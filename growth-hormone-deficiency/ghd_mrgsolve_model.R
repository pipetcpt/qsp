##  Paediatric Growth Hormone Deficiency (GHD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Paediatric growth hormone deficiency — impaired hypothalamic
##             (GHRH/somatostatin/ghrelin) drive and/or reduced somatotroph
##             secretory mass -> low pulsatile GH -> reduced GHR/JAK2/STAT5b
##             signalling -> low hepatic IGF-1 AND low IGFBP-3/ALS carrier
##             capacity (a DOUBLE hit: less synthesis and faster clearance of
##             what is made) -> reduced growth-plate chondrocyte proliferation
##             and hypertrophic cell enlargement -> subnormal height velocity,
##             falling height SDS, increased fat mass, reduced lean mass and
##             BMD accrual. GH insensitivity (GHR/STAT5B/IGFALS/PAPPA2 defects,
##             i.e. Laron-type) is the mirror lesion and is representable with
##             the same structure by collapsing the transduction gains.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (built & numerically validated under mrgsolve 2.0.1,
##             R 4.3.3)
##
##  ---------------------------------------------------------------------------
##  MODELLING IDEA (why this model is structured the way it is)
##  ---------------------------------------------------------------------------
##  Linear growth is treated NOT as a state to be prescribed but as the PRODUCT
##  of a chain of independently breakable gains:
##
##      HV  =  [hypothalamic drive]  x  [somatotroph mass]
##             x  [GH PK & free fraction]  x  [GHR-JAK2-STAT5b transduction]
##             x  [IGF-1 output x its BINDING state]
##             x  [growth-plate responsiveness]
##             x  [REMAINING proliferative reserve]
##
##  Two consequences fall out of the structure rather than being coded:
##
##   (1) CATCH-UP GROWTH IS A CONSUMABLE, NOT A SETPOINT. The resting-zone
##       reserve RZ multiplies the proliferation rate and is itself spent in
##       proportion to proliferation. An untreated GHD child grows slowly and
##       therefore SAVES reserve; starting rhGH spends it fast. That is why
##       year-1 HV (~10-11 cm/yr) exceeds year-3 HV (~7 cm/yr) on an UNCHANGED
##       mg/kg/wk dose, and why age at initiation is the dominant modifiable
##       predictor of near-adult height. No "year-1 decay function" is fitted.
##
##   (2) OESTROGEN ENTERS TWICE WITH OPPOSITE SIGN. E2 amplifies GH pulse
##       amplitude (the pubertal spurt, HV up) AND accelerates reserve
##       consumption and epiphyseal fusion (growing time down). The net effect
##       of an aromatase inhibitor or a GnRH analogue is therefore an emergent
##       trade-off between cm/yr and years-of-growth, not a coded height gain.
##
##  A third structural point: IGF-1 clearance depends on its own BINDING state
##  (KE_IGF is a weighted average of the fast free-pool rate and the slow
##  150-kDa ternary-complex rate). In untreated GHD, low IGFBP-3/ALS raises the
##  free fraction and thus SPEEDS clearance, deepening the IGF-1 deficit beyond
##  the drop in synthesis. In IGFALS deficiency the same term reproduces very
##  low total IGF-1 with a near-normal growth phenotype relative to the number.
##
