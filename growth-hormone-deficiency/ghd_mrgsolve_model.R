[ODE]
// ===========================================================================
// 0. Derived quantities used throughout
// ===========================================================================
double AGE  = AGE0 + SOLVERTIME/365.0;              // chronological age (yr)
double WT   = LBM + FM;                             // total body weight (kg)
double WTA  = pow(WT/70.0, 0.75);                   // allometric scalar
double WTL  = WT/70.0;                              // linear (volume) scalar

// GH free fraction: GHBP sequesters GH reversibly.
double FU   = 1.0/(1.0 + GHBP/KD_BP);
double GF   = GHC*FU;                               // free GH (the cleared species)
if (GF < 0) GF = 0;
// NEUTRALISING anti-drug antibodies block receptor binding without accelerating
// clearance. They must therefore act on the PD side: if they were written into
// the free fraction they would cancel exactly, because receptor-mediated
// clearance also acts on free GH, leaving steady-state active GH unchanged.
double GA   = GF/(1.0 + ADA/KADA);                  // ACTIVE (receptor-available) GH

// IGF-1 binding state: the 150-kDa ternary carrier pool sets the free fraction,
// and therefore the CLEARANCE, of total IGF-1 (the second hit in GHD).
double BINDCAP = BP3*ALSC;
double FU_IGF  = 1.0/(1.0 + KB_TERN*BINDCAP + KB_BIN*BP1);
double FIGF    = IGF1*FU_IGF*(0.55 + 0.45*PAPPA2A);  // free/bioactive IGF-1
double FIGFN   = FIGF/FIGFREF;                       // normalised to healthy reference

// Thyroid permissive factor on the growth plate and on bone age. What the
// growth plate sees is the T3-equivalent tissue signal, NOT free T4: GH raises
// type-2 deiodinase activity, so free T4 FALLS on rhGH while tissue T3 is
// preserved. The measured biomarker (FT4) and the growth-relevant signal
// therefore move in opposite directions — which is exactly why an FT4 fall
// after starting rhGH unmasks central hypothyroidism rather than causing it.
double THYR = (FT4/FT4REF)*(1.0 + KD2*GA/(EC50_LIP + GA));
if (THYR > 1.15) THYR = 1.15;
if (THYR < 0.20) THYR = 0.20;

// exogenous bioactive GH input (ug/day) — used for immunogenicity drive
double EXOIN = KA_D*DEPD*1000.0 + KREL*PROD*1000.0*POT_W;

// ===========================================================================
// 1-3. Hypothalamic oscillator
// ===========================================================================
double s    = sin(2.0*M_PI*(SOLVERTIME - PHASE));
double CIRC = 1.0 + AMPC*pow(s > 0 ? s : 0.0, HILLC);

dxdt_GHRH = KIN_GHRH*CIRC*SLEEPQ
            /(1.0 + SST/KI_SST_G)
            *(1.0 + EMAX_GHRL*GHREL/(EC50_GHRL + GHREL))
            /(1.0 + GAIN_IGFG*(FIGFN > 1.0 ? FIGFN - 1.0 : 0.0))
            - KOUT_GHRH*GHRH;

dxdt_SST = KIN_SST*(1.0
             + SL_IGF_S*(FIGFN > 1.0 ? FIGFN - 1.0 : 0.0)
             + SL_GH_S *(GA > 1.2 ? GA/1.2 - 1.0 : 0.0)
             + SL_FFA_S*(FFA > FFAREF ? FFA/FFAREF - 1.0 : 0.0))
           - KOUT_SST*SST;

dxdt_GHREL = KIN_GHRL/(1.0 + INS/KI_INS_GL) - KOUT_GHRL*GHREL;

// ===========================================================================
// 4-5. Somatotroph mass and releasable granule pool
// ===========================================================================
double pitcap = PITMAX > 1e-4 ? PITMAX : 1e-4;
dxdt_PITM = KGROW*PITM*(1.0 - PITM/pitcap) - KDAM*XRT_ON*PITM;

double SIZEC = pow(WT/WTREF, 0.75);        // secretion capacity scales with size
double SYNTH = KSYN_GH*SIZEC*PITM*(1.0 + EMAX_CREB*GHRH/(EC50_CREB + GHRH));
double SECR  = VMAX_SEC*SIZEC*PITM
               *(GHRH/(KM_GHRH + GHRH))
               /(1.0 + SST/KI_SST_S)
               *(GHPOOL/(KM_POOL + GHPOOL));
dxdt_GHPOOL = SYNTH - SECR - KDEG_POOL*GHPOOL;

// ===========================================================================
// 6-8. GH pharmacokinetics (2-compartment, saturable receptor-mediated CL)
// ===========================================================================
double VC   = VC70*WTL;
double VP   = VP70*WTL;
double Q    = Q70*WTA;
double CLGH = CL70*WTA + (CLRMAX*GHRc*WTA)/(KM_CLR + GF);

dxdt_GHC = (SECR + EXOIN)/VC
           - CLGH*GF/VC
           - (Q/VC)*(GHC - GHP);
dxdt_GHP = (Q/VP)*(GHC - GHP);

dxdt_GHBP = KSYN_BP*GHRc - KOUT_BP*GHBP;

// ===========================================================================
// 9-14. Drug kinetics
// ===========================================================================
dxdt_DEPD = -KA_D*DEPD;                              // daily somatropin depot
dxdt_DEPW = -KA_W*DEPW;                              // weekly LAGH depot
dxdt_PROD =  KA_W*DEPW - (KREL + CLP_K)*PROD;        // circulating carrier
dxdt_DEPM = -KA_M*DEPM;                              // mecasermin depot
dxdt_LEUP =  LEUPRATE*1000.0/VLEU - KEL_LEU*LEUP;    // GnRH analogue
dxdt_AIC  =  AIRATE *1000.0/VAI  - KEL_AI *AIC;      // aromatase inhibitor

// ===========================================================================
// 15-17. GHR / pSTAT5b / SOCS2
// ===========================================================================
double OCC = GA/(KD_GHR + GA);

dxdt_GHRc = KSYN_R*GHRCAP/(1.0 + SOCS/KI_SOCS_R)
            - KDEG_R*GHRc*(1.0 + KDOWN*OCC);

dxdt_PS5  = KON_S*OCC*GHRc*STAT5CAP/(1.0 + SOCS/KI_SOCS_S) - KOFF_S*PS5;

dxdt_SOCS = KSYN_SOC*PS5 - KOUT_SOC*SOCS;

// ===========================================================================
// 18-22. IGF system
// ===========================================================================
double ps5h    = pow(PS5 > 0 ? PS5 : 0.0, HS);
// hepatic maturation: circulating IGF-1 rises through childhood at roughly
// constant GH secretion because hepatic synthetic mass grows with the child
double MATIGF  = pow(AGE/AGE_IREF, KMATI);
double SYN_IGF = KSYN_IGF*NUTR*LIVER*MATIGF
                 *(BAS_IGF + (1.0 - BAS_IGF)*ps5h/(pow(KM_S,HS) + ps5h))
                 *(1.0 + EMAX_E2I*E2/(EC50_E2I + E2));

double KE_IGF  = KEF_IGF*FU_IGF + KET_IGF*(1.0 - FU_IGF);

dxdt_IGF1 = SYN_IGF
            + KA_M*DEPM*1000.0/(VD_IGF*WTL)          // mecasermin input
            - KE_IGF*IGF1;

double ps3 = pow(PS5 > 0 ? PS5 : 0.0, H3);
dxdt_BP3  = KSYN_BP3*(BAS_BP3 + (1.0 - BAS_BP3)*ps3/(pow(KM3,H3) + ps3))
            - KOUT_BP3*BP3*(1.0 + KPA*PAPPA2A);

dxdt_ALSC = KSYN_ALS*ALSCAP*(BAS_ALS + (1.0 - BAS_ALS)*PS5/(KMA + PS5)) - KOUT_ALS*ALSC;

dxdt_BP1  = KSYN_BP1/(1.0 + INS/KI_INS_B1) - KOUT_BP1*BP1;

dxdt_IGFL = KSYN_L*PS5/(KML + PS5) - KOUT_L*IGFL;

// ===========================================================================
// 23-27. Growth plate — the multiplicative engine
// ===========================================================================
// (a) the three drives on chondrocyte proliferation
// The direct (dual-effector) GH action on the resting zone still needs a GH
// RECEPTOR, so it is gated by receptor density. This is what separates GH
// DEFICIENCY (low GH, intact receptor) from GH INSENSITIVITY (high GH, no
// receptor): in Laron syndrome the high circulating GH buys nothing.
double DIR_GH = EMAX_GHD*(GHRc/GHRREF)*STAT5CAP*GA/(EC50_GHD + GA);  // direct, resting zone
double DR_IGF = EMAX_IGF*FIGFN/(EC50_IGF + FIGFN);           // endocrine IGF-1
double DR_LOC = EMAX_LOC*IGFL/(EC50_LOC + IGFL);             // paracrine IGF-1
double DRIVE  = DIR_GH + DR_IGF + DR_LOC;

// (b) brakes: FGFR3 tone, glucocorticoid, thyroid permissiveness, ageing
double BRAKE = 1.0/(1.0 + FGF_TONE);
double GCEFF = 1.0/(1.0 + GCDOSE/IC50_GC);
double AGEF  = exp(-KAGE*(BA - BA_REF));

// (c) proliferation rate. Split into the DRIVE per unit reserve and the
// remaining reserve itself, because senescence is spent by the per-cell cycling
// rate (KDRIVE), not by the product. Keeping these separate is what makes the
// initial-reserve formula in [MAIN] and this ODE the same law, so that starting
// a simulation at age 8 gives the same reserve as running from age 5 to 8.
double KDRIVE = DRIVE*BRAKE*GCEFF*THYR*AGEF;
double KPROL  = KPROL0*KDRIVE*RZ;

dxdt_PZ = KPROL*(1.0 - PZ/PZMAX) - KDIFF*PZ;

// (d) hypertrophic cell height, the hypertrophic zone, and height velocity
double IGFARM = (DR_IGF + DR_LOC)/(EMAX_IGF + EMAX_LOC);   // 0-1 IGF-1 tone
double HYPSZ  = HYP0*(1.0 + EMH*IGFARM)*THYR;
double FLUX   = KDIFF*PZ;                                    // cells entering hypertrophy
dxdt_HZ = FLUX*HYPSZ - KREM*HZ;

double OPEN = 1.0 - GPS;
if (OPEN < 0) OPEN = 0;
double HV = KHV*FLUX*HYPSZ*OPEN;                             // cm/yr
dxdt_HT = HV/365.0;

// (e) reserve consumption. Keyed to the REALISED growth rate, not to the drive:
// reserve is spent by cell divisions, and the number of divisions is what
// actually produced the centimetres. This is the term that makes catch-up growth
// self-limiting — a child pushed to 10 cm/yr spends reserve about twice as fast
// as a child growing 6 cm/yr — while leaving a child who is already growing at
// the age-normal rate almost unpenalised. Oestrogen accelerates it on top.
dxdt_RZ = -KSEN*RZ*pow(HV/HVREF_SEN, NSEN)*(1.0 + KSEN_E2*E2/(EC50_SE2 + E2));
if (RZ < 1e-4 && dxdt_RZ < 0) dxdt_RZ = 0.0;

// (f) oestrogen-driven epiphyseal fusion program
dxdt_GPS = (KFUS*E2/(EC50_FUS + E2) + KFUS0)*(1.0 - GPS);

// ===========================================================================
// 28-30. Bone age and bone mineral
// ===========================================================================
// bone age advances with maturation, is accelerated by oestrogen and (modestly,
// saturably) by the IGF-1 tone, is slowed by hypothyroidism, and stops at fusion
double tone = IGFARM/IGFARMREF;  if (tone > 1.8) tone = 1.8;
dxdt_BA = (KBA0
           + KBA_GH*tone
           + KBA_E2*E2/(EC50_BAE2 + E2))*THYR*(1.0 - 0.85*GPS)/365.0;

// BMD Z-score tracks a target set by the IGF-1 tone, oestrogen-driven mineral
// accrual, glucocorticoid/aromatase-inhibitor penalties, MINUS a transient
// penalty proportional to how fast the child is currently growing: newly formed
// bone is under-mineralised, so areal BMD-for-age dips while height velocity is
// supranormal and recovers as the velocity falls. This reproduces the observed
// early-BMD-dip-then-net-gain pattern without a second bone compartment.
double BZTGT = MPHSDS
               + KBZ_TONE*(IGFARM - IGFARMREF)
               + KBZ_E2*E2/(EC50_BE2 + E2)
               - KBZ_HV*(HV/HVREF - 1.0)
               - KBZ_GC*GCDOSE/(IC50_GC + GCDOSE)
               - KBZ_AI*AIC/(IC50_AI + AIC);
dxdt_BMDZ = KBZ_TURN*(BZTGT - BMDZ);

// ===========================================================================
// 31-33. Puberty and the oestrogen clock
// ===========================================================================
double FMPCT = 100.0*FM/(WT > 0.1 ? WT : 0.1);
double MAT   = 1.0/(1.0 + exp(-(BA - BA50)/TAUP));
double gonad = (HYPOGON > 0.5) ? 0.0 : 1.0;

dxdt_GT = KG_IN*MAT*gonad*(1.0 + KLEP*(FMPCT/FMPREF - 1.0))/(1.0 + LEUP/IC50_LEU)
          - KG_OUT*GT;

double AROMA = 1.0/(1.0 + AIC/IC50_AI);

dxdt_TST = KT_SYN*GT*SEX - KT_OUT*TST;
dxdt_E2  = KARO*AROMA*TST/(KMT + TST)
           + KOV*GT*(1.0 - SEX)*AROMA
           + 0.9                                        // small adrenal/extragonadal source
           - KOUT_E2*E2;

// ===========================================================================
// 34-40. Body composition and intermediary metabolism
// ===========================================================================
double LIPO   = ELIP*GA/(EC50_LIP + GA);
double FMTGT  = FMBASE *pow(HT/100.0, HEXP)/(1.0 + LIPO);
double LBMTGT = LBMBASE*pow(HT/100.0, HEXP)*(1.0 + ELEAN*DR_IGF);

dxdt_FM  = KFTURN*(FMTGT - FM);
dxdt_LBM = KLTURN*(LBMTGT - LBM);

dxdt_IRES = KIR_IN*(1.0
              + EMAX_IR*GA/(EC50_LIP + GA)
              + KIR_FFA*(FFA/FFAREF - 1.0)
              + KIR_FM *(FMPCT/FMPREF - 1.0))
            - KIR_OUT*IRES;

dxdt_INS = KI_IN*INSREF*(GLU/85.0)*IRES - KI_OUT*INS;
dxdt_GLU = KG_PROD*(1.0 + KGH_GNG*GA/(EC50_LIP + GA))*(0.5 + 0.5*IRES)
           - KG_UP*GLU*(1.0 + KINS_UP*INS/(IRES > 0.1 ? IRES : 0.1));

dxdt_FFA = KFFA_IN*(1.0 + EMAX_LIP2*GA/(EC50_LIP + GA))*(FM/(FMTGT > 0.1 ? FMTGT : 0.1))
           - KFFA_OUT*FFA;

dxdt_LDL = KL_IN - KL_OUT*LDL*(1.0 + ELDL*GA/(EC50_LIP + GA));

// ===========================================================================
// 41-43. Safety states
// ===========================================================================
dxdt_ADA = KADA_IN*IMGEN*EXOIN/(EC50_EXO + EXOIN) - KADA_OUT*ADA;

// replacement substitutes for what the thyrotroph cannot make
double THYSUP = THYRCAP + (1.0 - THYRCAP)*LT4;
if (THYSUP > 1.0) THYSUP = 1.0;
dxdt_FT4 = KT4_IN*FT4REF*THYSUP
           - KT4_OUT*FT4*(1.0 + KD2*GA/(EC50_LIP + GA));

// early, dose-related and self-limiting (adaptation term in the denominator)
dxdt_ICPX = KICP_IN*(GA/(EC50_LIP + GA))/(1.0 + KICP_ADAPT*ICPX) - KICP_OUT*ICPX;

