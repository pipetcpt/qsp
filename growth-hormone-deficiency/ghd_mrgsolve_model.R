[PROB]
QSP model of paediatric growth hormone deficiency. Linear growth is computed as
the product of separable gains: hypothalamic GHRH/somatostatin/ghrelin drive,
somatotroph secretory mass, GH pharmacokinetics and free fraction (GHBP),
GHR-JAK2-STAT5b transduction under a SOCS2 brake, hepatic IGF-1 output and its
binding state (IGFBP-3/ALS ternary complex), growth-plate chondrocyte
proliferation/hypertrophy, and the REMAINING resting-zone proliferative
reserve. Catch-up growth and the year-on-year decline of height velocity on an
unchanged dose emerge from reserve consumption; the oestrogen trade-off between
cm/yr and years-of-growth emerges from E2 entering with opposite signs.
Includes daily somatropin, three weekly long-acting GH constructs, mecasermin,
a GnRH analogue and an aromatase inhibitor, plus body composition, insulin
resistance, bone, and safety (IGF-1 cap, ADA, free T4, intracranial pressure).

