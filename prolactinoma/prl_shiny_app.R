server <- function(input, output, session) {

  observeEvent(input$preset, {
    p <- switch(input$preset,
      "microadenoma (F)"          = list(ns0=0.35, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "macroadenoma (F)"          = list(ns0=3.20, d2rs=0.35, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "giant, male"               = list(ns0=18.0, d2rs=0.25, sex="male", fgen=1.0,
                                         fdrive=1.3, stalkp=1, apab=0, ap_drug="none"),
      "partial resistance"        = list(ns0=3.20, d2rs=0.15, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "true resistance (AIP-like)"= list(ns0=3.20, d2rs=0.04, sex="male", fgen=1.3,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "stalk effect (NFPA)"       = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=0.05, apab=0, ap_drug="none"),
      "macroprolactinaemia"       = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=2.2, ap_drug="none"),
      "antipsychotic-induced"     = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0,
                                         ap_drug="risperidone-like"),
      "healthy control"           = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"))
    updateSliderInput(session, "ns0", value = p$ns0)
    updateSliderInput(session, "d2rs", value = p$d2rs)
    updateSliderInput(session, "fgen", value = p$fgen)
    updateSliderInput(session, "fdrive", value = p$fdrive)
    updateSliderInput(session, "stalkp", value = p$stalkp)
    updateSliderInput(session, "apab", value = p$apab)
    updateRadioButtons(session, "sex", selected = p$sex)
    updateSelectInput(session, "ap_drug", selected = p$ap_drug)
  })

  sim <- reactive({ simulate(reactiveValuesToList(input)) })

  # ---- tab 1 --------------------------------------------------------------
  output$tbl_profile <- renderDT({
    d <- sim()
    tt <- c(PRESIM, PRESIM + 365, max(d$time))
    lab <- c("진단 시점", "1년 후", sprintf("%.0f년 후", (max(d$time)-PRESIM)/365))
    vars <- c(PRLB="생물학적 프로락틴 (ng/mL)", PRLMEAS_="보고된 프로락틴 (ng/mL)",
              PEGREC="PEG 회수율 (%)", TVOL_="종양 부피 (mL)",
              CELLN="종양 세포량 (mL)", VCELL="평균 세포 부피",
              COMPR_="시신경교차 압박 (cm)", VFMD="시야 MD (dB)",
              OVF="배란 능력", TST="테스토스테론 (ng/dL)", E2G="에스트라디올 (pg/mL)",
              TSCORE="요추 T-score", PFRACT="척추 골절 확률 (%)",
              BW="체중 (kg)", IR="HOMA-IR", CORT="코르티솔 예비능",
              SIGDRIVE="D2 신호 구동", PTR="중등도 이상 TR 확률 (%)",
              PICD="충동조절장애 확률 (%)")
    m <- sapply(tt, function(t) sapply(names(vars), function(v) atd(d, v, t)))
    df <- data.frame(metric = unname(vars), round(m, 3), check.names = FALSE)
    names(df) <- c("지표", lab)
    datatable(df, rownames = FALSE, options = list(pageLength = 20, dom = "t"))
  })

  output$p_profile <- renderPlot({
    d <- sim()
    dd <- d %>% select(year, PRLB, PRLMEAS_, TVOL_, VFMD, TSCORE, OVF) %>%
      pivot_longer(-year)
    lv <- c(PRLB="생물학적 PRL", PRLMEAS_="보고된 PRL", TVOL_="종양 부피 mL",
            VFMD="시야 MD dB", TSCORE="요추 T-score", OVF="배란 능력")
    dd$name <- factor(lv[dd$name], levels = lv)
    ggplot(dd, aes(year, value)) +
      geom_line(colour = PAL[1], linewidth = 0.9) +
      facet_wrap(~name, scales = "free_y", ncol = 3) + pres_line() +
      labs(x = "년 (0 = 종양 seeding)", y = NULL,
           title = "생성된 표현형의 전체 경과",
           subtitle = "점선 = 환자가 내원하고 치료가 시작되는 시점") +
      theme_prl()
  })

  # ---- tab 2 --------------------------------------------------------------
  output$txt_occ <- renderText({
    d <- sim(); r <- d[which.min(abs(d$time - max(d$time))), ]
    p <- build_par(reactiveValuesToList(input))
    paste0(
      "SIGDRIVE = SUM_i e_i (C_i/K_i) / (1 + SUM_j C_j/K_j)   x   D2R density\n\n",
      sprintf("  건강한 도파민 단독 상태의 SIGDRIVE          : %.4f\n", 0.0909),
      sprintf("  현재 SIGDRIVE (모든 리간드 경쟁 후)         : %.4f  (%.2fx)\n",
              r$SIGDRIVE, r$SIGDRIVE/0.0909),
      sprintf("  종양 클론의 활성 수용체 신호 SIGS           : %.4f\n", r$SIGS),
      sprintf("  잔여 전사 활성 (branch 2, 낮을수록 억제)    : %.4f\n", r$RTRS),
      sprintf("  잔여 분비과립 방출 활성 (branch 1)          : %.4f\n", r$REXS),
