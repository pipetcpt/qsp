# =============================================================================
#  PROLACTINOMA QSP — Shiny dashboard
#
#  11 tabs built directly on the model spec in prl_mrgsolve_model.R, which is
#  read out of that file at start-up so the app and the model cannot drift
#  apart.
#
#  The organising ideas the dashboard is built to make visible:
#    * ONE D2 occupancy equation drives everything, so the same slider set
#      produces dopamine-agonist therapy, antipsychotic-induced
#      hyperprolactinaemia, the aripiprazole add-on paradox and stalk-effect
#      disconnection. Tab 2 shows the competition explicitly.
#    * The MEASUREMENT LAYER is separate from the biology. Tab 4 plots
#      bioactive, immunoreactive, reported and post-dilution prolactin on the
#      same axes, so the hook effect and macroprolactinaemia are visible as
#      gaps between curves rather than as footnotes.
#    * Efficacy runs off the PITUITARY BIOPHASE and valvular risk off PLASMA,
#      so tab 9 can show them diverging.
#    * Presenting values are GENERATED by a silent natural-history phase, not
#      typed in: every plot marks the day of presentation.
#
#  Run with:  shiny::runApp("prl_shiny_app.R")
# =============================================================================

