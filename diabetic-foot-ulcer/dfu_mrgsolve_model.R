//===========================================================================
// 0. Shared algebra
//===========================================================================
double A     = fmax(AREA, 0.0);
double PERIM = 2.0 * sqrt(M_PI * fmax(A, 1e-9));
double healed = 1.0 - SWONW(A, AREA_CLOSE, 0.02);  // ~1 once AREA < AREA_CLOSE
double open_w = 1.0 - healed;

double hyperg = fmax(HBA1C - 6.0, 0.0);
double PROT   = MMP9 / (TIMP1 + 0.05);             // MMP-9 / TIMP-1 ratio
double PROTn  = PROT / (PROT + 1.5);

// --- offloading: efficacy x adherence -------------------------------------
double on_off  = WINDOW(SOLVERTIME, T_OFF_ON, T_OFF_OFF);
double offload = DEV_EFF * ADHERENCE * on_off;
double ppp_idx = (1.0 + 0.60 * (DEFORMITY - DEFORM_REF)) * STEPS_REL;
double STRESS  = ppp_idx * (1.0 - offload);
double MG      = INHIB(STRESS, S50_MECH, H_MECH);
double over    = fmax(STRESS - STRESS_TOL, 0.0);
// re-injury is a MARGIN process too: proportional to perimeter, bounded by the
// anatomical extent of the high-pressure zone
double REINJ = K_REINJ * over * over * PERIM
               * fmax(1.0 - A / AREA_MAXPR, 0.0) * open_w;

// --- perfusion, oxygen and the HIF competence defect ----------------------
double rev      = SWON(SOLVERTIME, T_REVASC);
double resten   = exp(-K_RESTEN * fmax(SOLVERTIME - T_REVASC, 0.0));
double perf_tgt = fmin(PERF_TGT + REVASC_GAIN * rev * resten, 1.0);

double hb_f = fmin(HB_GDL / 13.0, 1.0);
double WPO2 = fmax(TCPO2_MAX * PERF * (0.45 + 0.55 * VASC) * hb_f
                   - OEDEMA_PEN * (1.0 - 0.5 * NPWT)
                   + E_OXY * HILL(OXY, 0.5, 1.0), 1.0);
double OG   = HILL(WPO2, PO2_50, HILL_O2);         // THE anabolic oxygen gate

double hypoxia  = INHIB(WPO2, PO2_HIF, 2.0);
double hif_comp = fmax(1.0 - MGO_BLOCK * hyperg, 0.05);
double HIFdrive = hypoxia * hif_comp;              // hypoxia present, response absent

