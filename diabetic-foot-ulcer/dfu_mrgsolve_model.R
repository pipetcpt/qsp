              * pow(stress_post / 0.90, 1.5)
              * (1.0 - 0.55 * tens)
              * (1.0 - 0.10 * EDU) * (1.0 - 0.28 * TEMPMON) * (1.0 - 0.12 * SURVEIL);
dxdt_HAZREC = healed * haz;
dxdt_HAZAMP = A0_AMP * (2.0 * pow(OSTEO, 1.5)
                        + 1.2 * pow(1.0 - PERF, 2.0)
                        + 0.9 * fmax(bf - 0.6, 0.0) * 2.5) * open_w;
dxdt_UFD  = healed;
dxdt_ABXD = (R_ABX > 0 ? on_abx : 0.0);
dxdt_TOXIDX = (W_TOX_ABX  * on_abx  * (R_ABX > 0 ? 1.0 : 0.0)
             + W_TOX_HBOT * on_oxy  * (R_OXY > 0 ? 1.0 : 0.0)
             + W_TOX_BEC  * on_bec  * (R_BEC > 0 ? 1.0 : 0.0)
             + W_TOX_TCC  * DEV_EFF * on_off) / 100.0;
dxdt_AUCEDGE = EDGE;

