                * INHIB(PROT, PR50_K, 1.0)
                * (0.60 + 0.40 * OG)
                * (1.0 + E_ESM * HILL(ESM_W, EC50_ESM, 1.0))
                * (1.0 + E_CTP * HILL(CTP, EC50_CTP, 1.0))
                * (1.0 - 0.10 * fmin(hyperg / 4.0, 1.0));
dxdt_KERA = KIN_K * kdrive * (1.0 - KERA) - KOUT_K * KERA
            + 0.40 * DEBR * (1.0 - KERA);          // de-epibolisation

