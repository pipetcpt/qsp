           - K_SEN * (ROS + 0.40 * PROTn) * FIB - KD_FIB * FIB;
dxdt_SEN = K_SEN * (ROS + 0.40 * PROTn) * FIB - KCL_SEN * SEN - 1.6 * DEBR * SEN;
dxdt_COL = KS_COL * FIB * OG * open_w - KDEG_COL * PROTn * COL;
dxdt_GRAN = KG_GRAN * HILL(COL, 0.70, 1.0) * (0.30 + 0.70 * VASC) * OG
            * (1.0 + 0.35 * NPWT) * (1.0 - GRAN)
            - KD_GRAN * PROTn * GRAN - 0.25 * DEBR * GRAN;

//===========================================================================
