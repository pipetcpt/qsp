##  Diabetic Foot Ulcer (DFU) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Diabetic foot ulcer — the convergence of (i) diabetic peripheral
##             neuropathy with loss of protective sensation, (ii) peripheral
##             arterial disease / microvascular dysfunction, and (iii) repetitive
##             plantar pressure on an insensate, deformed foot.  The resulting
##             wound arrests in a protease-dominant, biofilm-colonised,
##             senescent-fibroblast state in which inflammation never resolves,
##             keratinocytes proliferate but do not migrate, and closure — when
##             it happens — is a remission, not a cure.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>= 1.5)
##
##  Scope    : 44 ODE compartments —
##               topical/systemic therapy PK (becaplermin gel, TLC-NOSF sucrose
##               octasulfate dressing, esmolol 14% gel, systemic antibiotic with
##               explicit wound- and bone-tissue compartments, cellular tissue
##               product, hyperbaric/topical oxygen, sharp debridement)
##             + slow systemic axes (HbA1c, neuropathy, perfusion)
##             + infection (planktonic bioburden, biofilm, osteomyelitis, exposed
##               bone nidus)
##             + wound inflammation (neutrophils, M1/M2 macrophages, IL-1beta, ROS)
##             + protease/anti-protease balance (MMP-9, TIMP-1)
##             + growth factors & angiogenesis (PDGF-BB, VEGF, SDF-1alpha, EPC,
##               granulation vascular density)
##             + repair tissue (fibroblasts, senescent fibroblasts, collagen,
##               granulation fill, keratinocyte migratory competence)
##             + wound geometry (AREA, DEPTH) and outcomes (scar maturation,
##               re-ulceration hazard, amputation hazard, ulcer-free days,
##               antibiotic-days, treatment-burden index).
##  Time     : days.  Default horizon 540 d (12-week closure window + 12 months
##             of post-closure remission follow-up); 1825 d for the slow axes.
##  Units    : AREA cm^2, DEPTH mm, wound pO2 mmHg, BACT log10 CFU/g, HbA1c %,
##             cytokine/protease/growth-factor states in normalised wound units
##             (1.0 = the level of a typical stalled chronic DFU at presentation),
##             topical/systemic drug states in dose-proportional units (au).
##
##  ---------------------------------------------------------------------------
##  SIX STRUCTURAL COMMITMENTS (what makes this model say something)
##  ---------------------------------------------------------------------------
##  1. CLOSURE IS A PERIMETER PROCESS, NOT AN AREA PROCESS.
##       dA/dt = -k(t) * P,  P = 2*sqrt(pi*A)   <=>   dr/dt = -k(t)
##     All biology enters through the linear edge-advance rate k (cm/day); the
##     geometry is exactly a shrinking radius.  Consequence: time-to-heal is
##     r0/k, so a 16-fold range of wound AREA is only a 4-fold range of healing
##     TIME, and the 4-week percent-area-reduction rule (Sheehan) has a
##     closed-form, size-free reading  t_heal = 28/(1 - sqrt(1 - PAR4)).
##
##  2. OFFLOADING IS DEVICE EFFICACY x ADHERENCE.
##     A removable cast walker is not a worse device than a total contact cast —
##     it is a slightly BETTER device (87% vs 85% peak-pressure reduction) that
##     is worn during only ~28% of daily activity (Armstrong 2003).  The model
##     encodes adherence separately, so the entire TCC-vs-walker healing gap is
##     recovered as an adherence effect and vanishes when adherence is set to 1.
##
##  3. TOPICAL GROWTH FACTOR IS A RACE AGAINST PROTEASE.
##     Becaplermin is cleared from the wound at (KOUT_BEC + KDEG_BEC_PROT*PROT)
##     where PROT = MMP-9/TIMP-1.  In a protease-dominant wound most of the
##     applied rhPDGF-BB is destroyed before it signals.
##
##  4. OXYGEN GATES EVERY ANABOLIC TERM.
##     One Hill gate OG = pO2^3/(pO2^3 + PO2_50^3) multiplies collagen synthesis
##     (prolyl hydroxylase is O2-dependent), angiogenesis, the M1->M2 switch, the
##     neutrophil oxidative burst and the epithelial edge.  Below the gate no
##     biologic can work.  Separately, methylglyoxal blocks HIF-1alpha
##     transactivation, so the hypoxic diabetic wound cannot even mount the
##     hypoxia response it is entitled to.
##
##  5. HbA1c IS A SLOW-AXIS DRUG.
##     Neuropathy relaxes with a ~4.6-year time constant.  Intensive glycaemic
##     control therefore does very little for the ulcer in front of you and a
##     great deal for the one three years from now — which is why HbA1c is a weak
##     predictor of index-ulcer healing and a strong predictor of incidence.
##
##  6. CLOSURE IS REMISSION, NOT CURE.
##     Healing resets AREA and leaves NEURO, plantar pressure and deformity
##     untouched, and leaves behind scar at ~80% of normal tensile strength.  The
##     post-closure re-ulceration hazard is driven by that unchanged substrate.
##
##  ---------------------------------------------------------------------------
##  CALIBRATION ANCHORS  (see dfu_references.md; model values from the
##  dependency-free reference implementation dfu_reference_implementation.py)
##  ---------------------------------------------------------------------------
##    Armstrong 2001 Diabetes Care 24:1019 — mean days to healing, A0 = 1.4 cm2
##        TCC        obs 33.5 d   model 36.3 d
##        RCW        obs 50.4 d   model 59.6 d
##        half-shoe  obs 61.0 d   model 64.4 d
##    Armstrong 2003 Diabetes Care 26:2595 — RCW worn during 28% of daily
##        activity; encoded directly as ADHERENCE = 0.28.
##    Sheehan 2003 Diabetes Care 26:1879 — PAR4 > 50% predicts 12-week closure.
##    Armstrong 2017 NEJM 376:2367 — ~40% recurrence at 1 year (model 41.8%);
##        ~60% at 3 years (model 79.4% — see LIMITATIONS).
##    Wieman 1998 Diabetes Care 21:822 — becaplermin 50% vs 35% closure at 20 wk
##        (model: 7% faster healing rate).
##    Edmonds 2018 Lancet Diabetes Endocrinol 6:186 (Explorer) — TLC-NOSF 48% vs
##        30% closure at 20 wk (model: 17% faster).
##    Lipsky 2012 Clin Infect Dis 54:e132 / IWGDF 2023 — infection & osteomyelitis
##        management; biofilm antibiotic tolerance 100-1000x planktonic MIC.
##
##  LIMITATIONS
##    * Deterministic single-patient trajectories.  "89.5% healed at 12 weeks"
##      style trial endpoints are represented as time-to-closure, not as a
##      population proportion.
##    * The post-closure re-ulceration hazard is constant in time-since-closure.
##      That reproduces the 1-year figure (41.8% vs ~40% observed) but
##      over-predicts 3-year recurrence (79.4% vs ~60%): in reality the hazard
##      declines as the highest-risk patients recur early and the scar matures.
##    * Drug amounts are dose-proportional surrogate units, not mg; the PK is
##      structurally correct (depot -> wound tissue -> bone) but not fitted to
##      measured tissue concentrations.
##    * BEXP (exposed bone) and AUCEDGE are bookkeeping states, not physiology.
##    * The Python reference implements the same 44 states; the declaration order
##      differs between the two files for readability. The equations do not.
##
##  Disclaimer: research / education / hypothesis generation only.  Not a
##              substitute for clinical judgment and not a regulatory artefact.
##  ============================================================================

[PROB]
QSP model of the diabetic foot ulcer: neuropathy + ischaemia + repetitive
plantar pressure drive ulceration; the wound then arrests in a protease-
dominant, biofilm-colonised, senescent state.  Closure is modelled as a
perimeter process (dA/dt = -k*P), offloading as device efficacy x adherence,
topical growth factor as a race against MMP-9, and every anabolic term is
gated by wound pO2.  Post-closure the model carries a re-ulceration hazard
driven by the unchanged neuropathic/biomechanical substrate.

