              * (1.0 + 0.25 * HILL(PDGF_tot, PDGF_50, 1.0));
double CONTR = K_CONTR * HILL(COL, C50_CONTR, 1.0) * A;

dxdt_AREA  = (-EDGE * PERIM - CONTR + REINJ) * open_w;
dxdt_DEPTH = (-K_FILL * GRAN + 0.06 * OSTEO + 0.04 * bf * (1.0 - GRAN))
             * open_w * (DEPTH > 0.05 ? 1.0 : 0.0);

//===========================================================================
// 9. Outcomes — closure is remission, not cure
//===========================================================================
