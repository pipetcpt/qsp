[MAIN]
RTX_CENT_0 = 0; RTX_PERIPH_0 = 0; BEN_CENT_0 = 0; BEN_PERIPH_0 = 0;
SUT_CENT_0 = 0; SUT_PERIPH_0 = 0; PEG_DEPOT_0 = 0; PEG_CENT_0 = 0;
COLD_PULSE_0 = 0;

double sev_eff0 = SEV * (SECONDARY>0 ? 0.6 : 1.0);
CLONE_0   = CLONE_MAX * sev_eff0;
IGM_0     = K_PROD_IGM * CLONE_0 / KOUT_IGM;

double amb0 = AMB_COLD * (1 - 0.5*COLD_AVOIDANCE);
double agg0 = K_AGG * IGM_0/100.0 * amb0;
if (agg0 > 1) agg0 = 1;
C1S_ACT_0 = agg0;
C4_0      = C4_NORMAL * (1 - 0.35*agg0);
C3_0      = C3_NORMAL * (1 - 0.35*agg0);
double cpflux0 = C1S_ACT_0 * (C4_0/C4_NORMAL);
C3B_RBC_0 = KON_C3B*cpflux0 / KOUT_C3B;
MAC_0     = KON_MAC*C3B_RBC_0 / KOUT_MAC;

double hemol0 = W_MAC_IV*MAC_0 + W_C3B_EV*C3B_RBC_0;
HB_0      = BASE_HB;
RETIC_0   = RETIC_BASE + K_EPO_RETIC*(HB_NORMAL - BASE_HB);
BILI_0    = BILI_BASE + K_BILI_HEMOL*hemol0;
LDH_0     = LDH_BASE + K_LDH_IV*MAC_0 + K_LDH_EV*C3B_RBC_0;
HAPTO_0   = HAPTO_BASE / (1 + K_HAPTO_CONSUME*MAC_0);

[ODE]
// ---------- Drug PK / exposure kinetics ----------
dxdt_RTX_CENT   = -KOUT_RTX*RTX_CENT - KTR_RTX*RTX_CENT + KTR_RTX*RTX_PERIPH;
dxdt_RTX_PERIPH =  KTR_RTX*RTX_CENT - KTR_RTX*RTX_PERIPH;
dxdt_BEN_CENT   = -KOUT_BEN*BEN_CENT - KTR_BEN*BEN_CENT + KTR_BEN*BEN_PERIPH;
dxdt_BEN_PERIPH =  KTR_BEN*BEN_CENT - KTR_BEN*BEN_PERIPH;
dxdt_SUT_CENT   = -KOUT_SUT*SUT_CENT - KTR_SUT*SUT_CENT + KTR_SUT*SUT_PERIPH;
dxdt_SUT_PERIPH =  KTR_SUT*SUT_CENT - KTR_SUT*SUT_PERIPH;
dxdt_PEG_DEPOT  = -KA_PEG*PEG_DEPOT;
dxdt_PEG_CENT   =  KA_PEG*PEG_DEPOT - KOUT_PEG*PEG_CENT;
dxdt_COLD_PULSE = -COLD_PULSE_KOUT*COLD_PULSE;

// ---------- Drug effect (Emax) terms ----------
double Rtx_eff = EMAX_RTX * RTX_CENT/(EC50_RTX + RTX_CENT);
double Ben_eff = EMAX_BEN * BEN_CENT/(EC50_BEN + BEN_CENT);
double Sut_block = EMAX_SUT * SUT_CENT/(EC50_SUT + SUT_CENT);
if (Sut_block > 0.97) Sut_block = 0.97;
double Peg_block = EMAX_PEG * PEG_CENT/(EC50_PEG + PEG_CENT);
if (Peg_block > 0.95) Peg_block = 0.95;

// ---------- Clonal B-cell / lymphoplasmacytic burden ----------
double synergy = 1 + K_SYNERGY_RB * ((Rtx_eff>0 && Ben_eff>0) ? 1.0 : 0.0);
double kill_rate = (K_KILL_RTX*Rtx_eff + K_KILL_BEN*Ben_eff) * synergy;
dxdt_CLONE = K_CLONE_GROW*CLONE*(1 - CLONE/CLONE_MAX) - kill_rate*CLONE;
if (CLONE < 0.01 && kill_rate > 0) dxdt_CLONE = 0;   // floor: residual clone, not eradicated

// ---------- Monoclonal IgM production/turnover ----------
dxdt_IGM = K_PROD_IGM*CLONE - KOUT_IGM*IGM;

// ---------- Cold-dependent agglutination signal ----------
double cold_now = AMB_COLD*(1 - 0.5*COLD_AVOIDANCE) + COLD_PULSE;
double agg_signal = K_AGG * (IGM/100.0) * cold_now;
if (agg_signal > 1) agg_signal = 1;

// ---------- Classical complement pathway: C1s, C4, C3 ----------
double c1s_target = agg_signal * (1 - Sut_block);
dxdt_C1S_ACT = KOUT_C1S * (c1s_target - C1S_ACT);

double cp_flux = C1S_ACT * (C4/C4_NORMAL);            // classical convertase (C4b2a) activity proxy
dxdt_C4 = KIN_C4 - KOUT_C4*C4 - K_CONSUME_C4*cp_flux*C4;

double c3_consume_flux = cp_flux * (1 - Peg_block);
dxdt_C3 = KIN_C3 - KOUT_C3*C3 - K_CONSUME_C3*c3_consume_flux*(C3/C3_NORMAL)*C3;

// ---------- C3b RBC opsonization & terminal complement (MAC) ----------
dxdt_C3B_RBC = KON_C3B*c3_consume_flux*(C3/C3_NORMAL) - KOUT_C3B*C3B_RBC;

double mac_drive = C3B_RBC * (1 - Peg_block);          // dual-pathway blockade also limits C5 convertase formation
dxdt_MAC = KON_MAC*mac_drive - KOUT_MAC*MAC;

// ---------- Hemolysis signal & hemoglobin ----------
double hemol = W_MAC_IV*MAC + W_C3B_EV*C3B_RBC;
double hb_suppression = hemol / (HEMOL_HALF + hemol);
double comp_boost = 1 + 0.20*(RETIC/RETIC_BASE - 1);   // partial marrow compensation
if (comp_boost < 1) comp_boost = 1;
double HB_target = HB_NORMAL * (1 - hb_suppression) * comp_boost;
if (HB_target > HB_NORMAL) HB_target = HB_NORMAL;
if (HB_target < 3) HB_target = 3;
dxdt_HB = KOUT_HB * (HB_target - HB);

// ---------- Reticulocytes (compensatory erythropoiesis) ----------
double hb_deficit = HB_NORMAL - HB;
if (hb_deficit < 0) hb_deficit = 0;
double RETIC_target = RETIC_BASE + K_EPO_RETIC*hb_deficit;
dxdt_RETIC = KOUT_RETIC * (RETIC_target - RETIC);

// ---------- Indirect bilirubin ----------
double BILI_target = BILI_BASE + K_BILI_HEMOL*hemol;
dxdt_BILI = KOUT_BILI * (BILI_target - BILI);

// ---------- LDH ----------
double LDH_target = LDH_BASE + K_LDH_IV*MAC + K_LDH_EV*C3B_RBC;
dxdt_LDH = KOUT_LDH * (LDH_target - LDH);

// ---------- Haptoglobin (consumed by intravascular hemolysis) ----------
double HAPTO_target = HAPTO_BASE / (1 + K_HAPTO_CONSUME*MAC);
dxdt_HAPTO = KOUT_HAPTO * (HAPTO_target - HAPTO);

