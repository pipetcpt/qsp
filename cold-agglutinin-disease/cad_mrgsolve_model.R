HB_NORMAL    : 14.5  : g/dL
W_MAC_IV     : 0.85  : weight, intravascular hemolysis contribution (MAC-driven)
W_C3B_EV     : 0.45  : weight, extravascular hemolysis contribution (C3b/Kupffer-driven, dominant in CAD)
HEMOL_HALF   : 18    : a.u., hemolysis signal producing half-maximal Hb suppression
KOUT_HB      : 0.10  : 1/day, Hb equilibration (RBC lifespan-scale)
RETIC_BASE   : 1.2   : %, baseline reticulocyte percentage
K_EPO_RETIC  : 0.55  : reticulocyte compensatory gain per g/dL Hb deficit
KOUT_RETIC   : 0.35  : 1/day
BILI_BASE    : 0.6   : mg/dL
K_BILI_HEMOL : 0.09  : mg/dL per unit hemolysis signal
KOUT_BILI    : 0.5   : 1/day
LDH_BASE     : 190   : U/L
K_LDH_IV     : 9.0   : U/L per unit MAC (intravascular hemolysis is LDH-dominant)
K_LDH_EV     : 2.5   : U/L per unit C3b (extravascular contributes less LDH)
KOUT_LDH     : 0.55  : 1/day
HAPTO_BASE   : 90    : mg/dL
K_HAPTO_CONSUME: 0.075: fractional haptoglobin consumption per unit MAC (binds free Hb)
