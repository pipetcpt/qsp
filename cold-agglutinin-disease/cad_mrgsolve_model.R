##  Cold Agglutinin Disease (CAD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Cold Agglutinin Disease — clonal marrow B-cell/lymphoplasmacytic
##             population secreting monoclonal IgM cold agglutinin (anti-I/i) ->
##             cold-dependent RBC binding -> classical complement pathway
##             activation (C1q-C1r-C1s -> C4 -> C3) -> C3b RBC opsonization ->
##             predominantly EXTRAvascular hemolysis (hepatic Kupffer-cell
##             CR1/CRIg erythrophagocytosis) plus a variable INTRAvascular
##             component (C5b-9 membrane attack complex) -> anemia, reticulocy-
##             tosis, indirect hyperbilirubinemia, LDH elevation, haptoglobin
##             depletion. Notably STEROID-REFRACTORY (unlike warm AIHA).
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 21 ODE compartments — IV drug PK for rituximab, bendamustine,
##             sutimlimab (anti-C1s), and SC pegcetacoplan (C3 inhibitor) +
##             clonal B-cell burden + monoclonal IgM titer + classical-pathway
##             activity (C1s, C4, C3, C3b-RBC opsonization) + terminal complement
##             (C5b-9/MAC) + hemolysis biomarkers (Hb, reticulocytes, indirect
##             bilirubin, LDH, haptoglobin) + a decaying acute cold-exposure
##             driver compartment for hemolytic-crisis challenge scenarios.
##  Time     : days (chronic outpatient horizon; default 180 d to capture
##             rituximab/bendamustine cycles and sutimlimab loading+maintenance).
##  Units    : IV/SC drug "exposure" compartments in arbitrary dose-proportional
##             units (au) — this library's standard surrogate for full
##             mechanistic plasma PK when the disease-relevant PD (B-cell
##             depletion, C1s/C3 blockade) is what matters; physiological states
##             in clinically familiar units (g/dL, mg/dL, U/L, %) — see [CMT].
##  Scenarios: 7 prebuilt — see CAD_simulate_scenarios() at bottom, including a
##             sutimlimab-discontinuation relapse case and an acute cold-
##             exposure hemolytic-crisis challenge on/off complement blockade.
##  Anchors  : Berentsen 2020 Blood 136:480 (232-patient multinational natural-
##             history/observational study); Jager 2020 Blood Rev 41:100648
##             (diagnostic criteria & consensus treatment recommendations);
##             Berentsen 2017 Blood 130:537 (Nordic bendamustine-rituximab
##             trial, 71% ORR); CARDINAL trial (Roth 2021 N Engl J Med
##             384:1323, sutimlimab, ~54% composite response, rapid Hb rise
##             within days); CADENZA trial (Roth 2022 Blood 140:980,
##             sutimlimab without recent transfusion history, ~73% response);
##             pegcetacoplan CAD/wAIHA phase 2 pilot (NCT03226678) and CASCADE
##             phase 3 (NCT05096403) (dual classical+alternative pathway C3
##             inhibition); Berentsen & Barcellini 2021 Blood 137:1295 (How I
##             treat cold agglutinin disease — corticosteroids not recommended,
##             i.e. steroid-refractory nature of CAD).
##  Disclaimer: For research / education / hypothesis generation only.
##              Not a substitute for clinical judgment or regulatory filings.
