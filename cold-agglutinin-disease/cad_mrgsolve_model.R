[PROB]
QSP model of Cold Agglutinin Disease linking clonal B-cell/lymphoplasmacytic
IgM cold-agglutinin production, cold-dependent RBC binding, classical
complement pathway activation (C1s-C4-C3), C3b-mediated extravascular
(Kupffer-cell) hemolysis, C5b-9 (MAC)-mediated intravascular hemolysis, and
downstream hemolysis biomarkers (Hb, reticulocytes, bilirubin, LDH,
haptoglobin), with mechanistic PK/PD for rituximab, bendamustine, sutimlimab
(anti-C1s), and pegcetacoplan (C3 inhibitor), plus an acute cold-exposure
challenge driver.

