EC50_SUT     : 0.9   : au, exposure for half-maximal C1s blockade
EMAX_SUT     : 0.92  : max fractional classical-pathway (C1s) blockade
KTR_SUT      : 0.30  : 1/day, central<->peripheral transfer

//--- Pegcetacoplan SC (investigational in CAD; C3/C3b binder, dual-pathway blockade)
KA_PEG       : 0.9   : 1/day, SC absorption
KOUT_PEG     : 0.35  : 1/day
EC50_PEG     : 1.0   : au
EMAX_PEG     : 0.85  : max fractional C3-convertase blockade (blocks both classical & alternative amplification)

//--- Clonal B-cell / lymphoplasmacytic burden
CLONE_MAX    : 100   : a.u., carrying capacity
K_CLONE_GROW : 0.010 : 1/day, intrinsic clonal growth rate
K_KILL_RTX   : 1.1   : scales rituximab-driven clone kill
K_KILL_BEN   : 1.3   : scales bendamustine-driven clone kill
K_SYNERGY_RB : 0.55  : additional multiplicative synergy when both RTX & BEN active

//--- Monoclonal IgM cold-agglutinin production
K_PROD_IGM   : 1.0   : production rate scalar per unit clone
KOUT_IGM     : 0.20  : 1/day, IgM turnover (slow, large pentamer)

//--- Cold-dependent agglutination -> classical pathway trigger
K_AGG        : 1.15  : agglutination signal scalar (IgM x cold exposure)
COLD_PULSE_KOUT: 2.5 : 1/day, decay of an acute cold-exposure event pulse
KOUT_C1S     : 1.8   : 1/day, C1s activation-state turnover (fast enzyme kinetics)

//--- Classical complement pathway (C4, C3) turnover & consumption
C4_NORMAL    : 100   : a.u. (~ percent of normal serum C4)
KIN_C4       : 14    : a.u./day, hepatic C4 synthesis
KOUT_C4      : 0.14  : 1/day, baseline C4 clearance
K_CONSUME_C4 : 0.55  : fractional C4 consumption rate by active classical pathway
C3_NORMAL    : 100   : a.u. (~ percent of normal serum C3)
KIN_C3       : 13    : a.u./day, hepatic C3 synthesis
KOUT_C3      : 0.13  : 1/day, baseline C3 clearance
K_CONSUME_C3 : 0.60  : fractional C3 consumption rate by classical convertase flux

//--- C3b RBC-surface opsonization & terminal complement (MAC)
KON_C3B      : 1.6   : 1/day, C3b deposition-accumulation rate
KOUT_C3B     : 0.9   : 1/day, C3b-opsonized RBC clearance (Kupffer phagocytosis)
KON_MAC      : 0.55  : 1/day, C5b-9 MAC formation rate (requires C3b + terminal pathway)
KOUT_MAC     : 1.3   : 1/day, MAC turnover

