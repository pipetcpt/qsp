# --- Prevention -------------------------------------------------------------

#' Vaginal micronized progesterone 200 mg capsule nightly
ev_vaginal_P4 <- function(start_d = 0, stop_d = 126, dose_mg = 200) {
  mrgsolve::ev(time = start_d, amt = dose_mg, cmt = "P4V_DEP",
               ii = 1, addl = max(0, floor(stop_d - start_d)))
}

#' 17-OHPC 250 mg IM weekly (classically 16+0 to 36+0 weeks)
ev_17OHPC <- function(start_d = 0, stop_d = 112, dose_mg = 250) {
  n <- max(0, floor((stop_d - start_d) / 7))
  mrgsolve::ev(time = start_d, amt = dose_mg, cmt = "OHPC_DEP", ii = 7, addl = n)
}

# --- Acute tocolysis --------------------------------------------------------

#' Atosiban: 6.75 mg IV bolus, then 300 ug/min x 3 h, then 100 ug/min x 45 h
#' (bolus + two zero-order infusions)
ev_atosiban <- function(start_d = 0) {
  bolus <- mrgsolve::ev(time = start_d, amt = 6.75, cmt = "ATO_C")
  # 300 ug/min = 432 mg/day for 3 h (0.125 d) -> 54 mg
  hi <- mrgsolve::ev(time = start_d, amt = 54, cmt = "ATO_C", rate = 432)
  # 100 ug/min = 144 mg/day for 45 h (1.875 d) -> 270 mg
  lo <- mrgsolve::ev(time = start_d + 0.125, amt = 270, cmt = "ATO_C", rate = 144)
  c(bolus, hi, lo)
}

#' Nifedipine IR: 20 mg PO loading, then 20 mg q6h
ev_nifedipine <- function(start_d = 0, hours = 48) {
  n <- max(0, floor(hours / 6) - 1)
  mrgsolve::ev(time = start_d, amt = 20, cmt = "NIF_GUT", ii = 0.25, addl = n)
}

#' Indomethacin: 100 mg PR loading, then 25 mg q6h for <= 48 h
ev_indomethacin <- function(start_d = 0, hours = 48) {
  load <- mrgsolve::ev(time = start_d, amt = 100, cmt = "IND_GUT")
  n    <- max(0, floor(hours / 6) - 1)
  main <- mrgsolve::ev(time = start_d + 0.25, amt = 25, cmt = "IND_GUT",
                       ii = 0.25, addl = n)
  c(load, main)
}

#' MgSO4: `load_g` grams IV over 30 min, then `rate_g_h` g/h.
#' Model units: 1 g MgSO4 -> 10 (mg/dL x L) in the central compartment, so a
#' 4 g load into VC_MG = 16 L raises serum Mg by ~2.5 mg/dL.
ev_magnesium <- function(start_d = 0, hours = 24, load_g = 4, rate_g_h = 1) {
  u <- 10
  load <- mrgsolve::ev(time = start_d, amt = load_g * u, cmt = "MG_C",
                       rate = load_g * u / (0.5 / 24))
  maint <- mrgsolve::ev(time = start_d + 0.5 / 24,
                        amt = rate_g_h * u * hours, cmt = "MG_C",
                        rate = rate_g_h * u * 24)
  c(load, maint)
}

#' Betamethasone 12 mg IM x 2, 24 h apart (phosphate + acetate, 1:1)
ev_betamethasone <- function(start_d = 0, n_doses = 2, dose_mg = 12) {
  p <- mrgsolve::ev(time = start_d, amt = dose_mg / 2, cmt = "BET_DP",
                    ii = 1, addl = n_doses - 1)
  a <- mrgsolve::ev(time = start_d, amt = dose_mg / 2, cmt = "BET_DA",
                    ii = 1, addl = n_doses - 1)
  c(p, a)
}

#' Terbutaline 0.25 mg SC q4h (historical; FDA boxed warning against
#' prolonged use for tocolysis)
ev_terbutaline <- function(start_d = 0, hours = 24) {
  n <- max(0, floor(hours / 4) - 1)
  mrgsolve::ev(time = start_d, amt = 0.25, cmt = "TERB_DEP",
               ii = 4 / 24, addl = n)
}

#' A null event (no drug) — needed because mrgsim_e() wants an event object
ev_none <- function() mrgsolve::ev(time = 0, amt = 0, cmt = "P4V_DEP")


