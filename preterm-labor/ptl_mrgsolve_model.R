#' Neonatal outcome probabilities given gestational age at delivery, the
#' lung-maturity index, the fetal inflammatory state and magnesium exposure.
PTL_neonatal_outcomes <- function(ga_wk, surf = 0.2, firs = 0, mgbrain = 0,
                                  transfer = 0, coamox = 0, p = list()) {
  d <- list(RDS_GA50 = 30.2, RDS_STEEP = 1.9, RDS_SURF_B = 2.0,
            IVH_GA50 = 26.5, IVH_STEEP = 1.5,
            DEATH_GA50 = 24.3, DEATH_STEEP = 1.4,
            NEC_GA50 = 26.0, NEC_STEEP = 2.0,
            CP_BASE = 0.020, EMAX_MGN = 0.45, EC50_MGN = 1.2,
            FIRS_ON_CP = 2.00, FIRS_ON_SEP = 0.45, SEP_BASE = 0.020,
            FIRS_ON_IVH = 1.00, FIRS_ON_NEC = 1.40, FIRS_ON_DEATH = 0.60)
  d[names(p)] <- p
  inv <- function(x) 1 / (1 + exp(-x))

  # A fetal inflammatory response is not a spectator: it raises IVH, NEC,
  # sepsis, death and cerebral palsy. This is the term that makes buying days
  # inside an infected amniotic cavity a LOSING trade.
  rds   <- inv(-(ga_wk - d$RDS_GA50) / d$RDS_STEEP - d$RDS_SURF_B * surf)
  ivh   <- inv(-(ga_wk - d$IVH_GA50) / d$IVH_STEEP) * (1 - 0.45 * surf) *
             (1 + d$FIRS_ON_IVH * firs)
  nec   <- inv(-(ga_wk - d$NEC_GA50) / d$NEC_STEEP) * (1 + d$FIRS_ON_NEC * firs) *
             (1 + 0.35 * coamox)
  death <- inv(-(ga_wk - d$DEATH_GA50) / d$DEATH_STEEP) * (1 - 0.22 * surf) *
             (1 + d$FIRS_ON_DEATH * firs) * (1 - 0.20 * transfer)
  sepsis <- d$SEP_BASE + d$FIRS_ON_SEP * firs

  cp_ga  <- d$CP_BASE * (1 + 2.4 * inv(-(ga_wk - 28.5) / 2.0))
  mg_eff <- d$EMAX_MGN * mgbrain / (d$EC50_MGN + mgbrain)
  cp     <- cp_ga * (1 + d$FIRS_ON_CP * firs) * (1 - mg_eff)

  comp <- 1 - (1 - rds) * (1 - ivh) * (1 - nec) * (1 - sepsis)

  data.frame(GA_wk = ga_wk, RDS = rds, severe_IVH = ivh, NEC = nec,
             sepsis = sepsis, death = death, CP = cp, composite = comp)
}


