##  Preterm Labor / Spontaneous Preterm Birth (sPTB) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Spontaneous preterm birth — delivery before 37+0 weeks arising
##             not from one disease but from a SYNDROME with several
##             aetiologies (intra-amniotic infection/inflammation, functional
##             progesterone withdrawal, decidual haemorrhage/thrombin, uterine
##             overdistension, cervical insufficiency, an advanced placental
##             CRH clock) that all converge on ONE common terminal pathway
##             with THREE effector limbs:
##                 (1) MYOMETRIUM  quiescence -> activation -> contraction
##                 (2) CERVIX      softening -> ripening -> dilation
##                 (3) MEMBRANES   weakening -> rupture (PPROM)
##
##             THE STRUCTURAL POINT THIS MODEL IS BUILT TO MAKE
##             ---------------------------------------------------------------
##             Every tocolytic in clinical use acts on limb (1) only. Atosiban
##             blocks OXTR, nifedipine blocks Cav1.2, indomethacin blocks COX,
##             magnesium antagonises Ca2+ at the myofilament — four different
##             molecular targets, all of them inside the same limb, all of them
##             leaving limbs (2) and (3) running at full speed. That is not a
##             pharmacological accident; it is the reason forty years of
##             tocolytic trials have reproducibly bought ~48 hours and
##             reproducibly failed to move gestational age at delivery or any
##             neonatal outcome. In this model the delivery hazard is written
##             as a PRODUCT of the three limbs,
##                 lambda(t) = LAMBDA0 * f_contr * f_cerv * f_memb * f_term
##             so silencing one factor can only reduce lambda by the amount
##             that factor contributes. When the cervix is already 12 mm and
##             MMP-driven remodelling is running, f_cerv alone keeps lambda
##             high and the tocolytic's effect is ARITHMETICALLY BOUNDED —
##             PTL_limb_decomposition() prints that bound as a number.
##
##             The corollary — and the second thing the model is built to show
##             — is that the interventions that DO change outcome are the ones
##             that do not treat the uterus at all. Antenatal corticosteroids
##             mature the fetal lung; MgSO4 protects the fetal brain; in-utero
##             transfer moves the baby to a level-III unit. Tocolysis is
##             valuable exactly insofar as it buys the 48 hours those three
##             need, and worthless outside that window (hence: no maintenance
##             tocolysis). And when the trigger is intra-amniotic infection,
##             tocolysis is worse than worthless, because the days are bought
##             inside an inflamed amniotic cavity — trading RDS risk for FIRS,
##             sepsis and cerebral-palsy risk. PTL_infection_paradox() prices
##             this out: prolonging by ~2 days raises cumulative fetal
##             inflammatory exposure by ~25%, raises cerebral palsy from 0.060
##             to 0.063 and raises early-onset sepsis, while lowering RDS — so
##             the composite comes out FLAT. A wash is already a damning
##             result for an intervention whose entire justification is that
##             the days bought improve outcome.
