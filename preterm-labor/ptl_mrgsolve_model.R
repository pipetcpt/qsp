#' Run every scenario and return one tidy data frame.
PTL_simulate_scenarios <- function(mod, delta = 0.05) {
  sc <- PTL_scenarios()
  out <- lapply(names(sc), function(nm) {
    s <- sc[[nm]]
    m <- if (length(s$param)) mrgsolve::param(mod, s$param) else mod
    e <- if (is.null(s$ev)) ev_none() else s$ev
    d <- as.data.frame(mrgsolve::mrgsim_e(m, e, end = s$end, delta = delta))
    d$scenario <- nm
    d$label    <- s$label
    d
  })
  do.call(rbind, out)
}


## ---------------------------------------------------------------------------
## Shared summariser: expected GA at delivery under the simulated hazard
## ---------------------------------------------------------------------------
PTL_summarise_run <- function(d) {
  d    <- d[order(d$time), ]
  pd   <- d$PDELIV
  dens <- c(0, diff(pd))
  rem  <- 1 - utils::tail(pd, 1)          # mass still undelivered at the horizon
  wavg <- function(x) sum(dens * x) + rem * utils::tail(x, 1)
  data.frame(
    E_GA_wk       = wavg(d$GAW),
    P_deliver_48h = stats::approx(d$time, pd, xout = 2, rule = 2)$y,
    P_deliver_7d  = stats::approx(d$time, pd, xout = 7, rule = 2)$y,
    P_deliver_end = utils::tail(pd, 1),
    surf_at_birth = wavg(d$SURF),
    FIRS_at_birth = wavg(d$FIRS),
    # Magnesium exposure enters as the PEAK, not the delivery-weighted mean:
    # the trials gave MgSO4 to women at imminent risk, so the relevant
    # exposure is the level reached during the at-risk window.
    MgBrain       = max(d$MGBRAIN),
    cum_IL6_exp   = wavg(d$CUMINFL),   # exposure accrued UP TO delivery
    min_CL_mm     = min(d$CLEN),
    max_MVU       = max(d$CONTR),
    max_Mg        = max(d$CMGo),
    max_ductrisk  = max(d$DUCTRISK)
  )
}


## ---------------------------------------------------------------------------
## PTL_ledger() — the accounting this model exists to produce
## ---------------------------------------------------------------------------
## For each scenario: expected gestational age at delivery, days gained versus
## its matched comparator, and the resulting neonatal outcome probabilities.
## The point of printing these side by side is that DAYS GAINED AND OUTCOME
## GAINED ARE NOT THE SAME QUANTITY — and in scenario 10 they move in
## OPPOSITE directions.
## ---------------------------------------------------------------------------
PTL_ledger <- function(mod, delta = 0.05) {
  sim <- PTL_simulate_scenarios(mod, delta = delta)
  sc  <- PTL_scenarios()

  rows <- lapply(names(sc), function(nm) {
    r <- PTL_summarise_run(sim[sim$scenario == nm, ])
    o <- PTL_neonatal_outcomes(r$E_GA_wk, surf = r$surf_at_birth,
                               firs = r$FIRS_at_birth, mgbrain = r$MgBrain)
    cbind(data.frame(scenario = nm, label = sc[[nm]]$label,
                     stringsAsFactors = FALSE), r, o[, -1, drop = FALSE])
  })
  led <- do.call(rbind, rows)

  comp <- c("3_short_cervix_vaginalP4"      = "2_short_cervix_untreated",
            "4_prior_PTB_17OHPC"            = "4b_prior_PTB_untreated",
            "5_cerclage_plus_P4"            = "2_short_cervix_untreated",
            "7_acute_PTL_atosiban_ACS"      = "6_acute_PTL_untreated",
            "8_acute_PTL_nifedipine_ACS_Mg" = "6_acute_PTL_untreated")
  led$days_gained <- NA_real_
  for (i in seq_len(nrow(led))) {
    cn <- comp[[led$scenario[i]]]
    if (!is.null(cn) && !is.na(cn) && cn %in% led$scenario) {
      led$days_gained[i] <- 7 * (led$E_GA_wk[i] -
                                 led$E_GA_wk[led$scenario == cn])
    }
  }

  cat("\n=========================================================================\n")
  cat("  PTL_ledger() — days gained vs OUTCOME gained\n")
  cat("  Compare scenarios 7/8 (days gained -> outcome gained, via steroids\n")
  cat("  and magnesium) with scenario 10 (days gained -> outcome LOST, because\n")
  cat("  the days are bought inside an inflamed amniotic cavity).\n")
  cat("=========================================================================\n\n")
  print(led[, c("scenario", "E_GA_wk", "days_gained", "P_deliver_48h",
                "P_deliver_7d", "surf_at_birth", "FIRS_at_birth",
                "RDS", "severe_IVH", "sepsis", "CP", "composite")],
        digits = 3, row.names = FALSE)
  invisible(led)
}


## ---------------------------------------------------------------------------
## PTL_limb_decomposition() — why tocolysis is arithmetically bounded
## ---------------------------------------------------------------------------
## lambda = LAMBDA0 * f_contr * f_cerv * f_memb * f_term.
## Tocolytics move f_contr and nothing else. This prints, at peak tocolytic
## effect, how much of the hazard each limb is carrying — the whole argument,
## in three numbers per row.
## ---------------------------------------------------------------------------
PTL_limb_decomposition <- function(mod, ga0 = 29, cl0 = 14, at_day = 1) {
  base <- mrgsolve::param(mod, GA0_WK = ga0, CL0 = cl0, STERILE_DRIVE = 0.55,
                          THROMBIN_DRV = 0.25, OT_TONE = 2.0, ACTIVATED = 0.75)
  arms <- list(
    "untreated"    = ev_none(),
    "atosiban"     = ev_atosiban(0),
    "nifedipine"   = ev_nifedipine(0, 48),
    "indomethacin" = ev_indomethacin(0, 48),
    "MgSO4 2 g/h"  = ev_magnesium(0, 48, load_g = 4, rate_g_h = 2),
    "nifed + Mg"   = c(ev_nifedipine(0, 48), ev_magnesium(0, 48, 4, 2)),
    "terbutaline"  = ev_terbutaline(0, 48)
  )
  res <- lapply(names(arms), function(nm) {
    d <- as.data.frame(mrgsolve::mrgsim_e(base, arms[[nm]], end = 4, delta = 0.02))
    i <- which.min(abs(d$time - at_day))
    data.frame(arm = nm, f_contr = d$FCONTR[i], f_cerv = d$FCERV[i],
               f_memb = d$FMEMB[i], lambda = d$LAMBDA[i],
               MVU = d$CONTR[i], CL_mm = d$CLEN[i],
               P_48h = stats::approx(d$time, d$PDELIV, xout = 2, rule = 2)$y,
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, res)
  ref <- out$lambda[out$arm == "untreated"]
  out$lambda_rel <- out$lambda / ref
  floor_contr <- 0.15
  bound <- floor_contr / out$f_contr[out$arm == "untreated"]

  cat("\n=========================================================================\n")
  cat("  Hazard limb decomposition at day", at_day,
      sprintf("(GA %.0f wk, CL %.0f mm)\n", ga0, cl0))
  cat("  lambda = LAMBDA0 x f_contr x f_cerv x f_memb x f_term\n")
  cat("  Tocolytics move f_contr ONLY. f_cerv and f_memb are essentially\n")
  cat("  identical across arms, which is why lambda_rel has a hard floor.\n")
  cat("=========================================================================\n\n")
  print(out, digits = 3, row.names = FALSE)
  cat(sprintf(
    "\n  Arithmetic floor on lambda_rel with f_contr driven to its minimum: %.3f\n",
    bound))
  cat(sprintf(
    "  i.e. ABOLISHING contractions entirely still leaves %.0f%% of the\n  untreated hazard, carried by the cervical and membrane limbs.\n\n",
    100 * bound))
  invisible(out)
}


## ---------------------------------------------------------------------------
## PTL_acs_window() — the 24 h to 7 d corticosteroid window, quantified
## ---------------------------------------------------------------------------
PTL_acs_window <- function(mod, ga0 = 29,
                           delays_d = c(0, 0.5, 1, 2, 3, 5, 7, 10, 14)) {
  m    <- mrgsolve::param(mod, GA0_WK = ga0, CL0 = 14, STERILE_DRIVE = 0.55,
                          ACTIVATED = 0.75)
  acs  <- as.data.frame(mrgsolve::mrgsim_e(m, ev_betamethasone(0),
                                           end = 16, delta = 0.05))
  none <- as.data.frame(mrgsolve::mrgsim_e(m, ev_none(), end = 16, delta = 0.05))

  rows <- lapply(delays_d, function(dl) {
    i <- which.min(abs(acs$time - dl))
    j <- which.min(abs(none$time - dl))
    ga <- acs$GAW[i]
    a <- PTL_neonatal_outcomes(ga, surf = acs$SURF[i])
    b <- PTL_neonatal_outcomes(ga, surf = none$SURF[j])
    data.frame(delay_d = dl, GA_wk = ga,
               surf_ACS = acs$SURF[i], surf_none = none$SURF[j],
               RDS_ACS = a$RDS, RDS_none = b$RDS,
               ARR = b$RDS - a$RDS,
               NNT = ifelse(b$RDS - a$RDS > 0, 1 / (b$RDS - a$RDS), NA_real_))
  })
  out <- do.call(rbind, rows)
  cat("\n=========================================================================\n")
  cat("  Antenatal corticosteroid window (betamethasone 12 mg x 2 from t = 0)\n")
  cat("  GA at first dose:", ga0, "weeks\n")
  cat("  This is what the 48 hours of tocolysis is FOR.\n")
  cat("=========================================================================\n\n")
  print(out, digits = 3, row.names = FALSE)
  invisible(out)
}


## ---------------------------------------------------------------------------
## PTL_infection_paradox() — the scenario where days gained cost outcome
## ---------------------------------------------------------------------------
PTL_infection_paradox <- function(mod) {
  m <- mrgsolve::param(mod, GA0_WK = 29, CL0 = 12, INFECT_DRIVE = 0.75,
                       BACTBASE = 2.0, STERILE_DRIVE = 0.25, OT_TONE = 2.0,
                       ACTIVATED = 0.75)
  arms <- list(
    "no tocolysis"        = ev_betamethasone(0),
    "atosiban 48 h"       = c(ev_atosiban(0), ev_betamethasone(0)),
    "prolonged tocolysis" = c(ev_atosiban(0), ev_nifedipine(0.1, 24 * 7),
                              ev_betamethasone(0))
  )
  rows <- lapply(names(arms), function(nm) {
    d <- as.data.frame(mrgsolve::mrgsim_e(m, arms[[nm]], end = 14, delta = 0.05))
    r <- PTL_summarise_run(d)
    o <- PTL_neonatal_outcomes(r$E_GA_wk, surf = r$surf_at_birth,
                               firs = r$FIRS_at_birth)
    data.frame(arm = nm, E_GA_wk = r$E_GA_wk, surf = r$surf_at_birth,
               FIRS = r$FIRS_at_birth, cumIL6 = r$cum_IL6_exp,
               RDS = o$RDS, sepsis = o$sepsis, CP = o$CP,
               composite = o$composite, stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  out$days_vs_none <- 7 * (out$E_GA_wk - out$E_GA_wk[1])
  out <- out[, c("arm", "E_GA_wk", "days_vs_none", "surf", "FIRS", "cumIL6",
                 "RDS", "sepsis", "CP", "composite")]
  cat("\n=========================================================================\n")
  cat("  The infection paradox — MIAC at 29 weeks\n")
  cat("  Tocolysis prolongs gestation AND worsens the composite outcome,\n")
  cat("  because every extra day is spent inside an inflamed amniotic cavity.\n")
  cat("=========================================================================\n\n")
  print(out, digits = 3, row.names = FALSE)
  invisible(out)
}


