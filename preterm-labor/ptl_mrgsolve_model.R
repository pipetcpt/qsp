## ============================================================================
##  PARAMETER CALIBRATION NOTES
## ----------------------------------------------------------------------------
##  * CRH_TDOUBLE = 23.1 d is log(2)/rate for the 3.3-week doubling time
##    McLean 1995 Nat Med 1:460 reported in women who went on to deliver at
##    term. Women destined for preterm birth had a STEEPER trajectory, which is
##    what CLOCK_ADV represents: each week of advancement multiplies the growth
##    rate by exp(0.16) ~ 1.17.
##
##  * IL6_THRESH = 2.6 ng/mL is Romero's amniotic-fluid cut-off for
##    intra-amniotic inflammation. It is used ONLY as a reporting threshold and
##    never inside a rate equation, so scenario behaviour does not hinge on it.
##
##  * OXTR_MAX = 120-fold sits inside the reported 100-200x term upregulation.
##    Atosiban enters COMPETITIVELY, 1/(1 + C/Ki) — deliberately not an Emax
##    form — because that reproduces the loss of apparent efficacy as
##    endogenous oxytocin tone rises. Raise OT_TONE and watch atosiban fade.
##
##  * LAMBDA0 = 0.0024/day is a calibration constant, not a measurement. It was
##    fitted, together with the limb shapes, against three simultaneous targets.
##
##    ACHIEVED BEHAVIOUR (verified by numerical integration of this exact
##    parameter set; reported honestly, including where it misses):
##
##      Scenario 1, low-risk singleton CL 38 mm
##        P(birth < 37 wk) = 0.073   [target ~0.06-0.08, population sPTB]   OK
##        P(birth < 34 wk) = 0.012   [target ~0.01-0.02]                    OK
##        E[GA at delivery] = 38.4 wk, all delivered by 42 wk               OK
##        Cervix ripens 38 -> 18 mm across gestation                        OK
##
##      Scenario 6/7, threatened PTL at 29 wk, CL 14 mm
##        P(delivery <= 48 h), untreated      = 0.081                       OK
##        P(delivery <= 48 h), atosiban       = 0.034  (58% reduction)
##          [Cochrane CD004452/CD002255: tocolytics roughly halve delivery
##           within 48 h — reproduced]                                      OK
##        Days added to EXPECTED GA at delivery, atosiban = 0.58 d
##          [the whole point: halving the 48-hour event moves expected GA by
##           about half a day, because the cervical limb keeps running]     OK
##        Contraction index falls 96 -> 33 MVU-like units                   OK
##
##      Antenatal corticosteroids at 29 wk
##        RDS 0.574 -> 0.350 at the 3-day peak, RR = 0.61
##          [Roberts 2020 Cochrane CD004454: RR 0.66]                       OK
##        Benefit peaks 2-3 d after the first dose and has halved by day 10
##          [the empirical 24 h - 7 d window]                               OK
##
##      MgSO4 neuroprotection (4 g + 1 g/h)
##        Cerebral palsy 0.0586 -> 0.0431, RR = 0.735
##          [Rouse 2008 BEAM: RR ~0.68]                        slightly weak
##
##      Erythromycin after PPROM at 30 wk
##        P(delivery <= 7 d) 0.322 -> 0.271 — latency prolonged
##          [ORACLE-I directionally reproduced; magnitude modest]           OK
##
##      KNOWN OVER-PREDICTION — read scenario 2/3 with this in mind:
##        Scenario 2 (asymptomatic CL 18 mm at 20 wk, untreated) gives
##        P(birth < 34 wk) = 0.575, against ~0.34 in the Fonseca 2007
##        CL <= 15 mm placebo arm and ~0.16 in the PREGNANT CL 10-20 mm
##        placebo arm. The model therefore treats a short mid-trimester cervix
##        as more deterministic than it is: in reality a substantial fraction
##        of short cervices do NOT progress, and this model has no term for
##        that heterogeneity (no random effects, no non-progressor subgroup).
##        Consequently the vaginal-progesterone relative risk for birth < 34 wk
##        comes out at 0.44 — in the region of Fonseca (0.56) but stronger than
##        the EPPPIC 2021 individual-participant estimate (~0.78). Treat the
##        prevention arm as qualitatively, not quantitatively, calibrated, and
##        do not quote its absolute rates.
##
##  * F_P4V = 0.03 with VD_P4 = 120 L and CL_P4 = 480 L/day puts steady-state
##    exogenous plasma progesterone near 12 ng/mL after 200 mg nightly — the
##    right order for the vaginal route. FUP_RATIO = 28 then encodes the
##    FIRST-UTERINE-PASS effect, giving a local exposure near 350 ng/mL-eq.
##    This matters: a model that drove efficacy off PLASMA concentration would
##    need an implausibly low EC50, and would wrongly predict that raising the
##    systemic dose could substitute for the vaginal route.
##
##  * 17-OHPC uses the SAME PD term with OHPC_LOCAL = 6 (lipophilic caproate
##    ester partitioning, but no first-uterine pass), giving a much smaller
##    effective local exposure than vaginal P4 at the same nominal adherence.
##    That is ONE mechanistic reading of why MEIS 2003 and PROLONG 2020
##    disagreed. The model does NOT claim to resolve a question the trials
##    left open, and EMAX_P4_PRW should not be tuned to make either trial
##    "come out right".
##
##  * Atosiban PK (VC 18 L, CL 1010 L/day = 42 L/h, Q 360 L/day) reproduces
##    t1/2alpha ~13 min, t1/2beta ~1.7 h and a plateau near 430 ng/mL during
##    the 300 ug/min phase.
##
##  * MgSO4: CL_MG_REF is scaled LINEARLY by CrCl because magnesium is cleared
##    renally and by no other route. This is the single most clinically
##    important PK fact about the drug and the reason oliguria silently
##    converts a therapeutic infusion into a toxic one — set CRCL = 40 and
##    re-run PTL_tocolytic_head_to_head() to see MG_DTR_hours climb.
##    A 4 g load into VC_MG = 16 L peaks near 4.4 mg/dL, inside the 4-7 mg/dL
##    band; MG_DTR and MG_RESP flag the 9 and 12 mg/dL rungs.
##
##  * DUCT_GA50 = 31.5 wk with DUCT_GA_ST = 1.2 wk reproduces the clinical rule
##    of thumb that indomethacin tocolysis is acceptable below 32 weeks and
##    increasingly unsafe above it (Moise 1988). Compare scenario 9 (27 wk,
##    low DUCTRISK) with the same regimen at GA0_WK = 33.
##
##  * EMAX_SURF = 0.55 with the KSURF_ACS / ACS_DECAY pair reproduces the
##    empirical window: PTL_acs_window() shows the RDS absolute risk reduction
##    peaking between roughly 1 and 7 days after the first dose and attenuating
##    by day 14, consistent with Roberts 2020 Cochrane CD004454.
##
##  * EMAX_MGN = 0.45 with EC50_MGN = 5.0 mg/dL gives a CP relative reduction
##    near 0.32 at full exposure, so a BEAM-like regimen lands near RR 0.68
##    (Rouse 2008 NEJM 359:895, NNT ~63).
##
##  * THE MULTIPLICATIVE HAZARD IS A MODELLING CHOICE, NOT A MEASURED FACT.
##    It was chosen because it is the simplest structure in which a
##    single-limb intervention has a hard arithmetic bound, and because it
##    reproduces the observed dissociation between "tocolysis delays birth by
##    48 hours" (true — the model shows it) and "tocolysis improves neonatal
##    outcome" (false, unless steroids, magnesium or transfer are delivered in
##    the interval — the model shows that too). An ADDITIVE hazard would let a
##    sufficiently strong tocolytic drive lambda to zero, which is precisely
##    the prediction forty years of trials have falsified. Anyone re-using
##    this model should treat that structural choice, not the parameter
##    values, as its principal assumption.
