// =========================================================================
//  0. Gestational age and the physiologic term drive
// =========================================================================
double GA = GA0_WK + SOLVERTIME / 7.0;
double TERMDRIVE = 1.0 / (1.0 + exp(-(GA - GA_RIPEN) / GA_STEEP));

// =========================================================================
//  1. Drug concentrations derived from amounts
// =========================================================================
double CP4      = P4_C / VD_P4;                    // ng/mL, exogenous progesterone
double CP4_LOC  = CP4 * FUP_RATIO;                 // first-uterine-pass local exposure
double COHPC    = 1000.0 * OHPC_C / VD_OHPC;       // ng/mL 17-OHPC
double CP4_EFF  = CP4_LOC + OHPC_LOCAL * COHPC;    // combined LOCAL progestogen exposure
double CATO     = 1000.0 * ATO_C / VC_ATO;         // ng/mL atosiban
double CNIF     = 1000.0 * NIF_C / VD_NIF;         // ng/mL nifedipine
double CIND     = 1000.0 * IND_C / VD_IND;         // ng/mL indomethacin
double CMG      = MG_BASE + MG_C / VC_MG;          // mg/dL serum magnesium
double CBET     = 1000.0 * BET_C / VD_BET;         // ng/mL maternal betamethasone
double CTERB    = 1000.0 * TERB_C / VD_TERB;       // ng/mL terbutaline

// Local progestogen protection, computed once — it acts on THREE things:
// the PR-A/PR-B withdrawal drive, the PR/NF-kB trans-repression, and cervical
// MMP induction. That third arm is why progestogens are a CERVICAL therapy as
// much as a myometrial one, and why they work in short cervix specifically.
double p4prot = EMAX_P4_PRW * CP4_EFF / (EC50_P4_LOC + CP4_EFF);

// =========================================================================
//  2. ARM 1 — the placental CRH clock
//     Exponential growth to a ceiling, accelerated by a user-set clock
//     advancement, by ischaemia/stress proxies, and by the fetal cortisol
//     POSITIVE feedback that is unique to the placenta.
// =========================================================================
double kgrow   = log(2.0) / CRH_TDOUBLE;
double advance = exp(0.16 * CLOCK_ADV);
double crhfb   = 1.0 + FB_CORT * (CORTF - 1.0);
dxdt_CRH = kgrow * advance * crhfb * CRH * (1.0 - CRH / CRH_MAX)
           + 0.10 * KOUT_CRH * CRHBASE * (1.0 + 2.0 * THROMBIN_DRV)
           - 0.10 * KOUT_CRH * CRH;

double crhdrive = CRH / (EC50_CRH_ADR + CRH);
dxdt_DHEAS = KIN_DHEAS * (0.25 + 3.5 * crhdrive) - KOUT_DHEAS * DHEAS;
dxdt_CORTF = KIN_CORTF * (0.30 + 2.6 * crhdrive) - KOUT_CORTF * CORTF;
dxdt_E3    = KIN_E3 * DHEAS - KOUT_E3 * E3;

// =========================================================================
//  3. ARM 3 — intra-amniotic infection and inflammation
// =========================================================================
// Antibiotic effect is deliberately PARTIAL: ORACLE-I bought latency, not
// sterilisation, and Ureaplasma is only intermittently eradicated in vivo.
double abx = KKILL_ABX * (ERY_ON + 0.8 * COAMOX_ON + 1.4 * AZI_ON);

// Ruptured membranes remove the barrier to ascending colonisation.
double inoc = INFECT_DRIVE * (1.0 + 0.8 * (MEMB < 0.35 ? 1.0 : 0.0));
dxdt_BACT = KGROW_BACT * inoc * (1.0 - BACT / BACT_MAX) * (BACT + 0.35 * inoc)
            - abx * BACT;

double pamp = BACT / (EC50_BACT + BACT);
double damp = STERILE_DRIVE + 0.45 * THROMBIN_DRV + 0.30 * STRETCH
              + 0.25 * (1.0 - MEMB);
// Intact PR-B trans-represses NF-kB; functional withdrawal removes that brake.
double prrepress = PR_ON_NFKB * (1.0 - PRW);
double nfdrive   = (pamp + damp) * (1.0 - prrepress) * (1.0 - P4_NFKB * p4prot);
dxdt_NFKB = KIN_NFKB * nfdrive * (1.0 - NFKB) - KOUT_NFKB * NFKB;

dxdt_IL6 = KIN_IL6 * NFKB - KOUT_IL6 * IL6;

double firsdrive = IL6 / (EC50_IL6_FIRS + IL6);
dxdt_FIRS = KIN_FIRS * firsdrive * (1.0 - FIRS) - KOUT_FIRS * FIRS;

// =========================================================================
//  4. ARM 2 — functional progesterone withdrawal
//     Withdrawal is a PR-A/PR-B RATIO shift, not a fall in plasma P4.
//     Progestogen therapy works by holding PR-B signalling, which is why the
//     LOCAL (first-uterine-pass) exposure is the concentration that matters.
// =========================================================================
double e3term = (E3 - 1.0) / (1.0 + (E3 > 1.0 ? E3 - 1.0 : 0.0));
if (e3term < 0.0) e3term = 0.0;
double prwdrive = E3_ON_PRW * e3term + INFL_ON_PRW * NFKB
                  + 0.35 * TERMDRIVE + 0.20 * STRETCH;
dxdt_PRW = KIN_PRW * prwdrive * (1.0 - p4prot) * (1.0 - PRW)
           - KOUT_PRW * PRW * (0.4 + p4prot);

// =========================================================================
//  5. The CAP programme — uterotonin machinery
// =========================================================================
double capdrive = 0.55 * PRW + 0.35 * NFKB + 0.30 * TERMDRIVE
                  + 0.25 * STRETCH + 0.20 * THROMBIN_DRV;

// COX-2 EXPRESSION is NF-kB / CAP driven ...
dxdt_COX2 = KIN_COX2 * (0.6 * NFKB + 0.5 * capdrive) * (COX2_MAX - COX2)
            - KOUT_COX2 * COX2;
// ... while indomethacin inhibits COX ACTIVITY, not expression.
double coxinhib = IMAX_IND * CIND / (IC50_IND + CIND);
double coxact   = COX2 * (1.0 - coxinhib);

// Progestogen maintains the chorionic 15-PGDH disposal barrier, so withdrawal
// simultaneously raises PG synthesis AND removes PG disposal — a double hit.
double pgdh = PGDH_FRAC * (1.0 - 0.75 * PRW) * (1.0 - 0.5 * NFKB);
dxdt_PG = KIN_PG * 8.0 * coxact / COX2_MAX
          - KOUT_PG * PG * ((1.0 - PGDH_FRAC) + pgdh);

// OXTR and Cx43 — the two CAPs that convert an activated myometrium into a
// synchronised, oxytocin-responsive one.
dxdt_OXTR = KIN_OXTR * capdrive * (OXTR_MAX - OXTR) - KOUT_OXTR * OXTR;
dxdt_CX43 = KIN_CX43 * (capdrive + 0.3 * PG / (1.0 + PG)) * (CX43_MAX - CX43)
            - KOUT_CX43 * CX43;

// =========================================================================
//  6. Relaxation: cAMP (the beta2-agonist target, with tachyphylaxis)
// =========================================================================
double b2resp  = 1.0 - DESENS;
double terbocc = CTERB / (EC50_TERB + CTERB);
double terbeff = EMAX_TERB * b2resp * terbocc;
dxdt_DESENS = KDES_ON * terbocc * (DES_MAX - DESENS) - KDES_OFF * DESENS;
dxdt_CAMP   = KOUT_CAMP * (CAMPBASE + terbeff - CAMP);

// =========================================================================
//  7. Excitation-contraction coupling
//     Ca2+ is driven by oxytocin (via OXTR), prostaglandin (FP/EP1), thrombin
//     (PAR-1) and electrical coupling (Cx43); it is opposed by nifedipine
//     (Cav1.2 block) and magnesium (competitive Ca2+ antagonism).
//     Atosiban enters as a COMPETITIVE OXTR antagonist — 1/(1 + C/Ki) — not
//     as an Emax term, because that is the form that reproduces the clinical
//     observation that atosiban's apparent efficacy falls as endogenous
//     oxytocin tone rises. An Emax form cannot express that.
// =========================================================================
double atoblock = 1.0 / (1.0 + CATO / KI_ATO);
// Receptor DENSITY is not signal: OXTR rises 100x but the downstream Gq
// response saturates, so the oxytocin arm enters as a fractional occupancy.
double ot_sig   = OT_TONE * (OXTR / (KM_OXTR + OXTR)) * atoblock;
double pg_sig   = PG / (KM_PG + PG);
double couple   = 0.35 + 0.65 * (CX43 / CX43_MAX);

double nifblock = IMAX_NIF * CNIF / (IC50_NIF + CNIF);
double cablock  = 1.0 - nifblock;
if (cablock < 0.05) cablock = 0.05;
double mgblock  = IMAX_MG * pow(CMG, 3.0) / (pow(IC50_MG, 3.0) + pow(CMG, 3.0));

double catarget = (W_TONIC + W_OT * ot_sig + W_PG * pg_sig
                   + W_PAR1 * THROMBIN_DRV) * couple * cablock;
dxdt_CAI = KOUT_CAI * (catarget - CAI);

double dcamp = CAMP - CAMPBASE;
if (dcamp < 0.0) dcamp = 0.0;
double camp_brake = CAMP_BRAKE * dcamp / (EC50_CAMP + dcamp);
double ctarget = CONTR_MAX
                 * pow(CAI, HILL_CONTR) / (pow(EC50_CONTR, HILL_CONTR) + pow(CAI, HILL_CONTR))
                 * (1.0 - camp_brake) * (1.0 - mgblock);
dxdt_CONTR = KIN_CONTR * (ctarget - CONTR);

// =========================================================================
//  8. Cervical remodelling — the limb tocolysis does not touch
// =========================================================================
double mmpdrive = (0.65 * NFKB + 0.30 * PRW + 0.85 * TERMDRIVE
                   + 0.30 * CERV_FRAGILE + 0.20 * (PG / (1.0 + PG)))
                  * (1.0 - P4_CERV * p4prot);
dxdt_MMP = KIN_MMP * mmpdrive * (MMP_MAX - MMP) - KOUT_MMP * MMP;

dxdt_HA = KIN_HA * (0.90 * TERMDRIVE + 0.45 * PRW + 0.30 * NFKB) * (1.0 - HA)
          - KOUT_HA * HA;

// Collagen loss is COOPERATIVE in MMP activity — a low background of MMP
// does not dissolve the cervix, which is why physiologic term shortening is
// gradual while inflamed ripening is abrupt.
double mmpfrac = MMP / MMP_MAX;
dxdt_COLL = -KDEG_COLL * pow(mmpfrac, HILL_MMPCOL) * COLL
            + KREP_COLL * (1.0 - COLL) * (1.0 - 0.8 * NFKB);

// Structural target length: collagen integrity sets the ceiling; hyaluronan
// water imbibition and intrinsic fragility subtract; cerclage/pessary add an
// effective mechanical offset.
double cl_struct = CL_MIN + (CL0 - CL_MIN) * COLL * (1.0 - 0.45 * HA)
                          * (1.0 - 0.25 * CERV_FRAGILE)
                   + CERC_SUPPORT * CERC_EFF + PESS_SUPPORT * PESS_EFF;
// Contractions transiently shorten the cervix (dynamic shortening / funnelling)
double cl_tgt = cl_struct - 2.5 * CONTR / (CONTR_REF + CONTR);
if (cl_tgt < CL_MIN) cl_tgt = CL_MIN;
dxdt_CLEN = KCL * (cl_tgt - CLEN);

// =========================================================================
//  9. Fetal membranes — the other limb tocolysis does not touch
// =========================================================================
double membdeg = KDEG_MEMB * (0.6 * MMP / MMP_MAX + 0.4 * NFKB)
                 * (1.0 + 0.6 * STRETCH);
dxdt_MEMB = -membdeg * MEMB + KREP_MEMB * (1.0 - MEMB);

double ffndrive = 0.55 * (1.0 - MEMB) + 0.30 * NFKB
                  + 0.25 * (1.0 - CLEN / (CL0 + 1e-6));
if (ffndrive < 0.0) ffndrive = 0.0;
dxdt_FFN = KIN_FFN * ffndrive * ffndrive - KOUT_FFN * FFN;

// =========================================================================
// 10. Fetal lung maturation and brain magnesium exposure
//     The corticosteroid term is written so the benefit accrues over ~24 h
//     and then wanes — the empirical 24 h to 7 d window.
// =========================================================================
double surf_endo = 1.0 / (1.0 + exp(-(GA - GA_SURF50) / GA_SURF_ST));
double acs_eff   = EMAX_SURF * BET_F / (EC50_BETF + BET_F);
double excess    = (SURF > surf_endo) ? (SURF - surf_endo) : 0.0;
dxdt_SURF = KIN_SURF * (surf_endo * (1.0 + 0.25 * (CORTF - 1.0)) - SURF)
            + KSURF_ACS * acs_eff * (1.0 - SURF)
            - ACS_DECAY * excess;
if (SURF > 1.0) dxdt_SURF -= 5.0 * (SURF - 1.0);

dxdt_MGBRAIN = KMG_BRAIN * ((CMG - MG_BASE) - MGBRAIN);

// =========================================================================
// 11. THE DELIVERY HAZARD — a PRODUCT of three limbs
//     This multiplicative form is the model's central structural claim: a
//     drug acting on one factor cannot push lambda below the product of the
//     other two, however completely it silences its own target.
// =========================================================================
double f_contr = CONTR_FLOOR + CONTR / CONTR_REF;
double f_cerv  = CERV_FLOOR + CERV_AMP / (1.0 + exp((CLEN - CL_REF) / CL_STEEP));
double f_memb  = 1.0 + MEMB_AMP / (1.0 + exp((MEMB - MEMB_REF) / MEMB_STEEP));
double f_term  = 1.0 + TERM_AMP * TERMDRIVE;
double ruptured = (MEMB < 0.30 || PPROM_FLAG > 0.5) ? 1.0 : 0.0;
double f_pprom = 1.0 + (PPROM_HAZ - 1.0) * ruptured;

dxdt_CUMHAZ  = LAMBDA0 * f_contr * f_cerv * f_memb * f_term * f_pprom;

// Cumulative fetal inflammatory exposure — the currency in which prolonging
// pregnancy inside an infected uterus is PAID for.
dxdt_CUMINFL = IL6;

// =========================================================================
// 12. Drug PK
// =========================================================================
// vaginal micronized progesterone (mg depot -> ng/mL x L plasma amount)
dxdt_P4V_DEP = -KA_P4V * P4V_DEP;
dxdt_P4_C    =  KA_P4V * P4V_DEP * F_P4V * 1000.0 - (CL_P4 / VD_P4) * P4_C;

// 17-OHPC: absorption-rate-limited (flip-flop) IM depot
dxdt_OHPC_DEP = -KA_OHPC * OHPC_DEP;
dxdt_OHPC_C   =  KA_OHPC * OHPC_DEP * F_OHPC - (CL_OHPC / VD_OHPC) * OHPC_C;

// atosiban, 2-compartment
dxdt_ATO_C = -(CL_ATO / VC_ATO) * ATO_C - (Q_ATO / VC_ATO) * ATO_C
             + (Q_ATO / VP_ATO) * ATO_P;
dxdt_ATO_P =  (Q_ATO / VC_ATO) * ATO_C - (Q_ATO / VP_ATO) * ATO_P;

// nifedipine
dxdt_NIF_GUT = -KA_NIF * NIF_GUT;
dxdt_NIF_C   =  KA_NIF * NIF_GUT * F_NIF - (CL_NIF / VD_NIF) * NIF_C;

// indomethacin
dxdt_IND_GUT = -KA_IND * IND_GUT;
dxdt_IND_C   =  KA_IND * IND_GUT * F_IND - (CL_IND / VD_IND) * IND_C;

// magnesium: 2-compartment, RENAL elimination only (CrCl-scaled)
dxdt_MG_C = -(CLMG / VC_MG) * MG_C - (Q_MG / VC_MG) * MG_C + (Q_MG / VP_MG) * MG_P;
dxdt_MG_P =  (Q_MG / VC_MG) * MG_C - (Q_MG / VP_MG) * MG_P;

// betamethasone: two IM depots (phosphate ester fast, acetate slow)
dxdt_BET_DP = -KA_BETP * BET_DP;
dxdt_BET_DA = -KA_BETA * BET_DA;
dxdt_BET_C  =  KA_BETP * BET_DP + KA_BETA * BET_DA - (CL_BET / VD_BET) * BET_C;
dxdt_BET_F  =  KEQ_BETF * (F_PLAC_BET * CBET - BET_F);

// terbutaline
dxdt_TERB_DEP = -KA_TERB * TERB_DEP;
dxdt_TERB_C   =  KA_TERB * TERB_DEP - (CL_TERB / VD_TERB) * TERB_C;

