               b2_lost       = max(d$B2_LOST),
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  out$days_gained <- 7 * (out$E_GA_wk - out$E_GA_wk[1])
  cat("\n=========================================================================\n")
  cat("  Tocolytic head-to-head at", ga0, "weeks (all arms receive steroids)\n")
  cat("  Read the efficacy columns and the safety columns TOGETHER — the\n")
  cat("  arms differ far more in harm than they do in days gained.\n")
  cat("=========================================================================\n\n")
  print(out, digits = 3, row.names = FALSE)
  invisible(out)
}


