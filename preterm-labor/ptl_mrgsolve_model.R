[PROB]
QSP model of spontaneous preterm birth. Four aetiologic ignition arms (placental
CRH clock, functional progesterone withdrawal, intra-amniotic infection/sterile
inflammation, decidual thrombin and uterine overdistension) converge on a common
terminal pathway whose three effector limbs — myometrial contraction, cervical
ripening and membrane weakening — enter the delivery hazard MULTIPLICATIVELY.
PK/PD is included for vaginal progesterone, 17-OHPC, atosiban, nifedipine,
indomethacin, magnesium sulfate, terbutaline, betamethasone and erythromycin,
with gestational-age-dependent neonatal outcome models for RDS, severe IVH,
NEC, early-onset sepsis, cerebral palsy and death.

