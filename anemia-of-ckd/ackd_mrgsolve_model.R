##  ---------------------------------------------------------------------------
##  What each scenario is meant to reproduce
##  ---------------------------------------------------------------------------
##   1     Hb drifts down as eGFR falls: the REP pool shrinks, EPO stays
##         "inappropriately normal" (~9 mIU/mL at Hb 9.4), hepcidin creeps up as
##         renal clearance is lost, TSAT sags.
##   2-5   Three ESA molecules on three schedules. A MAINTENANCE dose lands in
##         the KDIGO 10-11.5 g/dL band; the same molecule at a CORRECTION dose
##         held open-loop for a year overshoots past 13 g/dL — which is exactly
##         why real practice titrates. All of them unmask FUNCTIONAL iron
##         deficiency: ERFE rises, hepcidin falls ~35-45%, ferritin drains from
##         ~147 to ~90-105 ng/mL while TSAT stays flat. That emergent store-drain
##         at constant TSAT is the model's central iron-kinetic behaviour.
##   6     Proactive IV iron keeps the store term high, so the same ESA exposure
##         gets to target sooner; ferritin climbs to ~800 ng/mL (PIVOTAL's
##         proactive arm ran high too) and the thrombotic-hazard slope stays
##         below the Hb-normalisation arm.
##   7-8   HIF-PHIs raise Hb with EPO peaks of only ~3-5x baseline (vs ~10x for
##         ESA), drop hepcidin hardest of any arm (60 -> ~18-30 ng/mL), raise
##         TIBC, and lower LDL-C by ~8-14% — the qualitative fingerprint that
##         separates them from ESAs in the trials.
##   9     Oral iron alone loads STORES (ferritin 147 -> ~430) without fixing Hb,
##         because absorption is hepcidin-gated and hepcidin rises with the
##         stores it creates. The clinical futility of oral iron in advanced CKD.
##   10-12 The hyporesponsiveness triad. At a MATCHED ESA dose the inflamed
##         patient gains less Hb (EPOR-JAK2-STAT5 transduction is attenuated by
##         epor_at). Escalating the dose 3x does buy Hb, but the cumulative
