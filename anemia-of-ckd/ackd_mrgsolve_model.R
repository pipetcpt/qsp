//==========================================================================
//  Algebraic layer
//==========================================================================
double tsat    = 100.0 * FE_TF / fmax(1.0, TIBC);
double gate    = tsat / (tsat + KM_TSAT);                 // iron availability
double hypo    = fmin(1.0, 0.85 + 0.15 * gate / 0.75);    // corpuscular Hb factor
double hgb     = RBC * MCHC_F * hypo;                     // g/dL
double ferr    = FE_STORE / FERR_PER_MG + FERR_APR * IL6 / (IL6 + 10.0);

// --- oxygen sensing -----------------------------------------------------
double phd_act = 1.0 / (1.0 + PHI_CENT / IC50_PHD);       // PHD activity (drug-inhibited)
double hyp_drv = KHYP * fmax(0.0, (HB_SENSE - hgb) / HB_SENSE) * (1.0 - BLUNT);
double hif_ex  = fmax(0.0, HIF - 1.0);                    // HIF above intact-normoxic

// --- erythropoietic drive ----------------------------------------------
double epo_tot = EPO + ESA_POT * ESA_CENT;
// Inflammatory attenuation of EPOR-JAK2-STAT5 transduction: the mechanistic
// core of ESA hyporesponsiveness. It scales the DRUG signal, so a raised
// IL6_DRIVE blunts the Hb gained per unit of ESA exposure, not just baseline.
double epor_at = 1.0 + KIL6_EPOR * IL6 / (IL6 + IC50_EPOR);
double epo_eff = epo_tot / epor_at;
double drive   = 1.0 + EMAX_EPO * pow(epo_eff, HILL_EPO)
                       / (pow(EC50_EPO, HILL_EPO) + pow(epo_eff, HILL_EPO));
double infl_p  = 1.0 / (1.0 + IL6 / IC50_IL6_PROG);
double marrow  = 1.0 / (1.0 + 0.5 * PTH_SEV + 0.6 * NUTR);
double apop    = APOP_MAX * IL6 / (IL6 + IC50_IL6_PROG);

// --- red cell turnover --------------------------------------------------
double ls      = LS0 * (1.0 - LS_URE * URE);
double bl      = BLOODLOSS + 0.0035 * DIALYSIS;
double destr   = RBC / ls + bl * RBC;                     // 10^12/L/day
double retprod = KTR * EB2 * gate * (1.0 - apop);         // 10^9/L/day delivered
double demand  = KTR * EB2 * (1.0 - apop);                // iron demand if unrestricted

// --- iron fluxes (mg/day) ----------------------------------------------
double fpn_act = 1.0 / (1.0 + HEPC / IC50_HEPC_FPN);
double fpn_ref = 1.0 / (1.0 + HEPC_BASE / IC50_HEPC_FPN);
double fpn_rel = fmin(FPN_REL_MAX, fpn_act / fpn_ref);
double absfr   = FMAX_ABS / (1.0 + HEPC / IC50_HEPC_ABS)
                 * (1.0 + KHIF_ABS * hif_ex);
double fe_abs  = absfr * KA_FE * FE_GUT;
double rec_tot = FE_PER_CELL * destr * 1000.0;
// Hepcidin blockade of ferroportin is strong but NOT absolute: a floor of
// recycled iron keeps reaching transferrin and a floor of storage iron keeps
// being mobilised, otherwise high hepcidin becomes a one-way ratchet that
// buries iron in stores while the erythron starves.
double rel_eff = fmin(1.0, FPN_FLOOR + (1.0 - FPN_FLOOR) * fpn_rel);
double mob_eff = MOB_FLOOR + (1.0 - MOB_FLOOR) * fpn_rel;
double rec_rel = rec_tot * rel_eff;
double rec_trp = rec_tot - rec_rel;                       // hepcidin-trapped iron
double fe_mob  = MOB_MAX * mob_eff * (FE_STORE / (FE_STORE + KM_STORE));
double fe_util = FE_PER_CELL * retprod;
// Transferrin cannot hold more iron than TIBC: above TSAT_OVER the surplus is
// shunted into storage (and into NTBI below), which bounds TSAT below 100%.
double over_f  = 1.0 + KOVER_DEP * pow(fmax(0.0, tsat - TSAT_OVER) / 40.0, 2.0);
double fe_dep  = KDEP * FE_TF * PLASMA_DL / 1000.0 * over_f;
double iv_proc = KPROC_IV * FE_IV;
double fe_loss = LOSS_FE + DIAL_FE_LOSS * DIALYSIS;
double fe_net  = fe_abs + rec_rel + fe_mob + FIV_DIRECT * iv_proc
                 - fe_util - fe_loss - fe_dep;

//==========================================================================
//  Differential equations
//==========================================================================
// ---- 1-6  drug PK ------------------------------------------------------
dxdt_ESA_SC   = -KA_ESA * ESA_SC;
dxdt_ESA_CENT =  F_ESA * KA_ESA * ESA_SC - KEL_ESA * ESA_CENT;
dxdt_PHI_GUT  = -KA_PHI * PHI_GUT;
dxdt_PHI_CENT =  F_PHI * KA_PHI * PHI_GUT - KEL_PHI * PHI_CENT;
dxdt_FE_GUT   =  DIET_FE - KA_FE * FE_GUT;
dxdt_FE_IV    = -iv_proc;

// ---- 7-9  kidney -> oxygen sensing -> EPO ------------------------------
dxdt_REP      = KIN_REP * pow(EGFR / 90.0, HREP) / (1.0 + FIB) - KOUT_REP * REP;
dxdt_HIF      = KIN_HIF * (1.0 + hyp_drv) - KOUT_HIF * HIF * phd_act;
dxdt_EPO      = KIN_EPO_REN * (REP + REP_FLOOR) * pow(HIF, GAM_HIF)
                  / (1.0 + IL6 / IC50_IL6_EPO)
              + KIN_EPO_HEP * pow(hif_ex, GAM_HEP)
              - KEL_EPO * EPO;

// ---- 10-14  erythropoiesis --------------------------------------------
dxdt_PROG     = KIN_PROG * drive * infl_p * marrow - KTR * PROG;
dxdt_EB1      = KTR * PROG - KTR * EB1;
dxdt_EB2      = KTR * EB1  - KTR * EB2;
dxdt_RET      = retprod - KRET * RET;
dxdt_RBC      = KRET * RET / 1000.0 - destr;

// ---- 15-17  iron pools -------------------------------------------------
dxdt_FE_TF    = fe_net / (PLASMA_DL / 1000.0);
dxdt_FE_STORE = fe_dep + rec_trp + (1.0 - FIV_DIRECT) * iv_proc - fe_mob;
dxdt_TIBC     = KIN_TIBC * (1.0 + KHIF_TF * hif_ex) / (1.0 + IL6 / IC50_IL6_TF)
              - KOUT_TIBC * TIBC;

// ---- 18-19  hepcidin / erythroferrone ---------------------------------
dxdt_HEPC     = KIN_HEPC * fmin(STOREDRV_MAX, pow(FE_STORE / fmax(1.0, store0), HB_STORE))
                  * (1.0 + KIL6_HEPC * IL6 / (IC50_IL6_HEPC + IL6))
                  / ((1.0 + KERFE * fmax(0.0, ERFE - 1.0))
                     * (1.0 + KPHI_HEPC * hif_ex))
              - KOUT_HEPC * HEPC * (pow(EGFR / 90.0, HCL) + HEPC_NONREN);
dxdt_ERFE     = KIN_ERFE * pow((EB1 + EB2) / fmax(1.0, eb_ref), GAM_ERFE)
              - KOUT_ERFE * ERFE;

// ---- 20-21  inflammation ----------------------------------------------
dxdt_IL6      = KIN_IL6 * IL6_DRIVE * (1.0 + KUREM_IL6 * (1.0 - EGFR / 90.0))
                  / (1.0 + KANTI_IL6 * ANTI_IL6)
              - KOUT_IL6 * IL6;
dxdt_CRP      = KIN_CRP * IL6 - KOUT_CRP * CRP;

// ---- 22-23  FGF23 / phosphate (IV-iron safety axis) -------------------
dxdt_FGF23    = KIN_FGF * (1.0 + KFCM * FCM_FLAG * iv_proc
                             + KP_FGF * fmax(0.0, PHOS - PHOS0))
              - KOUT_FGF * FGF23;
dxdt_PHOS     = KIN_PHOS - KOUT_PHOS * PHOS * pow(fmax(0.1, FGF23), GAM_FGF);

// ---- 24-25  lipids / haemodynamics ------------------------------------
dxdt_LDL      = KIN_LDL / (1.0 + KPHI_LDL * hif_ex) - KOUT_LDL * LDL;
dxdt_MAP      = KIN_MAP * (1.0 + KESA_BP * ESA_CENT / (ESA_CENT + EC50_BP)
                             + KHB_BP * fmax(0.0, hgb - 11.0) / 11.0)
              - KOUT_MAP * MAP;

// ---- 26-27  labile iron / thrombotic hazard ---------------------------
dxdt_NTBI     = KIN_NTBI * fmax(0.0, tsat - 70.0) / 30.0
              + KIV_NTBI * iv_proc - KOUT_NTBI * NTBI;
dxdt_THR      = HAZ0 * (1.0
                + KVISC_T * pow(fmax(0.0, hgb - 12.0), 2.0)
                + KESA_T * ESA_CENT / (ESA_CENT + EC50_BP)
                + KPHI_T * PHI_CENT / (PHI_CENT + IC50_PHD)
                + KMAP_T * fmax(0.0, MAP - MAP0) / MAP0
                + KNTBI_T * NTBI);

// ---- 28-30  PRO / cardiac remodelling / progression -------------------
double fat_tgt = FAT_MIN + (FAT_MAX - FAT_MIN) * pow(hgb, HILL_FAT)
                 / (pow(EC50_FAT, HILL_FAT) + pow(hgb, HILL_FAT));
dxdt_FATIGUE  = KOUT_FAT * (fat_tgt - FATIGUE);
dxdt_LVMI     = KIN_LVMI * (1.0 + KAN_LV * fmax(0.0, 11.5 - hgb) / 11.5
                             + KBP_LV * fmax(0.0, MAP - MAP0) / MAP0)
              - KOUT_LVMI * LVMI;
dxdt_EGFR     = -(EGFR_SLOPE / 365.0)
                * (1.0 + KAN_PROG * fmax(0.0, HB_SENSE - hgb) / HB_SENSE);

