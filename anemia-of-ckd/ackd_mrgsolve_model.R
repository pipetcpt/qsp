##  ---------------------------------------------------------------------------
##  Known simplifications — read before drawing conclusions
##  ---------------------------------------------------------------------------
##   * BASELINE IS PINNED. [MAIN] back-calculates KIN_PROG so that EVERY virtual
##     patient starts at BASE_HB, including the inflamed one. That is convenient
##     but it means IL6_DRIVE does NOT lower the starting Hb; inflammation shows
##     up as a blunted Hb gain per unit ESA (KIL6_EPOR) and a tighter iron gate,
##     not as a worse presenting anemia. Compare hyporesponders at MATCHED DOSE
##     (scenario 10 vs 3), never by their proportional reserve.
##   * ESA and HIF-PHI exposures are in dose-proportional au, not mg/mL, and the
##     PK is first-order with no target-mediated (EPOR) disposition.
##   * A single lumped HIF activity stands in for HIF-1alpha and HIF-2alpha in
##     kidney, liver and gut; isoform- and tissue-specific programs are not
##     separated, so the model cannot speak to isoform-selective agents.
##   * Hepcidin, ERFE and IL-6 are single well-mixed pools — no hepatic/marrow
##     compartmentalisation, no diurnal rhythm.
##   * Oral-iron absorption uses FMAX_ABS = 0.28, a figure from iron-deficient
##     healthy volunteers; real CKD patients absorb less, so scenario 9 probably
##     OVERSTATES how much store loading oral iron achieves.
##   * The thrombotic hazard is a mechanistic index for RANKING arms, not a
##     calibrated absolute event rate. Do not read it as events/100 py.
##   * Transferrin saturation is bounded below 100% by an overflow term
##     (KOVER_DEP), not by explicit transferrin binding stoichiometry.
