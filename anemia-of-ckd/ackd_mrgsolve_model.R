##  Anemia of Chronic Kidney Disease (ACKD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Anemia of CKD (renal anemia) — progressive nephron loss and
##             tubulointerstitial fibrosis drive transdifferentiation/loss of
##             peritubular REP (renal EPO-producing) cells -> relative
##             erythropoietin deficiency (EPO "inappropriately normal" for the
##             degree of anemia, because the renal hypoxic drive is additionally
##             BLUNTED by the reduced tubular workload of a shrinking nephron
##             mass). Superimposed on this are (i) hepcidin-mediated FUNCTIONAL
##             iron deficiency — HAMP is driven up by IL-6/STAT3 inflammation
##             AND by loss of renal hepcidin clearance, so ferroportin is
##             degraded, recycled macrophage iron is trapped and duodenal
##             absorption is capped; (ii) shortened RBC lifespan from uremic
##             eryptosis and dialysis/GI blood loss; (iii) direct cytokine
##             suppression of BFU-E/CFU-E and of EPOR-JAK2-STAT5 signalling,
##             i.e. ESA hyporesponsiveness.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  Scope    : 30 ODE compartments —
##             * PK  : ESA SC depot + central (epoetin / darbepoetin /
##                     methoxy-PEG-epoetin beta by parameter switch), oral
##                     HIF-PHI gut + plasma (roxadustat / daprodustat /
##                     vadadustat), oral iron lumen pool, IV iron colloid pool.
##             * PD  : REP-cell pool, HIF-2alpha activity, plasma EPO,
##                     erythroid progenitor + 2 erythroblast transit
##                     compartments, blood reticulocytes, circulating RBC.
##             * Iron: transferrin-bound iron, storage iron, TIBC, hepcidin-25,
##                     erythroferrone, non-transferrin-bound (labile) iron.
##             * Systemic: IL-6, hs-CRP, FGF23, phosphate, LDL-C, mean
##                     arterial pressure, cumulative thrombotic hazard,
##                     FACIT-Fatigue, LV mass index, eGFR.
##  Time     : days (default horizon 365 d — long enough for a full titration
##             cycle, LVMI remodelling and an eGFR trajectory).
##  Units    : Hb g/dL · RBC 10^12/L · reticulocytes and marrow pools 10^9/L ·
##             serum iron & TIBC ug/dL · storage iron mg · hepcidin ng/mL ·
##             IL-6 pg/mL · CRP mg/L · phosphate & LDL mg/dL · MAP mmHg ·
##             eGFR mL/min/1.73m2 · drug amounts in dose-proportional "au"
##             (1 au ESA = 150 U/kg epoetin alfa equivalent; 1 au HIF-PHI =
##             100 mg roxadustat equivalent), the library's standard surrogate
##             when the disease-relevant PD, not the plasma assay, is the
##             object of interest. IV/oral iron are dosed in real mg.
##
##  SELF-CALIBRATING BASELINE
##  -------------------------
##  Rather than hard-coding 30 initial conditions, [MAIN] solves the baseline
##  steady state analytically from the patient descriptors (EGFR0, BASE_HB,
##  FIB, BLUNT, IL6_DRIVE, URE, BLOODLOSS, TSAT0, FERRITIN0, HEPC_BASE ...) and
##  back-calculates the production constants (KIN_PROG, KIN_HEPC, KIN_IL6,
##  KIN_TIBC, KIN_CRP, KIN_LDL, KIN_MAP, KIN_LVMI, KDEP, LOSS_FE) that make
##  that state stationary. Change a patient descriptor and the model still
##  starts in balance — the only intended drift in the untreated arm is the one
##  that is real: eGFR decline -> REP loss -> falling EPO -> falling Hb.
##  Iron balance is closed exactly: obligate loss is set equal to baseline
##  absorption, so any NET iron deficit in a scenario comes from a mechanism
##  the model actually represents (dialysis/GI loss, hepcidin trapping, or an
##  ESA/HIF-PHI-driven surge in erythroid iron demand) — never from bookkeeping.
##
##  Scenarios: 13 prebuilt — see ACKD_simulate_scenarios() at the bottom.
##
##  Anchors  :
##    * Eschbach 1987 NEJM 316:73 — first correction of ESKD anemia with rHuEPO
##      (dose-dependent Hct rise, iron demand unmasked).
##    * Normal Hematocrit Trial (Besarab 1998 NEJM 339:584), CHOIR (Singh 2006
##      NEJM 355:2085), CREATE (Drueke 2006 NEJM 355:2071), TREAT (Pfeffer 2009
##      NEJM 361:2019) — Hb normalisation targets give NO benefit and excess
##      stroke/thrombosis/access loss; drives the safety block of this model.
##    * KDIGO 2012 Anemia Guideline — Hb target 10-11.5 g/dL, start ESA <10,
##      TSAT >20% / ferritin >100 (non-dialysis) or >200 (dialysis) iron
##      thresholds; encoded in the titration logic and the endpoint flags.
##    * PIVOTAL (Macdougall 2019 NEJM 380:447) — proactive high-dose IV iron in
##      HD is ESA-sparing and non-inferior for MACE; scenario 5.
##    * Roxadustat: Chen 2019 NEJM 381:1011 (dialysis) & 381:1001 (ND);
##      daprodustat: ASCEND-D / ASCEND-ND (Singh 2021 NEJM 385:2325 / 2313);
##      vadadustat: INNO2VATE / PRO2TECT (Eckardt / Chertow 2021 NEJM 384:1601
##      / 1589) — HIF-PHIs raise Hb with only modest (near-physiological) EPO
##      excursions, lower hepcidin, raise TIBC and LOWER LDL-C; scenarios 6-7,
##      10 and the PHI block of the map.
##    * Kautz 2014 Nat Genet 46:678 (erythroferrone) and Nemeth 2004 Science
##      306:2090 / JCI 113:1271 (hepcidin-ferroportin, IL-6-STAT3) — the iron
##      restriction machinery.
##    * Krzyzanski & Perez-Ruixo 2007 Pharm Res 24:758 and Uehlinger 1992 Clin
##      Pharmacol Ther 51:76 — precedent lifespan/transit PK-PD structures for
##      EPO-driven erythropoiesis, which this model's PROG->EB1->EB2->RET->RBC
##      chain follows.
##    * Wolf 2020 JAMA 323:432 (PHOSPHARE-IDA) — ferric carboxymaltose raises
##      FGF23 and causes hypophosphatemia; scenario 12.
##  Disclaimer: For research / education / hypothesis generation only. Not a
##              substitute for clinical judgment or regulatory filings.
##  ============================================================================
[PROB]
QSP model of the anemia of chronic kidney disease. Couples (1) nephron loss ->
REP-cell attrition -> blunted HIF-2alpha/EPO output, (2) the hepcidin-
ferroportin-erythroferrone iron-restriction axis with loss of renal hepcidin
clearance, (3) inflammation-driven ESA hyporesponsiveness, and (4) a transit
model of erythropoiesis with an iron-availability gate, to the pharmacology of
ESAs, HIF prolyl-hydroxylase inhibitors, oral and IV iron, anti-IL-6 adjuncts
and transfusion — reporting Hb, reticulocytes, TSAT/ferritin/hepcidin,
FACIT-Fatigue, LV mass index, LDL-C, phosphate, blood pressure and a
cumulative thrombotic hazard index.

