##  ---------------------------------------------------------------------------
##  Sensitivity handles worth sweeping
##  ---------------------------------------------------------------------------
##   BLUNT          — how much of the renal hypoxic drive survives; the single
##                    biggest determinant of endogenous EPO in CKD.
##   IL6_DRIVE      — inflammation; drives hepcidin, erythroblast apoptosis and
##                    (via KIL6_EPOR) the ESA hyporesponsiveness itself.
##   HEPC_BASE      — the ferroportin operating point, i.e. how much of the
##                    recycled ~11 mg/day of iron actually reaches the marrow.
##   KM_TSAT        — steepness of the iron gate; controls how quickly an ESA
##                    response saturates into functional iron deficiency.
##   MOB_MAX        — mobilisable store capacity; too low and full stores cannot
##                    rescue the erythron (loaded ferritin with a starved marrow).
##   LS0 / URE      — RBC lifespan; sets the lag on every Hb response and the
##                    obligate iron turnover (~11 mg/day at baseline).
##   EMAX_EPO       — ceiling of the marrow's expansion capacity (~1.6x here).
