//==========================================================================
//  Self-calibrating baseline: solve the stationary state from the patient
//  descriptors, then back out the production constants that hold it.
//==========================================================================

// --- kidney, oxygen sensing, EPO -----------------------------------------
double rep0     = pow(EGFR0 / 90.0, HREP) / (1.0 + FIB);
double hypdrv0  = KHYP * fmax(0.0, (HB_SENSE - BASE_HB) / HB_SENSE) * (1.0 - BLUNT);
double hif0     = 1.0 + hypdrv0;
double il60     = IL6_BASE * IL6_DRIVE / (1.0 + KANTI_IL6 * ANTI_IL6);
double epo_ren0 = KIN_EPO_REN * (rep0 + REP_FLOOR) * pow(hif0, GAM_HIF)
                  / (1.0 + il60 / IC50_IL6_EPO);
double epo_hep0 = KIN_EPO_HEP * pow(fmax(0.0, hif0 - 1.0), GAM_HEP);
double epo0     = (epo_ren0 + epo_hep0) / KEL_EPO;

// --- iron status ---------------------------------------------------------
double fetf0    = TSAT0 * TIBC0 / 100.0;
store0          = fmax(50.0, (FERRITIN0 - FERR_APR * il60 / (il60 + 10.0)) * FERR_PER_MG);
double gate0    = TSAT0 / (TSAT0 + KM_TSAT);
double hypo0    = fmin(1.0, 0.85 + 0.15 * gate0 / 0.75);

// --- red cell mass and the erythroid chain ------------------------------
double rbc0     = BASE_HB / (MCHC_F * hypo0);
double ls0      = LS0 * (1.0 - LS_URE * URE);
double bl_tot   = BLOODLOSS + 0.0035 * DIALYSIS;
double destr0   = rbc0 / ls0 + bl_tot * rbc0;              // 10^12/L/day
double ret0     = destr0 * 1000.0 / KRET;                  // 10^9/L
double retprod0 = KRET * ret0;                             // 10^9/L/day
double apop0    = APOP_MAX * il60 / (il60 + IC50_IL6_PROG);
double eb0      = retprod0 / (KTR * gate0 * (1.0 - apop0));
double epor0    = 1.0 + KIL6_EPOR * il60 / (il60 + IC50_EPOR);
double epoe0    = epo0 / epor0;                            // EPOR-transduced signal
double drive0   = 1.0 + EMAX_EPO * pow(epoe0, HILL_EPO)
                        / (pow(EC50_EPO, HILL_EPO) + pow(epoe0, HILL_EPO));
double marrow0  = 1.0 / (1.0 + 0.5 * PTH_SEV + 0.6 * NUTR);
double infl0    = 1.0 / (1.0 + il60 / IC50_IL6_PROG);
// production constant that makes PROG stationary at eb0:
KIN_PROG        = KTR * eb0 / (drive0 * infl0 * marrow0);

// --- iron balance closure ------------------------------------------------
double fpn_act0 = 1.0 / (1.0 + HEPC_BASE / IC50_HEPC_FPN);
double absfr0   = FMAX_ABS / (1.0 + HEPC_BASE / IC50_HEPC_ABS)
                  * (1.0 + KHIF_ABS * fmax(0.0, hif0 - 1.0));
double abs0     = absfr0 * DIET_FE;                        // mg/day absorbed
double util0    = FE_PER_CELL * retprod0;                  // mg/day into erythron
double rec0     = FE_PER_CELL * destr0 * 1000.0;           // mg/day recycled
double mob0     = MOB_MAX * (store0 / (store0 + KM_STORE)); // mg/day mobilised
double over0    = 1.0 + KOVER_DEP * pow(fmax(0.0, TSAT0 - TSAT_OVER) / 40.0, 2.0);
// obligate loss set equal to baseline absorption  => closed iron balance.
// (Baseline recycling exactly equals baseline erythron utilisation, because at
//  steady state RBC destruction equals reticulocyte delivery, so plasma iron
//  balances iff absorption == obligate loss. Any NET deficit in a scenario is
//  therefore mechanistic, not a bookkeeping artefact.)
LOSS_FE         = abs0;
// deposition matched to mobilisation => stationary stores
KDEP            = mob0 / (fetf0 * PLASMA_DL / 1000.0 * over0);

// --- back-calculated production constants -------------------------------
double inflh0    = 1.0 + KIL6_HEPC * il60 / (IC50_IL6_HEPC + il60);
double rencl0    = pow(EGFR0 / 90.0, HCL) + HEPC_NONREN;
KIN_HEPC         = KOUT_HEPC * HEPC_BASE * rencl0
                   * (1.0 + KPHI_HEPC * fmax(0.0, hif0 - 1.0)) / inflh0;
KIN_IL6          = KOUT_IL6 * il60 * (1.0 + KANTI_IL6 * ANTI_IL6)
                   / (IL6_DRIVE * (1.0 + KUREM_IL6 * (1.0 - EGFR0 / 90.0)));
KIN_CRP          = KOUT_CRP * CRP0 / il60;
double tibcf0    = (1.0 + KHIF_TF * fmax(0.0, hif0 - 1.0)) / (1.0 + il60 / IC50_IL6_TF);
