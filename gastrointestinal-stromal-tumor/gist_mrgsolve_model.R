[PROB]
Polyclonal QSP model of gastrointestinal stromal tumor (GIST) linking oral PK
of five tyrosine kinase inhibitors to a drug x clone effective-IC50 matrix
over six tumor sub-populations (primary-driver sensitive, quiescent
drug-tolerant persister, exon 13/14 ATP-pocket resistant, exon 17/18
activation-loop resistant, primary-refractory PDGFRA-D842V/SDH-deficient, and
KIT-independent bypass), through KIT-PI3K/AKT-MAPK/ERK-ETV1-BIM signaling and
VEGFR-dependent vascular support, to imaging (RECIST size, Choi CT density,
FDG-PET SUVmax), molecular (clone-resolved plasma ctDNA VAF) and toxicity
endpoints.

