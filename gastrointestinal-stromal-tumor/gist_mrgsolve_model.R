//==========================================================================
// 1. DRUG PHARMACOKINETICS
//==========================================================================
dxdt_IMA_DEPOT = -KA_IMA*IMA_DEPOT;
dxdt_IMA_CENT  =  KA_IMA*IMA_DEPOT - (gCL_IMA_T/V1_IMA)*IMA_CENT
                  - (Q_IMA/V1_IMA)*IMA_CENT + (Q_IMA/V2_IMA)*IMA_PER;
dxdt_IMA_PER   =  (Q_IMA/V1_IMA)*IMA_CENT - (Q_IMA/V2_IMA)*IMA_PER;

dxdt_SUN_DEPOT = -KA_SUN*SUN_DEPOT;
dxdt_SUN_CENT  =  KA_SUN*SUN_DEPOT - (CL_SUN/V1_SUN)*SUN_CENT;

dxdt_REG_DEPOT = -KA_REG*REG_DEPOT;
dxdt_REG_CENT  =  KA_REG*REG_DEPOT - (CL_REG/V1_REG)*REG_CENT;

dxdt_RIP_DEPOT = -KA_RIP*RIP_DEPOT;
dxdt_RIP_CENT  =  KA_RIP*RIP_DEPOT - (CL_RIP/V1_RIP)*RIP_CENT;

dxdt_AVA_DEPOT = -KA_AVA*AVA_DEPOT;
