//    (Bliss-independent combination of competitive inhibition terms).
//==========================================================================
double res_S = 1.0/((1.0+Eima/gIC_IMA_S)*(1.0+Esun/gIC_SUN_S)
                   *(1.0+Ereg/IC_REG_S)*(1.0+Erip/IC_RIP_S)*(1.0+Eava/IC_AVA_S));
double res_A = 1.0/((1.0+Eima/gIC_IMA_A)*(1.0+Esun/gIC_SUN_A)
                   *(1.0+Ereg/IC_REG_A)*(1.0+Erip/IC_RIP_A)*(1.0+Eava/IC_AVA_A));
double res_L = 1.0/((1.0+Eima/gIC_IMA_L)*(1.0+Esun/gIC_SUN_L)
                   *(1.0+Ereg/IC_REG_L)*(1.0+Erip/IC_RIP_L)*(1.0+Eava/IC_AVA_L));
double res_D = 1.0/((1.0+Eima/IC_IMA_D)*(1.0+Esun/IC_SUN_D)
                   *(1.0+Ereg/IC_REG_D)*(1.0+Erip/IC_RIP_D)*(1.0+Eava/gIC_AVA_D));
double res_I = 1.0;   // KIT-independent bypass clone: no KIT-directed effect

double inh_S = 1.0 - res_S;
double inh_A = 1.0 - res_A;
double inh_L = 1.0 - res_L;
double inh_D = 1.0 - res_D;

//==========================================================================
// 3. TUMOR VASCULAR SUPPORT (VEGFR2/PDGFRB/TIE2)
//    The mechanism by which sunitinib and regorafenib retain activity in
//    KIT-refractory disease, and the main mechanism in SDH-deficient GIST.
//==========================================================================
double ang_ss = ANG_FLOOR + (1.0 - ANG_FLOOR)
                /(1.0 + Esun/ICA_SUN + Ereg/ICA_REG + Erip/ICA_RIP);
dxdt_ANG = KANG*(ang_ss - ANG);

double vasc_kit = (1.0 - WVASC) + WVASC*ANG;   // vascular modifier, KIT-driven clones
double vasc_ref = (1.0 - gWV_D) + gWV_D*ANG;   // vascular modifier, refractory clone

//==========================================================================
// 4. CLONAL POPULATION DYNAMICS
//    Growth  ~ KG * residual signaling * vascular support * logistic space
//    Death   ~ baseline + apoptotic drive that is a SIGMOID of inhibition,
//              i.e. partial inhibition is cytostatic, deep inhibition is
//              cytocidal (and is blunted by the BIM deletion polymorphism).
//==========================================================================
double space = 1.0 - Ttot/TMAX_BURDEN;
if (space < 0) space = 0;

double ap_S = EMAX_AP*gBIMF*pow(inh_S,HAP)/(pow(IC_AP,HAP)+pow(inh_S,HAP));
double ap_A = EMAX_AP*gBIMF*pow(inh_A,HAP)/(pow(IC_AP,HAP)+pow(inh_A,HAP));
double ap_L = EMAX_AP*gBIMF*pow(inh_L,HAP)/(pow(IC_AP,HAP)+pow(inh_L,HAP));
double ap_D = EMAX_AP*gBIMF*pow(inh_D,HAP)/(pow(IC_AP,HAP)+pow(inh_D,HAP));

double prol_S = KG          * res_S * vasc_kit * space * TS;
double prol_A = KG*FITCOST  * res_A * vasc_kit * space * TA;
double prol_L = KG*FITCOST  * res_L * vasc_kit * space * TL;
double prol_D = KG*FITCOST  * res_D * vasc_ref * space * TD;
double prol_I = KG*FITCOST  * res_I * vasc_kit * space * TI;

// Mutant supply is proportional to the DIVISION FLUX of the sensitive clone:
// a large, actively cycling sensitive clone manufactures its own resistance.
// This is what couples imatinib DOSE (which controls res_S) to PFS.
double sup_A = MU_A   * prol_S;
double sup_L = MU_L   * prol_S;
double sup_I = MU_IND * prol_S;

// Drug-induced quiescence (autophagy-dependent persister pool). Cells leave
// the cycling compartment when signaling is shut down and return when it
// recovers -> the source of rapid rebound after treatment interruption.
double q_in  = KQIN  * inh_S * TS;
double q_out = KQOUT * res_S * TQ;

dxdt_TS = prol_S - (KD0 + ap_S)*TS - sup_A - sup_L - sup_I - q_in + q_out;
dxdt_TQ = q_in - q_out - KDQ*TQ;
dxdt_TA = prol_A - (KD0 + ap_A)*TA + sup_A;
dxdt_TL = prol_L - (KD0 + ap_L)*TL + sup_L;
dxdt_TD = prol_D - (KD0 + ap_D)*TD;
dxdt_TI = prol_I - KD0*TI + sup_I;

//==========================================================================
// 5. SIGNAL TRANSDUCTION READOUTS (burden-weighted across clones)
//==========================================================================
double res_bar = (res_S*(TS+TQ) + res_A*TA + res_L*TL + res_D*TD + res_I*TI)/Ttot;

dxdt_PKIT = KPKIT*(res_bar - PKIT);
dxdt_AKTP = KAKT *(PKIT    - AKTP);
dxdt_ERKP = KERK *(PKIT    - ERKP);
dxdt_ETV1 = KETV1*(ERKP    - ETV1);           // ERK stabilizes ETV1 protein
dxdt_BIM  = KBIM *(1.0 + (BIM_MAX-1.0)*(1.0-ERKP)*gBIMF - BIM);

//==========================================================================
// 6. IMAGING BIOMARKERS
//    FDG-PET SUV tracks GLUT1/hexokinase, i.e. pKIT, within 24-48 h.
//    CT attenuation (Choi) tracks accumulated myxoid/cystic degeneration and
//    therefore falls WEEKS BEFORE any RECIST size change.
//==========================================================================
double suv_ss = SUV_MIN + (SUV_BASE - SUV_MIN)*PKIT;
dxdt_SUV = KSUV*(suv_ss - SUV);

double kill_flux = ap_S*TS + ap_A*TA + ap_L*TL + ap_D*TD;
double kill_rate_rel = kill_flux/Ttot;
// Myxoid/cystic degeneration is CUMULATIVE and only slowly reversible: this is
// why Choi density stays low for as long as therapy works, and climbs back
// when a resistant nodule starts to re-enhance.
dxdt_MYX = KMYX_IN*( kill_rate_rel/(KHU50 + kill_rate_rel) )*(1.0 - MYX)
           - KMYX_OUT*MYX;
double hu_ss = HU_BASE - (HU_BASE - HU_MIN)*MYX;
dxdt_HU = KHU*(hu_ss - HU);

//==========================================================================
// 7. CIRCULATING TUMOR DNA — clone-resolved
//    Resistant-clone ctDNA rises while total burden is still falling:
//    molecular progression precedes radiologic progression.
//==========================================================================
double death_S = (KD0 + ap_S)*TS + KDQ*TQ;
double death_R = (KD0 + ap_A)*TA + (KD0 + ap_L)*TL + (KD0 + ap_D)*TD + KD0*TI;
dxdt_CTDS = SHED_P*prol_S + SHED_D*death_S - KEL_CTD*CTDS;
dxdt_CTDR = SHED_P*(prol_A + prol_L + prol_D + prol_I)
            + SHED_D*death_R - KEL_CTD*CTDR;

//==========================================================================
// 8. ORGAN-SYSTEM TOXICITY
//==========================================================================
// Periorbital / peripheral edema — PDGFR-beta inhibition, imatinib-dominant
dxdt_EDEMA = KED*( EMAX_ED*Eima/(EC50_ED + Eima) - EDEMA );

// Myelosuppression — KIT/FLT3 on hematopoietic progenitors
double myelo = MS_IMA*(Eima/gIC_IMA_S)/(EC50_MS + Eima/gIC_IMA_S)
             + MS_SUN*(Esun/IC_SUN_S)/(EC50_MS + Esun/IC_SUN_S)
             + MS_REG*(Ereg/IC_REG_S)/(EC50_MS + Ereg/IC_REG_S)
             + MS_RIP*(Erip/IC_RIP_S)/(EC50_MS + Erip/IC_RIP_S);
if (myelo > 0.85) myelo = 0.85;
dxdt_ANC = KIN_ANC*(1.0 - myelo) - KOUT_ANC*ANC;

// Hypothyroidism — essentially sunitinib-specific
dxdt_TSH = KIN_TSH*(1.0 + ETSH_MAX*Esun/(EC50_TSH + Esun)) - KOUT_TSH*TSH;

// Hypertension — VEGFR blockade; tracks the anti-angiogenic effect itself
double aai = 1.0 - (ang_ss - ANG_FLOOR)/(1.0 - ANG_FLOOR);
dxdt_SBP = KSBP*(SBP0 + DSBP_MAX*aai - SBP);

// Hand-foot skin reaction — regorafenib > sunitinib
double hfs_ss = HFS_MAX*( 0.75*Ereg/(EC50_HFS_R + Ereg)
                        + 0.35*Esun/(EC50_HFS_S + Esun) );
if (hfs_ss > HFS_MAX) hfs_ss = HFS_MAX;
dxdt_HFS = KHFS*(hfs_ss - HFS);

