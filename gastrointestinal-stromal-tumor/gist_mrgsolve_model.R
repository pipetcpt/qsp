//--------------------------------------------------------------------------
// Genotype resolution
//   GENO 1 = KIT exon 11 (reference)
//   GENO 2 = KIT exon 9   -> 4-fold imatinib IC50 rise (dose 800 mg matters),
//                            sunitinib slightly MORE potent
//   GENO 3 = PDGFRA D842V -> tumor is essentially all "primary-refractory"
//                            clone; avapritinib is the only active agent
//   GENO 4 = SDH-deficient/quadruple-WT -> KIT-independent, strongly
//                            VEGF-dependent; TKI benefit is anti-angiogenic
//   GENO 5 = KIT exon 11 + BIM intron-2 deletion polymorphism (apoptosis-
//                            impaired; cytostatic rather than cytocidal)
//--------------------------------------------------------------------------
double f9  = (GENO == 2) ? GF_EX9 : 1.0;
gIC_IMA_S  = IC_IMA_S * f9;
gIC_IMA_A  = IC_IMA_A * f9;
gIC_IMA_L  = IC_IMA_L * f9;
gIC_SUN_S  = IC_SUN_S * ((GENO == 2) ? GF_EX9_SUN : 1.0);
gIC_SUN_A  = IC_SUN_A * ((GENO == 2) ? GF_EX9_SUN : 1.0);
gIC_SUN_L  = IC_SUN_L * ((GENO == 2) ? GF_EX9_SUN : 1.0);
gIC_AVA_D  = (GENO == 4) ? IC_AVA_D_SDH : IC_AVA_D;
gBIMF      = (GENO == 5) ? BIMFAC_DEL : BIMFAC_WT;
gWV_D      = (GENO == 4) ? WVASC_SDH  : WVASC;

// Time-dependent apparent imatinib clearance (rises ~35% toward steady state)
gCL_IMA_T  = CL_IMA * CLFAC_IMA * (1.0 + FCLDRIFT*(1.0 - exp(-KDRIFT*TIME)));

//--------------------------------------------------------------------------
// Initial conditions — baseline clonal composition
//--------------------------------------------------------------------------
gTB0 = (ADJUVANT > 0) ? TB0_ADJ : TB0;

double refractory_dominant = (GENO == 3 || GENO == 4) ? 1.0 : 0.0;
double fD0 = refractory_dominant ? 0.985 : 1.0e-4;
double fA0 = refractory_dominant ? FRAC_A0*0.05 : FRAC_A0;
double fL0 = refractory_dominant ? FRAC_L0*0.05 : FRAC_L0;
double fI0 = FRAC_IND0;
double fS0 = 1.0 - fD0 - fA0 - fL0 - fI0;
if (fS0 < 0) fS0 = 0;

TS_0 = gTB0 * fS0;
TA_0 = gTB0 * fA0;
TL_0 = gTB0 * fL0;
TD_0 = gTB0 * fD0;
TI_0 = gTB0 * fI0;
TQ_0 = 0.0;

AAG_0   = AAG_REF * (1.0 + GAAG*gTB0/500.0);
PKIT_0  = 1.0;
AKTP_0  = 1.0;
ERKP_0  = 1.0;
ETV1_0  = 1.0;
BIM_0   = 1.0;
ANG_0   = 1.0;
