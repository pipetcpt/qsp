##  ============================================================================
##  Gastrointestinal Stromal Tumor (GIST) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : GIST — the most common mesenchymal neoplasm of the GI tract,
##             arising from interstitial cells of Cajal (ICC) / their precursors
##             under an ETV1 lineage program, driven in ~85% of cases by a
##             mutually exclusive activating mutation of KIT (exon 11 ~65-70%,
##             exon 9 ~8-10%) or PDGFRA (exon 18 D842V ~5-6%), with a distinct
##             SDH-deficient / quadruple-wild-type minority that is
##             KIT-independent and pseudohypoxia (succinate-HIF1a-VEGF) driven.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>=1.5)
##
##  WHY THIS DISEASE NEEDS A *POLYCLONAL* QSP MODEL
##  -----------------------------------------------
##  GIST is the textbook case in which a single-compartment "tumor size vs
##  drug concentration" model cannot reproduce the clinic. Three facts force a
##  clonal structure:
##    (1) Imatinib almost always works, and almost always stops working at
##        ~20-24 months — not because the drug stops reaching the target, but
##        because the drug SELECTS a pre-existing / newly acquired secondary
##        kinase-domain mutant.
##    (2) The secondary mutants are POLYCLONAL: different metastases in the
##        same patient carry different secondary mutations, and the two major
##        families respond to OPPOSITE drugs — ATP-binding-pocket mutants
##        (exon 13 V654A, exon 14 T670I) are suppressed by sunitinib but poorly
##        by regorafenib, whereas activation-loop mutants (exon 17 D816/D820/
##        N822K, Y823D) are the reverse.
##    (3) Consequently, the winner of a head-to-head second-line trial depends
##        on the ctDNA-measured clonal composition of the enrolled population —
##        which is exactly what INTRIGUE (ripretinib vs sunitinib, 2nd line)
##        found: NEGATIVE overall, but with opposite subgroup directions.
##  This model therefore carries SIX tumor sub-populations and a
##  DRUG x CLONE effective-IC50 matrix, and lets the trial results emerge
##  rather than be asserted.
##
##  Scope    : 34 ODE compartments —
##             * oral PK for five TKIs (imatinib 1L, sunitinib 2L,
##               regorafenib 3L, ripretinib 4L, avapritinib for PDGFRA D842V),
##               with imatinib alpha-1-acid-glycoprotein (AAG) protein binding
##               and time-dependent clearance modeled explicitly;
##             * six tumor sub-populations (primary-driver sensitive clone;
##               quiescent drug-tolerant persister pool; exon 13/14 ATP-pocket
##               resistant clone; exon 17/18 activation-loop resistant clone;
##               primary-refractory clone [PDGFRA D842V or SDH-deficient
##               biology depending on genotype]; KIT-independent bypass clone);
##             * signal transduction readouts (pKIT, AKT/mTOR, ERK, ETV1, BIM);
##             * tumor vascular support (VEGFR-dependent, the mechanism by
##               which sunitinib/regorafenib work on KIT-refractory disease);
##             * imaging & molecular biomarkers (FDG-PET SUVmax, CT attenuation
##               for Choi criteria, and SEPARATE sensitive- and resistant-clone
##               plasma ctDNA so that molecular progression can be shown to
##               precede radiologic progression);
##             * organ-system toxicity (periorbital edema, neutropenia,
##               hypothyroidism, hypertension, hand-foot skin reaction).
##  Time     : days. Default horizon 1460 d (4 y) to span adjuvant therapy,
##             first-line response, secondary resistance and 2nd-4th line.
##  Units    : drug amounts mg; concentrations converted to nM internally;
##             tumor burden mL (cm3) of viable tumor; biomarkers in clinical
##             units (ng/mL, HU, SUV, %VAF, x10^9/L, mIU/L, mmHg).
##  Scenarios: 13 prebuilt scenario families (19 arms) — see GIST_scenarios()
##             at the bottom of this file.
##  Anchors  : B2222 (Demetri 2002 NEJM 347:472); EORTC 62005 / S0033 and the
##             MetaGIST pooled analysis (JCO 2010 28:1247, exon 9 800 mg PFS
##             benefit); Heinrich 2003 JCO 21:4342 & 2008 JCO 26:5352
##             (genotype-response); Antonescu 2005 Clin Cancer Res 11:4182 and
##             Wardelmann 2006 Clin Cancer Res 12:1743 (polyclonal secondary
##             mutations); Demetri 2009 J Clin Oncol 27:3141 (imatinib Cmin
##             1100 ng/mL threshold);
##             Widmer 2006 Br J Clin Pharmacol 62:97 (AAG binding);
##             Demetri 2006 Lancet 368:1329 (sunitinib GRID-precursor);
##             Demetri 2013 Lancet 381:295 (GRID, regorafenib);
##             Blay 2020 Lancet Oncol 21:923 (INVICTUS, ripretinib 4L);
##             Bauer 2022 J Clin Oncol 40:3918 (INTRIGUE, ripretinib vs
##             sunitinib 2L — negative overall) and Bauer 2024 Nat Med
##             30:498 (INTRIGUE ctDNA exon 11+13/14 vs 11+17/18 subgroups);
##             Heinrich 2020/2021 (NAVIGATOR, avapritinib in PDGFRA D842V);
##             Blay 2007 JCO 25:1107 (BFR14 interruption -> rapid regrowth);
##             Joensuu 2012 JAMA 307:1265 (SSGXVIII, 3 y adjuvant imatinib);
##             Choi 2007 JCO 25:1753 (CT density response criteria);
##             Van den Abbeele 2008 (FDG-PET early metabolic response).
##  Disclaimer: For research / education / hypothesis generation only.
