##  --- PK -------------------------------------------------------------------
##  Imatinib CL/F 183 L/d at the first dose, drifting to ~247 L/d (10.3 L/h) at
##  steady state via FCLDRIFT/KDRIFT, with total Vd/F 353 L (V1 200 + V2 153,
##  Q 600 L/d for rapid distribution). [VERIFIED] this gives a day-180 trough of
##  1,231 ng/mL at 400 mg/d, against the reported steady-state Cmin of
##  ~1,110 ng/mL and the ~1,100 ng/mL efficacy threshold of Demetri 2009
##  (J Clin Oncol 27:3141, PMID 19451435). The clearance drift reproduces the
##  ~30% fall in imatinib exposure between first dose and one year of
##  continuous therapy (Eechoute 2012 Clin Cancer Res 18:5780, PMID 22850565).
##  Sunitinib CL/F 816 L/d gives total (parent + SU12662) Cavg ~60 ng/mL at
##  50 mg/d, the target steady-state range. Regorafenib, ripretinib and
##  avapritinib volumes/clearances reproduce their reported Cmax ranges.
##
##  --- Protein binding and the effective-concentration convention ------------
##  FT_* are CALIBRATED EFFECTIVE target-site availability fractions, folding
##  together unbound fraction, tissue partitioning and active-metabolite
##  contribution. They are NOT measured fu values, and the IC50 matrix is
##  calibrated jointly with them: only the RATIO (effective concentration /
##  effective IC50) is identifiable from clinical response data, so neither
##  number should be quoted on its own.
##  The AAG term is the one binding effect modeled explicitly, because it is
##  clinically consequential and directionally counter-intuitive: a large tumor
##  burden raises alpha-1-acid glycoprotein, lowering FREE imatinib at unchanged
##  TOTAL plasma concentration (Widmer 2006 Br J Clin Pharmacol 62:97,
##  PMID 16842382). It also produces an emergent positive feedback the model was
##  not built to contain: as the tumor responds, AAG falls, free drug rises, and
##  suppression deepens — which partly offsets the clearance drift above.
##
##  --- IC50 matrix -----------------------------------------------------------
##  Set so that at label doses the effective pathway inhibition is: imatinib on
##  KIT exon 11 ~0.75 (deep, cytocidal); imatinib on exon 9 markedly less at
##  400 mg and substantially recovered at 800 mg (GF_EX9 = 5); sunitinib strong
##  on exon 13/14 and near-inert on exon 17/18; regorafenib the reverse;
##  ripretinib intermediate-to-good on BOTH families, which is the switch-control
##  design claim (Smith 2019 Cancer Cell 35:738, PMID 31085175); avapritinib
##  dominant on PDGFRA D842V but penalized on V654A, consistent with VOYAGER
##  failing to generalize beyond D842V (Kang 2021 JCO 39:3128, PMID 34343033).
##  The asymmetry itself is from Heinrich 2008 (JCO 26:5352, PMID 18955451) and
##  Serrano 2019 (Br J Cancer 120:612, PMID 30792533).
##
##  --- Growth and resistance timing ------------------------------------------
##  KG 0.011/d (untreated volume doubling ~63 d), pre-existing resistant subclone
##  fractions ~3e-4, and mutant-supply coefficients ~8e-4 per unit sensitive-clone
##  proliferative flux. [VERIFIED] first-line imatinib 400 mg in KIT exon 11
##  gives a best RECIST response of -56% with radiologic progression at 23.9
##  months, against the ~20-24 month median time to progression of B2222
##  (PMID 12181401) and EORTC 62005 (PMID 15451219).
##  MU_* are LUMPED phenomenological coefficients, not per-division point-mutation
##  probabilities: they absorb the mutation rate, the number of codons that can
##  confer resistance, and the probability that any given new mutant clone
##  actually establishes. Because mutant supply scales with the DIVISION FLUX of
##  the sensitive clone, deeper suppression delays resistance mechanistically
##  rather than by fiat. That is the model's main testable claim, and it is what
##  makes dose and trough matter for PFS rather than only for response depth.
##
##  --- What the model reproduces [VERIFIED] ----------------------------------
##  * Imaging ordering. FDG-PET SUV -63% by day 7; Choi density partial response
##    (-15% HU) at day 25; RECIST partial response (-30% diameter) at day 101 —
##    a 76-day lead of density over size. This is precisely the discordance that
##    motivated the Choi criteria (PMID 17470865) and it emerges from three
##    different time constants, not from three fitted curves.
##  * Molecular before radiologic. Resistant-clone ctDNA crosses the 0.1% VAF
##    limit of detection at day 531 while radiologic progression is at day 727 —
##    a ~6.5 month lead time (cf. PMID 30097488).
##  * Exon 9 dose effect. 400 mg gives a -22.9% best response, 800 mg -54.4%,
##    with time-to-return-to-baseline 28.7 vs 31.1 months (MetaGIST, PMID
##    20124181). The response-depth effect is large; the progression-delay
##    component is present but smaller than the published PFS separation.
##  * Exposure-response. At a 2.2-fold clearance multiplier (day-180 trough
##    373 ng/mL) time-to-baseline is 31.3 months vs 33.8 months at normal
##    clearance; escalating that patient to 600 and 800 mg recovers troughs of
##    560 and 746 ng/mL and 32.5 and 33.5 months, monotonically.
##  * Interruption. Stopping at day 365 from a -51% response: -38% at day 485,
##    -27% at day 545, above baseline by day 730, and never returning to the
##    continuous-therapy curve (BFR14, PMID 17369574). The rebound comes out of
##    the quiescent persister pool, which is also why pathologic complete
##    responses are rare despite dramatic radiologic ones.
##  * Adjuvant therapy. Recurrence to 10 mL at 1.8 y with observation vs 4.7 y
##    with 3 years of adjuvant imatinib — the "delay, not cure" shape of
##    SSGXVIII (PMID 22453568), with the hazard re-emerging after stopping.
##  * Genotype-directed therapy. PDGFRA D842V progresses at 2.9 months on
##    imatinib and responds -86.7% on avapritinib (NAVIGATOR, PMID 32615108).
##    SDH-deficient disease is inert to imatinib (PD at 2.9 months) but is
##    slowed by sunitinib (PD at 6.8 months) purely through the anti-angiogenic
##    arm, since res_D is unchanged — the mechanism, not just the outcome.
##  * BIM polymorphism. Same exposure and same pathway inhibition, best response
##    -47.4% vs -56.0% for BIM wild-type (PMID 22426421): cytostasis without
##    cytocidal effect.
##  * INTRIGUE ctDNA subgroups. In an exon-13/14-only background sunitinib is
##    ahead of ripretinib; in an exon-17/18-only background ripretinib is ahead
##    by a far larger margin. The DIRECTION of both subgroups matches the
##    published ctDNA analysis (PMID 38182785), and it is emergent from the
##    IC50 matrix rather than asserted.
##
##  --- What the model does NOT reproduce -------------------------------------
##  The INTRIGUE PRIMARY endpoint. In a mixed second-line population the model
##  puts ripretinib clearly ahead of sunitinib, whereas the trial was negative
##  (Bauer 2022 JCO 40:3918, PMID 35947817). The reason is structural and worth
##  stating plainly: with sunitinib near-inert against activation-loop mutants,
##  ANY population containing an appreciable exon-17/18 clone favours ripretinib,
##  because sunitinib's failure mode there is catastrophic while ripretinib's
##  disadvantage on exon 13/14 is merely moderate. For the arms to tie, one of
##  the following must be true and is not encoded here: ATP-pocket-only
##  resistance is considerably more prevalent than the ~1:1 split assumed;
##  sunitinib's anti-angiogenic contribution is larger than WVASC = 0.45 allows;
##  or ripretinib's real-world exposure at 150 mg/d is lower relative to its
##  IC50s than FT_RIP implies. Each is a falsifiable, quantitative hypothesis,
##  and separating them is a better use of this model than tuning until the
##  curves overlap.
##
##  --- Known artifact --------------------------------------------------------
##  Nadir-referenced RECIST progression behaves counter-intuitively when arms
##  differ in RESPONSE DEPTH: a shallower responder has a higher nadir, so the
##  ">=20% above nadir" rule fires LATER even though that patient is doing worse.
##  This is a property of the criterion, not of the biology, and it shows up in
##  the exon-9 400 mg and BIM-deletion arms. When comparing arms with different
##  response depths, prefer time-to-return-to-baseline-burden (see ttb() below)
##  or read response depth and progression as two separate endpoints.
##
