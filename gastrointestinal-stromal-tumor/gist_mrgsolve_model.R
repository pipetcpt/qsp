//--------------------------------------------------------------------------
// Total tumor burden (needed for the AAG acute-phase term)
//--------------------------------------------------------------------------
double Ttot = TS + TQ + TA + TL + TD + TI;
if (Ttot < 1e-9) Ttot = 1e-9;

// Alpha-1-acid glycoprotein: acute-phase protein induced by tumor burden.
// High AAG sequesters imatinib -> LOWER free drug at the SAME total plasma
// concentration (Widmer 2006). This is why total-drug TDM can mislead.
dxdt_AAG = KIN_AAG*AAG_REF*(1.0 + GAAG*Ttot/500.0) - KOUT_AAG*AAG;

//--------------------------------------------------------------------------
// Effective target-site concentrations (nM)
//--------------------------------------------------------------------------
double aag_now  = (AAG > 0.05) ? AAG : 0.05;
double ft_ima   = FT_IMA * (AAG_REF/aag_now);

double Eima = ft_ima * 1.0e6 * IMA_CENT / (V1_IMA * MW_IMA);
double Esun = FT_SUN * 1.0e6 * SUN_CENT / (V1_SUN * MW_SUN);
double Ereg = FT_REG * 1.0e6 * REG_CENT / (V1_REG * MW_REG);
double Erip = FT_RIP * 1.0e6 * RIP_CENT / (V1_RIP * MW_RIP);
double Eava = FT_AVA * 1.0e6 * AVA_CENT / (V1_AVA * MW_AVA);

