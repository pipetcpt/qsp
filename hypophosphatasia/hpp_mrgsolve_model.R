## ---------------------------------------------------------------------------
## HPP_report() — reproduce the scenario table of hpp_model_report.txt
## ---------------------------------------------------------------------------
HPP_report <- function() {
  scn <- HPP_scenarios()
  rows <- lapply(names(scn), function(k) {
    s <- scn[[k]]
    out <- do.call(HPP_run, s$args)
    e <- out[nrow(out), ]
    data.frame(scenario = s$label, PPIL = e$PPIL, MRELN = e$MRELN,
               osteoid = e$OST, RSS = e$RSS, dHTZ = e$HTZ, RESP = e$RESP,
               SURV = e$SURV, MUS = e$MUS, SEIZ = e$SEIZ, PAIN = e$PAIN,
               PLP = e$PLPP, CaU = e$JURN, NEPH = e$NEPH,
               stringsAsFactors = FALSE)
  })
  res <- do.call(rbind, rows)
  print(res, digits = 3, row.names = FALSE)
  invisible(res)
}

## ---------------------------------------------------------------------------
## HPP_dose_ranging() — T2: which readout saturates first?
##
##   Sweeps total WEEKLY dose (given as mg/kg three times weekly) and reports
##   plasma PLP, plasma PPi, perivesicular PPi, HA occupancy, relative mineral
##   apposition and RSS at 26 weeks. The point of the sweep is that plasma PLP
##   is maximally suppressed at a dose that leaves the mineralization capacity
##   far from its ceiling.
## ---------------------------------------------------------------------------
HPP_dose_ranging <- function(weekly = c(0, 0.375, 0.75, 1.5, 3, 6, 9, 12, 18, 30),
                             sev = "infantile", days = 182) {
  rows <- lapply(weekly, function(w) {
    out <- HPP_run(sev = sev, days = days, dose = w / 3, per_week = 3, delta = 7)
    e <- out[nrow(out), ]
    data.frame(mgkg_week = w, ALP_UL = e$ALPUL, occupancy = e$OCC, ELOC = e$ELOC,
               PLP_nM = e$PLPP, PPi_plasma = e$PPIP, PPi_local = e$PPIL,
               Mrel = e$MRELN, RSS = e$RSS, osteoid = e$OST)
  })
  res <- do.call(rbind, rows)
  print(res, digits = 3, row.names = FALSE)
  invisible(res)
}

## ---------------------------------------------------------------------------
## HPP_threshold_curve() — T1: the hyperbola, and its closed form
##
##   Mrel(E) = (1 + PPi0/Ki) / (1 + (Jppi + kout*PPi_pl) / (Ki*(kcat*E + kout)))
##
##   is the PPi << Km limit; the model itself solves the exact quadratic. Both
##   are returned so the linearisation error is visible (it reaches ~44% in the
##   mid-range, which is why every reported number uses the exact solution).
## ---------------------------------------------------------------------------
HPP_threshold_curve <- function(E = c(0.01, 0.02, 0.05, 0.10, 0.20, 0.35,
                                      0.50, 0.75, 1.00)) {
  p <- as.list(param(HPP_mod))
  rows <- lapply(E, function(e) {
    pars <- modifyList(HPP_genotype("infantile"), list(FRACENZ = e))
    y0 <- HPP_settle(pars)
    m <- mrgsolve::init(param(HPP_mod, pars), y0)
    out <- as.data.frame(mrgsim(m, end = 1, delta = 1))
    ex <- out[nrow(out), ]
    lin_ppi <- (p$JPPI + p$KOUT * ex$PPIP) / (p$KCATP * e + p$KOUT)
    lin_mrel <- (1 + p$PPI0 / p$KIPPI) / (1 + lin_ppi / p$KIPPI)
    data.frame(fracEnz = e, PPi_local_exact = ex$PPIL,
               PPi_local_linear = lin_ppi, Mrel_exact = ex$MRELN,
               Mrel_linear = lin_mrel, osteoid = ex$OST, PLP_nM = ex$PLPP)
  })
  res <- do.call(rbind, rows)
  print(res, digits = 3, row.names = FALSE)
  invisible(res)
}

## ---------------------------------------------------------------------------
## CALIBRATION NOTES — what each block is anchored to
## ---------------------------------------------------------------------------
##  PK (asfotase alfa)
##    F = 0.458, tmax 24-48 h, terminal t1/2 = 2.28 d are the label values.
##    V, KON/KOFF/KDEGB and BMAXKG are NOT published; they are chosen so that
##    (i) 2 mg/kg TIW gives serum ALP in the low thousands of U/L, matching the
##    supraphysiologic activity reported on therapy, and (ii) HA occupancy at
##    the label dose is ~0.19, i.e. inside the linear range so that dose still
##    matters — consistent with the murine bone-targeted dose-response study
##    (PMID 21458605). These four parameters are the model's main PK
##    identifiability gap; treat occupancy as a relative, not absolute, scale.
##
##  PPi / mineralization
##    Healthy plasma PPi ~3 uM and Ki(PPi) for hydroxyapatite growth in the
##    low-micromolar range come from the classical calcification literature
##    (PMIDs 13893487, 6326671); the TNSALP/ENPP1/ANK antagonism that sets the
##    perivesicular balance is from PMIDs 12082181 and 15039209. JPPI is then
##    fixed by requiring PPi_loc = 3 uM at ELOC = 1 — not fitted to outcomes.
##    The resulting osteoid volume fractions (2% healthy -> 9-11% infantile)
##    fall in the histomorphometric osteomalacia range without being fitted.
##
##  Vitamin B6
##    Plasma PLP normal ~30-110 nM and markedly raised in HPP; the requirement
##    for TNSALP to dephosphorylate PLP before it can cross the blood-brain
##    barrier — hence pyridoxine-responsive seizures — is from the Alpl-null
##    mouse (PMIDs 7550313, 9056646) and the clinical reports (PMID 17395561).
##
##  Survival
##    HAZ0 / KHZ / HAZS are calibrated so that untreated perinatal HPP has
##    ~12% and untreated infantile HPP ~51% one-year survival, against ~89% on
##    label-dose asfotase alfa (reported: ~95% treated vs ~27-42% historical
##    control, PMID 26529632). The model is deliberately conservative on the
##    treated arm rather than tuned to match it exactly.
##
##  NOT calibrated / phenomenological
##    Craniosynostosis (KCS, TCS) is a rate law, not a mechanism: HPP
##    craniosynostosis is common and is NOT reliably prevented by ERT, and the
##    model reproduces that only by construction. The calcium homeostat runs
##    near its excretory capacity, which makes serum Ca the most
##    parameter-sensitive output in the model.
## ---------------------------------------------------------------------------

