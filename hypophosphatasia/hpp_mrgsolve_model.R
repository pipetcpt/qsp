dxdt_PLBR = KINBR * FRACENZ * PLPP / (KMBR + PLPP) + KPN * PNDOSE
            - KOUTBR * PLBR;

// --- mineral homeostasis -------------------------------------------------
dxdt_CAS = (JIN - JDEP + JRES - JURN) / VCA;
dxdt_PIS = (PIIN - QPDEP * MAR - JPURN) / VPI;
double PTHTGT = PTH0 * 2.0 / (1.0 + exp(SPTH * (CAS - CA0)));
dxdt_PTHS = (PTHTGT - PTHS) / TAUPTH;
dxdt_VITD = (VITD0 * (1.0 + KPD * (PTHR - 1.0)) - VITD) / TAUD;
double cauex = JURN - CAUTHR; if (cauex < 0.0) cauex = 0.0;
dxdt_NEPH = KNEPH * cauex * (1.0 - NEPH) - KNEPHD * NEPH;

// --- bone matrix ---------------------------------------------------------
dxdt_OST  = KOSTF * OB - KCONS * MAR * OST;
dxdt_BMIN = KBF * MAR * pow(OST / OST0, POWOST) - KBR * OC * BMIN;

// --- growth plate & stature ---------------------------------------------
dxdt_GP = KGPR * fGPrep * (1.0 - GP) - KGPD * fGPdmg * GP;
double kirr = KIRR * (1.0 + KIRRINF * exp(-AGEN / TIRR));
dxdt_GPD = kirr * gpdef * PHYSIS * (1.0 - GPD);
dxdt_RSS = (RSSTGT - RSS) / TAURSS;
double dz = (GROWTHREL - 1.0) * KZ * PHYSIS;
dxdt_HTZ = (HTZ <= -6.0 && dz < 0.0) ? 0.0 : dz;

// --- thorax / respiration / survival ------------------------------------
dxdt_RIB  = KRIBR * fRBrep * (1.0 - RIB) - KRIBD * fRBdmg * RIB;
dxdt_RESP = (RESPTGT - RESP) / TAURESP;
dxdt_SURV = -HAZ * SURV;
dxdt_CUMHAZ = HAZ;

// --- symptoms / other organs --------------------------------------------
dxdt_MUS  = (MUSTGT - MUS) / TAUMUS;
dxdt_PAIN = (PAINTGT - PAIN) / TAUPAIN;
dxdt_DENT = KDR * fDNrep * (1.0 - DENT) - KDD * fDNdmg * DENT;
dxdt_CRAN = KCS * exp(-AGEN / TCS) * (1.0 - 0.3 * mrc) * (1.0 - CRAN);
dxdt_SEIZ = (SEIZTGT - SEIZ) / TAUSEIZ;
double ssx = SSATN - 1.0;        if (ssx < 0.0) ssx = 0.0;
double ppd = 1.0 - PPIL / PPI0;  if (ppd < 0.0) ppd = 0.0;
dxdt_ECT = KECT * ssx * ppd - KECTD * ECT;
double ostr = OST / OST0 - 1.0; if (ostr < 0.0) ostr = 0.0;
dxdt_FX = KFXO * ostr * LOAD * (1.0 + 2.0 * BPB / KIBP) - KFXH * mrc * FX;
dxdt_AUCPPI = PPIL;

[TABLE]
//--- BEGIN SHARED ALGEBRA (duplicate of the [ODE] block; keep in sync) ---
double VCL  = VCKG * WT;
double BMNZ = BMIN > 0.15 ? BMIN : 0.15;
double BMAX = BMAXKG * WT * BMNZ;
double Cp   = AC / VCL;
double OCC  = EB / BMAX;
double ELOC  = FRACENZ * OB + KBONE * OCC;
double ALPUL = ALPN * (FRACENZ * (1.0 - FISO) + FISO) + SPACT * Cp;
double EPL   = ALPUL / ALPN;
double c1a   = FVOL * KOUT;
double c2a   = KCATPP * EPL + CLPPI;
double alph  = KOUT * c2a / (c1a + c2a);
double beta  = KOUT * JPSYS / (c1a + c2a);
double Vm    = KCATP * KMPPI;
double Ssum  = JPPI + beta;
double bq    = Vm * ELOC + alph * KMPPI - Ssum;
double disc  = bq * bq + 4.0 * alph * Ssum * KMPPI;
if (disc < 0.0) disc = 0.0;
double PPIL  = (-bq + sqrt(disc)) / (2.0 * alph);
double PPIP  = (c1a * PPIL + JPSYS) / (c1a + c2a);
double PLPP  = (JPLP + KCATPL * EPL * PLPMIN) / (KCATPL * EPL + CLPL);
double PEAP  = JPEA / (KCATPEA * EPL + CLPEA);
double OPNX  = OPN > 1.0 ? (OPN - 1.0) : 0.0;
double MINH  = 1.0 / (1.0 + PPIL / KIPPI + BPB / KIBP + OPNX * 40.0 / KIOPN);
double MINH0 = 1.0 / (1.0 + PPI0 / KIPPI);
double SSATN = pow((CAS * PIS) / (CA0 * PI0), NSSAT);
double MRELN = MINH / MINH0;
double MAR   = KMIN * OB * MRELN * SSATN;
double PTHR = PTHS / PTH0;
double xca  = CAS - CATHR; if (xca < 0.0) xca = 0.0;
double JURN = QURN * xca / (KURN + xca) / (0.7 + 0.3 * PTHR);
double GP0   = KGPR * (1.0/(1.0+KGP50)) /
               (KGPR * (1.0/(1.0+KGP50)) + KGPD * (KGP50/(1.0+KGP50)));
double RIB0  = KRIBR * (1.0/(1.0+KRIB50)) /
               (KRIBR * (1.0/(1.0+KRIB50)) + KRIBD * (KRIB50/(1.0+KRIB50)));
double DEN0  = KDR * (1.0/(1.0+KD50)) /
               (KDR * (1.0/(1.0+KD50)) + KDD * (KD50/(1.0+KD50)));
double GPREL   = GP / GP0;
double RIBREL  = RIB / RIB0;
double DENTREL = DENT / DEN0;
double AGEN    = AGE0 + TIME;
//--- END SHARED ALGEBRA --------------------------------------------------

double PPILX  = 100.0 * PPIL / PPI0;      // % of healthy perivesicular PPi
double PPIPX  = 100.0 * PPIP / PPI0;      // % of healthy plasma PPi
double PLPX   = 100.0 * PLPP / PLP0;      // % of healthy plasma PLP
double VENT   = RESP < VENTTHR ? 1.0 : 0.0;
double SIXMWT = 100.0 * MUS;              // 6MWT-like, % predicted
double AGEY   = AGEN / 365.0;
double ALPZ   = ALPUL / ALPN;             // serum ALP, x age-normal
double OSTPCT = 100.0 * OST;              // osteoid volume, %

[CAPTURE] @annotated
ELOC   : -, LOCAL TNSALP activity (1 = healthy) — the causal variable
EPL    : -, PLASMA TNSALP activity (1 = healthy) — the measured variable
