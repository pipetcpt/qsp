## ---------------------------------------------------------------------------
## Build
## ---------------------------------------------------------------------------
HPP_mod <- mcode("HPP_QSP", HPP_code)

## ---------------------------------------------------------------------------
## Genotype presets — residual LOCAL TNSALP activity as a fraction of normal.
##
## These are the ONLY disease-severity inputs. The clinical phenotype is an
## OUTPUT: the same equations produce perinatal lethality at 0.01 and an
## asymptomatic carrier at 0.50 (see T1 in the header).
## ---------------------------------------------------------------------------
HPP_genotype <- function(which = c("perinatal", "infantile", "childhood",
                                   "adult", "carrier")) {
  which <- match.arg(which)
  switch(
    which,
    perinatal = list(FRACENZ = 0.010, WT = 3.2,  AGE0 = 1,     HYPOPL = 0.15),
    infantile = list(FRACENZ = 0.030, WT = 5.0,  AGE0 = 14,    HYPOPL = 0.0),
    childhood = list(FRACENZ = 0.120, WT = 18.0, AGE0 = 1825,  HYPOPL = 0.0),
    adult     = list(FRACENZ = 0.350, WT = 70.0, AGE0 = 14600, HYPOPL = 0.0),
    carrier   = list(FRACENZ = 0.500, WT = 70.0, AGE0 = 14600, HYPOPL = 0.0)
  )
}

## ---------------------------------------------------------------------------
## HPP_settle() — the genotype burn-in
##
##   Integrates the UNTREATED genotype to its quasi-steady state with the
##   irreversible / cumulative processes switched off, then zeroes those states.
##   Scenarios start from this state, so an untreated and a treated arm share
##   one continuous trajectory and no "diseased baseline" is ever hand-set.
##
##   Mirrors settle() in hpp_reference_model.py.
## ---------------------------------------------------------------------------
HPP_settle <- function(pars, days = 4000) {
  burn <- modifyList(
    as.list(pars),
    list(KIRR = 0, KCS = 0, HAZ0 = 0, HAZS = 0, GPCLOSE = 1e9,
         KBPIN = 0, ETPTD = 0, EBPOC = 0, PNDOSE = 0, KNEPH = 0)
  )
  out <- as.data.frame(mrgsim(param(HPP_mod, burn), end = days, delta = days))
  last <- out[nrow(out), ]
  cmts <- names(as.list(mrgsolve::init(HPP_mod)))
  y0 <- as.list(setNames(as.numeric(last[cmts]), cmts))
  ## reset cumulative / therapy-dependent states
  for (nm in c("GPD", "HTZ", "CUMHAZ", "AUCPPI", "CRAN", "ECT", "FX", "BPB",
               "NEPH", "ADA", "ASC", "AC", "EB")) y0[[nm]] <- 0
  y0[["SURV"]] <- 1
  y0
}

## ---------------------------------------------------------------------------
## Dosing helpers
## ---------------------------------------------------------------------------
## Asfotase alfa is given SC. Label: 2 mg/kg three times weekly OR 1 mg/kg six
## times weekly; may be increased to 3 mg/kg three times weekly for insufficient
## response in perinatal/infantile disease.
HPP_dosing <- function(mgkg, wt, start = 14, stop = 3650, per_week = 3) {
  if (mgkg <= 0 || per_week <= 0) return(NULL)
  interval <- 7 / per_week
  n <- length(seq(start, stop - 1e-9, by = interval))
  if (n < 1) return(NULL)
  ev(time = start, amt = mgkg * wt, cmt = "ASC", ii = interval, addl = n - 1)
}

## ---------------------------------------------------------------------------
## HPP_run() — one scenario
## ---------------------------------------------------------------------------
HPP_run <- function(sev = "infantile", days = 365, dose = 0, per_week = 3,
                    dstart = 14, dstop = NULL, pn = 0, ada_max = 0.20,
                    tptd = 0, bp = 0, cain_mult = 1, extra = list(),
                    delta = 1) {
  pars <- HPP_genotype(sev)
  pars$PNDOSE <- pn
  pars$ADAMAX <- ada_max
  pars$ETPTD  <- tptd
  pars$CAIN   <- 1.40 * cain_mult
  if (bp > 0) { pars$KBPIN <- bp; pars$EBPOC <- 0.6 }
  pars <- modifyList(pars, extra)

  y0 <- HPP_settle(pars)
  if (is.null(dstop)) dstop <- days
  dos <- HPP_dosing(dose, pars$WT, start = dstart, stop = min(dstop, days),
                    per_week = per_week)

  m <- param(HPP_mod, pars)
  m <- mrgsolve::init(m, y0)
  out <- if (is.null(dos)) mrgsim(m, end = days, delta = delta)
         else mrgsim(m, events = dos, end = days, delta = delta)
  as.data.frame(out)
}

