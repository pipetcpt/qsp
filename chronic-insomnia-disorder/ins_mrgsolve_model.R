##  Chronic Insomnia Disorder (CID) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Chronic insomnia disorder (DSM-5-TR / ICSD-3-TR) — difficulty
##             initiating or maintaining sleep, with daytime consequences,
##             >=3 nights/week for >=3 months, despite adequate opportunity.
##
##             The organising idea of this model is that insomnia is NOT a
##             deficiency of sleep drive. Process S and Process C are close to
##             normal in most patients. What is abnormal is a THIRD process —
##             24-hour HYPERAROUSAL (cortical beta/gamma intrusion, elevated
##             whole-brain metabolic rate, flattened evening cortisol nadir,
##             raised MSNA and reduced HRV) — which raises the wake side of the
##             VLPO/ascending-arousal flip-flop switch. Hypnotics push the
##             switch from the other side. They do not touch arousal, which is
##             why their effect disappears the night they are stopped.
##
##             The model therefore closes the loop that actually makes the
##             disease chronic (Spielman's 3-P model):
##
##                poor night -> lie in bed longer (TIB up) -> Process S is
##                diluted across more hours -> sleep efficiency falls further
##                -> more time awake in bed -> the bed is conditioned as a
##                wake cue (COND up) and sleep effort rises -> arousal rises
##                -> poorer night
##
##             CBT-I is the only intervention in this model that enters that
##             loop: sleep restriction re-concentrates S, stimulus control
##             extinguishes COND, cognitive therapy lowers DBAS, and the
##             gains therefore persist after treatment stops. Every drug in
##             this model acts distal to the loop and its benefit decays with
##             its concentration. Reproducing that asymmetry — same acute
##             effect size, completely different behaviour at 12 months — is
##             the model's main falsifiable claim.
##
