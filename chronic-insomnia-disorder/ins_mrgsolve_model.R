ins_run_scenario <- function(name, weeks = 12, extra = list()) {
  sc <- ins_scenarios()[[name]]
  if (is.null(sc)) stop("unknown scenario: ", name)
  pars <- modifyList(if (is.null(sc$par)) list() else sc$par, extra)
  sim <- ins_simulate(phenotype = sc$pheno, weeks = weeks,
                      treat = pars, events = sc$ev,
                      cbti_start_day = if (is.na(sc$cbti)) NA_real_ else sc$cbti)
  list(sim = sim, nightly = ins_nightly(sim), note = sc$note)
}

ins_run_all <- function(weeks = 12, verbose = TRUE) {
  nms <- names(ins_scenarios())
  out <- lapply(nms, function(n) {
    if (verbose) message("  running: ", n)
    r <- ins_run_scenario(n, weeks = weeks)
    nt <- r$nightly
    wk <- function(w) nt[nt$night >= (w*7 - 6) & nt$night <= w*7, , drop = FALSE]
    smry <- function(d) c(SOL = mean(d$SOL), WASO = mean(d$WASO),
                          TST = mean(d$TST), SE = mean(d$SE),
                          ISI = mean(d$ISI), sTST = mean(d$sTST),
                          N3 = mean(d$N3), REM = mean(d$REM),
                          HANG = mean(d$HANG))
    data.frame(
      scenario = n,
      t(smry(wk(1))) |> as.data.frame() |> setNames(paste0("w1_", c(
        "SOL","WASO","TST","SE","ISI","sTST","N3","REM","HANG"))),
      t(smry(wk(4))) |> as.data.frame() |> setNames(paste0("w4_", c(
        "SOL","WASO","TST","SE","ISI","sTST","N3","REM","HANG"))),
      t(smry(wk(min(weeks, 12)))) |> as.data.frame() |> setNames(paste0("wend_", c(
        "SOL","WASO","TST","SE","ISI","sTST","N3","REM","HANG"))),
      row.names = NULL, check.names = FALSE
    )
  })
  do.call(rbind, out)
}

