##
##  Sleep architecture at week 4 (nightly minutes): the qualitative ordering the
##  model is asked to reproduce is that DORAs raise REM (130-137 vs 88 untreated),
##  ethanol suppresses it (56), trazodone raises N3 (97 vs 86) and BzRA suppress
##  it slightly, and the elderly phenotype has roughly 40% of the young N3 (37).
##  All of these come out in the right direction and rough magnitude.
##
##  ---------------------------------------------------------------------------
##  Calibration notes, and where the model is honest about missing
##  ---------------------------------------------------------------------------
##  * NOTHING in the sleep block is fitted to a sleep metric directly. SOL,
##    WASO, TST and SE are all read out of one continuous sleep-probability
##    variable, and the only knobs used to place a phenotype are A0 (the
##    constitutive arousal of that patient) and the circadian phase peak TPKC.
##    The chronic-insomnia phenotype was placed by matching the LONG-RUN
##    equilibrium (150+ days) of SOL 47 / WASO 100 / TST 399 / SE 74.6% /
##    ISI 18.8 to the pooled baselines of the recent Phase 3 hypnotic
##    programmes, not by matching a 4-week transient.
##
##  * The 3-P loop is genuinely bistable, and this is deliberate rather than
##    incidental. Below roughly A0 = 0.65 the model settles into a good-sleeper
##    basin; above it, conditioned arousal, sleep effort and time-in-bed
##    extension reinforce each other into a chronic basin. That is Spielman's
##    model taken literally: an acute stressor that raises arousal past the
##    threshold does not have to persist for the insomnia to persist.
##    Consequence to be aware of: outcomes are STEEP in A0 near the threshold,
##    so small covariate changes there produce large predicted differences.
##
##  * The untreated arm has NO placebo response. Real trial placebo arms improve
##    LPS by 10-20 min and WASO by 15-25 min, so every "change from control"
##    number above is larger than the corresponding placebo-subtracted trial
##    delta by roughly that amount. The WASO column is where this matters most.
##    Comparisons BETWEEN active arms are the ones this model is built to make.
##
##  * There is a ceiling artefact that must not be over-read. Total sleep time
##    cannot exceed SLPMAX x TIB, so once a hypnotic consolidates sleep to near
##    continuity every effective drug converges on TST 465 min and SE 87.6% at
##    a fixed 8.85 h time in bed. The model therefore CANNOT rank suvorexant,
##    lemborexant, daridorexant 50 mg and zolpidem on total sleep time; it can
##    only rank them on latency, on the shape of the night, on residual
##    sedation and on what happens when the drug is stopped. Those are the
##    comparisons the arms are designed for.
##
##  * Awakenings are not stochastic. WASO emerges from an ultradian oscillator
##    whose phase advances only during sleep meeting a sleep drive whose margin
##    over the switch threshold has been eroded by arousal. This reproduces the
##    clinical observation that fragmentation is concentrated in the last third
##    of the night (Process S has dissipated, cortisol is rising, and the
##    ultradian troughs deepen), but it means the model produces the same
##    awakening pattern every night for a given patient.
##
##  * Tolerance is modelled only for the GABA-A benzodiazepine site, because
##    that is the only one of these mechanisms with a consistent tolerance and
##    rebound signal. Scenario 2 shows the intended behaviour: 4 weeks of
##    nightly zolpidem builds TOLB to 0.55, the ISI benefit is already eroding
##    by week 4, and stopping produces a rebound overshoot that leaves the
##    patient at week 12 slightly WORSE than the untreated arm (ISI 22.0 vs
##    19.7), because the rebound nights re-condition the bed. That last part is
##    a model prediction, not a fitted result.
##
##  * The single most important claim the model makes is the CBT-I / hypnotic
##    asymmetry, and it is structural rather than tuned. Both classes produce a
##    similar ISI drop at week 4. CBT-I does it by removing terms from the
##    arousal equation (COND, SEFF, DBAS) and by compressing TIB, so its effect
##    is still there at week 12 with nothing being taken. Zolpidem does it by
##    adding a term that is proportional to a concentration, so its effect is
##    gone the night the concentration is. No parameter in the model was set to
##    make that happen; it follows from where the two act.
##
##  * CBT-I is, if anything, still too good here (ISI 6.4 at week 4, 4.9 at week
##    12, i.e. a full responder). Real CBT-I trials report roughly 60-70%
##    response and 40-50% remission, which a single deterministic patient
##    cannot represent. Read arm 13 as "the trajectory of a CBT-I responder",
##    not as the average of a trial arm.
##
##  * The circadian block entrains rather than being imposed. PHI is a state
##    driven by an intrinsic period of 24.18 h against a sinusoidal light PRC,
##    so the entrained phase angle is an OUTPUT. This is why the bright-light
##    arm works at all (scenario 17 advances the delayed-phase patient and cuts
##    SOL from 181 to 116 min over 12 weeks without any sedative effect) and
##    why the delayed-phase phenotype is produced by changing the intrinsic
##    period and the evening light, not by moving the sleep metrics.
##
##  * Melatonin is carried in pg/mL and shares one receptor pool between the
##    endogenous pineal signal (nocturnal peak ~60 pg/mL), exogenous melatonin
##    and ramelteon plus its M-II metabolite. This is what makes the elderly
##    melatonin arm behave correctly: replacing a pineal output that is 35% of
##    young shortens latency by 14 min and does nothing at all to WASO, which
##    is exactly the shape of the clinical evidence.
##
##  * All volumes and clearances are APPARENT (V/F, CL/F). The F parameters are
##    retained for documentation only and are not applied a second time.
##  ============================================================================
