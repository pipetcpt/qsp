## ============================================================================
##  DOSING HELPERS
##  All hypnotics are given at BEDHOUR each evening; caffeine and light are
##  given on their own clock. `days` is the number of nights of treatment,
##  `start_day` the first treated day (day 1 = first simulated day).
## ============================================================================

ev_nightly <- function(cmt, amt, days, start_day = 1, bedhour = 22.0,
                       every = 1) {
  if (days <= 0) return(NULL)
  nights <- seq(0, days - 1, by = every)
  mrgsolve::ev(
    time = (start_day - 1 + nights)*24 + bedhour,
    amt  = amt, cmt = cmt, evid = 1
  )
}

ev_daily <- function(cmt, amt, days, start_day = 1, hour = 8) {
  if (days <= 0) return(NULL)
  mrgsolve::ev(
    time = (start_day - 1 + seq(0, days - 1))*24 + hour,
    amt  = amt, cmt = cmt, evid = 1
  )
}

`%+%` <- function(a, b) {
  if (is.null(a)) return(b)
  if (is.null(b)) return(a)
  a + b
}

## ============================================================================
##  SIMULATION DRIVER
##  A 21-day unmedicated lead-in is always simulated first so that the
##  perpetuating loop (COND, DBAS, SEFF, TIB, ISI, MISP) reaches the state that
##  actually corresponds to the phenotype. Only the post-lead-in window is
##  returned, with TIME re-zeroed at randomisation.
## ============================================================================

ins_simulate <- function(phenotype = "chronic_insomnia",
                         weeks = 12,
                         param = list(),
                         treat = list(),
                         events = NULL,
                         cbti_start_day = NA_real_,
                         leadin_days = 150,
                         delta = 0.25) {

  pheno <- if (is.character(phenotype)) ins_phenotype(phenotype) else phenotype
  pars  <- modifyList(pheno, param)

  m <- mod_ins
  if (length(pars)) m <- mrgsolve::param(m, pars)

  ## ---- lead-in: same patient, no drug, no CBT-I --------------------------
  cmts <- names(as.list(mrgsolve::init(mod_ins)))
  m0   <- mrgsolve::param(m, CBTION = 0, USEINIT = 1)
  li   <- as.data.frame(mrgsolve::mrgsim(m0, end = leadin_days*24, delta = 1,
                                         recover = "numeric", obsonly = TRUE))
  init_vec <- as.list(unlist(li[nrow(li), cmts]))

  ## ---- randomised phase, started from the lead-in end state ---------------
  cb <- if (is.na(cbti_start_day)) list(CBTION = 0, CBTIT0 = 1e6)
        else list(CBTION = 1, CBTIT0 = (cbti_start_day - 1)*24)
  ## `treat` holds anything that is switched on AT randomisation (light
  ## therapy, a CYP inhibitor, a schedule change) and must therefore NOT be
  ## present during the lead-in, or the arm silently becomes its own control.
  m1 <- mrgsolve::param(m, c(list(USEINIT = 0), cb, treat))
  m1 <- mrgsolve::init(m1, init_vec)

  end <- weeks*7*24
  out <- if (is.null(events)) {
    mrgsolve::mrgsim(m1, end = end, delta = delta, recover = "numeric")
  } else {
    mrgsolve::mrgsim(m1, events = events, end = end, delta = delta,
                     recover = "numeric")
  }
  as.data.frame(out)
}

## ============================================================================
##  NIGHTLY SUMMARY
##  The cumulative counters are differenced across "sleep days" that run from
##  midday to midday, so that a night is never split by the day boundary.
## ============================================================================

ins_nightly <- function(sim, split_hour = 12) {
  need <- c("time", "SOLCUM", "WASOCM", "TSTCUM", "NAWCUM", "RESCUM")
  stopifnot(all(need %in% names(sim)))
  brk <- sim[["time"]] %% 24
  night <- floor((sim[["time"]] - split_hour)/24) + 1
  d <- sim
  d$night <- night
  agg <- d %>%
    dplyr::group_by(night) %>%
    dplyr::summarise(
      t_end   = max(time),
      SOL     = max(SOLCUM) - min(SOLCUM),
      WASO    = max(WASOCM) - min(WASOCM),
      TST     = max(TSTCUM) - min(TSTCUM),
      NAW     = max(NAWCUM) - min(NAWCUM),
      RESID   = max(RESCUM) - min(RESCUM),
      TIB     = 60*mean(TIBS),
      ISI     = dplyr::last(ISI),
      SEbar   = dplyr::last(SEBAR),
      sTST    = dplyr::last(sTST),
      sSOL    = dplyr::last(sSOL),
      sWASO   = dplyr::last(sWASO),
      MISP    = dplyr::last(MISP),
      AROU    = mean(AROU),
      COND    = dplyr::last(COND),
      DBAS    = dplyr::last(DBAS),
      TOLB    = dplyr::last(TOLB),
      WDR     = dplyr::last(WDR),
      N3      = dplyr::last(N3BAR),
      REM     = dplyr::last(REMBAR),
      HANG    = max(HANG),
      .groups = "drop"
    ) %>%
    dplyr::mutate(SE = 100*TST/pmax(TIB, 1))
  agg <- agg[agg$night >= 1, ]
  agg$night <- agg$night - min(agg$night) + 1
  ## drop the last partial night
  agg[-nrow(agg), ]
}

