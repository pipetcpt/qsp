// Smooth in-window indicator on a 24-h circle. Handles both the wrapping
// case (bedtime after midnight boundary) and the non-wrapping case, and is
// continuous as the window edge crosses midnight.
double inwin(double tod, double t0, double t1, double sh) {
  double a = 1.0/(1.0 + exp(-(tod - t0)/sh));
  double b = 1.0/(1.0 + exp(-(tod - t1)/sh));
  if (t0 > t1) {                       // window wraps midnight
    double u = a + (1.0 - b) - a*(1.0 - b);
    return u;
  }
  return a*(1.0 - b);
}

double clamp01(double x, double lo, double hi) {
  if (x < lo) return lo;
  if (x > hi) return hi;
  return x;
}

