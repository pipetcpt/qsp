  AROU_0   = A0;
  CRH_0    = 1.00;
  ACTH_0   = 1.00;
  CORT_0   = CORT0;
  TIBS_0   = TIB0;
  DBAS_0   = DBAS0;
  SEFF_0   = SEFF0;
  SOLBAR_0 = 20.0;
  WASOBR_0 = 25.0;
  TSTBAR_0 = 400.0;
  SEBAR_0  = 0.85;
  N3BAR_0  = 80.0;
  REMBAR_0 = 95.0;
  MISP_0   = MISP0;
  ISI_0    = 6.0;
  DEP_0    = DEP0;
  IL6_0    = IL60;
}

$ODE
double tt  = SOLVERTIME;
double tod = tt - 24.0*floor(tt/24.0);

// ---------------------------------------------------------- bed schedule ---
double bedt = WAKET + 24.0 - TIBS;
bedt = bedt - 24.0*floor(bedt/24.0);
double inBed = inwin(tod, bedt, WAKET, SHBED);
double napwin = NAPW*inwin(tod, NAPT0, NAPT0 + NAPDUR, 0.2);

// ---------------------------------------------------------------- light ----
double dayw = inwin(tod, WAKET, EVEHR, 0.25);
double blt  = BLTON*inwin(tod, BLTT0, BLTT0 + BLTDUR, 0.15);
double lux  = inBed*LUXBED
            + (1.0 - inBed)*(dayw*LUXDAY + (1.0 - dayw)*LUXEVE)
            + blt*BLTLUX;

// ------------------------------------------------------------ circadian ----
double ct    = tod - PHI;
double Cwake = AMPC*cos(TWOPI*(ct - TPKC)/24.0);
double prcL  = -sin(TWOPI*(ct - 5.0)/24.0);   // + = delay, - = advance
double prcM  =  sin(TWOPI*(ct - 5.0)/24.0);   // melatonin PRC ~ inverse of light
double mgate = cos(TWOPI*(ct - 3.0)/24.0);
mgate = (mgate > 0.0) ? mgate*mgate : 0.0;
double msupp = 1.0/(1.0 + lux/LUX50);

// -------------------------------------------------------- concentrations ---
double CZOL = ZOLC/VZOL;
double CESZ = ESZC/VESZ;
double CSUV = SUVC/VSUV;
double CLEM = LEMC/VLEM;
double CDAR = DARC/VDAR;
double CRAM = RAMC/VRAM;
double CRM2 = RAMM/VRM2;
double CMLX = (MELC/VMEL)*1.0e6;              // pg/mL
double CDOX = DOXC/VDOX;
double CTRZ = TRZC/VTRZ;
double CCAF = CAFC/VCAF;
double CETH = ETHC/VETH;

// ------------------------------------------------------- target binding ----
double occBZraw = CZOL/EC50ZOL + CESZ/EC50ESZ + CETH/EC50ETH;
double occBZ    = occBZraw/(1.0 + occBZraw);
double Ebz      = EMAXBZ*occBZ/(1.0 + TOLB);

double occOXraw = CSUV/EC50SUV + CLEM/EC50LEM + CDAR/EC50DAR;
double oxBlk    = occOXraw/(1.0 + occOXraw);

double occMTraw = MELP/EC50MLE + CMLX/EC50MLX + CRAM/EC50RAM + CRM2/EC50RM2;
double occMT    = occMTraw/(1.0 + occMTraw);
double Emt      = EMAXMT*occMT;

double h1raw = CDOX/EC50DOX + CTRZ/EC50TZH;
double h1blk = h1raw/(1.0 + h1raw);
double e5ht  = (CTRZ/EC50TZ5)/(1.0 + CTRZ/EC50TZ5);
double a1blk = (CTRZ/EC50TZA)/(1.0 + CTRZ/EC50TZA);

// ------------------------------------------------------------- CBT-I -------
// A smooth ramp rather than a step: CBT-I is delivered over sessions, and a
// discontinuous parameter would also be unkind to the solver.
double CBTI  = CBTION/(1.0 + exp(-(tt - CBTIT0)/CBTIRMP));
double srt   = CBTI*WSRT;
double stimc = CBTI*WSTIMC;
double cogth = CBTI*WCOGTH;
double relax = CBTI*WRELAX;
double mindf = CBTI*WMINDF;

// -------------------------------------------------------- wake drive -------
double oxEff = OXA*(1.0 - oxBlk);
double haEff = HA*(1.0 - h1blk);
double Wdrv  = WNE*(NE/NE0)*(1.0 - 0.55*a1blk)
             + WHA*(haEff/HA0)
             + WOX*(oxEff/OX0);

// ---------------------------------------------------------- arousal --------
double Adrug = GADESZ*(CESZ/EC50ESZ)/(1.0 + CESZ/EC50ESZ)
             + GADTRZ*e5ht + GADDOX*h1blk;
double Atgt  = A0
             + GCOND*COND*inBed
             + GSEFF*SEFF*inBed
             + GDBAS*DBAS
             + GCORT*(CORT/CORT0 - 1.0)
             + GSTR*STR
             + GREB*WDR
             + GETRB*ETRB
             + GDEP*(DEP - DEP0)
             + GPAIN*PAIN
             + GVMS*VMS
             - GRELAX*relax
             - Adrug;
if (Atgt < 0.02) Atgt = 0.02;
dxdt_AROU = (Atgt - AROU)/TAUAR;

// ------------------------------------------------- the sleep switch --------
// Ultradian NREM-REM oscillator. Its phase only advances while asleep, so it
// is effectively reset at each sleep onset. Awakenings are not stochastic in
// this model: they occur when an ultradian trough (a REM or light-N2 window,
// deepening as Process S dissipates) meets a sleep drive whose margin over
// the switch threshold has already been eroded by arousal.
double ultgain = 0.55 + 0.90*(KSREM/(S + KSREM));
double ultra   = AULT*0.5*(ULTA + 1.0)*ultgain;
double adoEff = ADO/(1.0 + CCAF/KICAF);
double drive  = WS*S + WADO*adoEff + Emt + Ebz + E5HT*e5ht
              - WCBT*CBTD - Cwake - AROU - Wdrv - ultra - SWTH;
double opp    = inBed + (1.0 - inBed)*napwin;
if (opp > 1.0) opp = 1.0;
double SLP    = opp*SLPMAX/(1.0 + exp(-drive/KSHARP));

// ------------------------------------------------------ two-process core ---
double taudEff = TAUD*(1.0 + GN3BZ*occBZ)/(1.0 + GN35HT*e5ht + GN3GBP*GBPON);
dxdt_S   = (1.0 - SLP)*(SMAX - S)/TAUR - SLP*S/taudEff;
dxdt_ADO = KADOIN*(1.0 - SLP) - KADOOUT*ADO;

// -------------------------------------------------------- flip-flop --------
double neTgt = NE0*(NESLP + (1.0 - NESLP)*(1.0 - SLP))
                  *(1.0 + GOXNE*(oxEff/OX0 - 1.0))
                  *(1.0 + 0.25*(AROU/A0 - 1.0));
double haTgt = HA0*(HASLP + (1.0 - HASLP)*(1.0 - SLP))
                  *(1.0 + GOXHA*(oxEff/OX0 - 1.0));
double oxTgt = OX0*(OXSLP + (1.0 - OXSLP)*(1.0 - SLP))
                  *(1.0 + 0.25*Cwake/AMPC);
if (neTgt < 0.0) neTgt = 0.0;
if (haTgt < 0.0) haTgt = 0.0;
if (oxTgt < 0.0) oxTgt = 0.0;
double ultw = 6.283185307179586/PULT;
dxdt_ULTA =  SLP*ultw*ULTB;
dxdt_ULTB = -SLP*ultw*ULTA;
dxdt_NE  = (neTgt - NE )/TAUNE;
dxdt_HA  = (haTgt - HA )/TAUHA;
dxdt_OXA = (oxTgt - OXA)/TAUOX;

// -------------------------------------------------------- circadian ODEs ---
dxdt_MELP = KMELS*mgate*msupp*FMELAGE - KMELE*MELP;
dxdt_PHI  = (TAUINT - 24.0)/24.0
          + KLIGHT*prcL*log(1.0 + lux/LUXREF)
          + KMELPH*prcM*(MELP + CMLX)/1000.0;
double cbTgt = -AMPT*cos(TWOPI*(ct - 5.0)/24.0) - DROPT*SLP;
dxdt_CBTD = (cbTgt - CBTD)/TAUCBT;

// -------------------------------------------------------------- HPA --------
double circC = 1.0 + AMPCOR*cos(TWOPI*(ct - TPKCOR)/24.0);
if (circC < 0.05) circC = 0.05;
double fb = 1.0/(1.0 + FBGR*pow(CORT/IC50C, HILLC));
dxdt_CRH  = KINCRH*circC*(1.0 + ASTR*STR + AARO*(AROU/A0 - 1.0))*fb
          - KOUTCRH*CRH;
dxdt_ACTH = KINACT*CRH*fb - KOUTACT*ACTH;
dxdt_CORT = KINCOR*ACTH - KOUTCOR*CORT;
dxdt_STR  = -KSTRD*STR;

// ---------------------------------------------------- perpetuating loop ----
dxdt_COND = KCIN*inBed*(1.0 - SLP)*(CONDMAX - COND)
          - (KCOUT + KCSTIM*stimc + KCEXT*inBed*SLP)*COND;

double seffTgt = SEFF0 + GSEDBAS*DBAS + GSESOL*(SOLBAR/60.0) - GSEMIND*mindf;
if (seffTgt < 0.0) seffTgt = 0.0;
dxdt_SEFF = (seffTgt - SEFF)/TAUSE;

double dbasTgt = DBAS0 + GDBISI*(ISI/28.0) - GDBCOG*cogth;
if (dbasTgt < 0.0) dbasTgt = 0.0;
dxdt_DBAS = (dbasTgt - DBAS)/TAUDB;

// Maladaptive extension is an integrator, but not an unbounded one: the
// patient also drifts back toward their habitual schedule. Without that
// restoring term the untreated arm has no interior equilibrium at all and
// every insomniac ends the simulation pinned at TIBMAX.
double seGap = SETGT - SEBAR;
double dTIB;
if (CBTI > 0.5) {
  dTIB = KTIBUP*srt*((seGap < 0.0) ? -seGap : 0.0)*(TIBMAX - TIBS)
       - KTIBDN*srt*((seGap > 0.0) ?  seGap : 0.0)*(TIBS  - TIBMIN);
} else {
  dTIB = KTIBEXT*((seGap > 0.0) ? seGap : 0.0) - KTIBREL*(TIBS - TIB0);
}
if (TIBS >= TIBMAX && dTIB > 0.0) dTIB = 0.0;
if (TIBS <= TIBMIN && dTIB < 0.0) dTIB = 0.0;
dxdt_TIBS = dTIB;

// ------------------------------------------------------ drug adaptation ----
dxdt_TOLB = KTOLIN*occBZ*(TOLMAX - TOLB) - KTOLOUT*TOLB;
double wdrDrv = TOLB*((occBZ < OCCREF) ? (1.0 - occBZ/OCCREF) : 0.0);
dxdt_WDR  = (wdrDrv - WDR)/TAUWDR;
double etRb = KETIN*CETH - KETOUT*ETRB;
dxdt_ETRB = etRb - GET2*KETOUT*ETRB*CETH;

// ----------------------------------------------------------------- PK ------
dxdt_ZOLD = -KAZOL*ZOLD;
dxdt_ZOLC =  KAZOL*ZOLD - (CLZOL*CYP3A/VZOL)*ZOLC;
dxdt_ESZD = -KAESZ*ESZD;
dxdt_ESZC =  KAESZ*ESZD - (CLESZ*CYP3A/VESZ)*ESZC;
dxdt_SUVD = -KASUV*SUVD;
dxdt_SUVC =  KASUV*SUVD - (CLSUV*CYP3A/VSUV)*SUVC;
dxdt_LEMD = -KALEM*LEMD;
dxdt_LEMC =  KALEM*LEMD - (CLLEM*CYP3A/VLEM)*LEMC;
dxdt_DARD = -KADAR*DARD;
dxdt_DARC =  KADAR*DARD - (CLDAR*CYP3A/VDAR)*DARC;
dxdt_RAMD = -KARAM*RAMD;
dxdt_RAMC =  KARAM*RAMD - (CLRAM/VRAM)*RAMC;
dxdt_RAMM =  FMM2*(CLRAM/VRAM)*RAMC - (CLRM2/VRM2)*RAMM;
dxdt_MELD = -KAMEL*MELD;
dxdt_MELC =  KAMEL*MELD - (CLMEL/VMEL)*MELC;
dxdt_DOXD = -KADOX*DOXD;
dxdt_DOXC =  KADOX*DOXD - (CLDOX/VDOX)*DOXC;
dxdt_TRZD = -KATRZ*TRZD;
dxdt_TRZC =  KATRZ*TRZD - (CLTRZ*CYP3A/VTRZ)*TRZC;
dxdt_CAFD = -KACAF*CAFD;
dxdt_CAFC =  KACAF*CAFD - (CLCAF/VCAF)*CAFC;
dxdt_ETHD = -KAETH*ETHD;
dxdt_ETHC =  KAETH*ETHD - VMETH*ETHC/(KMETH*VETH + ETHC);

// ----------------------------------------------- sleep measurement ---------
dxdt_ONS = 6.0*SLP*inBed*(1.0 - ONS) - 3.0*(1.0 - inBed)*ONS;

double rSOL  = 60.0*inBed*(1.0 - ONS);
double rWASO = 60.0*inBed*ONS*(1.0 - SLP);
double rTST  = 60.0*SLP;
double rNAW  = inBed*ONS*(1.0 - SLP)/MAWD;

// sleep architecture -------------------------------------------------------
double pN3 = PN3MAX*(S/(S + KSN3))
                   *(1.0 + GN35HT*e5ht + GN3GBP*GBPON)
                   *(1.0 - GN3BZ*occBZ)*FN3AGE;
double remCirc = 1.0 + 0.35*cos(TWOPI*(ct - 6.0)/24.0);
double pREM = PREMAX*(KSREM/(S + KSREM))*remCirc
                    *(1.0 + GREDOR*oxBlk)
                    *(1.0 - GREBZ*occBZ)
                    *(1.0 - GRETRZ*e5ht)
                    *(1.0 - GREETH*CETH/(CETH + 0.30));
pN3  = clamp01(pN3 , 0.0, 0.55);
pREM = clamp01(pREM, 0.0, 0.45);
double pSum = pN3 + pREM;
if (pSum > 0.80) { pN3 *= 0.80/pSum; pREM *= 0.80/pSum; }

double sedIdx = Ebz + Emt + E5HT*e5ht + WOX*oxBlk + WHA*h1blk;

dxdt_SOLCUM = rSOL;
dxdt_WASOCM = rWASO;
dxdt_TSTCUM = rTST;
dxdt_NAWCUM = rNAW;
dxdt_RESCUM = 60.0*(1.0 - inBed)*sedIdx;

dxdt_SOLBAR = (rSOL *24.0 - SOLBAR)/TAUEW;
dxdt_WASOBR = (rWASO*24.0 - WASOBR)/TAUEW;
dxdt_TSTBAR = (rTST *24.0 - TSTBAR)/TAUEW;
dxdt_SEBAR  = (SLP*inBed*24.0/TIBS - SEBAR)/TAUEW;
dxdt_N3BAR  = (60.0*SLP*pN3 *24.0 - N3BAR )/TAUEW;
dxdt_REMBAR = (60.0*SLP*pREM*24.0 - REMBAR)/TAUEW;
dxdt_RESBAR = ((1.0 - inBed)*sedIdx*24.0/(24.0 - TIBS) - RESBAR)/TAUEW;

// ------------------------------------------------------- consequences ------
double frag = WASOBR/(WASOBR + 30.0);
double mispTgt = MISP0 + GMIAR*(AROU/A0 - 1.0)*0.5 + GMIFR*frag - GMICOG*cogth;
mispTgt = clamp01(mispTgt, 0.0, 0.70);
dxdt_MISP = (mispTgt - MISP)/TAUMI;

double sSOL  = SOLBAR*(1.0 + MISPS*MISP);
double sWASO = WASOBR*(1.0 + MISPS*MISP);
double sTST  = TSTBAR*(1.0 - MISP);
double debt  = (TSTNEED - TSTBAR); if (debt < 0.0) debt = 0.0;
double dayImp = debt/TSTNEED + RESBAR;
double isiTgt = ASOL*sSOL + AWASO*sWASO
              + ATST*((TSTNEED - sTST) > 0.0 ? (TSTNEED - sTST) : 0.0)
              + ADBAS*DBAS + ADAY*dayImp + AAR*(AROU/A0 - 1.0);
isiTgt = clamp01(isiTgt, 0.0, 28.0);
dxdt_ISI = (isiTgt - ISI)/TAUISI;

double depTgt = DEP0 + GDEPISI*(ISI/28.0);
dxdt_DEP = (depTgt - DEP)/TAUDEP;

double il6Tgt = IL60*(1.0 + GILTST*debt/TSTNEED + GILCOR*(CORT/CORT0 - 1.0));
if (il6Tgt < 0.2) il6Tgt = 0.2;
dxdt_IL6 = (il6Tgt - IL6)/TAUIL;

double n3Gap = 1.0 - N3BAR/N3REF; if (n3Gap < 0.0) n3Gap = 0.0;
dxdt_GLYM = KGIN*n3Gap - KGOUT*GLYM;

$TABLE
// The instantaneous quantities below are recomputed from the states and
// parameters so that they are exact at the output time. mrgsolve hoists
// block-local `double` declarations to a shared scope, so the names first
// declared in $ODE are assigned (not re-declared) here.
tod = TIME - 24.0*floor(TIME/24.0);
bedt = WAKET + 24.0 - TIBS;
bedt = bedt - 24.0*floor(bedt/24.0);
inBed = inwin(tod, bedt, WAKET, SHBED);
napwin = NAPW*inwin(tod, NAPT0, NAPT0 + NAPDUR, 0.2);
dayw = inwin(tod, WAKET, EVEHR, 0.25);
blt  = BLTON*inwin(tod, BLTT0, BLTT0 + BLTDUR, 0.15);
lux  = inBed*LUXBED + (1.0 - inBed)*(dayw*LUXDAY + (1.0 - dayw)*LUXEVE)
     + blt*BLTLUX;
ct    = tod - PHI;
Cwake = AMPC*cos(TWOPI*(ct - TPKC)/24.0);

CZOL = ZOLC/VZOL;
CESZ = ESZC/VESZ;
CSUV = SUVC/VSUV;
CLEM = LEMC/VLEM;
CDAR = DARC/VDAR;
CRAM = RAMC/VRAM;
CRM2 = RAMM/VRM2;
CMLX = (MELC/VMEL)*1.0e6;
CDOX = DOXC/VDOX;
CTRZ = TRZC/VTRZ;
CCAF = CAFC/VCAF;
CETH = ETHC/VETH;

occBZraw = CZOL/EC50ZOL + CESZ/EC50ESZ + CETH/EC50ETH;
occBZ    = occBZraw/(1.0 + occBZraw);
Ebz      = EMAXBZ*occBZ/(1.0 + TOLB);
occOXraw = CSUV/EC50SUV + CLEM/EC50LEM + CDAR/EC50DAR;
oxBlk    = occOXraw/(1.0 + occOXraw);
occMTraw = MELP/EC50MLE + CMLX/EC50MLX + CRAM/EC50RAM + CRM2/EC50RM2;
occMT    = occMTraw/(1.0 + occMTraw);
Emt      = EMAXMT*occMT;
h1raw = CDOX/EC50DOX + CTRZ/EC50TZH;
h1blk = h1raw/(1.0 + h1raw);
e5ht  = (CTRZ/EC50TZ5)/(1.0 + CTRZ/EC50TZ5);
a1blk = (CTRZ/EC50TZA)/(1.0 + CTRZ/EC50TZA);

oxEff = OXA*(1.0 - oxBlk);
haEff = HA*(1.0 - h1blk);
Wdrv  = WNE*(NE/NE0)*(1.0 - 0.55*a1blk) + WHA*(haEff/HA0) + WOX*(oxEff/OX0);
ultgain = 0.55 + 0.90*(KSREM/(S + KSREM));
ultra   = AULT*0.5*(ULTA + 1.0)*ultgain;
adoEff = ADO/(1.0 + CCAF/KICAF);
drive  = WS*S + WADO*adoEff + Emt + Ebz + E5HT*e5ht
       - WCBT*CBTD - Cwake - AROU - Wdrv - ultra - SWTH;
opp    = inBed + (1.0 - inBed)*napwin;
if (opp > 1.0) opp = 1.0;
SLP    = opp*SLPMAX/(1.0 + exp(-drive/KSHARP));

sedIdx = Ebz + Emt + E5HT*e5ht + WOX*oxBlk + WHA*h1blk;
sSOL  = SOLBAR*(1.0 + MISPS*MISP);
sWASO = WASOBR*(1.0 + MISPS*MISP);
sTST  = TSTBAR*(1.0 - MISP);
double SEpct = 100.0*SEBAR;
double NAWn  = WASOBR/60.0/MAWD;
double N3pct = 100.0*N3BAR/(TSTBAR + 1.0e-6);
double REMpct= 100.0*REMBAR/(TSTBAR + 1.0e-6);
double PSQI  = clamp01(1.0 + 0.62*ISI, 0.0, 21.0);
double REMIT = (ISI < 8.0 && SEBAR > 0.85) ? 1.0 : 0.0;
double TEMPC = 36.80 + CBTD;
double HANG  = 100.0*clamp01(sedIdx/1.5, 0.0, 1.0);

