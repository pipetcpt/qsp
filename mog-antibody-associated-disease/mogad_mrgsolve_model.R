##  CALIBRATION NOTES — what was fitted, to what, and what the model MISSES
##  ============================================================================
##  Every number below is printed by `python3 mogad_reference_impl.py`.
##
##  ---- Anchors used (all from published cohorts) ----
##  * Vilaseca 2026 JAMA Neurol (PMID 42440328; Americas MOGAD Treatment Group,
##    n = 116 on IL-6R blockade vs n = 59 on IVIG): relapsing MOGAD ARR before
##    preventive therapy 0.64 (95% CI 0.58-0.70); ARR on IL-6R blockade 0.09
##    (0.06-0.14); ARR on IVIG 0.22 (0.15-0.32); after IPTW, IL-6R blockade was
##    NOT significantly different from IVIG >= 1 g/kg q4wk (HR 2.0, 0.8-4.5) but
##    was better than lower-dose IVIG (HR 4.5, 2.0-9.8).
##      -> LAM0 was set so that the untreated inter-attack ARR is 0.64 exactly.
##  * Chen 2022 JAMA Neurol (PMID 35377395): maintenance IVIG; relapse in 5/29
##    (17%) at >= 1 g/kg q4wk vs 15/30 (50%) at lower/less frequent dosing
##    (HR 3.31).  -> reproduced qualitatively: model ARR 0.18 at 1 g/kg q4wk
##    vs 0.37 at 0.4 g/kg q8wk (scenarios S7 vs S8).
##  * Chen 2020 Neurology (PMID 32554760) and Thakolwiboon 2021 meta-analysis
##    (PMID 34634625): on-treatment ARR ~0.59-0.63 (rituximab), ~0.67-0.84
##    (mycophenolate), ~0.2-0.29 (azathioprine), ~0.08 (maintenance IVIG);
##    relapse still occurs in ~49-74% on the antimetabolites and rituximab.
##  * Chen 2018 Am J Ophthalmol (PMID 30055153): MOG-ON — VA at nadir of the
##    worst attack averaged count-fingers, average FINAL VA 20/30, only 6%
##    ended <= 20/200; disc oedema and pain each 86%; perineural enhancement
##    50%; longitudinally extensive 80%; persistent seropositivity 61/62.
##  * Dubey 2019 JAMA Neurol (PMID 30575890): MOG myelitis — ~1/3 wheelchair-
##    dependent at nadir yet recovering better than AQP4-IgG myelitis;
##    CSF oligoclonal bands in only 1/38.
##  * Stiebel-Kalish 2017 PLoS One (PMID 28125740): RNFL better preserved after
##    MOG-IgG than AQP4-IgG optic neuritis.
##  * Marignier 2025 JNNP (PMID 39939136) / Mariotto 2019 JNNP (PMID 30952681):
##    serum NfL rises with attack severity in MOGAD while serum GFAP stays low,
##    in contrast to AQP4-IgG NMOSD.
##  * Lledo-Garcia 2022 CPT PSP (PMID 34735735): anti-FcRn (rozanolixizumab)
##    PK/PD — total IgG reductions of roughly 50-70% at clinical doses; FRN_INH
##    was set to give ~53% total-IgG reduction at steady state (10.0 -> 4.7 g/L).
##  * Remlinger 2022 NNN (PMID 35027475): anti-FcRn treatment ameliorates
##    MOG-IgG-associated EAE — the mechanistic basis for the FcRn arm.
##
##  ---- What the model reproduces (365-day horizon, index optic neuritis) ----
##  Therapy                     model ARR   observed ARR (source)
##    none (steroid wean only)     0.64       0.64  (0.58-0.70) Vilaseca 2026
##    maintenance IVIG 1 g/kg      0.18       0.22  (0.15-0.32) Vilaseca 2026
##    IL-6R blockade               0.23       0.09  (0.06-0.14) Vilaseca 2026
##    rituximab                    0.48       0.59-0.63         Chen 2020/meta
##    mycophenolate                0.49       0.67-0.84         Chen 2020/meta
##  Attack course (S4): VA nadir logMAR 1.60 (~20/800) -> 0.37 at 1 year
##    (~20/47); RNFL 98 -> 75 um; serum NfL 8 -> peak 160 pg/mL; serum GFAP
##    peak 150 pg/mL; CSF peak 72 cells/uL; surviving oligodendrocytes 0.88.
##  AQP4 comparator (S15, AQP4_MODE = 1, identical attack and steroids):
##    oligodendrocytes fall to 0.07, VA settles at logMAR 0.79 (~20/122)
##    instead of 0.37, RNFL 63 instead of 75 um, and serum GFAP peaks at
##    3661 instead of 150 pg/mL. The MOGAD-vs-NMOSD recovery gap and the
##    sGFAP discrimination both fall out of the single KOLD/AQP4_OLD switch.
##
##  ---- The result the structure forces (commitment 3) ----
##  Titre reduction does NOT predict relapse protection:
##    therapy              titre vs none   ARR vs none
##      maintenance IVIG        0.76           0.28
##      rituximab               0.70           0.75
##      IL-6R blockade          0.59           0.35
##      mycophenolate           0.79           0.77
##      FcRn inhibitor          0.47           0.39
##      C5 inhibitor            1.00           0.75
##  Rituximab lowers the measured titre MORE than IVIG does and yet prevents
##  far fewer relapses; the C5 inhibitor lowers the titre not at all and still
##  helps. Under a threshold hazard (HAZ_H = 3) with the baseline titre on the
##  Hill plateau, what matters is whether an intervention takes the
##  FUNCTIONALLY ACTIVE antibody past the threshold — so effector- and
##  clearance-node drugs outperform source-node drugs at equal titre effect.
##  Falsifiable consequence: serial MOG-IgG titres should be a poor surrogate
##  for treatment benefit, and IVIG's benefit should survive in patients whose
##  titres do not fall. Both are testable in existing cohorts.
##
##  ---- A NEGATIVE result worth stating ----
##  At matched cumulative dose (840 mg prednisone-equivalent), stretching the
##  oral wean from 14 to 180 days moves the 1-year relapse probability only
##  from 0.500 to 0.479. The model therefore does NOT support taper duration
##  as an important lever in itself: the hazard reduction bought is roughly
##  proportional to steroid spent, and a longer wean mostly defers the rebound
##  rather than preventing it. Raising the total dose helps a little more
##  (2700 mg over 90 d -> 0.46) at a real BMD cost. The mechanistic reading is
##  that oral steroids buy time in proportion to exposure and cannot deliver
##  remission, which is the argument for starting a steroid-sparing agent
##  early rather than for tapering slowly.
##
##  ---- Known misses, stated up front ----
##  1. IL-6R BLOCKADE IS UNDER-PREDICTED (0.23 vs observed 0.09). The model
##     reaches an IVIG-like effect but not the reported point estimate. Two
##     readings, and the model does not distinguish them: (a) the observed
##     incidence-rate ratio of 0.08 is a pre-versus-on-treatment comparison in
##     a retrospective cohort and is inflated by regression to the mean, and
##     the trustworthy contemporaneous comparison (vs IVIG >= 1 g/kg) was NOT
##     significant — in which case the model is right; or (b) IL-6R blockade
##     has an effect on plasmablast survival or CNS-compartment inflammation
##     larger than EMAX_IL6/KAMP allow — in which case the model is wrong.
##     Distinguishing them needs the randomised data.
##  2. AZATHIOPRINE vs MYCOPHENOLATE. Both are one antimetabolite arm here,
##     so the model cannot reproduce the reported ordering (azathioprine ARR
##     ~0.2-0.29 better than mycophenolate ~0.67-0.84). That ordering is
##     mechanistically unexplained and may be confounding/channelling in
##     retrospective series; the model takes no position.
##  3. FRAC_ESC = 0.60 IS FITTED, NOT MEASURED. It is the single parameter that
##     makes rituximab weaker than IVIG, and the whole source-vs-clearance
##     conclusion is contingent on it. A competing explanation — that MOGAD
##     relapses on rituximab cluster in B-cell repopulation windows rather than
##     arising from CD20-negative escape — would be captured by a low FRAC_ESC
##     plus under-dosed redosing, and would predict that strict CD19-guided
##     redosing rescues rituximab. That is the experiment that separates them.
##  4. ATTACK NADIR IS SOMEWHAT UNDER-PREDICTED. Treated nadir is logMAR 1.60
##     (~20/800) against a reported average nadir of count-fingers, and final
##     VA is 20/47 against a reported average 20/30. The model is therefore
##     pessimistic about recovery and optimistic about nadir; both would
##     improve with an explicit conduction-block state separate from myelin
##     content, which is not implemented.
##  5. RELAPSES ARE A HAZARD, NOT EVENTS. CUMHAZ gives the probability of
##     relapse but no relapse actually fires, so simulated disability never
##     accrues step-wise over multiple attacks. Stochastic relapse firing
##     (drawing attack times from the hazard and injecting TRIG) is the natural
##     extension and is what would be needed for disability trajectories.
##  6. NO PAEDIATRIC ADEM PHYSIOLOGY. Phenotype is set by SITE_ON/SITE_SC
##     weights only; the encephalopathy, seizure and cognitive endpoints in the
##     mechanistic map have no ODE counterpart, and paediatric ADEM's much
##     higher rate of transient seropositivity is not modelled.
##  7. TITRE-TO-ASSAY MAPPING IS LINEAR (TITER_REF). Real live cell-based assay
##     dilutions are ordinal and step in twofold increments; comparisons of
##     absolute simulated titres to reported dilutions should be read as
##     order-of-magnitude only.
