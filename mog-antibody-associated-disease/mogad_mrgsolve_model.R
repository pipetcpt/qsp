//== Glucocorticoid PK and receptor occupancy ==============================
// The oral prednisone wean is a zero-order input with a LINEAR taper, so
// TAPER_DAYS is a continuously tunable lever and total dose = PRED0*TAPER/2.
double trel    = SOLVERTIME - PRED_START;
double PRED_IN = 0.0;
if (PRED0 > 0.0 && trel >= 0.0 && trel < TAPER_DAYS)
  PRED_IN = PRED0 * (1.0 - trel / TAPER_DAYS);

dxdt_MP_C   = -KEL_MP * MP_C;
dxdt_PRED_G = PRED_IN - KA_PRED * PRED_G;
dxdt_PRED_C = KA_PRED * PRED_G * F_PRED - KEL_PRED * PRED_C;

double PEQ   = PRED_C + MPPOT * MP_C;
dxdt_GC_EFF  = KIN_GC * PEQ - KOUT_GC * GC_EFF;
double GC_occ = GC_EFF / (GC50 + GC_EFF);

//== Other drug exposures =================================================
dxdt_IVIG_C = -KEL_IVIG * IVIG_C;
dxdt_RTX_C  = -KEL_RTX  * RTX_C;
dxdt_TCZ_C  = -KEL_TCZ  * TCZ_C;
dxdt_MMF_C  = MMF_RATE - KEL_MMF * MMF_C;
dxdt_FCRN_C = -KEL_FCRN * FCRN_C;
dxdt_C5I_C  = -KEL_C5I  * C5I_C;
dxdt_PLEX_D = -KOUT_PLEX * PLEX_D;
dxdt_TRIG   = -KOUT_TRIG * TRIG;

double RTX_occ    = RTX_C  / (EC50_RTX  + RTX_C);
double IL6R_block = IMAX_TCZ * TCZ_C / (EC50_TCZ + TCZ_C);
double MMF_eff    = IMAX_MMF * MMF_C / (EC50_MMF + MMF_C);
double FCRN_occ   = FCRN_C / (EC50_FCRN + FCRN_C);
double C5I_block  = IMAX_C5I * C5I_C / (EC50_C5I + C5I_C);
double IVIG_sat   = IVIG_C / (EC50_IVIG + IVIG_C);

//== COMMITMENT 1: short-lived CD20-negative plasmablast source ============
double IL6_sig = IL6 * (1.0 - IL6R_block);
double FIL6    = 1.0 + EMAX_IL6 * IL6_sig / (EC50_IL6 + IL6_sig);
double GCsup   = IMAX_GC_PB * GC_occ;

dxdt_MBC = KIN_MBC * (1.0 - MMF_eff) * (1.0 + ATRIG * TRIG)
           - KOUT_MBC * MBC - KDEP_RTX * RTX_occ * MBC;

// FRAC_ESC of plasmablast generation is CD20-independent: rituximab drives
// MBC to ~0 but can never take the bracket below FRAC_ESC.
double gen = (1.0 - FRAC_ESC) * MBC + FRAC_ESC;
dxdt_PB = KGEN_PB * gen * FIL6 * (1.0 - GCsup) * (1.0 - 0.5 * MMF_eff)
          * (1.0 + BTRIG * TRIG) - KOUT_PB * PB;

// FcRn-dependent catabolism: IVIG saturates FcRn, FcRn inhibitors block it.
double FcRn_acc = FRN_IVIG * IVIG_sat + FRN_INH * FCRN_occ;
dxdt_AB = KSYN_AB * PB - KEL_AB * AB * (1.0 + FcRn_acc) - KPLEX * PLEX_D * AB;
dxdt_TOTIgG = KSYN_IgG * (FLOOR_IgG + (1.0 - FLOOR_IgG) * MBC)
              - KEL_AB * TOTIgG * (1.0 + FcRn_acc) - KPLEX * PLEX_D * TOTIgG;

//== Cytokines, T cells, barrier ==========================================
dxdt_IL6 = KIN_IL6 * (1.0 + CTRIG * TRIG + KT_IL6 * TCELL)
           * (1.0 - IMAX_GC_IL6 * GC_occ) - KOUT_IL6 * IL6;
dxdt_TCELL = KIN_T * (1.0 + DTRIG * TRIG) * (1.0 - IMAX_GC_T * GC_occ)
             * (1.0 - MMF_eff) - KOUT_T * TCELL;

double bbb_drive = 1.0 + ETRIG * TRIG
                   + KIL6_BBB * IL6_sig / (EC50_IL6B + IL6_sig)
                   + KT_BBB * TCELL;
dxdt_BBB = KIN_BBB * bbb_drive * (1.0 - BBB)
           - KOUT_BBB * BBB * (1.0 + IMAX_GC_BBB * GC_occ);

//== CNS transit and effector arm =========================================
// AB_EFF is the FUNCTIONALLY ACTIVE antibody. IVIG lowers it far more than it
// lowers the measured titre (FcgR blockade, anti-idiotype, C scavenging) —
// this is why titre is a poor surrogate for protection (commitment 3).
double AB_eff = AB / (1.0 + KNEUT * IVIG_sat);
dxdt_AB_CNS = KIN_CNS * BBB * AB_eff - KOUT_CNS * AB_CNS;

double OPS = AB_CNS;
dxdt_COMP = KIN_COMP * OPS * (1.0 - C5I_block) - KOUT_COMP * COMP;
dxdt_MPHI = KIN_MPHI * (OPS + KC5A * COMP) * (1.0 - IMAX_GC_M * GC_occ)
            - KOUT_MPHI * MPHI;

double OPS_eff = KCDC * COMP + KADCP * MPHI * OPS + KDIR * OPS;
double ops_h   = pow(fmax(OPS_eff, 0.0), HI);
double INJ     = SEV * INJMAX * ops_h / (pow(OPS50, HI) + ops_h);
double INJ_ON  = SITE_ON * INJ;
double INJ_SC  = SITE_SC * INJ;

//== COMMITMENT 2: myelin is lost, the oligodendrocyte survives ============
// Remyelination is proportional to OL, so OL sets the recovery CEILING.
dxdt_MYEL_ON = -INJ_ON * MYEL_ON + KREMY * OL * (1.0 - MYEL_ON);
dxdt_MYEL_SC = -INJ_SC * MYEL_SC + KREMY * OL * (1.0 - MYEL_SC);

double ax_on = KAX * fmax(INJ_ON - AXTHR, 0.0) * AXON_ON
               + KAX2 * fmax(1.0 - MYEL_ON - DEMYTHR, 0.0) * AXON_ON;
double ax_sc = KAX * fmax(INJ_SC - AXTHR, 0.0) * AXON_SC
               + KAX2 * fmax(1.0 - MYEL_SC - DEMYTHR, 0.0) * AXON_SC;
dxdt_AXON_ON = -ax_on;
dxdt_AXON_SC = -ax_sc;

dxdt_OL = -KOLD * (1.0 + AQP4_MODE * AQP4_OLD) * INJ * OL + KOLREP * (1.0 - OL);
dxdt_EDEMA = KIN_ED * INJ - KOUT_ED * EDEMA * (1.0 + 2.0 * GC_occ);

//== Biomarkers ===========================================================
dxdt_NFL = KIN_NFL * (ax_on + ax_sc) + KBASE_NFL - KOUT_NFL * NFL;
double ASTRO_INJ = (BYST_GFAP + AQP4_MODE * AQP4_GFAP) * INJ;
dxdt_GFAP = KIN_GFAP * ASTRO_INJ + KBASE_GFAP - KOUT_GFAP * GFAP;
dxdt_CSFC = KIN_CSF * (BBB + KM_CSF * MPHI) - KOUT_CSF * CSFC;

//== COMMITMENT 3: relapse hazard is a THRESHOLD function of AB_EFF ========
double ab_h    = pow(fmax(AB_eff, 0.0), HAZ_H);
double Hill_AB = ab_h / (pow(AB50, HAZ_H) + ab_h);
double amp_il6 = (1.0 + KAMP * IL6_sig / (EC50_AMP + IL6_sig))
                 / (1.0 + KAMP * IL6_BASE / (EC50_AMP + IL6_BASE));
double amp_bbb = pow(fmax(BBB, 1e-9) / BBB_BASE, POW_BBB);
double AMP     = amp_il6 * amp_bbb * (1.0 - IMAX_C5H * C5I_block);
dxdt_CUMHAZ    = LAM0 * Hill_AB * AMP;

//== Glucocorticoid toxicity ==============================================
// Elimination flux integrates to total administered dose.
dxdt_CUMSTER = (KEL_PRED * PRED_C + KEL_MP * MP_C) / 1000.0;
dxdt_BMD = -KBMD * GC_occ + KBMDREC * (1.0 - BMD);

