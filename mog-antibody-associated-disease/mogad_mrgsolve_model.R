##  MOG Antibody-Associated Disease (MOGAD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : MOGAD — a CNS-restricted, antibody-mediated demyelinating disease
##             in which class-switched IgG1 against myelin oligodendrocyte
##             glycoprotein (MOG) reaches the CNS through a permeabilised
##             blood-brain barrier, opsonises the OUTERMOST myelin lamella, and
##             destroys myelin by complement-dependent lysis and
##             antibody-dependent cellular phagocytosis — while sparing the
##             oligodendrocyte cell body and the astrocyte/AQP4 compartment.
##             Attacks are optic neuritis, myelitis, ADEM and cortical
##             encephalitis (FLAMES); disability accrues step-wise from relapses
##             with no secondary progressive phase.
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>= 1.5)   —   mod <- mread_cache("mogad_mrgsolve_model.R")
##
##  ---------------------------------------------------------------------------
##  THREE STRUCTURAL COMMITMENTS
##  ---------------------------------------------------------------------------
##  (1) SOURCE. The pathogenic IgG1 is made by a SHORT-LIVED, CD20-NEGATIVE
##      plasmablast pool (t1/2 = 1/KOUT_PB = 7.1 d) whose generation is only
##      partly fed by CD20+ memory B cells. FRAC_ESC (= 0.60) is the share of
##      plasmablast generation that rituximab cannot reach. Everything
##      downstream of the plasmablast inherits that short time constant, which
##      is why titres fall within days of steroids/PLEX and rebound within
##      weeks of stopping them.
##
##  (2) TARGET. MYEL_* (myelin) and AXON_* (axon) are separate states, and OL
##      (surviving oligodendrocytes) multiplies the remyelination rate. In
##      MOGAD, KOLD is small — myelin is destroyed, the oligodendrocyte lives,
##      so remyelination proceeds and the recovery ceiling is high. Setting
##      AQP4_MODE = 1 multiplies oligodendrocyte death by (1 + AQP4_OLD) and
##      astrocytic GFAP release by (1 + AQP4_GFAP), converting the SAME model
##      into an AQP4-IgG NMOSD comparator with poor recovery and high sGFAP.
##      This one switch is the model's built-in control experiment.
##
##  (3) NODE OF ACTION. Relapse hazard is a Hill function (HAZ_H = 3) of the
##      FUNCTIONALLY ACTIVE antibody AB_EFF, not of the measured titre. Drugs
##      act either at the antibody SOURCE (steroids, MMF/AZA, rituximab, IL-6R
##      blockade) or at the CLEARANCE/EFFECTOR node (PLEX, IVIG, FcRn
##      inhibition, C5 inhibition). Because baseline titre sits on the Hill
##      plateau, partial source suppression buys little, and the simulated
##      ordering of therapies does NOT follow the simulated ordering of titre
##      reduction — see the calibration notes at the bottom.
##
##  Scope    : 34 ODE compartments —
##             * drug PK/exposure (11): methylprednisolone, oral prednisone
##               (gut+central) and a GC effect compartment, IVIG, rituximab,
##               IL-6R blocker, antimetabolite, FcRn inhibitor, C5 inhibitor,
##               a plasma-exchange driver, and an attack-trigger driver
##             * immune source (7): CD20+ memory B cells, plasmablasts, serum
##               MOG-IgG, total serum IgG, IL-6, activated T cells, BBB
##               permeability
##             * CNS effector arm (3): parenchymal MOG-IgG, complement
##               activation, activated microglia/macrophages
##             * tissue (6): optic-nerve and cord myelin and axons, surviving
##               oligodendrocytes, lesion oedema
##             * biomarkers (3): serum NfL, serum GFAP, CSF cell count
##             * cumulative (4): relapse hazard, prednisone-equivalent dose,
##               bone mineral density
##  Time     : days. Default horizon 365 d (index attack at t = 0, IV
##             methylprednisolone from day 4, oral prednisone from day 9,
##             maintenance therapy from day 28).
##  Units    : antibody titre in arbitrary units mapped to a live cell-based
##             assay dilution via TITER_REF (AB = 3 -> 1:300); myelin/axon/
##             oligodendrocyte states as surviving fractions (0-1); IgG in g/L;
##             NfL and GFAP in pg/mL; CSF cells in cells/uL; prednisone in mg
##             and cumulative dose in g; hazard in 1/day (ARR = 365 * hazard).
##  Scenarios: 17 prebuilt — see MOGAD_simulate_scenarios() at the bottom.
##  Verify   : `mogad_reference_impl.py` in this directory re-implements these
##             same 34 ODEs with the same parameter values in dependency-free
##             Python (RK4) and prints every number quoted in README.md and in
##             the calibration notes below. Run `python3 mogad_reference_impl.py`.
##  Disclaimer: For research / education / hypothesis generation only.
##             Not a substitute for clinical judgement or regulatory filings.
##  ============================================================================

