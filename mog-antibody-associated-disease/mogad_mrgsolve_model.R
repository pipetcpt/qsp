double GC_occ2    = GC_EFF / (GC50 + GC_EFF);
double IL6R_blk2  = IMAX_TCZ * TCZ_C / (EC50_TCZ + TCZ_C);
double IVIG_sat2  = IVIG_C / (EC50_IVIG + IVIG_C);
double C5I_blk2   = IMAX_C5I * C5I_C / (EC50_C5I + C5I_C);
double RTX_occ2   = RTX_C / (EC50_RTX + RTX_C);
double FCRN_occ2  = FCRN_C / (EC50_FCRN + FCRN_C);
double AB_eff2    = AB / (1.0 + KNEUT * IVIG_sat2);
double IL6_sig2   = IL6 * (1.0 - IL6R_blk2);
double ab_h2      = pow(fmax(AB_eff2, 0.0), HAZ_H);
double Hill_AB2   = ab_h2 / (pow(AB50, HAZ_H) + ab_h2);
double amp_il62   = (1.0 + KAMP * IL6_sig2 / (EC50_AMP + IL6_sig2))
                    / (1.0 + KAMP * IL6_BASE / (EC50_AMP + IL6_BASE));
double amp_bbb2   = pow(fmax(BBB, 1e-9) / BBB_BASE, POW_BBB);
double HAZ        = LAM0 * Hill_AB2 * amp_il62 * amp_bbb2
                    * (1.0 - IMAX_C5H * C5I_blk2);

// Deficit = REVERSIBLE conduction block from demyelination + IRREVERSIBLE
// axonal loss beyond a functional reserve. The reserve term is what allows
// marked RNFL thinning together with good visual recovery — the MOGAD
// structure-function dissociation.
double logMAR = WM * (1.0 - MYEL_ON)
                + WA * fmax((1.0 - AXON_ON) - AXRES, 0.0);
if (logMAR > 3.0) logMAR = 3.0;
double edss = 4.5 * (1.0 - MYEL_SC)
              + 9.0 * fmax((1.0 - AXON_SC) - 0.05, 0.0)
              + 0.48 * fmin(logMAR, 2.0);
if (edss > 9.5) edss = 9.5;

