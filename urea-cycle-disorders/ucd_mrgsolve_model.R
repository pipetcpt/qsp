## ============================================================================
##  Urea Cycle Disorders (UCD) — QSP / PK-PD Model
##  ============================================================================
##  Disease  : Inherited block of hepatic ureagenesis. The index defect modelled
##             here is ORNITHINE TRANSCARBAMYLASE (OTC) DEFICIENCY — X-linked,
##             the commonest UCD — but the same structure covers CPS1, NAGS,
##             ASS1, ASL and ARG1 deficiency through the activity parameters
##             (OTCACT, CPS1A, NAGSA, DISTALA, ARG1A).
##
##             Physiology in one paragraph. Waste nitrogen from dietary protein
##             and from endogenous proteolysis reaches the periportal hepatocyte
##             as ammonia. The only route by which the body can dispose of that
##             nitrogen in bulk is the urea cycle: NAG-activated CPS1 makes
##             carbamoyl phosphate, OTC condenses it with ornithine to
##             citrulline, and the cytosolic arm (ASS1 -> ASL -> ARG1) adds a
##             second nitrogen from aspartate and releases urea. Block any step
##             and nitrogen backs up. The body's response is not to accumulate
##             ammonia linearly but to BUFFER it as glutamine (glutamine
##             synthetase, mostly skeletal muscle, ~300 umol/kg/h of flux). That
##             buffer is why plasma glutamine rises BEFORE ammonia does, and why
##             glutamine is the early-warning biomarker. It is also why the
##             disease is a cliff rather than a slope: while the buffer holds,
##             the patient looks well; when the nitrogen load exceeds residual
##             ureagenic capacity for long enough, ammonia rises steeply.
##
##             The lethal organ is the brain, and the mechanism is osmotic.
##             Astrocytes are the only CNS cells with glutamine synthetase, so
##             blood-borne ammonia is trapped there as glutamine. Glutamine is
##             an osmolyte; the astrocyte defends its volume by extruding
##             myo-inositol. In CHRONIC hyperammonaemia myo-inositol is already
##             spent — which is exactly why a chronically-elevated patient
##             decompensates catastrophically on a trigger that a naive brain
##             would tolerate. This model reproduces that interaction explicitly
##             (MINSB compartment), because it is the single most important
##             non-obvious behaviour in UCD.
##
##  Pharmacology modelled
##             * Sodium phenylbutyrate (NaPBA) and glycerol phenylbutyrate (GPB,
##               Ravicti/HPN-100): prodrugs -> PBA -> (beta-oxidation) ->
##               PHENYLACETATE -> conjugated with GLUTAMINE by GLYATL1 ->
##               PHENYLACETYLGLUTAMINE, excreted by OAT1/3. Two nitrogens per
##               molecule. GPB's slow lipase-dependent release is modelled as a
##               separate hydrolysis step, which is what produces its lower
##               Cmax, flatter 24-h profile and better overnight ammonia control.
##             * Sodium benzoate (and IV Na-phenylacetate/Na-benzoate, Ammonul):
##               benzoyl-CoA + GLYCINE -> hippurate. One nitrogen per molecule.
##             * Carglumic acid (N-carbamylglutamate): stable NAG analogue that
##               allosterically activates CPS1 — curative in NAGS deficiency.
##             * L-citrulline: bypasses the OTC block, adding an OTC-INDEPENDENT
##               nitrogen sink through ASS1 (one aspartate nitrogen per
##               citrulline) and regenerating ornithine.
##             * L-arginine HCl: substrate replacement + allosteric NAGS
##               stimulation.
##             * Haemodialysis / CVVHDF: direct ammonia clearance, with the
##               post-dialysis REBOUND that comes from re-equilibration of the
##               deep tissue glutamine reservoir (GLNM compartment).
##             * AAV8-OTC gene transfer (DTX301) and OTC mRNA-LNP (ARCT-810):
##               transgene template -> transgene-derived OTC activity.
##             * Liver transplantation: step restoration of ureagenic capacity.
##
##  Authors  : Generated by Claude Code Routine (QSP Disease Model Library)
##  Engine   : mrgsolve (>= 1.0; developed and run against 2.0.1)
##
##  Scope    : 35 ODE compartments (see $CMT).
##  Time     : HOURS. Default horizons: 72 h for crises, 8760 h (1 y) for
##             chronic scenarios.
##  Units    : amounts umol · concentrations umol/L · nitrogen fluxes umol N/h ·
##             brain glutamine and myo-inositol reported in mmol/L · brain water
##             excess in % · ICP mmHg · drug doses entered in umol (helper
##             functions convert from g / mg/kg / mL).
##
##  SELF-CALIBRATING BASELINE
##  -------------------------
##  Nothing is hard-coded as an initial condition. From the patient descriptors
##  (WT, OTCACT, PROT, CPS1A, NAGSA, ARGBASE, CITBASE, ...) [$MAIN] solves the
##  untreated steady state ANALYTICALLY and sets every compartment to it:
##
##    N load        RA_N  = FDISP * PROT * WT * 11430 / 24            umol N/h
##    ureagenesis   V     = A * C / (KMNH4 + C),  A = UCAP*WT*ACT*fNAG*fORN
##    other N loss  (CLNH4R + CLRGLN*RATIO) * C                       [linear]
##    =>  CLReff*C^2 + (A + CLReff*KMNH4 - RA_N)*C - RA_N*KMNH4 = 0
##
##  which is solved with the positive root. Glutamine, brain ammonia, brain
##  glutamine, myo-inositol, brain water, ornithine, orotate, glycine and BCAA
##  all follow in closed form from that root, and every production constant is
##  back-calculated so the untreated arm is EXACTLY stationary. Change the
##  patient and the model still starts in balance — so any drift you see in a
##  simulation is mechanism, not bookkeeping.
##
##  KEY CALIBRATION ANCHORS (see ucd_references.md for the full list)
##  -----------------------------------------------------------------
##   * Maximal ureagenesis capacity ~4-5x the habitual nitrogen load in healthy
##     adults; healthy operating point ~20% of Vmax at ammonia 30 umol/L.
##     -> UCAP = 2400 umol N/kg/h, KMNH4 = 120 umol/L reproduce both.
##   * Whole-body glutamine flux ~300 umol/kg/h (Darmaun 1986 Am J Physiol) and
##     the clinically observed plasma Gln:NH3 ratio of ~20-22 in normals and in
##     UCD -> KGS = 700 L/h, (KGLNASE + CLRGLN) = 32.3 L/h for a 70 kg adult.
##   * Renal glutamine-derived ammoniagenesis disposes ~30-50 mmol N/day
##     -> CLRGLN = 1.924 L/h.
##   * NaPBA 20 g/day == GPB 17.5 mL/day == ~107-109 mmol PBA/day; urinary PAGN
##     recovery ~60-75% of administered PBA (Monteleone 2013; Diaz 2013)
##     -> VMPAGN = 115 umol/kg/h, KMPAA = 300, KMGLNP = 400 give 70%.
##   * Diaz 2013 Hepatology 57:2171 (GPB vs NaPBA crossover): equivalent 24-h
##     ammonia AUC with LOWER Cmax and better overnight/early-morning control —
##     reproduced by scenarios 3 vs 4.
##   * PAA neurotoxicity threshold ~500 ug/mL and the PAA:PAGN ratio >2.5
##     (ug/mL basis) as the marker of saturated conjugation (Mokhtarani 2013).
##   * Msall 1984 NEJM 310:1500 / Bachmann 2003: duration of neonatal
##     hyperammonaemic coma is the dominant predictor of later IQ -> the NEURO
##     injury integrator is driven by ammonia x time x brain water.
##   * Haemodialysis ammonia clearance far exceeds any pharmacological route;
##     ammonia >360-500 umol/L is a dialysis indication (Haberle 2019 revised
##     European guideline) -> scenario 9.
##   * Brain glutamine rises from ~5 mM to ~15-20 mM with reciprocal
##     myo-inositol depletion on 1H-MRS (Connelly 1993; Gropman 2008).
##
##  IMPORTANT: this is an educational / exploratory QSP model. It is not
##  validated for clinical decision-making, dose selection or regulatory use.
## ============================================================================

