## ---------------------------------------------------------------------------
##  Number of `addl` doses needed to carry an every-`ii`-hours regimen for
##  `days` days (the first dose is the one in the ev(), hence the -1)
## ---------------------------------------------------------------------------
ucd_addl <- function(days, ii = 8) ceiling(days*24/ii) - 1

## ---------------------------------------------------------------------------
##  Fourteen prebuilt scenarios
## ---------------------------------------------------------------------------
#' @param mod   a model object from UCD_build()
#' @param which integer vector of scenario numbers (default all 14)
#' @return a data.frame with one row per output time and a `scenario` column
UCD_simulate_scenarios <- function(mod = UCD_build(), which = 1:14) {

  wt      <- 70
  chr_end <- 90*24     # chronic horizon: 90 days
  acu_end <- 96        # acute horizon: 96 hours

  ## a scavenger regimen carried for the whole chronic horizon
  A90  <- ucd_addl(90, 8)
  A30  <- ucd_addl(30, 12)

  run <- function(label, events = NULL, end = chr_end, delta = 1, pars = list()) {
    m <- mod
    if (length(pars)) m <- do.call(mrgsolve::param, c(list(m), pars))
    out <- mrgsolve::mrgsim(m, events = events, end = end, delta = delta,
                            hmax = 0.25, atol = 1e-8, rtol = 1e-6)
    d <- as.data.frame(out)
    d$scenario <- label
    d
  }

  ## regimen building blocks -------------------------------------------------
  GPB90  <- ucd_gpb(17.5, n = 3, ii = 8, addl = A90)
  PBA90  <- ucd_napba(20,  n = 3, ii = 8, addl = A90)
  CIT90  <- ucd_citrulline(170, wt, n = 3, ii = 8, addl = A90)
  BZ90   <- ucd_benzoate(250, wt, n = 3, ii = 8, addl = A90)

  S <- list(

    ## 1 — natural history: late-onset OTC male on diet alone
    function() run(
      "1. Diet alone (late-onset OTC, 0.60 g/kg/d)",
      NULL, end = chr_end),

    ## 2 — stricter protein restriction + L-citrulline
    function() run(
      "2. Protein 0.45 g/kg/d + citrulline 170 mg/kg/d",
      CIT90, end = chr_end, pars = list(PROT = 0.45)),

    ## 3 — sodium phenylbutyrate TID + citrulline
    function() run(
      "3. NaPBA 20 g/d TID + citrulline",
      c(PBA90, CIT90), end = chr_end),

    ## 4 — glycerol phenylbutyrate TID (matched PBA-equivalent dose)
    function() run(
      "4. GPB 17.5 mL/d TID + citrulline",
      c(GPB90, CIT90), end = chr_end),

    ## 5 — sodium benzoate monotherapy
    function() run(
      "5. Sodium benzoate 250 mg/kg/d TID",
      BZ90, end = chr_end),

    ## 6 — GPB + benzoate combination
    function() run(
      "6. GPB 17.5 mL/d + benzoate 250 mg/kg/d",
      c(GPB90, BZ90), end = chr_end),

    ## 7 — intercurrent illness, no treatment escalation
    function() run(
      "7. Severe catabolic crisis (sepsis), no escalation",
      GPB90, end = acu_end, delta = 0.25,
      pars = list(CATAMP = 4.0, CATT0 = 12, CATDUR = 96)),

    ## 8 — the same crisis, rescued medically
    function() run(
      "8. Crisis + Ammonul + arginine + anabolic rescue at 30 h",
      c(GPB90, ucd_ammonul(wt, start = 30), ucd_arginine_iv(400, wt, start = 30)),
      end = acu_end, delta = 0.25,
      pars = list(CATAMP = 4.0, CATT0 = 12, CATDUR = 96,
                  PROT2 = 0.0, TPROT = 30, ANAB = 0.8)),

    ## 9 — the neonatal counterfactual: the same baby as scenario 10, rescued
    ##     with maximal MEDICAL therapy but WITHOUT extracorporeal removal.
    ##     Scenarios 9 and 10 are the clearest statement the model can make
    ##     about why dialysis, not pharmacology, is the emergency treatment of
    ##     neonatal hyperammonaemia.
    function() run(
      "9. Neonatal OTC (1%): medical therapy only, no dialysis",
      c(ucd_gpb(2.2, n = 4, ii = 6, addl = ucd_addl(6, 6), start = 60),
        ucd_ammonul(3.4, start = 60),
        ucd_arginine_iv(400, 3.4, start = 60)),
      end = 168, delta = 0.25,
      pars = list(WT = 3.4, BSA = 0.22, VBR = 0.40, AGEY = 0,
                  OTCACT = 0.01, PROT = 0.05,
                  PROT2 = 1.80, TPROT = 12,
                  PROT3 = 0.20, TPROT3 = 60,
                  CATAMP = 1.5, CATT0 = 6, CATDUR = 150,
                  ANAB = 1.0)),

    ## 10 — neonatal-onset OTC: the classical presentation. A 3.4 kg boy with
    ##      1% residual activity is well at birth (placental clearance), feeds
    ##      are established at 12 h, he is obtunded by 48 h, and full rescue
    ##      (protein withdrawal + Ammonul + arginine + CVVHD) starts at 60 h.
    function() run(
      "10. Neonatal OTC (1%): the same rescue plus CVVHD at 62 h",
      c(ucd_gpb(2.2, n = 4, ii = 6, addl = ucd_addl(6, 6), start = 60),
        ucd_ammonul(3.4, start = 60),
        ucd_arginine_iv(400, 3.4, start = 60)),
      end = 168, delta = 0.25,
      pars = list(WT = 3.4, BSA = 0.22, VBR = 0.40, AGEY = 0,
                  OTCACT = 0.01, PROT = 0.05,
                  PROT2 = 1.80, TPROT = 12,     # feeds established
                  PROT3 = 0.20, TPROT3 = 60,    # protein withdrawn at rescue
                  CATAMP = 1.5, CATT0 = 6, CATDUR = 150,
                  CLHD = 3.0, HDT0 = 62, HDDUR = 24, ANAB = 1.0)),

    ## 11 — NAGS deficiency rescued by carglumic acid
    function() run(
      "11. NAGS deficiency + carglumic acid 150 mg/kg/d",
      ucd_carglumic(150, wt, n = 2, ii = 12, addl = A30),
      end = 30*24,
      pars = list(OTCACT = 1.0, NAGSA = 0.05, PROT = 0.80)),

    ## 12 — AAV8-OTC gene transfer with the scavenger continued
    function() run(
      "12. AAV8-OTC gene transfer (DTX301) on GPB",
      c(GPB90, ucd_aav(200, start = 24)), end = chr_end),

    ## 13 — organ impairment unmasks phenylacetate accumulation: slower renal
    ##      PAGN clearance AND a halved hepatic conjugation capacity, which is
    ##      the combination that pushes the PAA:PAGN ratio through 2.5 and PAA
    ##      towards the 500 ug/mL neurotoxicity threshold
    function() run(
      "13. GPB with renal + hepatic impairment (PAA accumulation)",
      ucd_gpb(20, n = 3, ii = 8, addl = A90), end = 21*24, delta = 0.25,
      pars = list(CLPGN = 1.8, CLPAA = 0.6, CLHIP = 4.0, VMPKG = 45)),

    ## 14 — a manifesting OTC heterozygote started on valproate. She is stable
    ##      at an ammonia of ~45 until valproate inhibits NAGS at 24 h; the
    ##      accompanying illness adds a modest catabolic load.
    function() run(
      "14. Valproate started in a manifesting OTC heterozygote",
      NULL, end = 240, delta = 0.25,
      pars = list(OTCACT = 0.65, PROT = 0.80,
                  VPAI = 0.80, TVPA = 24,
                  CATAMP = 0.40, CATT0 = 24, CATDUR = 168))
  )

  res <- do.call(rbind, lapply(S[which], function(f) f()))
  rownames(res) <- NULL
  res
}

## ---------------------------------------------------------------------------
##  Compact numeric summary of a scenario set
## ---------------------------------------------------------------------------
UCD_summarise <- function(sim) {
  sp <- split(sim, sim$scenario)
  out <- do.call(rbind, lapply(names(sp), function(nm) {
    d <- sp[[nm]]
    tail1 <- d[nrow(d), ]
    data.frame(
      scenario     = nm,
      hours        = max(d$time),
      NH3_start    = round(d$NH3[1], 1),
      NH3_end      = round(tail1$NH3, 1),
      NH3_peak     = round(max(d$NH3), 1),
      GLN_end      = round(tail1$GLNP, 0),
      BrainGln_pk  = round(max(d$GLNBRAIN), 1),
      mIns_end     = round(tail1$MINSMM, 2),
      BW_peak_pct  = round(max(d$BW), 2),
      ICP_peak     = round(max(d$ICP), 1),
      HE_peak      = round(max(d$HESTAGE), 2),
      coma_h       = round(tail1$COMAH, 1),
      PAA_peak_ug  = round(max(d$PAAUG), 1),
      PAAPGN_pk    = round(max(d$PARATIO), 2),
      PAAPGN_med   = round(stats::median(d$PARATIO), 2),
      UPAGN_mmold  = round(stats::median(d$UPAGN), 1),
      ProtTol_end  = round(tail1$PROTTOL, 2),
      IQ_end       = round(tail1$IQEST, 1),
      Nurea_pct    = round(100*stats::median(d$NUREA/pmax(d$NTOTAL,1)), 0),
      Npagn_pct    = round(100*stats::median(d$NPAGN/pmax(d$NTOTAL,1)), 0),
      Nhipp_pct    = round(100*stats::median(d$NHIPP/pmax(d$NTOTAL,1)), 0),
      stringsAsFactors = FALSE
    )
  }))
  rownames(out) <- NULL
  out
}

## ---------------------------------------------------------------------------
##  Quick-look plot (base graphics; no extra dependencies)
## ---------------------------------------------------------------------------
UCD_plot <- function(sim, yvar = "NH3", ylab = NULL, log = "") {
  sp <- split(sim, sim$scenario)
  cols <- grDevices::hcl.colors(length(sp), "Dark 3")
  ylim <- range(unlist(lapply(sp, function(d) d[[yvar]])), na.rm = TRUE)
  xlim <- range(sim$time)
  plot(NA, xlim = xlim/24, ylim = ylim, log = log,
       xlab = "Time (days)", ylab = ylab %||% yvar,
       main = paste("UCD QSP —", yvar))
  for (i in seq_along(sp)) {
    lines(sp[[i]]$time/24, sp[[i]][[yvar]], col = cols[i], lwd = 2)
  }
  legend("topright", legend = names(sp), col = cols, lwd = 2,
         cex = 0.6, bty = "n")
  invisible(NULL)
}
`%||%` <- function(a, b) if (is.null(a)) b else a

