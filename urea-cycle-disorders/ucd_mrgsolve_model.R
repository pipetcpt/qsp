UCD_build <- function() {
  mrgsolve::mcode("ucd_qsp", ucd_code, quiet = TRUE)
}

## ---------------------------------------------------------------------------
##  Dose helpers — convert clinical units to umol
## ---------------------------------------------------------------------------
MW <- list(NaPBA = 186.2, PBA = 164.2, GPB = 530.6, PAA = 136.15,
           NaPAA = 158.13, PAGN = 264.28, NaBz = 144.11, BZ = 122.12,
           HIP = 179.17, CIT = 175.19, ARGHCL = 210.66, NCG = 190.15)

#' Sodium phenylbutyrate, g/day split over `n` doses -> umol PBA per dose
ucd_napba <- function(g_per_day, n = 3, ii = 8, days = 1, addl = NULL, start = 0) {
  amt <- g_per_day / MW$NaPBA * 1e6 / n
  if (is.null(addl)) addl <- ucd_addl(days, ii)
  mrgsolve::ev(time = start, amt = amt, cmt = "PBAG", ii = ii, addl = addl)
}

#' Glycerol phenylbutyrate, mL/day -> umol PBA-equivalents per dose (3 PBA/GPB)
ucd_gpb <- function(mL_per_day, n = 3, ii = 8, days = 1, addl = NULL, start = 0,
                    density = 1.1) {
  amt <- mL_per_day * density / MW$GPB * 1e6 * 3 / n
  if (is.null(addl)) addl <- ucd_addl(days, ii)
  mrgsolve::ev(time = start, amt = amt, cmt = "GPBG", ii = ii, addl = addl)
}

#' Sodium benzoate, mg/kg/day -> umol per dose
ucd_benzoate <- function(mgkg_per_day, wt = 70, n = 3, ii = 8, days = 1,
                         addl = NULL, start = 0) {
  amt <- mgkg_per_day * wt / MW$NaBz * 1e3 / n
  if (is.null(addl)) addl <- ucd_addl(days, ii)
  mrgsolve::ev(time = start, amt = amt, cmt = "BZG", ii = ii, addl = addl)
}

#' Ammonul-style IV load: 250 mg/kg each of Na-phenylacetate and Na-benzoate
#' over 90 min, then the same amount as a 24-h infusion.
ucd_ammonul <- function(wt = 70, load_mgkg = 250, maint_mgkg = 250,
                        start = 0, load_dur = 1.5, maint_dur = 24) {
  paa_load <- load_mgkg  * wt / MW$NaPAA * 1e3
  bz_load  <- load_mgkg  * wt / MW$NaBz  * 1e3
  paa_mnt  <- maint_mgkg * wt / MW$NaPAA * 1e3
  bz_mnt   <- maint_mgkg * wt / MW$NaBz  * 1e3
  c(
    mrgsolve::ev(time = start, amt = paa_load, cmt = "PAAC", rate = paa_load/load_dur),
    mrgsolve::ev(time = start, amt = bz_load,  cmt = "BZC",  rate = bz_load /load_dur),
    mrgsolve::ev(time = start + load_dur, amt = paa_mnt, cmt = "PAAC",
                 rate = paa_mnt/maint_dur),
    mrgsolve::ev(time = start + load_dur, amt = bz_mnt,  cmt = "BZC",
                 rate = bz_mnt /maint_dur)
  )
}

#' L-citrulline, mg/kg/day PO -> umol per dose
ucd_citrulline <- function(mgkg_per_day, wt = 70, n = 3, ii = 8, days = 1,
                           addl = NULL, start = 0) {
