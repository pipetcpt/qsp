// ------------- untreated steady state, solved by bisection.
//   RA_N = A*C/(KM+C) + CLNH4R*C + CLRGLN*vgs(C)/(KGLNASE+CLRGLN)
// The right-hand side is strictly increasing in C, so 60 bisections on
// [1e-6, 1e6] umol/L give the root to machine-useful precision. Every other
// initial condition follows from it in closed form, which is what makes the
// untreated arm exactly stationary for ANY patient descriptor set.
