double hi = 1e6;
double mid = 0.0;
for(int i = 0; i < 60; i++) {
  mid = 0.5*(lo + hi);
  double ran = FDISP*PROT*WT*NPERG/24.0 * ucd_feed(mid, FEEDTHR, FEEDSC) + NOBL;
  double fv = A_UC*mid/(KMNH4 + mid) + CLNH4R*mid
              + CLRGLN*ucd_vgs(mid, VG0, KG0, KGS, KGSAT)/GDENOM - ran;
  if(fv > 0.0) hi = mid; else lo = mid;
}
C0 = mid;
if(C0 < 0.5) C0 = 0.5;
RA_N0 = FDISP*PROT*WT*NPERG/24.0 * ucd_feed(C0, FEEDTHR, FEEDSC) + NOBL;
GLN0C = ucd_vgs(C0, VG0, KG0, KGS, KGSAT)/GDENOM;

VUREA0 = A_UC * C0 / (KMNH4 + C0);

// ------------------------------------------------------- baseline brain
double ph0  = PHART + PHSLOPE*(C0 - 30.0)/100.0;
if(ph0 > PHMAX) ph0 = PHMAX;
NH3F0       = 1.0/(1.0 + pow(10.0, PKANH3 - ph0));
double fbr  = 1.0/(1.0 + pow(10.0, PKANH3 - PHBR));
// PSBBB*(NH3F0*C0 - fbr*CB) = VMGSB*CB/(KMGSB+CB)  ->  quadratic in CB
double aa = PSB*fbr;
double bb = PSB*fbr*KMGSB + VMGS - PSB*NH3F0*C0;
double cc = -PSB*NH3F0*C0*KMGSB;
CB0 = (-bb + sqrt(bb*bb - 4.0*aa*cc)) / (2.0*aa);
if(CB0 < 0.0) CB0 = 0.0;
double vgsb0 = VMGS * CB0/(KMGSB + CB0);
GLNB0 = vgsb0 / KOUTGB;                       // umol of de-novo brain glutamine

double glnb_mM0 = GLNBREF + GLNB0/VBR/1000.0;
double gexc0    = glnb_mM0 - GLNBTHR; if(gexc0 < 0.0) gexc0 = 0.0;
MI0  = KINMI / (KOUTMI + KEXTMI*gexc0);       // mmol/L
double comp0 = MIREF - MI0; if(comp0 < 0.0) comp0 = 0.0;
if(comp0 > FCOMP*gexc0) comp0 = FCOMP*gexc0;  // osmolyte loss can only ever
OSM0 = gexc0 - comp0;                         // offset part of the load
if(OSM0 < 0.0) OSM0 = 0.0;

// ------------------------------------------------- baseline orotate / pools
double actx0 = ACTB; if(actx0 > 1.0) actx0 = 1.0;
CPOVER0 = KCPOVR * CPS1A * FNAG0 * (C0/(KMNH4 + C0)) * (1.0 - actx0);
if(CPOVER0 < 0.0) CPOVER0 = 0.0;

KINORN = KOUTORN*ORNBASE*VORN - KARGORN*ARGBASE*VORN;
if(KINORN < 0.0) KINORN = 0.0;
KINCIT = cCIT * CITBASE;
KINARG = cARG * ARGBASE;
KINGLY = cGLY * GLYBASE;
KINBCA = cBCA * BCABASE;

// --------------------------------------------------- initial conditions
NH4C_0  = C0 * VECF;
GLNC_0  = GLN0C * VGLNC;
GLNM_0  = GLN0C * VGLNM;
NH4B_0  = CB0 * VBR;
GLNB_0  = GLNB0;
MINSB_0 = MI0 * VBR * 1000.0;
BRWAT_0 = KBWIN * OSM0 / KBWOUT;
ORNP_0  = ORNBASE * VORN;
GLYP_0  = GLYBASE * VGLY;
BCAAP_0 = BCABASE * VBCA;
CITC_0  = CITBASE * VCIT;
ARGC_0  = ARGBASE * VARG;
OROTP_0 = KOROT * CPOVER0 / KOUTOR;

$ODE
// ------------------------------------------------------- forcing functions
double sw_prot = (PROT2 < 0) ? 0.0 :
                 1.0/(1.0 + exp(-(SOLVERTIME - TPROT)/0.5));
double protnow = PROT + ((PROT2 < 0 ? PROT : PROT2) - PROT)*sw_prot;
if(PROT3 >= 0) {
  double sw3 = 1.0/(1.0 + exp(-(SOLVERTIME - TPROT3)/0.5));
  protnow = protnow + (PROT3 - protnow)*sw3;
}

double trig = 1.0/(1.0 + exp(-(SOLVERTIME - CATT0)/0.5))
            - 1.0/(1.0 + exp(-(SOLVERTIME - CATT0 - CATDUR)/0.5));

double hdon = 1.0/(1.0 + exp(-(SOLVERTIME - HDT0)/0.25))
            - 1.0/(1.0 + exp(-(SOLVERTIME - HDT0 - HDDUR)/0.25));
double clhd = CLHD * hdon;

double sw_tx = 1.0/(1.0 + exp(-(SOLVERTIME - TTX)/1.0));

// ------------------------------------------------------- catabolic state
dxdt_CATB = KINCAT*CATAMP*trig*(1.0 - CATB) - KOUTCAT*CATB;
double catnow = CATB * (1.0 - 0.70*ANAB);

// ------------------------------------------------------- nitrogen load
double feedsup = ucd_feed(CNH4, FEEDTHR, FEEDSC);
double ra_n = FDISP * protnow * WT * NPERG / 24.0 * feedsup
              + NOBL + NCATA * catnow;

// ------------------------------------------- effective ureagenic activity
double actbase = OTCACT;
if(CPS1A   < actbase) actbase = CPS1A;
if(DISTALA < actbase) actbase = DISTALA;
double otcx = OTCX; if(otcx > OTCXMAX) otcx = OTCXMAX;
double acteff = actbase + otcx;
if(ACTX >= 0) acteff = acteff + (ACTX - acteff)*sw_tx;
if(acteff > 1.0) acteff = 1.0;

// NAG-equivalent activation: endogenous NAGS (arginine-stimulated, valproate-
// inhibitable) plus any carglumic acid on board
double sw_vpa = 1.0/(1.0 + exp(-(SOLVERTIME - TVPA)/0.5));
double nagsx  = NAGSA*(1.0 - VPAI*sw_vpa);
double nagact = nagsx*(1.0 + GARG*(CARG/ARGBASE - 1.0)) + GNCG*CNCG;
if(nagact < 0.0) nagact = 0.0;
double fnag = nagact/(KNAG + nagact);
double forn = CORN/(KORN + CORN);

double vurea = UCAP*WT*acteff*fnag*forn * CNH4/(KMNH4 + CNH4);   // umol N/h

// supplemental citrulline: OTC-independent nitrogen sink through ASS1
double citex = CCIT - CITBASE; if(citex < 0.0) citex = 0.0;
double vcitn = KCITN * DISTALA * citex;                          // umol N/h

// ------------------------------------------------------- scavenger fluxes
double vpagn = VMPAGN * (CPAA/(KMPAA + CPAA)) * (CGLNC/(KMGLNP + CGLNC));
double vhip  = VMHIP  * (CBZ /(KMBZ  + CBZ )) * (CGLY /(KMGLY  + CGLY ));

// ------------------------------------------------------- BBB ammonia flux
double phart = PHART + PHSLOPE*(CNH4 - 30.0)/100.0;
if(phart > PHMAX) phart = PHMAX;
double fnh3  = 1.0/(1.0 + pow(10.0, PKANH3 - phart));
double fbrn  = 1.0/(1.0 + pow(10.0, PKANH3 - PHBR));
double jbbb  = PSB*(fnh3*CNH4 - fbrn*CNH4B);
double vgsb  = VMGS * CNH4B/(KMGSB + CNH4B);

// ======================================================================
//  PK — phenylbutyrate axis
// ======================================================================
dxdt_GPBG = -KHYDG*GPBG;
dxdt_PBAG =  KHYDG*GPBG - KAPBA*PBAG;
dxdt_PBAC =  FPBA*KAPBA*PBAG - cPBA*CPBA;
dxdt_PAAC =  FMPAA*cPBA*CPBA - cPAA*CPAA - vpagn;
dxdt_PGNC =  vpagn - cPGN*CPGN;
dxdt_PGNU =  cPGN*CPGN;

// ======================================================================
//  PK — benzoate axis
// ======================================================================
dxdt_BZG  = -KABZ*BZG;
dxdt_BZC  =  FBZ*KABZ*BZG - cBZ*CBZ - vhip;
dxdt_HIPC =  vhip - cHIP*CHIP;
dxdt_HIPU =  cHIP*CHIP;

// ======================================================================
//  PK — cycle substrates and the NAG analogue
// ======================================================================
dxdt_CITG = -KACIT*CITG;
dxdt_CITC =  FCIT*KACIT*CITG + KINCIT - cCIT*CCIT - vcitn;
dxdt_ARGG = -KAARG*ARGG;
dxdt_ARGC =  FARG*KAARG*ARGG + KINARG - cARG*CARG;
dxdt_NCGG = -KANCG*NCGG;
dxdt_NCGC =  FNCG*KANCG*NCGG - cNCG*CNCG;

// ======================================================================
//  Nitrogen balance — the core of the model
// ======================================================================
//  Glutamine carries TWO nitrogens, so glutamine synthesis debits 2 N from the
//  free pool and glutaminase credits 2 N back. Renal glutamine utilisation
//  excretes one N as urinary NH4+ and returns the other. PAGN formation
//  therefore removes a full 2 N from the body per molecule, and hippurate 1 N —
//  the stoichiometric reason phenylbutyrate is the more nitrogen-efficient
//  scavenger per mole.
//  Hippurate carries one nitrogen out of the body. That nitrogen leaves as
//  glycine, and the glycine pool is re-filled from the free amino-nitrogen
//  pool — so hippurate formation is debited directly against ammonia here
//  (the GLYP compartment tracks the transient pool depletion separately).
double vgs = ucd_vgs(CNH4, VG0, KG0, KGS, KGSAT);

dxdt_NH4C = ra_n
            - vurea
            - vcitn
            - vhip
            - 2.0*vgs
            + 2.0*KGLNASE*CGLNC
            + 1.0*CLRGLN*CGLNC
            - CLNH4R*CNH4
            - clhd*CNH4
            - jbbb
            + KOUTGB*GLNB;

dxdt_GLNC =  vgs
            - KGLNASE*CGLNC
            - CLRGLN*CGLNC
            - vpagn
            - KEXM*(CGLNC - CGLNM)
            - FHDGLN*clhd*CGLNC;

dxdt_GLNM =  KEXM*(CGLNC - CGLNM);

dxdt_UREAX = vurea;

// ======================================================================
//  CNS — astrocytic glutamine trap and osmolyte compensation
// ======================================================================
dxdt_NH4B = jbbb - vgsb;
dxdt_GLNB = vgsb - KOUTGB*GLNB;

double glnb_mM = GLNBREF + GLNB/VBR/1000.0;
double gexc    = glnb_mM - GLNBTHR; if(gexc < 0.0) gexc = 0.0;
double mi_mM   = MINSB/VBR/1000.0;

dxdt_MINSB = (KINMI - KOUTMI*mi_mM - KEXTMI*gexc*mi_mM) * VBR * 1000.0;

double micomp = MIREF - mi_mM; if(micomp < 0.0) micomp = 0.0;
if(micomp > FCOMP*gexc) micomp = FCOMP*gexc;   // partial compensation only
double osmnet = gexc - micomp; if(osmnet < 0.0) osmnet = 0.0;

dxdt_BRWAT = KBWIN*osmnet - KBWOUT*BRWAT;

// ======================================================================
//  Ancillary pools
// ======================================================================
dxdt_ORNP  = KINORN + KARGORN*CARG*VORN - KOUTORN*ORNP;
dxdt_GLYP  = KINGLY - cGLY*CGLY - vhip;
dxdt_BCAAP = KINBCA - cBCA*CBCA - kBPAA*CPAA;

double actc  = acteff; if(actc > 1.0) actc = 1.0;
double cpover = KCPOVR * CPS1A * fnag * (CNH4/(KMNH4 + CNH4)) * (1.0 - actc);
if(cpover < 0.0) cpover = 0.0;
dxdt_OROTP = KOROT*cpover - KOUTOR*OROTP;

// ======================================================================
//  Genetic therapy
// ======================================================================
dxdt_TRANSG = -KTRANS*TRANSG;
dxdt_OTCX   =  KEXPR*TRANSG - KDEGOTC*OTCX;

// ======================================================================
//  Injury / exposure integrators
// ======================================================================
double exc100 = CNH4 - 100.0; if(exc100 < 0.0) exc100 = 0.0;
dxdt_NAUC = exc100;

double sc = 1.0/(1.0 + exp(-(CNH4 - COMATHR)/10.0));
dxdt_COMAH = sc;

double excinj = CNH4 - NH3THR; if(excinj < 0.0) excinj = 0.0;
dxdt_NEURO = KINJ * (excinj/100.0) * (1.0 + 2.0*BRWAT);

double paaug = CPAA*136.15/1000.0;
double exctox = paaug - 500.0; if(exctox < 0.0) exctox = 0.0;
dxdt_PAATOX = exctox;

$TABLE
double NH3     = CNH4;
double GLNP    = CGLNC;
double GLNDEEP = CGLNM;
double NH3BR   = CNH4B;
double GLNBRAIN= GLNBREF + GLNB/VBR/1000.0;         // mmol/L, total
double MINSMM  = MINSB/VBR/1000.0;                  // mmol/L
double BW      = BRWAT;                             // %
double ICP     = ICP0 * exp(KICP*BRWAT);            // mmHg

// hepatic-encephalopathy stage 0-4 driven by oedema AND by ammonia itself
double hedrv = BRWAT/1.0 + (NH3 > 100.0 ? (NH3-100.0)/300.0 : 0.0);
double HESTAGE = 4.0*pow(hedrv,2.5)/(1.0 + pow(hedrv,2.5));

double PAAUG  = CPAA*136.15/1000.0;                 // ug/mL
double PGNUG  = CPGN*264.28/1000.0;                 // ug/mL
double PBAUG  = CPBA*164.20/1000.0;                 // ug/mL
double BZUG   = CBZ *122.12/1000.0;                 // ug/mL
double HIPUG  = CHIP*179.17/1000.0;                 // ug/mL
double PARATIO= (PGNUG > 0.01) ? PAAUG/PGNUG : 0.0;
double UPAGN  = CLPGN*CPGN*24.0/1000.0;             // mmol/day
double UHIPP  = CLHIP*CHIP*24.0/1000.0;             // mmol/day

double CITP = CCIT;
double ARGP = CARG;
double NCGP = CNCG;
double ORNC = CORN;
double GLYC = CGLY;
double BCAC = CBCA;
double OROTC= OROTP;

double IQEST = IQMAX - IQDROP*NEURO/(NEURO + IQ50);

// instantaneous nitrogen-disposal accounting (umol N/h)
double actbase2 = OTCACT;
if(CPS1A   < actbase2) actbase2 = CPS1A;
if(DISTALA < actbase2) actbase2 = DISTALA;
double otcx2 = OTCX; if(otcx2 > OTCXMAX) otcx2 = OTCXMAX;
double ACTEFF = actbase2 + otcx2;
double swtx2 = 1.0/(1.0 + exp(-(TIME - TTX)/1.0));
if(ACTX >= 0) ACTEFF = ACTEFF + (ACTX - ACTEFF)*swtx2;
if(ACTEFF > 1.0) ACTEFF = 1.0;

double swvpa2  = 1.0/(1.0 + exp(-(TIME - TVPA)/0.5));
double nagact2 = NAGSA*(1.0 - VPAI*swvpa2)*(1.0 + GARG*(CARG/ARGBASE - 1.0))
                 + GNCG*CNCG;
if(nagact2 < 0.0) nagact2 = 0.0;
double fnag2 = nagact2/(KNAG + nagact2);
double forn2 = CORN/(KORN + CORN);
double NUREA = UCAP*WT*ACTEFF*fnag2*forn2 * NH3/(KMNH4 + NH3);
double citex2 = CCIT - CITBASE; if(citex2 < 0.0) citex2 = 0.0;
double NCITR  = KCITN*DISTALA*citex2;
double NPAGN = 2.0*cPGN*CPGN;
double NHIPP = 1.0*cHIP*CHIP;
double NRENL = CLRGLN*CGLNC + CLNH4R*NH3;
double NBENZ = NHIPP;
double NTOTAL= NUREA + NCITR + NPAGN + NHIPP + NRENL;

// natural-protein tolerance: the intake (g/kg/day) at which this patient,
// on the CURRENT scavenger regimen, would sit at an ammonia of 60 umol/L
double gln60 = ucd_vgs(60.0, VG0, KG0, KGS, KGSAT)/GDENOM;
double ntol  = UCAP*WT*ACTEFF*fnag2*forn2*60.0/(KMNH4+60.0)
               + CLNH4R*60.0 + CLRGLN*gln60
               + NPAGN + NHIPP + NCITR - NOBL;
if(ntol < 0.0) ntol = 0.0;
double PROTTOL = ntol*24.0/(FDISP*WT*NPERG);

double CATNOW = CATB;

$CAPTURE @annotated
NH3      : Plasma ammonia (umol/L)
GLNP     : Plasma glutamine (umol/L)
GLNDEEP  : Deep tissue glutamine (umol/L)
NH3BR    : Brain ammonia (umol/L)
GLNBRAIN : Brain glutamine (mmol/L)
MINSMM   : Brain myo-inositol (mmol/L)
BW       : Brain water excess (%)
ICP      : Intracranial pressure (mmHg)
HESTAGE  : Encephalopathy stage (0-4)
PAAUG    : Plasma phenylacetate (ug/mL)
PGNUG    : Plasma phenylacetylglutamine (ug/mL)
PBAUG    : Plasma phenylbutyrate (ug/mL)
BZUG     : Plasma benzoate (ug/mL)
HIPUG    : Plasma hippurate (ug/mL)
PARATIO  : PAA:PAGN ratio (ug/mL basis)
UPAGN    : Urinary PAGN excretion rate (mmol/day)
UHIPP    : Urinary hippurate excretion rate (mmol/day)
CITP     : Plasma citrulline (umol/L)
ARGP     : Plasma arginine (umol/L)
NCGP     : Plasma carglumic acid (umol/L)
ORNC     : Ornithine pool (umol/L)
GLYC     : Plasma glycine (umol/L)
BCAC     : Plasma BCAA (umol/L)
OROTC    : Orotic acid pool (umol)
IQEST    : Modelled full-scale IQ
ACTEFF   : Effective ureagenic activity (fraction)
NUREA    : Nitrogen disposed as urea (umol N/h)
NCITR    : Nitrogen disposed via supplemental citrulline (umol N/h)
NPAGN    : Nitrogen disposed as PAGN (umol N/h)
NHIPP    : Nitrogen disposed as hippurate (umol N/h)
NRENL    : Nitrogen disposed renally (umol N/h)
NTOTAL   : Total nitrogen disposal (umol N/h)
PROTTOL  : Natural-protein tolerance at ammonia 60 (g/kg/day)
CATNOW   : Catabolic state (0-1)
'

## ---------------------------------------------------------------------------
##  Build
