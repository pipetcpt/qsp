// Whole-body glutamine synthesis as a function of plasma ammonia. Two
// components, BOTH proportional to ammonia at low concentration so that no
// scenario can drive the free-nitrogen pool negative:
//   * a high-affinity, near-saturated term  -> the ~400 umol/L glutamine floor
//   * a low-affinity, ammonia-driven term   -> the rise of glutamine in UCD
double ucd_vgs(double C, double vg0, double kg0, double kgs, double ksat) {
  if(C < 0.0) C = 0.0;
  return vg0*C/(kg0 + C) + kgs*C/(1.0 + C/ksat);
}

// Anorexia, vomiting and obtundation: a hyperammonaemic patient stops eating.
// Without this negative feedback an untreated severe defect integrates its
// nitrogen load without bound; with it, ammonia plateaus in the range actually
// seen in decompensation. Protein aversion is also the classic history in
// late-onset disease, so the same term carries a real clinical sign.
double ucd_feed(double C, double thr, double sc) {
  double e = C - thr;
  if(e < 0.0) e = 0.0;
  return 1.0/(1.0 + (e/sc)*(e/sc));
}
